/**
 * Чёткость карты на слабом устройстве (вариант «Авто» с карточки владельца в треде «Плавность
 * игры», 2026-10-20: слабый телефон сам переходит на пониженную чёткость карты, в настройках её
 * можно вернуть).
 *
 * Кадр большой карты на слабом телефоне — почти целиком пиксели: небо, выпечка, рамка стекла,
 * живые границы и сведение кадра растут с их числом. При одном пикселе холста на точку экрана
 * вместо двух точек вчетверо меньше. Окна, кнопки и панели — разметка, а не холст карты: их
 * чёткость не меняется.
 *
 * 1. **Слабое устройство решают кадры, а не модель телефона.** Медиана промежутка между кадрами
 *    матча за {@link JUDGE_FRAMES} кадров дольше {@link SLOW_FRAME_MS} — устройство слабое.
 *    Считаются кадры с {@link JUDGE_WARMUP_MS} после того, как карта показалась: первые выпечки
 *    — не обычный кадр. На экране 60 Гц промежутки идут ступенями по 16,7 мс: 30 кадров в
 *    секунду — 33 мс, и чёткость остаётся, 20 кадров — 50 мс, и её уже нет. Телефон, которого
 *    энергосбережение держит на 30 кадрах, чёткость не теряет.
 * 2. **Слабое один раз — слабое и дальше.** Вердикт запоминается, и следующий вход сразу
 *    начинается с пониженной чёткости, без медленных первых секунд. Нечёткая карта рисуется
 *    быстрее, и суд по ней вернул бы чёткость, а за ней и медленные кадры. Нормальное
 *    устройство не запоминается: его кадры судят в каждом сеансе.
 * 3. **Выбор игрока сильнее вердикта в обе стороны**, как у свечения: тумблер «Чёткая карта»
 *    держит своё значение, что бы ни сказали кадры, и пока он выбран, кадры не судят.
 * 4. **Пониженная чёткость — {@link SOFT_MAP_DPR} пиксель на точку.** Экрану, у которого
 *    плотность не выше, понижать нечего: у него нет ни тумблера, ни суда кадров.
 */

/** Сколько кадров матча судят устройство (правило 1). */
export const JUDGE_FRAMES = 90;

/** С какой задержки после показа карты кадры начинают считаться, мс (правило 1). */
export const JUDGE_WARMUP_MS = 2000;

/** Медиана промежутка между кадрами, дольше которой устройство слабое, мс (правило 1). */
export const SLOW_FRAME_MS = 40;

/** Плотность пикселей холста карты при пониженной чёткости (правило 4). */
export const SOFT_MAP_DPR = 1;

/** Есть ли экрану что понижать (правило 4). */
export function sharpnessMatters(screenDpr: number): boolean {
  return screenDpr > SOFT_MAP_DPR;
}

/** Чёткая ли карта: выбор игрока, а без него — не слабое ли устройство (правила 2–3). */
export function mapSharp(chosen: boolean | null, slow: boolean): boolean {
  return chosen ?? !slow;
}

/** Плотность пикселей холста карты: экрана или пониженная (правило 4). */
export function mapDpr(screenDpr: number, sharp: boolean): number {
  return sharp ? screenDpr : Math.min(screenDpr, SOFT_MAP_DPR);
}

/** Судят ли кадры этого сеанса устройство (правила 2–4). `judged` — кадры сеанса уже сказали,
 *  что устройство не слабое. */
export function judgingFrames(
  screenDpr: number,
  chosen: boolean | null,
  slow: boolean,
  judged: boolean,
): boolean {
  return sharpnessMatters(screenDpr) && chosen === null && !slow && !judged;
}

/** Слабое ли устройство по промежуткам между кадрами матча, мс (правило 1); `null` — кадров
 *  меньше {@link JUDGE_FRAMES}, судить рано. */
export function slowFrames(gaps: readonly number[]): boolean | null {
  if (gaps.length < JUDGE_FRAMES) return null;
  const sorted = [...gaps].sort((a, b) => a - b);
  return sorted[sorted.length >> 1]! > SLOW_FRAME_MS;
}
