/**
 * Конвейер стройки мира: когда очередь пускает следующий заказ и когда сборный флот
 * перестаёт собирать (REFM-172).
 *
 * Цены, уровни и порядок активной стройки — `buildOrders.ts` (REFM-32) и
 * `buildProgress.ts` (REFM-31); вердикт по конкретному заказу даёт ЯДРО. Здесь то, что
 * стояло прямо в кадре: условия, при которых конвейер шевелится.
 *
 * 1. **Очередь двигают только у СВОЕГО мира.** Потерянный мир строит уже не тебе, а
 *    оставшаяся на нём очередь — не твоя очередь.
 * 2. **В полосе одновременно ровно один заказ.** Пока идёт стройка, голова ждёт: ядро всё
 *    равно не примет второй, и очередь существует именно чтобы держать его до срока.
 *    Пустая полоса не пускает ничего, и это проверяется ДО вердикта ядра — вердикт берут
 *    по конкретному заказу, а несуществующий заказ ядру не предъявишь.
 * 3. **Полосы независимы.** Здание не держит верфь и наоборот — иначе одна долгая
 *    постройка замораживала бы весь мир.
 * 4. **Голова уезжает, только если её вердикт — не «ждём денег».** Ожиданием лечится
 *    ровно одна причина; любой другой отказ голова везёт в ядро и получает НАСТОЯЩУЮ
 *    причину строкой игроку вместо молчаливого зависания.
 * 5. **Полосы решаются ПО ОЧЕРЕДИ, а не единым планом.** Пуск головы ТРАТИТ ресурсы,
 *    поэтому вердикт по следующей полосе зависит от уже применённой. Посчитать план
 *    целиком и потом его применить значило бы выпустить два заказа на одни деньги —
 *    поэтому модуль отдаёт ПРЕДИКАТЫ, а не готовый список шагов.
 * 6. **Сбор закрывается, когда на мире не осталось ни идущей постройки корабля, ни
 *    очереди.** Флот с меткой `rally` глотает свежепостроенные корабли; пока мир строит,
 *    партия ещё не полна.
 * 7. **Закрытие — снятие МЕТКИ, а не роспуск флота.** Корабли остаются на месте, а
 *    следующий заказ откроет НОВЫЙ сборный флот: иначе одна эскадра росла бы весь матч и
 *    отделить свежую партию было бы нечем.
 * 8. **О летящем флоте решения не принимают.** У него нет мира под ногами — читать «строит
 *    ли ещё его мир» попросту не по чему, и метка ждёт возвращения.
 * 9. **Вердикт ядра спрашивают ЛЕНИВО — только у заказа, который вот-вот издадут.** Занятая
 *    полоса и пустая полоса обрываются раньше, чем дело дойдёт до ядра. Пока это стояло в
 *    кадре, лень обеспечивал `||`; при выносе она чуть не потерялась (аргументы вычисляются
 *    жадно), и сверка перебором поймала именно это — поэтому вердикт приходит функцией.
 */

/** Метка сборного флота: он глотает свежепостроенные корабли своего мира. */
export const RALLY_TRAIT = 'rally';

/** Полосы конвейера в порядке обхода (правила 3, 5). */
export const BUILD_LANES = ['buildings', 'units'] as const;

/** Полоса конвейера. */
export type PipelineLane = (typeof BUILD_LANES)[number];

/** Двигать ли очередь этого мира вообще (правило 1). */
export function queueRuns(hasQueue: boolean, worldMine: boolean): boolean {
  return hasQueue && worldMine;
}

/**
 * Пора ли отдать голову полосы ядру (правила 2–4).
 *
 * Вердикт приходит ФУНКЦИЕЙ, а не значением, и это несущая деталь (правило 9): его
 * спрашивают только у заказа, который вот-вот издадут. Наличие головы сюда не передаётся
 * по той же причине — пустую полосу отсекают до вызова.
 */
export function headStarts(laneBusy: boolean, waitsForMoney: () => boolean): boolean {
  return !laneBusy && !waitsForMoney();
}

/** Флот, о котором решают судьбу сбора. */
export interface RallyFleetView {
  mine: boolean;
  /** Мир под ногами; `null` — флот в пути (правило 8). */
  location: string | null;
  moving: boolean;
  traits: readonly string[] | undefined;
}

/** Закрывать ли сбор этому флоту (правила 6, 8). */
export function rallyCloses(
  f: RallyFleetView,
  stillBuilding: (planetId: string) => boolean,
): boolean {
  if (!f.mine || !f.location || f.moving) return false;
  if (!f.traits?.includes(RALLY_TRAIT)) return false;
  return !stillBuilding(f.location);
}

/** Метки флота без сбора — корабли при этом остаются на месте (правило 7). */
export function withoutRally(traits: readonly string[]): string[] {
  return traits.filter((t) => t !== RALLY_TRAIT);
}

/** Строит ли мир корабли прямо сейчас: идущая постройка ИЛИ непустая очередь (правило 6). */
export function shipsPending(activeBuild: boolean, queuedShips: number): boolean {
  return activeBuild || queuedShips > 0;
}
