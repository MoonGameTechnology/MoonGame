/**
 * БОСС ЗАБЕГА — задача «Убить Левиафана» и награда за неё (PVR-4.7, резолюция владельца
 * 2026-09-24: «убьёте его — стая перестаёт расти; за это доп. задача «Убить Левиафана»
 * с наградой»).
 *
 * ПОЧЕМУ НЕ ЗАДАЧА ГЛАВЫ (`missionObjectives.ts`). Задачи главы — запас карты: видна его
 * часть, выполненная закрывается навсегда, и её место занимает следующая. Босс устроен
 * иначе: он приходит только к матёрому Рою и только с последней волной, и убить его можно
 * в каждом таком забеге. Положи его в запас главы — он занимал бы место в слабом забеге,
 * где его нет, и закрывался бы навсегда после первой же победы.
 *
 * Поэтому задача появляется вместе с боссом (`state.pve.boss`) и платит ровно ту награду,
 * которую режим объявил и которую матч записал при появлении босса. Чистая функция
 * состояния: панель зовёт её каждый кадр, итоги — один раз, и разойтись они не могут.
 */
import type { GameState } from '../packages/shared-core/src/index';

/** Задача босса в этом забеге. */
export interface BossTask {
  /** Архетип босса (`data.heroes`) — по нему строится имя. */
  hero: string;
  slain: boolean;
  /** Надбавка к награде забега за убитого босса. */
  reward: number;
}

/** Задача босса; `null` — босса в этом забеге нет (слабый Рой или волны ещё идут). */
export function bossTask(state: GameState): BossTask | null {
  const boss = state.pve?.boss;
  if (!boss) return null;
  return {
    hero: boss.hero,
    slain: boss.slainAt !== undefined,
    reward: Math.max(0, Math.trunc(boss.reward) || 0),
  };
}

/** Сколько забег платит за босса: убит — объявленная награда, жив или не приходил — ноль. */
export function bossBounty(state: GameState): number {
  const task = bossTask(state);
  return task?.slain ? task.reward : 0;
}
