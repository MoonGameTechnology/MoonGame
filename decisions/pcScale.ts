/**
 * Масштаб интерфейса ПК (UIX-2.1, UIX-2.2): во сколько раз голографический интерфейс крупнее
 * базового и какие узкие раскладки включаются под этим зумом.
 *
 * Голографический интерфейс — единственный на ПК — стоял в масштабе 1 на любом мониторе:
 * медиана текста партии 12 px и при 1366×768, и при 2560×1440, окно науки — 10 px. На
 * большом экране игрок сидит дальше, и тот же текст читается мельче. Основа — XAG 101: при
 * 1080p текст от 18 px высоты глифа.
 *
 * 1. **Растёт с высотой окна: высота / 864.** 1366×768 — масштаб 1 (ниже не мельчим:
 *    раскладка ноутбука проверена именно там), 1920×1080 — 1,25, 2560×1440 — 1,667.
 * 2. **Не больше 2.** На 4K двукратного хватает, дальше окна займут весь экран.
 * 3. **Ширине раскладки не дают стать уже 1366 px.** Под зумом раскладка видит окно
 *    уменьшенным: браузер на половине монитора 2560×1440 (1280×1440) по одной высоте
 *    получил бы 1,667, и раскладке осталось бы 768 px — уже, чем ПК-раскладка бывает вовсе
 *    (900 px, правило 5). Масштаб по окну места у раскладки не отнимает, отдать место за
 *    размер может только сам игрок. Для экранов 16:9 правило ничего не меняет: у них
 *    ширина / 1366 больше, чем высота / 864.
 * 4. **Нечисловой размер — масштаб 1.** Замер окна, которого нет, не должен ронять зум в NaN.
 * 5. **«Размер интерфейса» игрока умножает этот масштаб (UIX-2.2).** 80–150 % из настроек
 *    «Графики»; 150 % на 4K дают 3, правило 2 ограничивает только масштаб по окну. Растить
 *    раскладку меньше 900 × 500 px множитель не даёт: уже 900 px раскладка ПК не включается
 *    вовсе (медиа-запрос ПК), а 500 по высоте остаются ноутбуку 1366×768 при 150 %, и там
 *    окна проверены. На экранах от 1366×768 доступны все 150 %, а в маленьком окне браузера
 *    множитель упирается в этот предел. Уменьшать (80 %) можно всегда: раскладке становится
 *    только просторнее.
 * 6. **Узкие раскладки консоли считаются от раскладки, а не от окна (UIX-2.2).** Зумленный
 *    слой верстается в `окно / зум` px, а медиа-запрос видит настоящее окно: на 150 % у
 *    ноутбука 1366×768 верхняя строка верстается в 911 px, а `(max-width:1200px)` молчал, и
 *    доходы в ней обрезались. Поэтому узкие правила `holographic.css` и `bridge-shell.css`
 *    включает класс `body` по {@link narrowLayouts}. При зуме 1 ответ совпадает с прежними
 *    `(max-width: N px)` и `(max-height: N px)`.
 */

/** Высота окна, при которой интерфейс в масштабе 1. */
export const PC_SCALE_BASE_HEIGHT = 864;
/** Уже этого раскладку под зумом не сжимают: столько она видит у ноутбука 1366×768. */
export const PC_SCALE_MIN_WIDTH = 1366;
/** Потолок масштаба по окну. */
export const PC_SCALE_MAX = 2;
/** Меньше этого раскладку не сжимает множитель игрока. */
export const PC_LAYOUT_MIN_WIDTH = 900;
export const PC_LAYOUT_MIN_HEIGHT = 500;

/**
 * Масштаб голографического интерфейса ПК для окна `width × height` (CSS px): по окну 1..2,
 * умноженный на «Размер интерфейса» `userPct` (проценты, нечисло — 100).
 */
export function pcScale(width: number, height: number, userPct = 100): number {
  const fit = Math.min(height / PC_SCALE_BASE_HEIGHT, width / PC_SCALE_MIN_WIDTH);
  if (!Number.isFinite(fit)) return 1;
  const auto = Math.min(PC_SCALE_MAX, Math.max(1, fit));
  const user = Number.isFinite(userPct) && userPct > 0 ? userPct / 100 : 1;
  const room = Math.min(width / PC_LAYOUT_MIN_WIDTH, height / PC_LAYOUT_MIN_HEIGHT);
  const zoom = user > 1 ? Math.max(auto, Math.min(auto * user, room)) : auto * user;
  // Три знака: дробь длиннее только дёргала бы стиль на каждом пикселе ресайза.
  return Math.round(zoom * 1000) / 1000;
}

/** Пороги узких раскладок консоли в px раскладки (правило 6): классы `holo-w1200` … `holo-h650`. */
export const NARROW_LAYOUT_WIDTHS = [1200, 1100, 1050, 980, 900] as const;
export const SHORT_LAYOUT_HEIGHTS = [760, 650] as const;

/**
 * Узкие раскладки для окна `width × height` (CSS px) при зуме слоёв `zoom`: класс `body` →
 * включён ли (правило 6). Нечисловой зум — 1.
 */
export function narrowLayouts(
  width: number,
  height: number,
  zoom: number,
): Record<string, boolean> {
  const z = Number.isFinite(zoom) && zoom > 0 ? zoom : 1;
  const out: Record<string, boolean> = {};
  for (const n of NARROW_LAYOUT_WIDTHS) out[`holo-w${n}`] = width / z <= n;
  for (const n of SHORT_LAYOUT_HEIGHTS) out[`holo-h${n}`] = height / z <= n;
  return out;
}
