/**
 * Жизнь долгого нажатия: от касания до «съеденного» завершающего тапа (REFM-80, REFM-131).
 *
 * У пальца нет наведения, поэтому то, что мышь получает по наведению, телефон открывает
 * УДЕРЖАНИЕМ. Из этого следует неприятная механика: то же касание завершится обычным
 * тапом, и без присмотра игрок получит за одно движение два действия — то, что дало
 * удержание, и то, что даст отпускание.
 *
 * 1. **Нажатие взводит ожидание и запоминает точку** — от неё считается, поехал палец
 *    или лежит.
 * 2. **Поехавший палец снимает ожидание.** Прокрутка панели не должна оборачиваться
 *    подсказками, которых игрок не просил.
 * 3. **Отпускание и отмена гасят всё** — и ожидание, и уже показанный пузырь.
 * 4. **СОЗРЕВШЕЕ УДЕРЖАНИЕ СЪЕДАЕТ СЛЕДУЮЩИЙ ТАП.** Иначе поверх подсказки откроется
 *    ещё и кодекс — за одно касание игрок получает два действия, из которых просил одно.
 * 5. **Право съесть тап ОДНОРАЗОВОЕ.** Не сняв флаг, следующий честный тап по плитке
 *    молча пропадёт, и игрок решит, что интерфейс сломался.
 *
 * ДВЕ ПОВЕРХНОСТИ, ОДНА ЖИЗНЬ (REFM-131). Правила выше писались под плитку каталога, но
 * ровно то же удержание живёт на КАРТЕ: там оно добирает флот в группу или растягивает
 * рамку — пальцевые заменители Ctrl-клика и Shift-протяжки. У карты была своя копия этой
 * механики (свой флаг «уже сработало», своё гашение отпускания), и копия — это две жизни
 * одного правила: почини «двойное действие» в одной, и вторая продолжит его делать.
 *
 * 6. **Условия проверяются В МОМЕНТ СОЗРЕВАНИЯ, а не только на взводе.** Между касанием
 *    и срабатыванием проходят сотни миллисекунд: палец успевает поехать, а на карте — ещё
 *    и прийти второй. Решение, принятое на старте, к моменту выстрела уже неверно;
 *    поэтому созревание — отдельный переход (`mature`), и он срабатывает, только пока
 *    ожидание не снято.
 * 7. **Что именно делает созревшее удержание — решает поверхность, а не эта жизнь.**
 *    Кому достался жест на карте, говорит `pressIntent.ts`; здесь только фазы, общие для
 *    обеих поверхностей, — иначе модуль снова разошёлся бы на две копии.
 */

/** Что известно о текущем нажатии. */
export interface HoldState {
  /** Точка касания; `null` — нажатия нет. */
  from: { x: number; y: number } | null;
  /** Ожидание взведено (таймер идёт). */
  armed: boolean;
  /** Удержание созрело: пузырь показан и клик надо съесть. */
  matured: boolean;
}

export const IDLE: HoldState = { from: null, armed: false, matured: false };

/**
 * Сколько ждёт удержание НА КАРТЕ. Своё число, отдельно от панельного `HOLD_TIP_MS`: на
 * карте удержание конкурирует с протяжкой камеры, и ждать оно обязано ровно столько,
 * чтобы не спутаться со случайным тапом, но меньше, чем игрок решит, что не сработало.
 */
export const MAP_HOLD_MS = 350;

/** Касание плитки: взвести ожидание от этой точки (правило 1). */
export function press(at: { x: number; y: number }): HoldState {
  return { from: at, armed: true, matured: false };
}

/** Ожидание доиграло: пузырь показан, клик теперь наш (правило 4). */
export function mature(st: HoldState): HoldState {
  return st.armed ? { from: st.from, armed: false, matured: true } : st;
}

/** Палец поехал — это прокрутка, ожидание снимается (правило 2). */
export function moveAway(st: HoldState): HoldState {
  return st.armed ? { ...IDLE, matured: st.matured } : st;
}

/** Отпустили или система отменила жест: гаснет всё, кроме права съесть клик (правило 3). */
export function release(st: HoldState): HoldState {
  return { from: null, armed: false, matured: st.matured };
}

/**
 * Надо ли съесть этот клик, и каким станет состояние после (правила 4–5). Право
 * одноразовое: второй клик уже проходит.
 */
export function consumeClick(st: HoldState): { eat: boolean; next: HoldState } {
  if (!st.matured) return { eat: false, next: st };
  return { eat: true, next: { ...st, matured: false } };
}
