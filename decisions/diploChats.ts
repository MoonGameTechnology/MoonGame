/**
 * Какие чаты показывать во вкладке сообщений окна дипломатии (COAL-1, заказ владельца
 * 2026-10-20).
 *
 * Раньше список держал личку с КАЖДЫМ местом партии: на карте в 20 мест это 19 пустых
 * строк, среди которых тонула единственная живая переписка. Теперь чат появляется
 * по факту:
 *
 * 1. **Личка — только с тем, с кем была переписка или висит предложение.** Написал ты,
 *    написали тебе, кто-то из двоих предложил стойку или обмен картами — чат есть.
 *    Предложение без единого слова тоже создаёт чат: в нём игрок принимает или
 *    отказывается.
 * 2. **Открытая переписка не пропадает.** Игрок нажал «✉» у места в ростере — чат
 *    открыт и пуст; спрятать его до первого сообщения значило бы спрятать поле ввода.
 * 3. **Чат коалиции — только у вступившего.** Пока у игрока нет ни одного союзника,
 *    канала нет вовсе, а не «пустой коалиции из одного».
 */

/** Что решению нужно знать о переписке игрока. */
export interface ChatFacts {
  /** Места партии, кроме своего, в порядке ростера. */
  others: readonly string[];
  /** Открытая сейчас переписка (id места или групповой канал). */
  open: string;
  /** Была ли переписка с местом в любую сторону. */
  talked(id: string): boolean;
  /** Висит ли между нами предложение в любую сторону. */
  offered(id: string): boolean;
}

/** Места, личка с которыми видна в списке (правила 1–2). Порядок — порядок `others`. */
export function shownDms(f: ChatFacts): string[] {
  return f.others.filter((id) => id === f.open || f.talked(id) || f.offered(id));
}

/** Виден ли канал коалиции (правило 3): в коалиции кроме меня есть хотя бы один. */
export function coalitionChatShown(members: number): boolean {
  return members > 1;
}
