/**
 * Таймер бомбардировки: когда рухнет следующая постройка мира под обстрелом (заказ
 * владельца 2026-11-01: «таймер до следующего тика бомбардировки»).
 *
 * 1. **«Тик» — снос постройки.** Обстрел в ядре идёт непрерывно: урон копится по часам
 *    (`orbital`), и прочность построек тает без шагов. Заметное игроку событие одно —
 *    постройка рухнула (`building.destroyed`): гаснет её доход, защита и выданный ею
 *    гарнизон. Его и отсчитывает таймер.
 * 2. **Рухнет первая уязвимая постройка по порядку мира.** `construction` тратит урон
 *    обстрела по постройкам в порядке массива; постройка без прочности в данных не
 *    разрушаема и пропускается. Таймер берёт тот же порядок, иначе назвал бы не ту.
 * 3. **Скорость — сумма по обстреливающим флотам**, каждый — в уроне после хуков (техи,
 *    фракция, прикрытие мира постройками). Её считает хост через `traceHooks` ядра; здесь
 *    только деление. Прикрытие меняется лишь со сносом постройки, поэтому до ближайшего
 *    сноса скорость постоянна и отсчёт точен (пока не сменился состав флотов).
 * 4. **Нечего сносить — таймера нет.** Без уязвимых построек обстрел только прореживает
 *    гарнизон и до порога (`groundFire.ts`); отсчитывать нечего. Нулевая скорость — тоже
 *    нет таймера: «никогда» на табло хуже пустого места.
 * 5. **Таймер видят только стороны обстрела**: хозяин мира и хозяин обстреливающего
 *    флота. Прочность чужих построек — не знание третьего игрока.
 * 6. **Отсчёт не уходит в минус**: между сроком и его обработкой миром игрок видит ноль.
 */

/** Постройка мира в том виде, какой нужен таймеру: тип, текущая и полная прочность. */
export interface FallCandidate {
  type: string;
  hp: number;
  /** Полная прочность уровня по данным; 0 — постройка неразрушаема (правило 2). */
  maxHp: number;
}

export interface BuildingFall {
  /** Тип постройки, которая рухнет следующей. */
  building: string;
  /** Сколько времени мира до её сноса, мс (правило 6). */
  leftMs: number;
}

/**
 * Правила 2–4 и 6: какая постройка рухнет и через сколько. `ratePerHour` — урон обстрела
 * за игровой час после хуков, `hourMs` — длина игрового часа в мс мира (масштаб матча).
 */
export function nextBuildingFall(
  buildings: readonly FallCandidate[],
  ratePerHour: number,
  hourMs: number,
): BuildingFall | null {
  if (!(ratePerHour > 0) || !(hourMs > 0)) return null; // правило 4
  const target = buildings.find((b) => b.maxHp > 0); // правило 2
  if (!target) return null; // правило 4
  const leftMs = (Math.max(0, target.hp) / ratePerHour) * hourMs;
  return { building: target.type, leftMs: Math.max(0, leftMs) };
}

/** Правило 5: видит ли смотрящий таймер этого мира. */
export function bombardTimerShown(
  viewer: string,
  worldOwner: string | null,
  bombarderOwners: readonly string[],
): boolean {
  return worldOwner === viewer || bombarderOwners.includes(viewer);
}
