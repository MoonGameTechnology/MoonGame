/**
 * Что снимок сервера делает с миром на экране (REFM-146).
 *
 * Пятый срез сетевой секции, продолжение `netWelcome.ts`: там решалось, что значит ПЕРВЫЙ
 * снимок (вход в матч), здесь — что делает КАЖДЫЙ пришедший, включая рядовое обновление
 * мира. Разбор стоял хвостом внутри `onSnapshot` — четыре разных решения подряд, вперемешку
 * с присваиваниями глобальным переменным.
 *
 * Общая рамка: снимок приходит УЖЕ в тумане войны — сервер вырезал из него всё, чего мы не
 * видим. Поэтому «объекта нет в снимке» не значит «объекта нет в мире», и каждое правило
 * ниже — про то, как не соврать игроку в обе стороны.
 *
 * 1. **Радар-контакты живут ровно один снимок.** Замеченные, но не опознанные чужие флоты
 *    в состояние не попадают — сервер шлёт их отдельным грубым списком рядом с кадром.
 *    Нет списка — он ПУСТ, а не «оставим прежний»: переживший снимок контакт рисовал бы
 *    отметку там, где сервер уже никого не показывает, и игрок принимал бы решения по
 *    призраку.
 * 2. **Десинк считается только когда сервер прислал хеш.** Нет хеша — нет вердикта, и наш
 *    считать незачем: сравнение с пустотой объявило бы расхождение на каждом снимке от
 *    хоста, который хеши не шлёт, и индикатор в углу перестал бы что-либо значить.
 * 3. **Одиночный выбор снимается, только если объекта в снимке НЕТ; групповой — оставляет
 *    лишь СВОИ.** Разница намеренная: одиночным выбором смотрят и на чужой флот (карточка
 *    противника), а групповой существует ради приказов, которые чужому флоту отдать нельзя.
 *    Без этой чистки приказ ушёл бы на идентификатор, которого в новом мире уже нет.
 * 4. **Баннер ожидания снимает тот, кто его поставил** — та же дисциплина, что у входа
 *    (`netWelcome.ts`, правило 4): безусловная очистка стёрла бы чужое сообщение (итог
 *    матча, переподключение), о котором приход снимка ничего не знает. Канал баннера
 *    различается по метке в начале строки.
 */

/** Метка баннера ожидания — по ней снимок узнаёт СВОЙ баннер (правило 4). */
export const WAIT_MARK = '⏳';

/** Радар-контакты этого кадра (правило 1). */
export function radarContacts<T>(signatures: readonly T[] | undefined): readonly T[] {
  return signatures ?? [];
}

/**
 * Расходится ли наша картина мира с серверной (правило 2): `null` — вердикта нет,
 * сервер хеш не прислал. Наш хеш считается лениво — незачем хешировать состояние,
 * когда сравнивать не с чем.
 */
export function desyncVerdict<H>(theirs: H | undefined, ours: () => H): boolean | null {
  return theirs === undefined ? null : ours() !== theirs;
}

/** Одиночный выбор после снимка: держится, пока объект в снимке есть (правило 3). */
export function keepFocus(selected: string | null, present: boolean): string | null {
  return selected && present ? selected : null;
}

/** Групповой выбор после снимка: только свои и только уцелевшие (правило 3). */
export function keepGroup(
  selected: Iterable<string>,
  ownerOf: (id: string) => string | undefined,
  me: string,
): string[] {
  return [...selected].filter((id) => ownerOf(id) === me);
}

/** Что делать с баннером ожидания (правило 4). */
export type WaitBanner = 'show' | 'clear' | 'keep';

export function waitingBanner(waiting: boolean, banner: string | null): WaitBanner {
  if (waiting) return 'show';
  return banner?.startsWith(WAIT_MARK) ? 'clear' : 'keep';
}
