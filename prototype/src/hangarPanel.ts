/**
 * АНГАР ГЛАЗАМИ ИГРОКА (SHU-3.1) — что показывает и что предлагает панель про челноки.
 *
 * До этого модуля челноков в интерфейсе не было ВООБЩЕ. Вкладка «Крылья» панели мира
 * показывала `planet.garrison`, отфильтрованный по трейту `shuttle`, — а челнок с
 * SHU-1.1 в гарнизоне не бывает никогда, он лежит в `planet.hangar`. То есть вкладка
 * была гарантированно пустой, и построенные машины исчезали для игрока: он платил за
 * них, а увидеть и применить не мог.
 *
 * Правила, которые здесь закреплены:
 *
 * 1. **Ангар показывается, пока есть ВМЕСТИМОСТЬ, даже пустой.** «0 из 6» говорит «сюда
 *    можно строить»; отсутствие блока читалось бы как «здесь такого не бывает». А вот
 *    места БЕЗ вместимости (нет порта, корабль без ангара) блока не получают вовсе:
 *    «0 из 0» — это не факт о мире, а строка ни о чём.
 * 2. **Топливо принадлежит МЕСТУ, а не машине** (SHU-1.2): у порта один счётчик на все
 *    вылеты, поэтому и в панели он один — над составом, а не в каждой строке.
 * 3. **«Готов» — это И топливо, И конец перезарядки, И живые машины, И не в бою.** Четыре
 *    причины «нельзя лететь» показываются РАЗНЫМИ словами: пустой ангар, носитель в бою,
 *    перезарядка, нет топлива. Одна общая заглушка заставляла бы игрока гадать, чего
 *    ждать. ДВИЖЕНИЕ причиной больше не является (решение владельца 2026-09-16): ядро
 *    пускает вылет с идущего носителя, и панель идёт следом.
 * 4. **Перегрузка порт ⇄ носитель предлагается только когда она ПРОЙДЁТ.** Носитель
 *    должен стоять у этого мира, быть свой и иметь свободное место; иначе кнопки нет —
 *    не серой, а нет. Серая кнопка обещала бы действие, которого в этом месте не
 *    бывает (то же правило, что у командного ряда, `cmdPresence.ts`).
 * 5. **Предлагается она с ОБЕИХ сторон — и от носителя, и от мира.** Найдено в живой
 *    игре: у игрока был «Шаттл», а кнопок он не нашёл. Всё работало, но они стояли
 *    только на панели флота-носителя, тогда как челноки игрок видит и строит во вкладке
 *    мира. Место, где лежат машины, и место, где их можно погрузить, оказались разными
 *    панелями — а значит механики для игрока не существовало.
 *    Кому грузить со стороны мира, решает `dockedCarrier`, и решает СТРОГО: носителей у
 *    мира должно быть ровно ДВА варианта — один или ни одного. При двух и больше панель
 *    мира молчит, потому что цена ошибки тут выше, чем у выбора звена (`transferPick`):
 *    машины уедут с чужим флотом. Адресный приказ остаётся на панели самого носителя,
 *    где цель однозначна.
 * 6. **Место называет себя САМО** (`kind`). Форма у порта и трюма одна — это правильно, —
 *    но подписи разные, а секция в разметке одна на обоих. Пока `kind` не было, она
 *    печатала «Ангар порта» и «порт перезаряжается» над составом КОРАБЛЯ: игрок читал про
 *    порт, стоя на идущем «Шаттле». Признак живёт в данных, а не в разметке, потому что
 *    разметка его не выведет — по составу порт от трюма не отличить.
 */
import type { GameData, Fleet, Planet, Squadron, UnitStack } from '../../packages/shared-core/src/index';
import {
  canSortie,
  fleetShuttleBay,
  hangarMachines,
  hangarSize,
  shuttleBayAt,
  stacksSize,
  sortieSpec,
  type SortieState,
} from '../../packages/shared-core/src/index';

/** Почему вылет невозможен прямо сейчас — или `null`, если возможен (правило 3). */
export type HangarBlock = 'empty' | 'busy' | 'rearming' | 'no-fuel' | null;

/** Ангар одного места — порта мира или трюма носителя. Форма одна: у ангара везде
 *  один и тот же смысл, и вторая структура развела бы две панели по мелочам. */
export interface HangarView {
  /** ЧЕЙ это ангар. Форма у порта и трюма одна (см. ниже), но НАЗЫВАЮТСЯ они по-разному:
   *  одна и та же секция рисует оба, и заголовок «Ангар порта» на идущем «Шаттле» —
   *  это строка про порт над составом корабля. Место называет себя само, чтобы разметке
   *  не приходилось угадывать по косвенным признакам. */
  kind: 'port' | 'hold';
  /** ЭСКАДРЫ места (SHU-4.2) — то, чем адресуются приказы: вылет, перегрузка, делёж.
   *  Панель со списком соединений придёт в SHU-4.3; пока отсюда берётся id. */
  squadrons: Squadron[];
  /** Сколько мест трюма занимает каждая эскадра `squadrons` (тот же порядок): место
   *  меряется `cargoSize` машины (SHU-5.1), тяжёлый страйкер занимает два. */
  sizes: number[];
  /** Машины места одним списком — состав, без деления на соединения. */
  stacks: UnitStack[];
  /** Занято МЕСТ (не машин, SHU-5.1). */
  used: number;
  /** Вместимость в местах; у стоящего порта — `Infinity` (порт без предела). */
  bay: number;
  free: number;
  /** Топливо места (правило 2). `undefined` — счётчика нет (пустой носитель). */
  sortie?: { fuel: number; maxFuel: number; rearming: number };
  /** Почему нельзя поднять вылет; `null` — можно. */
  blocked: HangarBlock;
}

/** Есть ли у места ангар вообще (правило 1): вместимость больше нуля. */
export function hasHangar(view: HangarView | null): view is HangarView {
  return view !== null && view.bay > 0;
}

function view(
  data: GameData,
  kind: HangarView['kind'],
  host: { hangar?: Squadron[] },
  bay: number,
  sortie: SortieState | undefined,
  maxFuel: number,
  busy = false,
): HangarView | null {
  if (bay <= 0) return null;
  const squadrons = (host.hangar ?? []).filter((sq) => sq.units.some((st) => st.count > 0));
  const stacks = hangarMachines(host).filter((st) => st.count > 0);
  const used = hangarSize(host, data);
  const live: SortieState = sortie ?? { fuel: maxFuel, rearming: 0 };
  // `busy` идёт СРАЗУ за «пусто»: у порта его не бывает вовсе, а у носителя он значит
  // БОЙ и перебивает топливо с перезарядкой — ждать их бессмысленно, пока идут раунды.
  const blocked: HangarBlock =
    used <= 0
      ? 'empty'
      : busy
        ? 'busy'
        : live.rearming > 0
          ? 'rearming'
          : canSortie(live)
            ? null
            : 'no-fuel';
  return {
    kind,
    squadrons,
    sizes: squadrons.map((sq) => stacksSize(sq.units, data)),
    stacks,
    used,
    bay,
    free: Math.max(0, bay - used),
    ...(maxFuel > 0 ? { sortie: { fuel: live.fuel, maxFuel, rearming: live.rearming } } : {}),
    blocked,
  };
}

/** Ангар КОСМОПОРТА мира. `null` — порта нет, блока в панели быть не должно. */
export function planetHangar(planet: Planet, data: GameData): HangarView | null {
  // Ёмкость топлива задаёт САМА МАШИНА (`fuel` первой в ангаре) — та же величина, по
  // которой ядро заводит счётчик базы, и та же функция: своя копия этого чтения жила
  // здесь, пока `sortieSpec` читала старое место (`fleet.units` мёртвого «крыла»).
  // Пустой порт показывает состав без топлива: выводить «0 из 0 вылетов» там, где
  // лететь некому, значит пугать числом ни о чём.
  return view(
    data,
    'port',
    planet,
    // Порт — только ворота: стоит — держит сколько угодно (SHU-5.1).
    shuttleBayAt(planet, data) > 0 ? Infinity : 0,
    planet.sortie,
    sortieSpec(planet, data).maxFuel,
  );
}

/**
 * Трюм НОСИТЕЛЯ («Шаттл», SHU-2.1). `null` — корабль ангара не несёт.
 *
 * Носитель, в отличие от порта, бывает ЗАНЯТ — но с 2026-09-16 только одним: БОЕМ
 * (`requireOwnedUnengagedFleet` → `E_FLEET_BUSY`). Прежде ядро требовало стоянки, и
 * панель зеркалила все три условия; решением владельца движение перестало быть помехой,
 * и «Удар» на ходу больше не гаснет. Условие здесь по-прежнему ЗЕРКАЛО ядра, а не своя
 * копия: кнопка не должна обещать приказ, который отобьют после прицеливания.
 */
export function fleetHangar(fleet: Fleet, data: GameData): HangarView | null {
  const busy = !!fleet.battleId;
  return view(
    data,
    'hold',
    fleet,
    fleetShuttleBay(fleet, data),
    fleet.sortie,
    sortieSpec(fleet, data).maxFuel,
    busy,
  );
}

/** Что можно перегрузить между портом мира и стоящим у него носителем (правило 4). */
export interface TransferOffer {
  /** Поднять машины с мира на носитель (`shuttle.load`). */
  load: boolean;
  /** Ссадить машины с носителя на мир (`shuttle.unload`). */
  unload: boolean;
}

export function transferOffer(
  port: HangarView | null,
  hold: HangarView | null,
  opts: { docked: boolean; mine: boolean },
): TransferOffer {
  if (!opts.docked || !opts.mine || !hasHangar(port) || !hasHangar(hold)) {
    return { load: false, unload: false };
  }
  return { load: port.used > 0 && hold.free > 0, unload: hold.used > 0 && port.free > 0 };
}

/**
 * КОМУ грузить со стороны МИРА (правило 5): единственный свой носитель, стоящий у этого
 * узла и готовый принять приказ. `null` — кандидата нет ИЛИ их несколько; в обоих случаях
 * панель мира кнопок не показывает.
 *
 * «Готов принять» — те же три условия, что спрашивает ядро (`requireOwnedIdleFleet`):
 * стоит на узле, не в движении, не в бою. Своей копии правила здесь нет — есть его
 * зеркало, ровно как у остальных кнопок панели: показывать кнопку, которую редьюсер
 * отобьёт, значит обещать действие, которого не будет.
 */
export function dockedCarrier(
  fleets: readonly Fleet[],
  planetId: string,
  owner: string,
  data: GameData,
): Fleet | null {
  const found = fleets.filter(
    (f) =>
      f.owner === owner &&
      f.location === planetId &&
      !f.movement &&
      !f.battleId &&
      fleetShuttleBay(f, data) > 0,
  );
  return found.length === 1 ? found[0]! : null;
}

/**
 * КАКУЮ ЭСКАДРУ перегружать одной кнопкой (SHU-3.1, форма — SHU-4.2). Кнопка у игрока
 * одна, а соединений в ангаре может быть несколько — выбор обязан быть
 * ДЕТЕРМИНИРОВАННЫМ и объяснимым: берётся ПЕРВАЯ живая эскадра источника, и только если
 * она влезает в приёмник ЦЕЛИКОМ (ядро возит соединение целиком, половину оно отобьёт
 * кодом `E_NO_CAPACITY`). Первая, а не «лучшая»: какое звено нужнее — решение игрока, и
 * когда для него появится выбор, он появится списком, а не догадкой кнопки.
 *
 * `null` — перегружать нечего: кнопку в этом состоянии не показывают вовсе.
 */
export function transferPick(
  from: HangarView | null,
  to: HangarView | null,
): { squadronId: string; count: number } | null {
  if (!hasHangar(from) || !hasHangar(to)) return null;
  const sq = from.squadrons[0];
  if (!sq) return null;
  const count = sq.units.reduce((n, st) => n + st.count, 0);
  // Влезает ли — по МЕСТАМ (SHU-5.1), а не по штукам: ядро меряет трюм `cargoSize`.
  return count > 0 && (from.sizes[0] ?? count) <= to.free ? { squadronId: sq.id, count } : null;
}
