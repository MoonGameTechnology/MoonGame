/**
 * Пометки о долгах владельца на карточках панели (REFM-89).
 *
 * Неоплаченный ресурс бьёт по игроку штрафом, и панель обязана об этом сказать — иначе
 * бой проигрывается «непонятно почему». Проверка `(s.players[ME]?.arrears ?? [])
 * .includes(...)` катается по карточкам в трёх местах, и условия вокруг неё в каждом
 * свои. Правила общие, и им место в одном файле.
 *
 * 1. **Долг показывается только СВОЕМУ.** Чужие долги — не наша беда и не наша
 *    информация: панель врага не обязана раскрывать его экономику.
 * 2. **Голод отмечается только там, где есть кому голодать.** Штраф −25% на земле бьёт
 *    по НАЗЕМНЫМ частям; флот без десанта и мир без гарнизона его не получают, и метка
 *    у них была бы ложной тревогой.
 * 3. **Блэкаут — свойство ВЛАДЕЛЬЦА, а не отдельного мира.** Неоплаченная энергия глушит
 *    радары и ПВО у всех его миров разом, поэтому метка висит на каждом своём мире, а не
 *    только там, где стоит электростанция.
 * 4. **Долги независимы: одна метка не заменяет другую.** Долг по еде ничего не говорит
 *    про энергию, и наоборот — списки проверяются порознь.
 */

/** Есть ли долг по этому ресурсу. Отсутствующий список — долгов нет. */
export function owes(arrears: readonly string[] | undefined | null, resource: string): boolean {
  return (arrears ?? []).includes(resource);
}

/** Показывать ли метку голода: свой, есть кому голодать, и долг по еде (правила 1–2). */
export function showsStarving(
  mine: boolean,
  /** Сколько наземного есть. Частей или стопок — важно лишь, больше ли нуля: карточка
   *  флота считает части, карточка мира — стопки гарнизона, и обе спрашивают «есть ли». */
  ground: number,
  arrears: readonly string[] | undefined | null,
): boolean {
  return mine && ground > 0 && owes(arrears, 'food');
}

/** Показывать ли блэкаут: свой мир и долг по энергии (правила 1, 3). */
export function showsBlackout(
  mine: boolean,
  arrears: readonly string[] | undefined | null,
): boolean {
  return mine && owes(arrears, 'energy');
}
