import { randomInt } from 'node:crypto';

/**
 * Идентификатор партии (ADDR-1, номер партии — плейтест 2026-10-17).
 *
 * Заказ владельца — «сама сессия должна падать в отдельную ссылку, как у Bytro». Ссылка
 * работает адресом ровно до тех пор, пока идентификатор принадлежит ПАРТИИ, а не месту
 * партии в списке процесса. Прото-хост раздавал `proto`, `proto-2`, … по порядку из
 * `MATCHES=N`: после перезапуска те же имена достались бы другим мирам, и закладка
 * игрока указала бы не туда — а угадать соседнюю сессию можно было бы, прибавив единицу.
 *
 * Поэтому правило живёт в ОДНОМ месте и одинаково у обоих хостов (тот же приём, что с
 * `matchKind()` и `joinSeat()`).
 *
 * 1. **Номер из цифр.** Игрок видит номер партии и копирует его, как у Bytro («Партия
 *    № 48219370»), а не адрес с UUID. Номер случайный, а не порядковый: соседнюю партию
 *    прибавлением единицы не найти, и перезапуск хоста не раздаёт старые номера заново.
 * 2. **Восемь цифр без ведущего нуля.** Девяносто миллионов номеров — коротко для глаза и
 *    достаточно, чтобы совпадение было редкостью. Ведущего нуля нет: номер не теряет цифру,
 *    если его прочтут как число.
 * 3. **Совпадение проверяет тот, кто знает занятые номера** ({@link freeMatchId}): номер
 *    чужой партии не переписывает её сохранение. Старые id `m-<uuid>` и `proto` остаются
 *    действительными — правило касается только новых партий.
 */
export function newMatchId(): string {
  return String(randomInt(10_000_000, 100_000_000));
}

/** Сколько раз пробовать номер, прежде чем признать, что свободного нет (правило 3). */
const MINT_ATTEMPTS = 32;

/** Свободный номер партии: `taken` говорит, занят ли номер (живой комнатой или стором). */
export async function freeMatchId(taken: (id: string) => boolean | Promise<boolean>): Promise<string> {
  for (let i = 0; i < MINT_ATTEMPTS; i++) {
    const id = newMatchId();
    if (!(await taken(id))) return id;
  }
  throw new Error('no free match id'); // → 500: столько совпадений подряд — поломка, не случай
}
