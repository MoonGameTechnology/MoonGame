/**
 * Адреса запросов к серверу матчей и разбор его ответа (REFM-150).
 *
 * Девятый срез сетевой секции. Браузер матчей ходит на сервер по HTTP четырьмя местами
 * (список, места, архив, разархив), и каждое собирало свой адрес прямо в строке `fetch`,
 * а неудачу разбирало собственной парой `if`-ов. Правила у всех четырёх одни, но
 * повторены они были по-разному — а одно место (список) их и вовсе смешивает, см. ниже.
 *
 * 1. **Всё, что уходит в АДРЕС, экранируется.** Позывной набирает человек, а
 *    идентификатор матча приходит по ссылке: пробел, `&` или `?` внутри них иначе
 *    разорвут запрос — сервер получит не то, что просили, а игрок увидит непонятный
 *    отказ. Тот же довод, что у дозвона (`netDial.ts`, REFM-142).
 * 2. **Адрес HTTP выводится из адреса сокета** заменой схемы (`ws→http`, `wss→https`):
 *    игрок вводит ОДИН адрес сервера, и второй, «а теперь то же самое, но по HTTP», у
 *    него спрашивать нельзя — разъедутся при первой же опечатке.
 * 3. **«Сервер ответил отказом» и «до сервера не дошли» — разные беды.** Отказ (`4xx`,
 *    `5xx`) значит «сервер жив, но так нельзя» — повторять действие бессмысленно, надо
 *    прочитать причину. Недоступность значит «связи нет» — тут как раз надо повторить
 *    позже. Свалить их в одно сообщение — послать игрока чинить не ту беду.
 * 4. **Не разобранный ответ — тоже неудача, а не «список не изменился».** Сломанный JSON
 *    оставил бы на экране прежний список, и игрок жал бы «Войти» по матчу, которого уже
 *    нет; честнее показать, что списка сейчас нет.
 */

/** HTTP-адрес того же сервера, что и адрес сокета (правило 2). */
export function httpBase(wsBase: string): string {
  return wsBase.replace(/^ws/, 'http');
}

/** Список матчей для этого позывного (правила 1–2). */
export function matchesUrl(wsBase: string, nick: string): string {
  return `${httpBase(wsBase)}/matches?nick=${encodeURIComponent(nick)}`;
}

/**
 * Места матча — кто какой стороной играет (правила 1–2).
 *
 * Позывной уходит в адрес не для вида: идущую партию сервер показывает только её
 * участникам (ADDR-6), а на безаккаунтном хосте `?nick=` — единственное, чем игрок
 * может назваться. На хосте с учётками личность приезжает заголовком `Authorization`,
 * и этот параметр там просто не смотрят.
 */
export function seatsUrl(wsBase: string, matchId: string, nick: string): string {
  return `${httpBase(wsBase)}/matches/${encodeURIComponent(matchId)}/seats?nick=${encodeURIComponent(nick)}`;
}

/** Убрать матч из списка или вернуть обратно (правила 1–2). */
export function archiveUrl(wsBase: string, matchId: string, nick: string, restore: boolean): string {
  const op = restore ? 'unarchive' : 'archive';
  return `${httpBase(wsBase)}/matches/${encodeURIComponent(matchId)}/${op}?nick=${encodeURIComponent(nick)}`;
}

/** Чем кончился запрос (правила 3–4). */
export type QueryOutcome =
  /** Ответ получен и разобран. */
  | 'ok'
  /** Сервер жив и ОТВЕТИЛ отказом — повторять бессмысленно. */
  | 'refused'
  /** До сервера не дошли (или ответ не разобрался) — можно повторить позже. */
  | 'unreachable';

/** Разбор исхода: `ok` — ответ 2xx, `refused` — ответ с кодом ошибки, `unreachable` —
 *  запрос не состоялся (`null`: исключение сети или неразобранный ответ, правило 4). */
export function queryOutcome(res: { ok: boolean } | null): QueryOutcome {
  if (!res) return 'unreachable';
  return res.ok ? 'ok' : 'refused';
}
