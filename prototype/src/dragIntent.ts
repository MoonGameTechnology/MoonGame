/**
 * REFM-199 — ЧТО ОЗНАЧАЕТ ЕДУЩИЙ ПАЛЕЦ.
 *
 * Родной брат `aimGesture.ts`. Тот отвечает на вопрос «коммитит ли ОТПУСКАНИЕ», этот —
 * на вопрос «а что вообще происходит, пока палец едет». Оба выросли из одной находки
 * аудита ввода («слепой приказ»), и оба ломаются ОДИНАКОВО ТИХО: жест не падает и ничего
 * не пишет в консоль, он просто делает не то, что задумал игрок. Панорама съедала
 * прицеливание — приказ не доходил вовсе; второй палец отменял вооружённый приказ — и
 * камеру при вооружённом «Курсе» было не сдвинуть, а цель за краем экрана становилась
 * недостижимой. Оба раза чинили правкой одного условия в цепочке `if` внутри
 * обработчика, у которого нет юнит-харнеса, — то есть проверялось это пальцем на
 * телефоне, а не тестом.
 *
 * ПРАВИЛА И ПРИЧИНЫ:
 *
 * 1. Два пальца — ВСЕГДА щипок, что бы ни было вооружено. Второй палец ВЕЗЁТ камеру, а не
 *    отменяет приказ: раньше он отменял, и это запирало игрока — одним пальцем целятся,
 *    значит камеру при вооружённом «Курсе» было не сдвинуть вовсе. Отменить приказ
 *    по-прежнему можно кнопкой и Back/Escape, обе дороги живы.
 *
 * 2. Палец + вооружённый приказ = палец ВЕДЁТ ПРИЦЕЛ, камера стоит. Это и есть починка
 *    «слепого приказа»: пока протяжку забирала панорама, целиться на телефоне было
 *    нечем — приказ молча растворялся.
 *
 * 3. На PC вооружённый приказ протяжку НЕ забирает. Мышь целится наведением, а
 *    перетаскивание там — привычная панорама; отобрав её, мы сломали бы работающий ввод
 *    ради проблемы, которой на PC нет. Приказ панораму переживает, коммит — чистый клик.
 *
 * 4. Рамка выделения требует ТОЧКИ НАЧАЛА жеста: без неё второй угол не из чего строить,
 *    и рамка вышла бы из случайного места.
 *
 * 5. Всё остальное — панорама. Это базовый смысл движения по карте, а не отдельный
 *    случай: любой жест, который никем не занят, обязан возить карту.
 *
 * 6. Камера едет ТОЛЬКО в щипке и панораме. В прицеле и рамке сдвиг камеры увёз бы
 *    вместе с собой и цель, и углы рамки: игрок тянет одно, а меняется другое.
 *
 * 7. Пометка «жест был протяжкой» ставится по-разному, и это не небрежность: щипок
 *    помечается БЕЗУСЛОВНО (два пальца — уже не тап, даже если легли и поднялись на
 *    месте), прицел — НИКОГДА (протяжка и ЕСТЬ прицеливание, и считать её «уездом»
 *    значило бы отменять то, ради чего она делалась), а рамка и панорама — только когда
 *    палец ушёл дальше порога тапа.
 */

/** Что делает жест прямо сейчас. Ровно один из четырёх — взаимоисключающе. */
export type DragIntent =
  /** Два пальца: масштаб + перенос середины. */
  | 'pinch'
  /** Палец ведёт остриё вооружённого приказа; камера стоит. */
  | 'aim'
  /** Тянется рамка выделения. */
  | 'box'
  /** Ничем не занятое движение возит карту. */
  | 'pan';

export interface DragFacts {
  /** Сколько пальцев на экране. */
  pointers: number;
  /** Вооружён ли приказ («Курс» / ШТУРМ). */
  armed: boolean;
  /** PC-раскладка: мышь целится наведением, перетаскивание — панорама. */
  pc: boolean;
  /** Начата ли рамка выделения. */
  boxing: boolean;
  /** Есть ли запомненная точка начала жеста. */
  hasStart: boolean;
}

/** Вердикт: чем занят этот жест. Порядок веток и есть приоритет правил 1–5. */
export function dragIntent(f: DragFacts): DragIntent {
  if (f.pointers >= 2) return 'pinch'; // правило 1
  if (f.armed && !f.pc) return 'aim'; // правила 2–3
  if (f.boxing && f.hasStart) return 'box'; // правило 4
  return 'pan'; // правило 5
}

/** Едет ли камера за этим жестом (правило 6). */
export function cameraFollows(intent: DragIntent): boolean {
  return intent === 'pinch' || intent === 'pan';
}

/** Помечать ли жест протянутым — тем самым признаком, который потом гасит тап (правило 7). */
export function marksDragged(intent: DragIntent, moved: boolean): boolean {
  if (intent === 'pinch') return true;
  if (intent === 'aim') return false;
  return moved;
}
