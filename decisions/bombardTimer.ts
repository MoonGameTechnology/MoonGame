/**
 * Таймер бомбардировки: через сколько ударит следующий залп обстрела (заказ владельца
 * 2026-11-01 «таймер до следующего тика бомбардировки», уточнён 2026-11-02: «таймер должен
 * показывать, через сколько будет следующая атака… каждый час, как обычная атака флота»).
 *
 * 1. **Залп — по часам флота.** Обстрел бьёт раз в игровой час, у каждого флота свои часы
 *    (`Fleet.bombardNextAt`, модуль `orbital`), как атака в бою. Таймер их только читает.
 * 2. **Над миром — ближайший залп.** Если мир обстреливают несколько флотов, таймер мира
 *    показывает, когда ударит первый из них. Метка флота — его собственные часы.
 * 3. **Нет часов — нет таймера.** Флот без `bombardNextAt` (старое сохранение до первого
 *    шага мира) просто не попадает в отсчёт: «никогда» на табло хуже пустого места.
 * 4. **Таймер видят только стороны обстрела**: хозяин мира и хозяин обстреливающего
 *    флота. Чужая осада — не знание третьего игрока.
 * 5. **Отсчёт не уходит в минус**: между сроком и его обработкой миром игрок видит ноль.
 */

/** Правила 1–3: когда ближайший залп (мировые мс), или `null`, если часов нет. Окно, которое
 *  сравнивает разметку, пишет этот срок, а не остаток: остаток менялся бы с часами. */
export function nextVolleyAt(clocks: readonly (number | undefined)[]): number | null {
  let next: number | null = null;
  for (const at of clocks) {
    if (at === undefined || !Number.isFinite(at)) continue;
    if (next === null || at < next) next = at;
  }
  return next;
}

/** Правила 1–3 и 5: сколько мс мира до ближайшего залпа, или `null`, если часов нет. */
export function nextVolleyIn(clocks: readonly (number | undefined)[], now: number): number | null {
  const next = nextVolleyAt(clocks);
  return next === null ? null : Math.max(0, next - now);
}

/** Правило 4: видит ли смотрящий таймер этого мира. */
export function bombardTimerShown(
  viewer: string,
  worldOwner: string | null,
  bombarderOwners: readonly string[],
): boolean {
  return worldOwner === viewer || bombarderOwners.includes(viewer);
}
