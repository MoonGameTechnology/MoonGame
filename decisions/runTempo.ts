/**
 * Темп ЗАБЕГА — с какой скоростью идёт его мировой клок (PVR-2.2). Чистое решение
 * обоих клиентов.
 *
 * **Почему у забега своя скорость.** Соло-песочница открывается на ×10, и это верно для
 * неё: там играют в своё удовольствие, часами. Забег — другой продукт: решение владельца
 * (§0.3 `sector-zero-roadmap.md`) требует ПОЛНОГО прохождения за 25–35 минут, а с
 * ускорением — за 15–25. На ×10 тот же забег идёт около четырнадцати часов, то есть
 * дефолт песочницы делает его не «долгим», а несуществующим.
 *
 * **Откуда взялись именно эти множители.** Забег нельзя пройти быстрее, чем придёт
 * последняя волна: десять волн с шагом шесть игровых часов — это {@link RUN_SPINE_HOURS}
 * часов, и ниже этого числа не опускается никто. Сверху — хвост: контратака и зачистка
 * улья, около {@link RUN_TAIL_HOURS} часов. Значит пройденный забег живёт примерно
 * 60–85 игровых часов, и множители подобраны так, чтобы ВЕСЬ этот отрезок попал в
 * названные владельцем минуты. Проверено тестом рядом, а не на глаз.
 *
 * Здесь только числа и арифметика — ни DOM, ни таймеров: кто и как крутит часы, решает
 * клиент.
 */

/** Игровых часов до последней волны: 10 волн × 6 часов (`data/modes.json`). Пройти
 *  забег быстрее нельзя физически — это его хребет. */
export const RUN_SPINE_HOURS = 60;

/** Хвост после последней волны: контратака и зачистка улья. Оценка, а не замер:
 *  бот на месте игрока улей не берёт, поэтому измерить прохождение прогоном нечем. */
export const RUN_TAIL_HOURS = 25;

/** Обычный темп забега. */
export const RUN_SPEED_NORMAL = 150;

/** Ускорение. Ровно в полтора раза быстрее обычного — столько же, во сколько раз
 *  различаются названные владельцем полосы (30 минут против 20). */
export const RUN_SPEED_FAST = 225;

/**
 * Сколько РЕАЛЬНЫХ минут занимают `hours` игровых часов при множителе `mult`.
 *
 * Основание — `PLAY_BASE` прототипа: ×1 это настенные часы, то есть один игровой час за
 * один реальный. Отсюда вся арифметика темпа и берётся, и держать её здесь честнее, чем
 * пересчитывать в уме при каждой правке множителя.
 */
export function runMinutes(hours: number, mult: number): number {
  return (hours * 60) / mult;
}
