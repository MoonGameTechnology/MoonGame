/**
 * Что показать вместо списка матчей, когда списка нет (REFM-151).
 *
 * Десятый срез сетевой секции. Браузер матчей — первый экран сетевой игры, и чаще всего
 * игрок видит его в худшем состоянии: сервер не отвечает, список пуст, адрес не введён.
 * Решение «что вместо списка» стояло тремя вложенными тернарниками внутри `renderMatches`,
 * и разница между сборкой игрока и dev-клиентом была размазана по тем же строкам.
 *
 * 1. **Никогда не тупик.** Что бы ни ответил сервер, dev-клиент предлагает путь, который
 *    работает ВСЕГДА — соло без сервера. Экран, который только сообщает о беде и не даёт,
 *    что делать дальше, для новичка равен закрытой игре.
 * 2. **Соло предлагают ОБЕИМ сборкам, а тексты у них разные.** Кнопка соло нужна и в
 *    мобильной сборке — там сервер ещё и адресом не задан, так что путь без сервера
 *    нужнее всего. А вот причина, по которой списка нет, звучит по-разному: игроку сразу
 *    говорят «укажите адрес сервера», dev-клиенту — «нажмите „Обновить“», потому что у
 *    него адрес обычно уже свой.
 * 3. **«Сервер не ответил» и «мы ещё не спрашивали» — разные сообщения.** Первое зовёт
 *    проверить связь или адрес, второе — просто нажать «Обновить»; одинаковый текст на оба
 *    случая заставил бы игрока чинить работающую связь.
 * 4. **Строка адреса сервера всплывает ровно тогда, когда список не загрузился** (только в
 *    сборке игрока): у мобильной сборки нет полезного адреса страницы, поэтому сервер
 *    вводят руками — но ровно один раз, а дальше строка прячется и не мозолит глаза.
 * 5. **Одно сообщение об одной беде.** Если «сервер недоступен» уже написано под списком,
 *    строку статуса нужно очистить: два одинаковых сообщения на экране читаются как две
 *    разные беды.
 * 6. **«Ничего не найдено» — это НЕ «сервер пуст», и это НЕ тупик** (BRW-3). Когда список
 *    пуст, потому что игрок сузил его фильтром, соло предлагать неверно: путь у него под
 *    рукой — ослабить фильтр, панель прямо над списком. Кнопка «в соло» отвечала бы на
 *    вопрос, которого он не задавал, и прятала бы настоящую причину пустого экрана.
 *    Беда связи важнее: сервер, который не ответил, называется бедой связи даже если
 *    фильтр в это время что-то скрывал бы — иначе «ничего не найдено» отправит игрока
 *    крутить фильтры вместо проверки адреса.
 */

/** Что рисуем вместо списка. */
export type Fallback =
  /** Список есть — рисуем его. */
  | { kind: 'list' }
  /** Списка нет: сообщение + кнопка соло (правило 1). */
  | { kind: 'empty'; message: FallbackMessage }
  /** Список есть, но фильтр скрыл всё: ОДНО сообщение, без соло (правило 6). */
  | { kind: 'filtered'; message: 'browser.filter.none' };

/** Ключ сообщения — почему списка нет. */
export type FallbackMessage =
  /** Сервер не ответил (сборка игрока: с подсказкой про адрес). */
  | 'browser.server-down'
  | 'acc.server-down'
  /** Список ещё не запрашивали. */
  | 'browser.loading'
  | 'browser.refresh-hint'
  /** Ответ пришёл, матчей нет. */
  | 'browser.empty';

export interface BrowserState {
  /** Список получен (пусть даже пустой). */
  loaded: boolean;
  /** Прошлый запрос кончился неудачей. */
  failed: boolean;
  /** В текущей вкладке есть строки. */
  rows: number;
  /** Сборка игрока: свои тексты причин, адрес сервера вводится руками. */
  playerBuild: boolean;
  /** Сколько строк этой вкладки скрыл фильтр (BRW-3). Нет поля ⇒ фильтра нет —
   *  вкладки «Активные»/«Архив» он не трогает, да и панель там не показывается. */
  hiddenByFilter?: number;
}

/** Что показать вместо списка (правила 1–3, 6). */
export function fallbackFor(st: BrowserState): Fallback {
  if (!st.loaded) {
    const message: FallbackMessage = st.failed
      ? st.playerBuild
        ? 'browser.server-down'
        : 'acc.server-down'
      : st.playerBuild
        ? 'browser.loading'
        : 'browser.refresh-hint';
    return { kind: 'empty', message };
  }
  if (st.rows === 0) {
    // Правило 6: список ПРИШЁЛ и он не пуст — пусто на экране из-за фильтра.
    if (st.hiddenByFilter) return { kind: 'filtered', message: 'browser.filter.none' };
    return { kind: 'empty', message: 'browser.empty' };
  }
  return { kind: 'list' };
}

/** Показывать ли строку адреса сервера (правило 4) — только в сборке игрока. */
export function showServerRow(playerBuild: boolean, loaded: boolean): boolean {
  return playerBuild && !loaded;
}

/** Гасить ли строку статуса, чтобы не дублировать сообщение под списком (правило 5). */
export function clearStatusLine(playerBuild: boolean, failed: boolean): boolean {
  return playerBuild && failed;
}
