/**
 * Дальность карты на экране: одна величина — один перевод (REFM-132).
 *
 * Радиусы радара, дальность способности, зона поражения — всё это ФИЗИЧЕСКИЕ величины
 * в единицах карты. Чтобы нарисовать их, нужен перевод в пиксели, и в кадровом цикле он
 * жил в четырёх видах сразу: именованным помощником, дважды выражением
 * `world({x: x + r, y}).x - centre.x` в соседних функциях и один раз — проекцией по ОБЕИМ
 * осям с рисованием эллипса. Четыре записи одного и того же не просто дублируют друг
 * друга: последняя ещё и УТВЕРЖДАЕТ другое устройство проекции, чем первые три.
 *
 * 1. **Радиус переводится ТЕМ ЖЕ множителем, что и позиции.** Множитель — это подгон
 *    карты под экран, умноженный на зум камеры (`fitTransform().scale * cam.scale`).
 *    Взять один зум камеры (так когда-то и было) — и круг дальности оказывается меньше
 *    настоящей дальности ровно во столько раз, во сколько карта вписана в экран: игрок
 *    видит одно, а правила считают другое.
 * 2. **Проекция РАВНОМЕРНА по осям — круг остаётся кругом.** Это не совпадение, а
 *    обещание камеры: `fitTransform` берёт один общий масштаб по меньшей стороне и
 *    добивает разницу полями. Значит второй радиус, посчитанный по вертикали, всегда
 *    равен первому, а нарисованный эллипс — это обещание неравномерности, которой нет:
 *    читающий такой код начинает считать её возможной и копирует «на всякий случай»
 *    дальше.
 * 3. **Считать радиус проекцией смещённой точки — окольный путь к тому же числу.**
 *    `world({x: x + r}).x - world({x}).x` раскрывается ровно в `r * множитель`, только
 *    ценой двух лишних проекций.
 */

/** Множитель «единица карты → пиксель» при текущей камере: подгон под экран × зум. */
export function mapScale(fitScale: number, camScale: number): number {
  return fitScale * camScale;
}

/**
 * Дальность карты в пикселях экрана (правила 1–3). Единственный перевод: и круги
 * радара, и радиусы способностей, и зоны поражения обязаны считаться им же — иначе
 * слои разъедутся между собой, показывая разную дальность для одного числа.
 */
export function screenRadius(reach: number, scale: number): number {
  return reach * scale;
}
