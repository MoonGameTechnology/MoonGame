/**
 * Когда меню десанта вообще открывается и чьи числа в него попадают (REFM-173).
 *
 * Арифметика меню — `troopsMenu.ts` (GRND-1), источники и типы — `troopsSources.ts`
 * (REFM-81). Здесь предыдущий шаг, до сих пор стоявший прямо в кадре: ЖИВАЯ СЦЕНА
 * превращается в вопрос «показывать ли меню и с какой стороны».
 *
 * 1. **Меню открывается только у ПРИШВАРТОВАННОГО флота вне боя.** Летящий или дерущийся
 *    не грузится: ядро всё равно отобьёт приказ, а открытое меню обещало бы то, чего нет.
 * 2. **Над ЧУЖИМ миром меню открывается только на ВЫСАДКУ** и только если ядро её примет.
 *    Круг «свой мир или мир союзника» здесь НЕ переписывается — задаётся вопрос про
 *    НАСТОЯЩИЙ приказ, поэтому если ядро когда-нибудь расширит его (скажем, на пакт),
 *    клиент поедет за ним сам, без правки этой строки.
 * 3. **Высаживать нечего — над чужим миром меню не открывается.** Гостю оно годится
 *    ровно на одно действие, и без груза это пустое окно.
 * 4. **На чужом мире гарнизонные числа обнуляются.** Поднимать оттуда нечего, и счётчик
 *    выходит односторонним сам собой — без отдельного «режима гостя» в самом меню.
 * 5. **Пустое меню не открывается.** Ни одного наземного типа ни в гарнизоне, ни в трюме
 *    — показывать нечего, а пустой поповер игрок читает как поломку.
 * 7. **Вердикт ядра спрашивают ЛЕНИВО** — только когда вопрос осмыслен: на своём мире
 *    разрешение не нужно, а с пустым трюмом приказ не из чего собрать.
 * 6. **План берётся только у СВОЕГО флота.** Незавершённый набор, начатый на другом
 *    флоте, не должен подставляться сюда: игрок подтвердил бы чужие числа не глядя.
 */

/** Живая сцена вокруг флота — всё, что нужно, чтобы решить судьбу меню (правила 1–3). */
export interface TroopsScene {
  /** Флот есть, стоит у мира, не летит и не в бою. */
  docked: boolean;
  /** Мир под ним — мой. */
  worldMine: boolean;
  /** В трюме есть живой наземный груз. */
  carriesGround: boolean;
  /**
   * Примет ли ядро высадку этого груза на этот мир — ФУНКЦИЕЙ, а не значением.
   *
   * Спрашивать ядро можно только когда вопрос осмыслен: на своём мире разрешение не
   * нужно, а с пустым трюмом высаживать нечего и приказ не из чего собрать. Пока это
   * стояло в кадре, лень обеспечивал `&&`; при выносе она теряется молча (аргументы
   * вычисляются жадно) — та же ловушка, что поймана в REFM-172.
   */
  landingAllowed: () => boolean;
}

/** Судьба меню: закрыто, обе стороны, только высадка (правила 1–3). */
export type TroopsGate = 'closed' | 'both' | 'landing-only';

/** Открывать ли меню и с какой стороны (правила 1–3). */
export function troopsGate(sc: TroopsScene): TroopsGate {
  if (!sc.docked) return 'closed';
  if (sc.worldMine) return 'both';
  return sc.carriesGround && sc.landingAllowed() ? 'landing-only' : 'closed';
}

/** Гарнизонные числа строки: на чужом мире их нет (правило 4). */
export function garrisonSide(
  mine: boolean,
  healthy: number,
  all: number,
): { garrison: number; garrisonAll: number } {
  return mine ? { garrison: healthy, garrisonAll: all } : { garrison: 0, garrisonAll: 0 };
}

/** План этого флота, а не соседнего (правило 6). */
export function planFor(
  planFleetId: string | null | undefined,
  fleetId: string,
  plan: Readonly<Record<string, number>> | undefined,
): Record<string, number> {
  return planFleetId === fleetId && plan ? { ...plan } : {};
}
