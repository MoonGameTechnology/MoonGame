// Статический список локалей и «запекание» фолбэка. Единственное место, где тексты
// всех языков импортируются разом.
//
// Зачем отдельный файл (LOC-6): русский — не просто локаль, а ФОЛБЭК. Пока рантайм
// искал промах в `LOCALES[DEFAULT_LOCALE]`, каждый игрок обязан был скачать русский
// поверх своего языка — то есть обе локали (30% веса клиентского бандла). Поэтому
// фолбэк «запекается» в каждую локаль на сборке: `bakedLocale('en')` — это
// самодостаточная карта (английский поверх русского), и клиенту достаточно ОДНОГО
// файла. Здесь же живёт `LOCALE_SOURCES` — сырые локали для потребителей, которым
// нужны все языки сразу (прототип собирается в один HTML, тесты).
import { ru } from './ru';
import { en } from './en';
import { DEFAULT_LOCALE } from './index';
import type { LocaleId, Messages } from './index';

/** Сырые тексты локалей, как они лежат в файлах: без фолбэка, ключа может не быть. */
export const LOCALE_SOURCES: Record<LocaleId, Messages> = { ru, en };

/** Локаль поверх фолбэка. Результат самодостаточен: промаха, за которым пришлось бы
 *  идти в другой язык, в нём нет. */
export const bakeMessages = (locale: Messages, fallback: Messages): Messages => ({
  ...fallback,
  ...locale,
});

/** Готовая к отдаче игроку карта одного языка (используется сборкой клиента). */
export const bakedLocale = (id: LocaleId): Messages =>
  bakeMessages(LOCALE_SOURCES[id], LOCALE_SOURCES[DEFAULT_LOCALE]);
