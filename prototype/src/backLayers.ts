// BACK-1: реестр слоёв Android-Back / Escape.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Раньше лестница «что закрыть первым» была цепочкой из полутора
// десятков `if` внутри main.ts, и у неё не было ни теста, ни описи. Итог предсказуемый:
// экран заводили, а в реестр не вписывали — и Back закрывал слой ПОД видимым окном.
// Игрок при этом терял невидимую ему работу (снятое выделение, выброшенный черновик
// приказа), а вторым нажатием выходил из матча, потому что подсказка «нажмите ещё раз»
// рисуется НИЖЕ модалки и её физически не видно. Этот баг чинили поштучно (ST-4 —
// окно «Хранителя»), и он возвращался: опись нашла 37 оверлеев, из них вне реестра 29.
//
// ЧТО ЗДЕСЬ. Лестница — данные (`BackLayer[]`), а не код: порядок виден списком, каждый
// слой умеет ответить «я открыт?» и «закройся». Тест держит и порядок, и ПОЛНОТУ описи
// (`LAYER_INVENTORY`): новый оверлей в CSS обязан объявить себя слоем или не-слоем с
// причиной, иначе гейт краснеет. Это тот же приём, что сторож тумана в ядре (SEC-16):
// дешевле заставить автора выбрать, чем ловить пропуск глазами на ревью.

/** Один слой: как узнать, что открыт, и как закрыть. Порядок в массиве = визуальная
 *  стопка сверху вниз, поэтому закрывается ровно то, что игрок видит верхним. */
export interface BackLayer {
  /** id узла (или короткое имя для слоёв без своего узла — режимы прицела). */
  id: string;
  isOpen(): boolean;
  close(): void;
}

/** Есть ли что закрывать (проба без побочных эффектов). */
export function topLayerOpen(layers: readonly BackLayer[]): boolean {
  return layers.some((l) => l.isOpen());
}

/**
 * Закрыть ВЕРХНИЙ открытый слой. Возвращает его id — или null, если закрывать нечего.
 *
 * Возвращается именно id, а не `true`: вызывающему это даёт диагностику, а тесту —
 * возможность проверить ПОРЯДОК, а не только факт закрытия.
 */
export function closeTopLayer(layers: readonly BackLayer[]): string | null {
  for (const l of layers) {
    if (!l.isOpen()) continue;
    l.close();
    return l.id;
  }
  return null;
}

/**
 * Вердикт описи. `'layer'` — слой, который Back обязан закрывать (и который обязан быть
 * в лестнице). Всё остальное — явная причина, почему элемент слоем НЕ является.
 */
export type LayerVerdict =
  | 'layer'
  /** Не слой поверх чего-то, а сам режим приложения: у Back для него своя ветка. */
  | 'экран'
  /** Не принимает ввод и не перекрывает работу: тост, баннер, подсказка под курсором. */
  | 'декорация'
  /** Фича снесена, открыть элемент нельзя (проверено по коду). */
  | 'мёртвый код'
  /** Закрывать по Back нельзя по смыслу — например, возврат в доигранный матч. */
  | 'терминальный'
  /** Живёт внутри уже зарегистрированного слоя и закрывается вместе с ним. */
  | 'часть другого слоя';

