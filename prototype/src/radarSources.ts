/**
 * Источники радарного покрытия: чьи круги рисовать и какого размера (REFM-63).
 *
 * На карте видна сводная граница обзора — объединение кругов всех своих радаров. В её
 * сборке четыре места, где легко ошибиться незаметно.
 *
 * 1. **Только СВОИ источники.** Чужой радар — не наш обзор, и нарисовать его значило бы
 *    выдать игроку и факт наличия радара у соседа, и его точный радиус. Это ровно та
 *    утечка, ради которой существует туман.
 * 2. **Нулевой радиус — не источник.** Мир или корабль без радара не даёт кольца:
 *    точка нулевого радиуса нарисовалась бы засечкой там, где обзора нет вовсе.
 * 3. **Кольцо флота стоит в его ФАКТИЧЕСКОМ месте.** У летящего флота позиция
 *    интерполируется; поставь кольцо в узел назначения — и покрытие «прыгнет» вперёд
 *    флота, показав обзор там, куда он ещё не долетел. Нет позиции — нет и кольца.
 * 4. **Внутренний круг — ДОЛЯ внешнего, а не своё число.** Внешний радиус — дальность
 *    засечки, внутренний — дальность опознания, и они связаны физически. Разъедутся —
 *    карта покажет опознание дальше засечки, чего не бывает.
 */

/** Кандидат в источники: то, что о нём нужно знать до отбора. */
export interface RadarCandidate {
  /** Наш ли это мир/флот (правило 1). */
  mine: boolean;
  /** Радиус засечки в мировых единицах; `0` — радара нет (правило 2). */
  radius: number;
  /** Где стоит источник; `null` — позиция неизвестна (правило 3). */
  at: { x: number; y: number } | null;
  /** Выбран ли игроком — у выбранного рисуются ещё и собственные кольца. */
  selected: boolean;
}

/** Источник, годный к отрисовке. */
export interface RadarSource {
  x: number;
  y: number;
  r: number;
  selected: boolean;
}

/** Отобрать источники: свои, с положительным радиусом и известной позицией. */
export function radarSources(candidates: readonly RadarCandidate[]): RadarSource[] {
  const out: RadarSource[] = [];
  for (const c of candidates) {
    if (!c.mine || !(c.radius > 0) || !c.at) continue; // правила 1–3
    out.push({ x: c.at.x, y: c.at.y, r: c.radius, selected: c.selected });
  }
  return out;
}

/**
 * Радиус полного опознания: доля от радиуса засечки (правило 4). Доля приходит из
 * ядра — второй копии этого числа в клиенте быть не должно.
 */
export function identifyRadius(outerRadius: number, fraction: number): number {
  return outerRadius * fraction;
}

/** Есть ли что рисовать — пустой список кругов не стоит и заходить в отрисовку. */
export function hasCoverage(sources: readonly RadarSource[]): boolean {
  return sources.length > 0;
}
