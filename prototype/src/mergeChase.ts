/**
 * Догоняющее слияние флотов: что делать с приказом в этом кадре (REFM-107).
 *
 * «Слить» отдаётся когда угодно, а исполняется, только когда оба флота стоят рядом,
 * поэтому приказ живёт в клиентской очереди и каждый кадр решает свою судьбу заново.
 * Решение стояло цепочкой `return` внутри `filter`, и из неё не читалось главное:
 * почему бой приказ ПРИОСТАНАВЛИВАЕТ, а отказ на догоняющем ходу — ОТМЕНЯЕТ.
 *
 * 1. **Пропавший флот снимает приказ.** Один из двух уже слит или погиб — сливать
 *    нечего и не с чем.
 * 2. **Бой ПРИОСТАНАВЛИВАЕТ, а не отменяет:** после боя уцелевшие, скорее всего, всё
 *    ещё рядом, и отменённый приказ игроку пришлось бы отдавать заново.
 * 3. **Сливаются только те, кто СТОИТ в одном узле.** На ходу сливать нечего: у флота
 *    в транзите нет места стоянки, куда влить второго.
 * 4. **Иначе догоняющий идёт к цели** — к её узлу, а если она сама в пути, то к узлу
 *    её назначения: гнаться за движущейся точкой бессмысленно.
 * 5. **Отвергнутый догоняющий ход ВЫБРАСЫВАЕТ приказ** (consume-on-reject). Нет права
 *    прохода — и стоящий флот пережимал бы этот ход каждый кадр, заливая экран
 *    отказами; один отказ равен одному приказу.
 * 6. **Уже идущий догоняющий второго хода не получает** — он и так летит.
 */

/** Флот глазами очереди слияния. */
export interface MergeFleet {
  location?: string | null;
  movement?: { to: string } | null;
  battleId?: unknown;
}

/** Что делать с приказом слияния в этом кадре. */
export type MergeStep =
  /** Снять приказ: флота нет либо догоняющий ход отвергнут. */
  | { do: 'drop' }
  /** Ждать: идёт бой, или догоняющий уже в пути. */
  | { do: 'hold' }
  /** Сливать: оба стоят в одном узле. */
  | { do: 'fuse' }
  /** Догонять: вести `mover` к этому узлу. */
  | { do: 'chase'; to: string };

/** Судьба приказа слияния в этом кадре (правила 1–4, 6). */
export function mergeStep(mover: MergeFleet | undefined, into: MergeFleet | undefined): MergeStep {
  if (!mover || !into) return { do: 'drop' }; // правило 1
  if (mover.battleId || into.battleId) return { do: 'hold' }; // правило 2
  const together =
    !!mover.location &&
    !!into.location &&
    mover.location === into.location &&
    !mover.movement &&
    !into.movement;
  if (together) return { do: 'fuse' }; // правило 3
  const dest = into.location ?? into.movement?.to ?? null; // правило 4
  if (!mover.movement && dest && mover.location !== dest) return { do: 'chase', to: dest };
  return { do: 'hold' }; // правило 6: догоняющий уже в пути (или цели некуда вести)
}
