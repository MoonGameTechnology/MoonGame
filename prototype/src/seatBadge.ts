/**
 * REFM-202 — КАК ПОДПИСАНО МЕСТО В СПИСКЕ (и починка того, что подпись не переводилась).
 *
 * ВНИМАНИЕ: этот кирпич МЕНЯЕТ ВИДИМОЕ ИГРОКУ — сознательно, потому что чинит нарушение
 * собственного правила проекта. Раньше `seatBadge()` возвращала в поле `tag` КЛЮЧ
 * (`'comms.you'`), а три места печатали его НАПРЯМУЮ, минуя `t()`: карточка игрока, ростер
 * дипломатии и композер пинга. Игрок видел буквально «comms.you» и «diplo.filter.ai» вместо
 * «ВЫ» и «ИИ». Ключи в обеих локалях есть и верны — не переводилось только потому, что
 * ключ никто не разворачивал.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, а не правка трёх строк. Правка трёх мест чинит СЛУЧАЙ; отдавать
 * из функции уже готовый ТЕКСТ чинит КЛАСС: ключу просто неоткуда доехать до разметки, и
 * четвёртый вызывающий не сможет повторить ту же ошибку. Ошибалась она максимально тихо —
 * ничего не падало и не логировалось, строка просто была не тем, чем выглядела.
 *
 * ПРАВИЛА И ПРИЧИНЫ:
 *
 * 1. Значок и подпись — ОДНО решение и живут вместе. Разъехавшись, они дадут «☻ ИИ»:
 *    человеческое лицо с машинной подписью, и игрок не поймёт, с кем говорит.
 *
 * 2. «Это я» важнее всех прочих признаков. Своё место опознаётся как СВОЁ раньше, чем как
 *    человек или машина: иначе игрок искал бы себя среди чужих.
 *
 * 3. Подпись возвращается УЖЕ ЛОКАЛИЗОВАННОЙ, а не ключом — см. шапку. Это то самое
 *    место, где класс ошибки закрывается: наружу выходит текст, ключ не выходит вовсе.
 *
 * 4. Значок у меня и у другого человека ОДИН И ТОТ ЖЕ. Разделяет их подпись, а не
 *    пиктограмма: человек остаётся человеком, кем бы он ни приходился мне.
 */

import { t } from '../../localization/runtime';

/** Кто занимает место: я, машина или другой человек. */
export type SeatKind = 'me' | 'ai' | 'player';

/** Правило 2: своё место опознаётся первым. */
export function seatKind(isMe: boolean, isAi: boolean): SeatKind {
  if (isMe) return 'me';
  return isAi ? 'ai' : 'player';
}

/** Правило 4: своё и чужое человеческое место носят один значок. */
const ICON: Record<SeatKind, string> = { me: '☻', ai: '⌬', player: '☻' };

/** Ключи подписей. Наружу не выходят — их разворачивает `seatBadgeOf` (правило 3). */
const TAG_KEY: Record<SeatKind, string> = {
  me: 'comms.you',
  ai: 'diplo.filter.ai',
  player: 'comms.tag.player',
};

/** Значок и ГОТОВАЯ подпись места (правила 1, 3, 4). */
export function seatBadgeOf(kind: SeatKind): { icon: string; tag: string } {
  return { icon: ICON[kind], tag: t(TAG_KEY[kind]) };
}
