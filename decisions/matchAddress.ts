/**
 * Адрес партии против приглашения в неё (ADDR-2) и форма самого адреса (ADDR-3).
 *
 * Ссылка входа описывала ДЕЙСТВИЕ: `?join=…&slot=p2&faction=azure` читается как «займи
 * место p2 за такой-то дом». Адресом партии она работала почти случайно — сервер
 * игнорирует выбор, когда место уже за тобой (`joinSeat.ts`, правило 2), — а вот
 * приглашением была вредна: отдал ссылку другу, и он просит ТВОЁ место и ТВОЙ дом.
 * Место ему сервер не отдаст (резолвер откатится на свободное), а дом — отдаст: для него
 * это НОВЫЙ захват, и выбор применяется. Человек сядет играть за чужую фракцию, не поняв,
 * почему.
 *
 * Развести их — это два разных ответа на два разных вопроса:
 *
 * 1. **Адрес партии несёт ТОЛЬКО идентификатор, и несёт его ПУТЁМ.** `/game/<id>` против
 *    `/?join=<id>`: технический хвост читается как временный — его хочется обрезать, и
 *    обрезанный он ведёт не туда, — а путь копируется целиком и выглядит тем, чем является:
 *    постоянным адресом, который живёт дольше одной партии. Идентификатор экранируется,
 *    потому что приходит от сервера, а не из кода.
 * 2. **Старая форма остаётся читаемой.** `?join=<id>` уже роздан игрокам и лежит в
 *    закладках; понимать только новую форму значило бы запереть человека снаружи его
 *    собственной партии. Поэтому путь — то, что мы ПИШЕМ, а хвост — то, что мы всё ещё
 *    ЧИТАЕМ. Обе формы отдаёт один и тот же сервер (`wsServer.ts` — `/game/:matchId`).
 * 3. **Параметры захвата вычищаются из строки ПОСЛЕ входа.** Не раньше: пока вход не
 *    удался, они ещё нужны — например, игрок уходит логиниться и возвращается доигрывать
 *    заход. Тот же приём и та же причина, что у `?reset=<token>` (он не должен осесть в
 *    истории и referer'е), только здесь речь не о безопасности, а о том, что игрок
 *    копирует из адресной строки.
 * 4. **Правка адреса — всегда `replaceState`, никогда `pushState`.** В APK аппаратный
 *    Back завязан на `history.back()` (`main.ts`), и лишняя запись в истории ломает выход
 *    из партии: первый Back возвращал бы игрока в ту же партию вместо выхода.
 * 5. **Чистка хирургическая.** Убираем ровно `slot`/`faction`/`sci` (и обесмысленный
 *    `join` — id уже в пути), остальное не трогаем: адрес может нести чужие параметры
 *    (язык, будущие флаги), и переписать его целиком значило бы молча их потерять. Мусор
 *    вместо адреса возвращается как есть — вход не должен падать из-за строки, которую мы
 *    не поняли.
 * 6. **Клиент не всегда смонтирован в корне.** Дев-сборка живёт на `/dev`, и адрес партии
 *    обязан остаться внутри неё: увести дев-клиент на `/game/<id>` значит подменить его
 *    игроцкой сборкой — без дев-оверлея, которым он и отличается.
 * 7. **Отданный адрес строится на адресе СЕРВЕРА, а не страницы.** В APK страница
 *    приходит с локального сервера Capacitor, а игровой сервер игрок задаёт сам — адрес,
 *    собранный из `location.origin`, привёл бы получателя в его собственный телефон.
 *    Отдаётся всегда корневая форма: получатель — посторонний, и уводить его в чужую
 *    сборку (тот же `/dev`) незачем.
 * 8. **Тому, кто уже сидит в партии, ссылка — просто адрес.** Даже если параметры в ней
 *    есть, намерения захвата у возврата нет: своё место у игрока уже занято, а стухшая
 *    закладка иначе просила бы место, давно отданное другому. Сервер это и так знает
 *    (правило 2 `joinSeat.ts`), но клиент не должен и слать — иначе адрес врёт о том, что
 *    произойдёт при переходе по нему.
 */

/** Параметры, которые описывают ЗАХВАТ, а не партию (правило 5). */
const CLAIM_PARAMS = ['slot', 'faction', 'sci'] as const;

/** Сегмент пути, с которого начинается адрес партии (правило 1). */
const MATCH_SEGMENT = 'game';

/** Хвост пути, которым партия себя называет: `/game/<id>` (правила 1, 6). */
const MATCH_PATH = new RegExp(`/${MATCH_SEGMENT}/([^/]*)/?$`);

/** Куда смонтирован клиент — тот же префикс, каким бы адресом партии его ни открыли
 *  (правило 6). Пустая строка = корень. */
export function appRoot(pathname: string): string {
  const mounted = pathname.replace(/\/index\.html$/, '').replace(MATCH_PATH, '');
  return mounted === '/' ? '' : mounted;
}

/** Постоянный адрес партии (правила 1, 6). */
export function matchAddress(pathname: string, matchId: string): string {
  return `${appRoot(pathname)}/${MATCH_SEGMENT}/${encodeURIComponent(matchId)}`;
}

/** Какую партию просит адрес: путь, а при его отсутствии — старый хвост (правила 1–2).
 *
 *  Пустая строка = адрес ни на какую партию не указывает. Битое экранирование не роняет
 *  загрузку: id уезжает на сервер как есть и получает там штатный отказ. */
export function matchIdFrom(pathname: string, params: URLSearchParams): string {
  const onPath = MATCH_PATH.exec(pathname);
  if (onPath) {
    const raw = onPath[1] ?? '';
    try {
      return decodeURIComponent(raw).trim();
    } catch {
      return raw.trim();
    }
  }
  return (params.get('join') ?? '').trim();
}

/** Что остаётся в адресной строке после входа (правила 1, 3, 5).
 *
 *  Строку, которую не удалось разобрать, отдаёт нетронутой: чистка адреса — удобство, а
 *  не условие входа. */
export function settledAddress(href: string, matchId: string): string {
  let url: URL;
  try {
    url = new URL(href);
  } catch {
    return href;
  }
  url.pathname = matchAddress(url.pathname, matchId);
  for (const p of CLAIM_PARAMS) url.searchParams.delete(p);
  url.searchParams.delete('join'); // id теперь в пути — хвост стал бы вторым ответом
  return url.toString();
}

/** Адрес партии, который можно ОТДАТЬ (правило 7): абсолютный и на адресе сервера.
 *
 *  `serverHttpBase` — HTTP-адрес того же сервера, куда стучится сокет (`httpBase()` в
 *  `matchQuery.ts` выводит его из адреса сокета заменой схемы). */
export function shareAddress(serverHttpBase: string, matchId: string): string {
  return `${serverHttpBase.replace(/\/+$/, '')}${matchAddress('/', matchId)}`;
}

/** Чего просит ссылка сверх самого адреса. */
export interface ClaimIntent {
  slot?: string;
  faction?: string;
  scientists?: string[];
}

/** Приглашение это или просто адрес (правила 1, 8).
 *
 *  `seated` — держит ли игрок место в ЭТОЙ партии; у сидящего намерения захвата нет,
 *  сколько бы параметров ни висело в ссылке. `null` = заходим по адресу, ничего не прося. */
export function claimIntent(params: URLSearchParams, seated: boolean): ClaimIntent | null {
  if (seated) return null; // правило 8
  const slot = (params.get('slot') ?? '').trim();
  const faction = (params.get('faction') ?? '').trim();
  const scientists = (params.get('sci') ?? '')
    .split(',')
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
  if (!slot && !faction && scientists.length === 0) return null;
  return {
    ...(slot ? { slot } : {}),
    ...(faction ? { faction } : {}),
    ...(scientists.length ? { scientists } : {}),
  };
}
