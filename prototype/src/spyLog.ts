/**
 * Шпионаж: кому адресовано событие и что оно говорит (REFM-177).
 *
 * Окна краденой разведки и сам журнал — `intel.ts` (REFM-28); здесь то, что до сих пор
 * стояло в кадре: КОМУ адресовано каждое из трёх событий, какими словами оно звучит и
 * когда перерисовывается ростер.
 *
 * 1. **Два события адресованы ИСПОЛНИТЕЛЮ, третье — ЖЕРТВЕ.** Успех и провал читает тот,
 *    кто послал агента; замеченную операцию — тот, у кого крали. В сети серверный фильтр
 *    тумана уже прячет их от второй стороны, и клиент обязан повторять тот же отбор:
 *    иначе одиночная игра покажет больше сетевой.
 * 2. **Успех называет ДОБЫЧУ.** Разведка (SPY-8) добывает мир, и подставляется САМ МИР (а
 *    не его владелец), потому что «добыты сведения о мире» без имени мира не сведения, а
 *    намёк.
 * 3. **Каждое событие идёт в ДВА места: ленту и журнал шпионажа.** Лента коротка и
 *    переполняется боем, а вкладка «Шпионаж» — история операций; в журнале строка КОРОЧЕ,
 *    потому что там вокруг уже стоит контекст.
 * 4. **Пойманный шпион называется по имени, незамеченная утечка — нет.** Это разные исходы
 *    контрразведки: поймали — жертва знает, кто лез; не поймали — знает только, что утекло.
 *    Назвать имя там, где вора не установили, значит выдать разведданные даром.
 * 5. **Ростер перерисовывается по РАЗНЫМ поводам и в разные моменты.** У кражи — ПОСЛЕ
 *    проверки адресата, потому что причина в появившейся строке разведки, а она только
 *    твоя. У обнаружения — ДО проверки: пойманный шпион двигает счётчик расположения бота,
 *    и это происходит независимо от того, жертва ты или сторонний наблюдатель.
 */

/** Событие шпионажа. */
export type SpyEvent = 'stolen' | 'failed' | 'detected';

/** Кому адресовано событие (правило 1). */
export function spyAddressee(kind: SpyEvent): 'actor' | 'victim' {
  return kind === 'detected' ? 'victim' : 'actor';
}

/** Когда перерисовывать ростер (правило 5). */
export function spyRepaint(kind: SpyEvent): 'before' | 'after' | 'never' {
  if (kind === 'detected') return 'before';
  if (kind === 'stolen') return 'after';
  return 'never';
}


/** Поймали вора или только заметили утечку (правило 4); убит ли раскрытый агент (SPY-7). */
export function counterLine(
  spy: string | undefined | null,
  killed = false,
): {
  key: 'log.spy.caught' | 'log.spy.leak' | 'log.spy.caught.killed' | 'log.spy.leak.killed';
  /** Называется ли имя вора. */
  named: boolean;
} {
  if (spy) return { key: killed ? 'log.spy.caught.killed' : 'log.spy.caught', named: true };
  return { key: killed ? 'log.spy.leak.killed' : 'log.spy.leak', named: false };
}
