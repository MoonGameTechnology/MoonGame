/**
 * Ряд значков построек под узлом: что стоит в системе, одной строкой плиток (REFM-122).
 *
 * Под каждым опознанным миром лежит ряд маленьких плиток — по одной на постройку. Это
 * единственное место на карте, где видно СОСТАВ системы, не открывая панель, и вся его
 * раскладка стояла в кадре голыми числами (`start = c.x - ((n - 1) * step) / 2`), из
 * которых не читалось ни почему ряд центрирован, ни почему у кегля есть пол.
 *
 * 1. **Ряд ЦЕНТРИРОВАН под узлом.** Он растёт с каждой новой постройкой; расти он от
 *    левого края — и мир с двумя плитками читался бы иначе, чем мир с шестью, а сам узел
 *    будто съезжал бы вбок при каждой достройке. Центр ряда обязан совпадать с центром
 *    мира, потому что ряд — это подпись К МИРУ, а не отдельный объект.
 * 2. **Весь ряд масштабируется вместе с узлом.** Шаг, размер плитки, отступ вниз и кегль
 *    идут через тот же `artScale`, что и сам маркер: иначе на дальнем зуме плитки станут
 *    крупнее мира, к которому относятся.
 * 3. **У кегля есть ПОЛ.** Масштаб тянет кегль вниз без предела, а буква мельче семи
 *    пикселей — уже не буква: глиф превращается в грязное пятно, которое читается как
 *    сор на экране. Пол держит значок узнаваемым до самой границы, где ряд и так гаснет
 *    по правилу 4.
 * 4. **Ряд — деталь, и он гаснет вместе с LOD.** На схематичном виде цвет провинции и
 *    счёт уже рассказывают главное, а строка плиток наваливается на сжавшийся маркер —
 *    это и была жалоба владельца про кашу на минимальном зуме в APK.
 * 5. **Под туманом ряда нет вовсе.** Состав построек чужой системы — разведданные, за
 *    которые платят сенсорами; нарисуй его — и туман перестанет что-либо значить.
 * 6. **Нет построек — нет ряда** (пустой мир не подписывают пустотой).
 * 7. **Незнакомый тип постройки рисуется ЗАГЛУШКОЙ, а не пропускается.** Пропуск сдвинул
 *    бы весь ряд и соврал бы о количестве построек — а количество здесь и есть главное,
 *    что игрок считывает одним взглядом.
 */

/** Базовый кегль значка (до масштаба). */
export const CHIP_FONT = 11;

/** Пол кегля: мельче — уже не буква (правило 3). */
export const CHIP_MIN_FONT = 7;

/** Шаг между центрами плиток (до масштаба). */
export const CHIP_STEP = 13;

/** Половина стороны плитки (до масштаба). */
export const CHIP_HALF = 5;

/** Насколько ряд опущен ниже края узла (до масштаба). */
export const CHIP_DROP = 19;

/** Заглушка для незнакомого типа постройки (правило 7). */
export const CHIP_FALLBACK = '▪';

/** Рисовать ли ряд (правила 4–6). */
export function chipsShown(identified: boolean, count: number, detail: number): boolean {
  return identified && count > 0 && detail > 0;
}

/** Кегль значка при масштабе узла — с полом (правила 2–3). */
export function chipFontPx(scale: number): number {
  return Math.max(CHIP_MIN_FONT, Math.round(CHIP_FONT * scale));
}

/** Размеры ряда при масштабе узла (правило 2). */
export interface ChipMetrics {
  /** Шаг между центрами соседних плиток. */
  step: number;
  /** Половина стороны плитки. */
  half: number;
}

export function chipMetrics(scale: number): ChipMetrics {
  return { step: CHIP_STEP * scale, half: CHIP_HALF * scale };
}

/** Центры плиток по горизонтали: ряд центрирован под узлом (правила 1–2). */
export function chipXs(count: number, centerX: number, scale: number): number[] {
  const { step } = chipMetrics(scale);
  const start = centerX - ((count - 1) * step) / 2;
  const out: number[] = [];
  for (let i = 0; i < count; i++) out.push(start + i * step);
  return out;
}

/** Высота ряда: под нижним краем узла (правило 2). */
export function chipY(nodeY: number, nodeRadius: number, scale: number): number {
  return nodeY + nodeRadius + CHIP_DROP * scale;
}

/** Значок типа постройки; незнакомый тип — заглушка (правило 7). */
export function chipGlyph(icon: string | undefined): string {
  return icon ?? CHIP_FALLBACK;
}
