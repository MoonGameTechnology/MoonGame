/**
 * Что показать вместо списка матчей, когда списка нет (REFM-151).
 *
 * Десятый срез сетевой секции. Браузер матчей — первый экран сетевой игры, и чаще всего
 * игрок видит его в худшем состоянии: сервер не отвечает, список пуст, адрес не тот.
 * Решение «что вместо списка» стояло тремя вложенными тернарниками внутри `renderMatches`.
 *
 * С 2026-10-16 у обеих сборок одна страница (UIX-17.1, заказ владельца: «вырезать
 * "сервер" и "позывной"»): позывной приходит со входа, адрес — со страницы, список
 * обновляется сам, кнопки «Обновить список» нет. Раньше dev-клиент показывал поля и
 * кнопку всегда, и тексты причин у сборок были разные.
 *
 * 1. **Никогда не тупик.** Сервер не ответил или открытых матчей нет — предлагается путь,
 *    который работает ВСЕГДА: одиночная игра без сервера. Экран, который только сообщает
 *    о беде и не даёт, что делать дальше, для новичка равен закрытой игре. Пустые «Мои»
 *    зовут на «Доступные»: свой матч начинают там. Пустому архиву звать некуда, вкладки
 *    стоят прямо над ним.
 * 2. **Пока список грузится, путей не предлагают.** Это секунда, а не беда: кнопка
 *    одиночной игры, мигнувшая перед списком, читается как «сервера нет».
 * 3. **«Сервер не ответил» и «мы ещё не спрашивали» — разные сообщения.** Первое зовёт
 *    проверить адрес, второе — подождать; одинаковый текст на оба случая заставил бы
 *    игрока чинить работающую связь.
 * 4. **Адрес сервера виден ровно тогда, когда сервер не ответил.** Адрес берётся со
 *    страницы, и у игры с сайта он верный. Нужен он APK (у страницы нет полезного адреса)
 *    и тому, чей сохранённый адрес умер: поле стоит в карточке «Сервер не отвечает» и
 *    уходит, как только список загрузился.
 * 5. **Одно сообщение об одной беде.** Карточка «Сервер не отвечает» уже говорит о беде —
 *    строку статуса с тем же «сервер недоступен» гасят: два одинаковых сообщения на экране
 *    читаются как две разные беды. Над старым списком карточки нет, и строка остаётся.
 * 6. **«Ничего не найдено» — это НЕ «сервер пуст», и это НЕ тупик** (BRW-3). Список пуст,
 *    потому что игрок сузил его фильтром: путь у него под рукой — сбросить фильтр, кнопка
 *    рядом с сообщением. Одиночная игра отвечала бы на вопрос, которого он не задавал.
 *    Беда связи важнее: сервер, который не ответил, называется бедой связи даже если
 *    фильтр в это время что-то скрывал бы — иначе игрок крутил бы фильтры вместо адреса.
 */

/** Вкладки страницы матчей. */
export type BrowserTab = 'available' | 'active' | 'archived';

/** Куда зовёт пустое место (правило 1). */
export type NextStep =
  /** Одиночная игра без сервера. */
  | 'solo'
  /** На вкладку «Доступные». */
  | 'available';

/** Что рисуем вместо списка. */
export type Fallback =
  /** Список есть — рисуем его. */
  | { kind: 'list' }
  /** Списка нет: сообщение и, если есть, путь дальше (правила 1–3). */
  | { kind: 'empty'; message: FallbackMessage; next: NextStep | null }
  /** Список есть, но фильтр скрыл всё: сообщение и сброс фильтра (правило 6). */
  | { kind: 'filtered'; message: 'browser.filter.none' };

/** Ключ сообщения — почему списка нет. */
export type FallbackMessage =
  /** Сервер не ответил. */
  | 'browser.server-down'
  /** Список ещё не пришёл. */
  | 'browser.loading'
  /** Ответ пришёл, а на вкладке пусто — у каждой вкладки своя причина. */
  | 'browser.empty.available'
  | 'browser.empty.active'
  | 'browser.empty.archived';

export interface BrowserState {
  /** Список получен (пусть даже пустой). */
  loaded: boolean;
  /** Прошлый запрос кончился неудачей. */
  failed: boolean;
  /** Открытая вкладка. */
  tab: BrowserTab;
  /** В открытой вкладке есть строки. */
  rows: number;
  /** Сколько строк этой вкладки скрыл фильтр (BRW-3). Нет поля ⇒ фильтра нет —
   *  вкладки «Мои» и «Архив» он не трогает, да и панель там не показывается. */
  hiddenByFilter?: number;
}

/** Пустая вкладка при пришедшем списке: у каждой своё сообщение и свой путь (правило 1). */
const EMPTY: Readonly<Record<BrowserTab, Fallback>> = {
  available: { kind: 'empty', message: 'browser.empty.available', next: 'solo' },
  active: { kind: 'empty', message: 'browser.empty.active', next: 'available' },
  archived: { kind: 'empty', message: 'browser.empty.archived', next: null },
};

/** Что показать вместо списка (правила 1–3, 6). */
export function fallbackFor(st: BrowserState): Fallback {
  if (!st.loaded) {
    return st.failed
      ? { kind: 'empty', message: 'browser.server-down', next: 'solo' }
      : { kind: 'empty', message: 'browser.loading', next: null };
  }
  if (st.rows === 0) {
    // Правило 6: список ПРИШЁЛ и он не пуст — пусто на экране из-за фильтра.
    if (st.hiddenByFilter) return { kind: 'filtered', message: 'browser.filter.none' };
    return EMPTY[st.tab];
  }
  return { kind: 'list' };
}

/**
 * Показывать ли карточку «Сервер не отвечает» с адресом (правило 4). Та же граница гасит
 * строку статуса (правило 5): карточка и есть сообщение о беде.
 */
export function showServerRow(st: Pick<BrowserState, 'loaded' | 'failed'>): boolean {
  return st.failed && !st.loaded;
}
