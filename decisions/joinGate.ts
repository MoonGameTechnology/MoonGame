/**
 * Что сделать с просьбой вступить в матч, пока игрок не вошёл (REFM-140).
 *
 * По ссылке на матч (или кнопкой в браузере матчей) игрок просит его впустить, а сервер с
 * аккаунтами сначала требует вход. Развилка «пустить / послать на карточку входа» стояла в
 * `connectToMatch` тремя почти одинаковыми ветками, и в каждой заново повторялось одно и то
 * же: запомнить просьбу, спрятать хаб, показать карточку.
 *
 * 1. **Просьбу вступить НЕ ТЕРЯЮТ.** Отправляя игрока на вход, её запоминают и доигрывают
 *    сразу после успешного входа. Иначе тот, кто пришёл по ссылке на конкретный матч,
 *    после ввода пароля окажется в хабе и будет искать этот матч заново — а он мог быть и
 *    приватным, найти его там нечем.
 * 2. **Пароль спрашивают, только когда известен СЕРВЕР.** Не знаем адрес — спрашивать
 *    пароль не у кого: сперва выбор сервера и позывного, строка пароля только мешала бы.
 * 3. **Сессия проверяется НАЛИЧИЕМ, а не совпадением позывного.** Историческая ошибка:
 *    поле ввода бывает пустым или устаревшим сразу после входа, и проверка «ник совпадает
 *    с сессией» молча уводила на карточку входа при живом токене. Токен и так выписан на
 *    аккаунт; если он мёртв — это выяснится отказом сервера, а не догадкой клиента.
 * 4. **Отказ в токене — ДВА РАЗНЫХ случая.** Сессия пропала (сервер её отверг) — значит
 *    вход просрочен, зовём войти заново. Сессия на месте — значит закрыт или полон САМ
 *    матч, и карточка входа тут ни при чём: игрок решил бы, что дело в пароле, и пошёл бы
 *    менять его вместо того, чтобы выбрать другой матч.
 */

/** Что клиент знает к моменту просьбы. */
export interface JoinState {
  /** Сервер требует аккаунт (подтверждено пробой). */
  accountsMode: boolean;
  /** Адрес сервера выбран. */
  serverKnown: boolean;
  /** Для этого сервера есть сохранённая сессия. */
  hasSession: boolean;
}

/** Следующий шаг: подключаться, идти за токеном или звать на вход. */
export type JoinStep =
  { step: 'connect' } | { step: 'token' } | { step: 'sign-in'; password: boolean };

/** Развилка «пустить или на вход» (правила 1–3). */
export function joinStep(st: JoinState): JoinStep {
  if (!st.accountsMode) return { step: 'connect' }; // сервер без аккаунтов — идём как есть
  if (!st.serverKnown) return { step: 'sign-in', password: false };
  if (!st.hasSession) return { step: 'sign-in', password: true };
  return { step: 'token' };
}

/**
 * Токен на вступление не выдан: звать ли на вход (правило 4). `sessionAlive` — уцелела ли
 * сохранённая сессия ПОСЛЕ отказа: сервер стирает её, когда признал просроченной.
 */
export function afterTokenRefused(sessionAlive: boolean): 'sign-in' | 'stay' {
  return sessionAlive ? 'stay' : 'sign-in';
}
