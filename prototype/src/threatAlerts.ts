/**
 * Тревога «враг у ваших рубежей»: когда она звенит и что говорит (REFM-169).
 *
 * Засечку делает ядро (`scanNodeThreats` — тот же честный по туману сторож, на который
 * опирается Стюард), учёт эпизодов — `alerts.ts` (REFM-96). Здесь то, что до сих пор
 * стояло прямо в кадре: РЕЖИМ звонка. Правила ниже — не защита от невозможного: каждое
 * чинит конкретную поломку, которая уже была или была бы неизбежна.
 *
 * 1. **Не чаще раза в игровой ЧАС.** Соло двигает `s.time` каждый кадр, поэтому сторож
 *    «время изменилось» пустой: полный обход тумана по всем своим мирам шёл бы на каждом
 *    кадре. Угрозы идут часами, часовой шаг не теряет ничего.
 * 2. **Выбывшему не звонят.** Игрок со статусом не `active` уже вне матча: тревога о
 *    мирах, которые ему больше не принадлежат, — чистый шум поверх экрана поражения.
 * 3. **Один звонок на ЭПИЗОД «мир + флот».** Флот, стоящий у границы, иначе звенел бы
 *    каждый час, и игрок перестал бы читать тревоги вообще — включая ту единственную,
 *    которая важна.
 * 4. **Кончившийся эпизод забывается.** Тот же флот, подошедший СНОВА, обязан прозвенеть:
 *    без забывания однажды объявленный сосед становится невидимым до конца матча.
 * 5. **Срок обещается, только пока он не истёк.** «Идёт, прибытие через …» — лишь у
 *    подхода (`inbound`) с прибытием в БУДУЩЕМ; всё остальное (уже на месте, стоит рядом,
 *    расчётный срок прошёл) говорит «враг здесь». Обещанный срок, который уже позади,
 *    хуже, чем отсутствие срока: игрок считает, что время ещё есть.
 * 6. **Порядок тревог — порядок засечек.** Игрок читает ленту сверху вниз и по ней судит,
 *    что случилось раньше. Чистка памяти идёт после и игроку не видна.
 */
import { episodeKey, forgetEnded, freshEpisodes } from './alerts';

/** Засечка ядра, сведённая к тому, что нужно для звонка. */
export interface ThreatSighting {
  /** Мой мир, к которому она относится. */
  node: string;
  /** Чужой флот — вторая половина ключа эпизода (правило 3). */
  fleetId: string;
  /** Как флот относится к миру: идёт, уже на месте, стоит рядом. */
  kind: 'present' | 'inbound' | 'nearby';
  /** Игровое время прибытия; у «на месте»/«рядом» — уже наступившее. */
  eta: number;
}

/** Готовая тревога: ключ текста, мир и срок (правило 5). */
export interface ThreatAlert {
  key: 'threat.incoming' | 'threat.here';
  node: string;
  /** Сколько осталось лететь; `null` — срока нет, текст без него. */
  left: number | null;
}

/** Пора ли обходить миры в этом кадре (правило 1). */
export function threatScanDue(bucket: number, lastBucket: number): boolean {
  return bucket !== lastBucket;
}

/** Слушает ли этот игрок тревоги (правило 2). */
export function threatsHeard(status: string | undefined): boolean {
  return status === 'active';
}

/** Что сказать про одну засечку (правило 5). */
export function threatWording(s: ThreatSighting, now: number): ThreatAlert {
  return s.kind === 'inbound' && s.eta > now
    ? { key: 'threat.incoming', node: s.node, left: s.eta - now }
    : { key: 'threat.here', node: s.node, left: null };
}

/**
 * Тревоги этого прохода — и учёт эпизодов заодно (правила 3, 4, 6).
 *
 * `memory` меняется на месте: объявленные эпизоды запоминаются, кончившиеся забываются.
 */
export function threatAlerts(
  sightings: readonly ThreatSighting[],
  now: number,
  memory: Set<string>,
): ThreatAlert[] {
  const live = new Set<string>();
  const out: ThreatAlert[] = [];
  for (const s of sightings) {
    const key = episodeKey(s.node, s.fleetId);
    live.add(key);
    if (freshEpisodes(memory, [key]).length === 0) continue; // эпизод уже объявлен
    out.push(threatWording(s, now));
  }
  forgetEnded(memory, live);
  return out;
}
