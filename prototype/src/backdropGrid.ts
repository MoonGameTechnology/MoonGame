/**
 * Координатная сетка фона: шаг, смещение под камерой и где лечь линиям (REFM-110).
 *
 * Сетка — не украшение, а ПРИБОР: по ней игрок читает расстояния и понимает, что карта
 * поехала под пальцем. Поэтому её геометрия завязана и на масштаб, и на камеру, и обе
 * связи легко испортить незаметно — картинка останется «какой-то сеткой».
 *
 * 1. **Шаг растёт с масштабом, но не мельче порога.** Базовый шаг, помноженный на
 *    масштаб, при сильном отдалении схлопнулся бы в несколько пикселей — линии слились
 *    бы в серую кашу, и прибор превратился бы в шум. Порог держит их различимыми.
 * 2. **Смещение — камера по модулю шага, приведённая к НЕОТРИЦАТЕЛЬНОЙ.** Сетка обязана
 *    ехать вместе с картой, а не стоять в экране. Двойной модуль здесь не украшение:
 *    `%` в JS сохраняет знак делимого, поэтому при камере левее нуля остаток
 *    отрицателен, первая линия уезжает за край, и на переходе через ноль вся сетка
 *    прыгает на клетку — ровно там, где игрок и смотрит, панорамируя.
 * 3. **Линии кладутся ОТ смещения ДО края включительно.** Оборви цикл на строгом «<» —
 *    и у правого/нижнего края останется непрокрашенная полоса шириной почти в клетку,
 *    тем заметнее, чем крупнее масштаб.
 *
 * _Замечено при выносе, НЕ чинил._ Порог правила 1 сейчас **недостижим**: камера зажата
 * снизу `MIN_SCALE = 1` (`@void/client · camera.ts`), поэтому шаг никогда не опускается
 * ниже базового — измерено живьём, на предельном отдалении клетка ровно `GRID_BASE_PX`.
 * Порог остаётся страховкой на случай, если минимальный масштаб когда-нибудь опустят
 * ниже `GRID_MIN_PX / GRID_BASE_PX`; убрать его значило бы молча привязать сетку к
 * чужому инварианту, а это не задача кирпича про её геометрию.
 */

/** Минимальный шаг сетки в пикселях экрана — ниже линии сливаются (правило 1). */
export const GRID_MIN_PX = 28;
/** Шаг сетки при масштабе 1 (правило 1). */
export const GRID_BASE_PX = 56;

/** Шаг сетки на экране при этом масштабе камеры (правило 1). */
export function gridGap(scale: number): number {
  return Math.max(GRID_MIN_PX, GRID_BASE_PX * scale);
}

/** Смещение первой линии: камера по модулю шага, всегда в `[0, gap)` (правило 2). */
export function gridOffset(pan: number, gap: number): number {
  return ((pan % gap) + gap) % gap;
}

/** Координаты линий от смещения до края включительно (правило 3). */
export function gridLines(offset: number, extent: number, gap: number): number[] {
  const out: number[] = [];
  for (let v = offset; v <= extent; v += gap) out.push(v);
  return out;
}
