/**
 * ОСТАТОК ЗАЛПА УХОДИТ В ЖИВЫЕ ЦЕЛИ (резолюция владельца 2026-11-17).
 *
 * «Остаточный урон должен дальше идти по целым. Тем самым нивелируя приманку. Прошёл
 * выстрел: у врага 1 HP, выстрел на 10 — 9 остаются заряженными на небольшое время.»
 *
 * Залп по-прежнему делится между врагами поровну (`volley.ts`, MSB-2). Раньше доля, которой
 * не хватило цели — флот погиб раньше, чем она кончилась, — сгорала. Поэтому флот из
 * одного разведчика забирал столько же залпа, сколько основной флот, и десять приманок
 * прикрывали главные силы почти от всего первого залпа. Теперь:
 *
 * 1. **Первый проход — как раньше:** каждой цели её равная доля. Пока никто не погиб, ни
 *    одно число не меняется.
 * 2. **Что не легло — делится поровну между теми, кто ещё жив и враждебен стрелку**, и так
 *    до тех пор, пока остаток не кончится. Остаток измеряется ДОЛЕЙ ЗАЛПА, а не уроном:
 *    у каждой цели свои бонусы атакующего и своя защита (хук `combat.damage`), поэтому
 *    вызывающий заново оценивает долю против новой цели.
 * 3. **Цель, которая что-то вернула, остаток больше не получает.** Погибшая и так выбывает,
 *    а живая, которая вернула долю, принять её не может (роду войск нечем навредить), —
 *    без этого правила цикл ходил бы по ней вечно. Каждый проход с остатком выбивает хотя
 *    бы одну цель, поэтому проходов не больше, чем целей.
 * 4. **Живых целей не осталось — доля возвращается вызывающему.** Он хранит её зарядом на
 *    флоте пять игровых минут ({@link OVERCHARGE_HOURS}) и разряжает в первую враждебную
 *    сторону, с которой флот сойдётся в бою; не успел — заряд пропадает.
 *
 * Читателей у правила два, как и у дележа: живой раунд (`util/battleExchanges.ts`) и
 * прогноз (`state/previewBattle.ts`). Оба зовут эту функцию — второй копии правила нет.
 */

import { volleyShare } from './volley';

/** Сколько игровых часов держится заряд — пять минут по часам матча, не компьютера. */
export const OVERCHARGE_HOURS = 5 / 60;

/** Меньше этой доли залпа — погрешность деления, а не остаток. */
const EPS = 1e-9;

/** Одна нога прохода: какой цели и какая доля залпа. */
export interface VolleyLeg<T> {
  target: T;
  budget: number;
}

/**
 * Разложить `budget` залпа по `first` поровну и перенести остаток на живых (правила 1–4).
 *
 * `pass` наносит урон ВСЕЙ пачке ног разом и возвращает, сколько доли не легло у каждой
 * (0 — легло всё). Пачка целиком, а не по одной ноге: так вызывающий оценивает доли
 * прохода до того, как ляжет первый урон, — тот же снимок, что у залпа без остатка.
 * `alive` — кто сейчас жив и враждебен стрелку, в порядке вступления в бой.
 *
 * Возвращает долю залпа, которой не нашлось живой цели (правило 4).
 */
export function spendVolley<T>(
  first: readonly T[],
  alive: () => readonly T[],
  pass: (legs: readonly VolleyLeg<T>[]) => readonly number[],
  budget = 1,
): number {
  if (first.length === 0) return budget;
  const spent = new Set<T>();
  // «Поровну» — то же правило, что у самого залпа (`volley.ts`): одна строка на оба места.
  let legs: VolleyLeg<T>[] = first.map((target) => ({
    target,
    budget: volleyShare(budget, first.length),
  }));
  while (legs.length > 0) {
    const unused = pass(legs);
    let left = 0;
    legs.forEach((leg, i) => {
      const back = Math.min(leg.budget, Math.max(0, unused[i] ?? 0));
      if (back > EPS) {
        left += back;
        spent.add(leg.target);
      }
    });
    if (!(left > EPS)) return 0;
    const next = alive().filter((target) => !spent.has(target));
    if (next.length === 0) return left;
    legs = next.map((target) => ({ target, budget: volleyShare(left, next.length) }));
  }
  return 0;
}
