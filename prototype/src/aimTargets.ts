/**
 * Кого можно взять целью взведённого приказа (REFM-187).
 *
 * У карты уже разобраны два соседних вопроса: КТО забирает тап решает `tapPriority.ts`
 * (REFM-64), а что станет с прицелом после тапа — `armedTap.ts` (REFM-88). Между ними
 * оставался третий, и он собирался вручную в каждой ветке `selectAt`: из какого
 * множества вообще берётся цель. Пять веток фильтровали флоты пятью похожими строчками,
 * и похожи они были только на вид.
 *
 * 1. **У слияния цель — СВОЙ флот, и обязательно НЕ из выделения.** Без этого исключения
 *    ближайшим к пальцу окажется сам выделенный флот (по нему же и целятся), приказ уйдёт
 *    «слить себя с собой», ядро его отклонит — а игрок увидит только то, что тап ничего
 *    не сделал, и повторит его ещё раз.
 *
 * 2. **У обстрела и удара крыла цель — ЧУЖОЙ флот.** Свой в список даже не попадает:
 *    узнать о запрете отказом ядра поздно, прицел к тому моменту уже потрачен, а взводить
 *    его заново — наказание за случайный тап по соседнему своему кораблю.
 *
 * 3. **У высадки героя флот имеет ПРИОРИТЕТ над миром — но только с абордажным перком.**
 *    Без перка тап по миру, над которым висит свой флот, обязан значить МИР: иначе
 *    корабль поднимется не там, где целился игрок, и понять это можно будет только по
 *    карте. С перком приоритет обратный, потому что «поднять на борт» — отдельное
 *    осмысленное действие, и целятся для него именно в корабль.
 *
 * 4. **У штурма годится только ЧУЖОЙ ЗАХВАТЫВАЕМЫЙ мир.** Свой штурмовать нечего,
 *    ничей — не у кого отнимать, а пустой космос не захватывается вовсе. Проверка тут, а
 *    не в ядре, потому что от неё зависит СУДЬБА ПРИЦЕЛА (`armedTap`): по неподходящей
 *    цели штурм прицел не теряет.
 *
 * 5. **Набор группы трогает только свои флоты.** Чужой в группу не берётся, и тап по нему
 *    не должен ни выделять его, ни сбрасывать набранное.
 */

/** Минимум, который модулю нужен от флота: чей он и как его звать. */
export interface OwnedFleet {
  id: string;
  owner: string;
}

/** Свои флоты — для набора группы и высадки на борт (правила 3, 5). */
export function ownFleets<T extends OwnedFleet>(fleets: readonly T[], me: string): T[] {
  return fleets.filter((f) => f.owner === me);
}

/** Чужие флоты — для обстрела и удара крыла (правило 2). */
export function hostileFleets<T extends OwnedFleet>(fleets: readonly T[], me: string): T[] {
  return fleets.filter((f) => f.owner !== me);
}

/**
 * Свои флоты БЕЗ уже выделенных — якорь слияния (правило 1).
 * `movers` — те, кто полетит сливаться; они и стоят под пальцем.
 */
export function mergeAnchors<T extends OwnedFleet>(
  fleets: readonly T[],
  me: string,
  movers: readonly string[],
): T[] {
  return fleets.filter((f) => f.owner === me && !movers.includes(f.id));
}

/** Что выбрал тап при взведённой высадке: корабль-носитель, мир или ничего (правило 3). */
export type DeployPick = 'fleet' | 'world' | 'none';

/**
 * Куда поднимать героя. `boarding` — есть ли у героя абордажный перк: без него флот
 * не рассматривается ВООБЩЕ, и мир под своим флотом остаётся миром.
 */
export function deployPick(boarding: boolean, fleetHit: boolean, worldHit: boolean): DeployPick {
  if (boarding && fleetHit) return 'fleet';
  if (worldHit) return 'world';
  return 'none';
}

/** Годится ли мир под штурм: чужой, не ничей и захватываемый (правило 4). */
export function assaultTargetOk(
  owner: string | null | undefined,
  capturable: boolean,
  me: string,
): boolean {
  return capturable && owner != null && owner !== me;
}
