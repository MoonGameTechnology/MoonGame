/**
 * Плитка каталога и замок повторного заказа (REFM-42).
 *
 * Два правила, каждое из которых уже ловилось живым плейтестом.
 *
 * **1. Заказанное гаснет — и заказать его снова нельзя ничем.** Здание по умолчанию
 * одно на мир, поэтому уже стоящее (или строящееся, или приостановленное) показывается
 * тусклой плиткой. Гасить мало: у обычной плитки ДВА пути заказа — левый клик открывает
 * карточку кодекса с кнопкой, правый заказывает сразу. Запертая плитка теряет ОБА
 * якоря (`data-codex`, `data-buildorder`) и сохраняет только `data-desc`, чтобы досье
 * по наведению осталось. Оставь один якорь — и «серая» плитка продолжит принимать
 * заказы, что и было живым багом: налоговую управу заказывали дважды.
 *
 * **2. Гасят ТОЛЬКО три кода отказа.** «Уже стоит», «уже в очереди», «приостановлено» —
 * это про повтор. Всё остальное (не хватает денег, мир под бомбардировкой, чужой
 * сектор) плитку НЕ гасит: нехватку игроку показывает сама цена с дефицитом, а серая
 * кнопка вместо цифры «сколько не хватает» была бы хуже. Это решение подачи, и его
 * легко потерять, «упростив» условие до «любой отказ = замок».
 */
import { esc } from './format';

/** Состояние плитки: уже построено, уже заказано, или заказывать можно. */
export type TileLock = 'built' | 'queued' | null;

/** Коды ядра, которые означают ПОВТОР заказа — и только они гасят плитку. */
const BUILT = 'E_ALREADY_BUILT';
const QUEUED = new Set(['E_ALREADY_QUEUED', 'E_ALREADY_PAUSED']);

/**
 * Вердикт ядра (`canOrder`) + местная очередь прототипа → состояние плитки.
 * Локальная очередь ядру неизвестна по определению: в сети её нет, там стройку
 * таймит сервер, — поэтому она приходит отдельным флагом, а не ещё одним правилом.
 */
export function tileLock(code: string | null | undefined, locallyQueued = false): TileLock {
  if (code === BUILT) return 'built';
  if (code != null && QUEUED.has(code)) return 'queued';
  return locallyQueued ? 'queued' : null;
}

/** Из чего собрать плитку: иконка — готовая разметка, имя и подпись — текст. */
export interface TileView {
  /** `b` — здание, `u` — юнит: определяет и досье, и вид приказа. */
  kind: 'b' | 'u';
  id: string;
  /** Готовая разметка иконки (svg или глиф) — вставляется как есть. */
  icon: string;
  /** Имя из данных — только текстом. */
  name: string;
  /** Подпись плитки (обычно цена) — только текстом. */
  label: string;
  /** Плитка меню стройки: правый клик заказывает без карточки кодекса. */
  orderable?: boolean;
  /** Заперта — почему; `null` значит «заказывать можно». */
  lock?: TileLock;
}

/** Построенное здание: что показать на его плитке в панели мира. */
export interface BuiltTileView {
  type: string;
  /** Текущий уровень; показывается ВСЕГДА — см. `builtTileHtml`. */
  level: number;
  /** Готовая разметка иконки — вставляется как есть. */
  icon: string;
  /** Локализованное имя здания — только текстом. */
  name: string;
}

/**
 * СТРОКА построенного здания: иконка, имя и уровень — в одну линию.
 *
 * Три решения подачи, каждое из которых чинит увиденное на телефоне:
 * — **список идёт в СТОЛБИК, строка на здание** (заказ владельца по скриншоту). Сетка
 *   крупных плиток переносилась на два ряда уже на четырёх постройках, длинные имена
 *   ломались на две строки, и секция «Здания» съедала пол-листа. Столбик сканируется
 *   сверху вниз одним движением глаза и растёт предсказуемо.
 * — **имя подписано.** Одна иконка 18-м кеглем не отвечает на вопрос «что это»:
 *   ряд из четырёх глифов читался как набор значков, и понять, где радар, а где
 *   космопорт, можно было только тапнув каждый.
 * — **уровень показан ВСЕГДА и коротко** (`L1`). Раньше здания без апгрейдов помечались
 *   галочкой, а улучшаемые — «L1», и один ряд говорил на двух языках: галочка читалась
 *   как «готово», а соседнее «L1» — как уровень, хотя оба построены одинаково.
 */
export function builtTileHtml(v: BuiltTileView): string {
  const desc = `b:${esc(v.type)}:${v.level}`;
  return (
    `<button class="asset-row built" data-codex="${desc}" data-desc="${desc}" data-name="${esc(v.name)}">` +
    `<span class="bicon">${v.icon}</span>` +
    `<b>${esc(v.name)}</b>` +
    `<span class="dim">L${v.level}</span></button>`
  );
}

/** Разметка одной плитки. Чистая: ни DOM, ни состояния. */
export function catalogTileHtml(v: TileView): string {
  const desc = `${v.kind}:${esc(v.id)}`;
  const head = `<span class="pt-ic">${v.icon}</span>`;
  if (v.lock) {
    // Ни `data-codex`, ни `data-buildorder` — оба пути заказа закрыты (см. шапку).
    const mark = v.lock === 'built' ? '✓' : '⏳';
    return (
      `<button class="ptile locked" data-desc="${desc}" data-name="${esc(v.name)}">` +
      `${head}<span class="pt-c">${mark} ${esc(v.label)}</span></button>`
    );
  }
  const order = v.orderable
    ? ` data-buildorder="${v.kind === 'u' ? 'unit' : 'building'}:${esc(v.id)}"`
    : '';
  return (
    `<button class="ptile" data-codex="${desc}" data-desc="${desc}"${order} data-name="${esc(v.name)}">` +
    `${head}<span class="pt-c">${esc(v.label)}</span></button>`
  );
}
