/**
 * УДАР ШАТТЛОВ ГЛАЗАМИ ИГРОКА (SHU-6.11) — кому на карте видна вспышка удара, откуда к
 * ней тянется трасса и когда о нём пишет журнал.
 *
 * Ядро издаёт `shuttle.hit` на каждый удар вылета по флоту или миру — и по прибытии
 * налёта, и на каждом 15-минутном тике патруля (SHU-6.2). До этого кирпича клиент его не
 * слушал: удар был виден только по полоске корпуса. Выбор владельца (2026-10-06,
 * «Вспышка и журнал»): трасса от круга к цели и вспышка на каждом ударе; строка в журнале,
 * когда бьют по моему флоту или миру.
 *
 * 1. **Вспышку видит жертва и тот, кто опознаёт цель.** Резолюция владельца 2026-09-20
 *    (`docs/open-questions.md`, «урон под туманом»): своё состояние после попадания
 *    игрок знает, а удар по цели в тумане не подтверждается — даже стрелявшему. Поэтому
 *    «свой вылет» сам по себе вспышку не открывает: открывает опознанная цель (патруль
 *    сам опознаёт флоты в своём круге, SHU-6.7, — свои тики стрелок видит всегда).
 * 2. **Числа урона нет нигде** — ни у вспышки, ни в журнале (та же резолюция: по
 *    величине вычисляют вражеские укрепления и ауры).
 * 3. **Трасса выходит только из ВИДИМОГО источника.** Свой вылет — из его точки. Чужой —
 *    только из чужого патруля, который игрок видит в обзоре (`patrolsSeenBy`, SHU-6.10)
 *    и в круге которого стоит цель ({@link seenPatrolOver}). Вылет, которого игрок не
 *    видит, трассой не выдаётся: она показала бы, откуда пришёл удар из тумана. Тогда —
 *    одна вспышка у цели.
 * 4. **Журнал пишет только жертве и один раз на налёт по цели** ({@link hitKey}). Патруль
 *    бьёт каждые 15 минут и висит до 4 ч: строка на каждый тик утопила бы журнал в
 *    шестнадцати одинаковых записях. Свои удары в журнал не идут вовсе — их и так видно
 *    на карте, а журнал собирает то, что случилось со мной.
 */

/** То, что решению нужно из `shuttle.hit`. */
export interface ShuttleHit {
  strikeId: string;
  /** Чей вылет ударил. */
  owner: string;
  targetId: string;
  /** Чья цель; у ничейного мира — пусто. */
  targetOwner?: string | null;
}

/** Что показать по удару (правила 1, 4). */
export interface ShuttleHitView {
  /** Рисовать ли вспышку (и трассу, если источник виден). */
  show: boolean;
  /** Писать ли строку в журнал. */
  journal: boolean;
}

/** Ключ «налёт по цели» для журнала (правило 4): новый вылет или новая цель — новая строка. */
export function hitKey(hit: ShuttleHit): string {
  return `${hit.strikeId}|${hit.targetId}`;
}

/** Кому и что показать (правила 1, 4). `announced` — ключи, о которых журнал уже писал. */
export function shuttleHitView(
  hit: ShuttleHit,
  me: string,
  targetKnown: boolean,
  announced: ReadonlySet<string>,
): ShuttleHitView {
  const victim = hit.targetOwner === me;
  return {
    show: victim || targetKnown,
    journal: victim && hit.owner !== me && !announced.has(hitKey(hit)),
  };
}

/** Чужой патруль в обзоре — то, что о нём знает игрок (`SeenPatrol` ядра). */
export interface SeenPatrolCircle {
  owner: string;
  at: { x: number; y: number };
  radius: number;
}

/**
 * Центр видимого патруля `owner`, в круге которого стоит цель (правило 3), или `null`.
 * Из нескольких — ближайший к цели: ядро бьёт из того круга, где цель, а у двух
 * перекрытых кругов ближний центр и есть тот, что накрывает её заведомо.
 */
export function seenPatrolOver(
  seen: readonly SeenPatrolCircle[],
  owner: string,
  target: { x: number; y: number },
): { x: number; y: number } | null {
  let best: { x: number; y: number } | null = null;
  let bestD = Infinity;
  for (const p of seen) {
    if (p.owner !== owner || !(p.radius > 0)) continue;
    const d = Math.hypot(p.at.x - target.x, p.at.y - target.y);
    if (d <= p.radius && d < bestD) {
      best = p.at;
      bestD = d;
    }
  }
  return best;
}
