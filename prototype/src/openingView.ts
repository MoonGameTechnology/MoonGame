/**
 * Стартовый вид карты: с чего открывается матч и куда сбрасывается вид (REFM-56).
 *
 * Одно и то же действие — открыть матч и двойной тап «сбросить вид», — и оно должно
 * приводить туда, где игрок собственно играет.
 *
 * 1. **Дом — это твой мир СО СТРОЙКОЙ.** Пустой мир может быть только что занятым
 *    клочком на другом конце карты; открыть матч на нём значит показать игроку не его
 *    дело. Застроенный мир — там, где идёт хозяйство.
 * 2. **Нет застроенного — годится любой свой; нет вообще своих — общий вид.** Матч
 *    можно открыть уже потеряв всё, и вид обязан остаться осмысленным, а не пустым.
 * 3. **Телефон открывается ПРИБЛИЖЕННЫМ к дому, широкий экран — целиком.** Плотную
 *    карту на телефоне целиком не прочесть: там начинают у дома и панорамируют, а на
 *    широком экране обзор читается сразу.
 * 4. **Приближение задано ОТНОСИТЕЛЬНО вписывания в экран**, а не в пикселях, поэтому
 *    один и тот же вид получается и на маленьком телефоне, и на планшете.
 */

/** Мир в том виде, в каком стартовый вид его различает. */
export interface WorldLike {
  owner: string | null;
  buildings: readonly unknown[];
  position: { x: number; y: number };
}

/** Во сколько раз стартовый вид на телефоне ближе вписывания карты в экран. */
export const HOME_ZOOM = 3;

/**
 * Найти дом: свой застроенный мир, иначе любой свой, иначе `null` (правила 1–2).
 * Порядок обхода — порядок вызывающего: одинаковый список даёт одинаковый дом.
 */
export function pickHome<T extends WorldLike>(worlds: readonly T[], me: string): T | null {
  return (
    worlds.find((w) => w.owner === me && w.buildings.length > 0) ??
    worlds.find((w) => w.owner === me) ??
    null
  );
}

/** Куда встать камере на старте: к дому с приближением или на обзор всей карты. */
export type OpeningView =
  { kind: 'home'; at: { x: number; y: number }; scale: number } | { kind: 'whole-map' };

/** Решить стартовый вид. `phone` — узкая раскладка, `home` — результат `pickHome`. */
export function openingView(phone: boolean, home: WorldLike | null): OpeningView {
  // Правило 3: приближение к дому — только на телефоне и только если дом есть.
  return phone && home
    ? { kind: 'home', at: home.position, scale: HOME_ZOOM }
    : { kind: 'whole-map' };
}
