/**
 * Какие строки списка «Цели первой сессии» видны (ONB-15).
 *
 * Список вырос до цели на каждую главу урока, это десять строк. Во весь рост он закрывал
 * бы полэкрана ПК слева и почти весь край телефона, а нужен игроку один ответ: что делать
 * сейчас.
 *
 * 1. **Видны ближайшие невыполненные цели, не больше `ahead`.** Первая из них — задача
 *    текущей главы, следующая показывает, куда урок ведёт дальше.
 * 2. **Перед ними — последняя выполненная.** Галочка только что закрытой цели и даёт
 *    ощущение прогресса; остальные выполненные считает счётчик «сделано/всего».
 * 3. **Порядок строк — порядок урока**, а не порядок выполнения: цель, закрытая раньше
 *    своей главы, не прыгает вверх.
 * 4. **Всё выполнено — видна последняя цель** с галочкой; похвала приходит в ленту.
 */
export function visibleGoalRows<T extends { done: boolean }>(
  rows: readonly T[],
  ahead = 2,
): T[] {
  let lastDone = -1;
  rows.forEach((r, i) => {
    if (r.done) lastDone = i;
  });
  const pending = rows.flatMap((r, i) => (r.done ? [] : [i])).slice(0, ahead);
  const shown = new Set([lastDone, ...pending]);
  return rows.filter((_, i) => shown.has(i));
}
