/**
 * Что теряет силу, когда состояние сменилось (REFM-102).
 *
 * После каждого применения шага интерфейс держит ссылки на флоты: выделенный, открытое
 * окно деления, ⇅-меню десанта и групповое выделение. Чистка лежала четырьмя строками
 * подряд в `apply`, и из них не читалось, почему у одиночных ссылок условие одно, а у
 * группы — ДВА.
 *
 * 1. **Ссылка на исчезнувший флот снимается, а не висит.** Панель, окно деления и
 *    ⇅-меню указывали бы на то, чего нет, и следующий приказ ушёл бы в пустоту.
 * 2. **Групповое выделение чистится ДВАЖДЫ: пропавшие И переставшие быть своими.**
 *    Захваченный противником флот жив, но он больше не мой — держать его в группе
 *    значит слать приказы, которые гарантированно отскочат.
 * 3. **Одиночная ссылка о владельце НЕ спрашивает.** Панель показывает и чужой флот —
 *    это осмотр, а не приказ; закрывать её при смене владельца значило бы отнимать у
 *    игрока возможность посмотреть, кто теперь хозяин.
 */

/** Держится ли одиночная ссылка: только «флот ещё существует» (правила 1, 3). */
export function refSurvives(
  id: string | null | undefined,
  exists: (id: string) => boolean,
): boolean {
  return !!id && exists(id);
}

/** Групповое выделение после смены состояния: живые И свои (правило 2). */
export function pruneGroup(
  ids: Iterable<string>,
  ownerOf: (id: string) => string | null | undefined,
  me: string,
): Set<string> {
  const out = new Set<string>();
  for (const id of ids) if (ownerOf(id) === me) out.add(id);
  return out;
}
