/**
 * Чем кончается «в архив» / «вернуть» и что игрок при этом видит (REFM-157).
 *
 * Пятнадцатый срез сетевой секции и последний кусок браузера матчей. Строку второй
 * кнопки выбирает `matchRow.ts` (REFM-52), адрес запроса и разбор исхода — `matchQuery.ts`
 * (REFM-150); между ними внутри `toggleArchive` оставалось само последствие: одно
 * действие, три конца, и каждый был выписан отдельным присваиванием по месту.
 *
 * 1. **Удача — это не сообщение, а ПЕРЕРИСОВАННЫЙ список.** Архивирование меняет вкладку,
 *    в которой живёт строка: матч обязан пропасть из «Активных» и появиться в «Архиве».
 *    Текстовое «готово» под списком этого не показывает, а список, оставшийся прежним,
 *    читается как «не сработало» — игрок жмёт кнопку второй раз.
 * 2. **Отказ сервера и обрыв связи говорят РАЗНОЕ** (тот же довод, что у `matchQuery.ts`,
 *    правило 3): «сервер жив, но так нельзя» повторять бессмысленно, «до сервера не дошли»
 *    — как раз стоит. Одно сообщение на оба случая послало бы игрока чинить не ту беду.
 * 3. **Отказ называет ДЕЙСТВИЕ, которое не прошло.** Человек нажал конкретную кнопку и
 *    ждёт ответа именно про неё: общее «не удалось» оставляет главный вопрос без ответа —
 *    так матч убрался в архив или нет.
 * 4. **А вот обрыв связи действий не различает.** Причина не в действии, а в канале:
 *    запрос не доехал целиком, и уточнять, какой именно, нечем — два разных текста про
 *    одну и ту же оборванную связь только делают вид, что клиент знает больше.
 */

/** Что игрок просил сделать со строкой (совпадает с ненулевыми `rowAction`, `matchRow.ts`). */
export type ArchiveOp = 'archive' | 'restore';

/** Чем кончился запрос — в тех же словах, что `queryOutcome` (`matchQuery.ts`). */
export type ArchiveResult = 'ok' | 'refused' | 'unreachable';

/** Что после этого делает экран. */
export type ArchiveEffect =
  /** Молча перечитать список: вкладка строки изменилась (правило 1). */
  | { kind: 'refresh' }
  /** Написать причину в строку статуса (правила 2–4). */
  | { kind: 'say'; key: 'browser.archive-failed' | 'browser.restore-failed' | 'browser.archive-error' };

/** Последствие запроса «в архив» / «вернуть» (правила 1–4). */
export function archiveEffect(op: ArchiveOp, result: ArchiveResult): ArchiveEffect {
  if (result === 'ok') return { kind: 'refresh' };
  // Правило 4: обрыв про канал, а не про действие — один текст на обе кнопки.
  if (result === 'unreachable') return { kind: 'say', key: 'browser.archive-error' };
  // Правило 3: отказ называет то самое действие, которое не прошло.
  return { kind: 'say', key: op === 'restore' ? 'browser.restore-failed' : 'browser.archive-failed' };
}
