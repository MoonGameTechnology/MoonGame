/**
 * Места rewarded-рекламы в Sector Zero (`YAG-3.2`).
 *
 * Резолюция владельца 2026-09-22 (§0.6а роадмапа экономики): реклама существует ТОЛЬКО
 * как rewarded по нажатию игрока, и мест ровно четыре — двойная награда за забег,
 * Суверены, обновление витрины и покупка лота. Список закрыт намеренно: пятое место —
 * это решение владельца, а не строчка кода, поэтому `watchAd` принимает только
 * {@link AdPlacement}, и место без записи здесь просто не соберётся.
 *
 * Id постоянные и не несут данных: лот, за который смотрят ролик, в id не входит, иначе
 * у одного места было бы столько имён, сколько лотов в каталоге, и воронку аналитики
 * пришлось бы собирать по префиксу.
 */
export const AD_PLACEMENTS = ['shop.lot', 'shop.refresh', 'shop.sovereigns', 'run.double'] as const;
export type AdPlacement = (typeof AD_PLACEMENTS)[number];

/** Исход ролика в терминах контракта площадки. Свой тип: `decisions/` прототип не
 *  импортирует. */
export type AdOutcome = 'ok' | 'cancelled' | 'unavailable';

/**
 * Что сказать игроку, когда ролик награды НЕ дал. `ok` здесь не бывает: сообщение об
 * успехе своё у каждого места («Куплено», «Витрина обновлена»).
 *
 * «Не досмотрел» и «рекламы нет» — разные вещи, и игроку это видно: в первом случае ролик
 * был и его закрыли, во втором показывать было нечего. Раньше оба читались одинаково
 * («Реклама не показана»), потому что место получало от площадки `boolean`.
 */
export function adRefusalKey(status: Exclude<AdOutcome, 'ok'>): string {
  return status === 'cancelled' ? 'sector-zero.ad.cancelled' : 'sector-zero.ad.unavailable';
}
