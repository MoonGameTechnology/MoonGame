/**
 * Одна вкладка — один писатель Sector Zero (`AUD-29`). Чистое решение, без DOM и таймеров.
 *
 * Профиль, журнал забега и отметка облака лежат в общем для всех вкладок хранилище, а
 * каждая вкладка держит их копию в памяти и пишет её целиком. Две вкладки одной игры
 * молча затирали изменения друг друга (прогон: модуль, поставленный в первой вкладке,
 * пропадал после записи второй). Облако этого не видело: у вкладок одно имя устройства
 * и одни номера правок, поэтому родословные совпадали и экрана выбора не было.
 *
 * Правило: в хранилище лежит id вкладки-хозяйки. Вкладка, открывающая Sector Zero,
 * становится хозяйкой; пишет только хозяйка, и спрашивает об этом хранилище в момент
 * записи, а не свою память — прежняя хозяйка не успеет записать даже между перехватом
 * и событием `storage`. Хранилища нет или запись стёрта — делить нечего, писать можно.
 */

/** Ключ хранилища с id вкладки-хозяйки. */
export const TAB_OWNER_KEY = 'sector-zero.tab.v1';

/** Вытеснена ли вкладка `own`: хозяйка записана, и это не она. */
export function tabSuperseded(own: string, owner: string | null): boolean {
  return owner !== null && owner !== '' && owner !== own;
}
