import type { GameModule } from '../kernel/module';
import { veteranFactor } from '../state/veterancy';

/**
 * БОЕВАЯ НАДБАВКА ВЕТЕРАНА (PERK-3.1): чем больше сражений сторона пережила, тем
 * сильнее она бьёт. Триггер выбран владельцем 2026-09-23 — «пережитые бои».
 *
 * ⚠️ Это СУЖЕНИЕ решения владельца 2 (`docs/unit-medals-roadmap.md` §0.0), а не обход
 * его: выплата за медаль по-прежнему силы в бою не даёт, но счётчик `UnitStack.battles`,
 * на котором стоит линия «Выслуга», теперь ещё и питает боевой множитель. Сужение
 * записано там же, где стоит само решение, — иначе в репозитории жили бы две правды.
 *
 * ПОЧЕМУ СНЕЖНОГО КОМА НЕ ЖДЁМ, хотя решение 2 было принято именно против него. Два
 * ограничителя, и оба измеренные, а не обещанные:
 *  - счётчик растёт у ТОГО, КОГО БЬЮТ: проигрывающий воюет чаще, значит надбавка
 *    достаётся отстающему раньше, чем ведущему;
 *  - заслуга НАСЫЩАЕТСЯ (`docs/unit-medals-roadmap.md` §0.5): потолок — 4 боя на юнит,
 *    p50 = 1, и удлинение матча вдвое распределения не двигает вообще, потому что много
 *    дерущийся стек погибает раньше, чем накопит больше. Потолок ставит сама механика,
 *    а не искусственный кап в коде.
 *
 * ГРУППА — ПОСЛЕДОВАТЕЛЬНАЯ (`combat.damage`, не `combat.damage.parallel`). Это
 * осознанно: надбавка редкая (её имеет четверть доживших стеков) и не обязана
 * разбавляться массовыми процентами технологий — ровно тот класс, под который
 * последовательная группа и заведена (PERK-0.1, `util/combat.ts`).
 *
 * САМО ПРАВИЛО ЗДЕСЬ НЕ ЖИВЁТ — оно в `state/veterancy.ts`, потому что читателя два:
 * этот хук и окно боя, которое показывает игроку получаемую надбавку (PERK-3.3). Две
 * копии разошлись бы молча: каждая половина верна сама по себе, и ни один тест этого
 * не поймал бы.
 */
export const veteranModule: GameModule = {
  id: 'veteran',
  version: '1.1.0',
  setup(api) {
    api.hook<number>('combat.damage', (damage, args, h) => {
      const { battleId, attacker } = args as { battleId?: string; attacker?: string | null };
      // Надбавка живёт РОВНО в том канале, который её и выдаёт: `battleId` несёт только
      // `combatModule`, и только он зовёт `creditBattle`. Обстрел с орбиты, перехват на
      // трассе и вылет эскадрильи боями не считаются (`creditBattle` их не начисляет) —
      // значит и платить по ним не за что. Отдельной проверки фазы для этого не нужно.
      if (battleId === undefined || attacker === undefined || attacker === null) return damage;
      const battle = h.state.battles[battleId];
      if (!battle) return damage;
      const factor = veteranFactor(h.state, battle, attacker, h.ctx.data);
      return factor !== 1 ? damage * factor : damage;
    });
  },
};
