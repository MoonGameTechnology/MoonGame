/**
 * Авто-имена флотам в духе Bytro/Supremacy («2-й Hunter Mech Бригада»): у каждого
 * соединения — узнаваемое имя вместо голого «ФЛОТ». Полностью ВЫВОДИМО из id
 * флота: одна и та же строка id → одно и то же имя на всех клиентах (в сети имя
 * не нужно передавать — все выведут его одинаково), без правки состояния/ядра и
 * без `Math.random`. При слиянии/разделении id меняется — меняется и имя, ровно
 * как у Bytro новое соединение получает новое имя.
 *
 * Формат: `Флот «{ПОЗЫВНОЙ} {N}»` — позывной латиницей (нейтрален к локали — как
 * «HUNTER MECH» у Bytro даже в русском клиенте), номер даёт уникальность при редкой
 * коллизии хэша. `fleetCallsign` — чистая функция id; `FLEET_KIND_KEY` — ключ слова
 * «Флот» (переводится через `t()` на месте рендера).
 *
 * **Слово одно, лестницы размеров больше нет (SHU-4.1).** Раньше тип отражал РАЗМЕР:
 * звено → эскадрилья → эскадра → флот → армада. Все ступени, кроме последней, —
 * авиационные слова, а по резолюции владельца (2026-09-10, §0.4 `shuttles-roadmap.md`)
 * они принадлежат ЧЕЛНОКАМ: группа челноков — эскадра, группа кораблей — флот. Пока
 * этими словами звали корабли, у игры было два словаря на одну вещь — ровно то, от чего
 * ушёл SHU-0.1. Размер для игрока не пропал: корабли и десант стоят числами в
 * подзаголовке карточки соединения.
 */

