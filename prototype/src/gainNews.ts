/**
 * Что игрок узнаёт о приобретениях: мир и открытие (REFM-184).
 *
 * Два последних необработанных случая свитча событий — захват провинции и завершённое
 * исследование. Общего у них больше, чем кажется: оба сообщают, что кто-то ЧТО-ТО
 * приобрёл навсегда, и у обоих решение распадается надвое — «кто услышит строку» и «что
 * перерисовать». Второе до сих пор стояло за пределами первого, и это правильно, но по
 * инлайну прочитать это было нельзя: `renderDiplo()` просто висел ниже закрывающей скобки.
 *
 * 1. **Строку захвата слышит только УЧАСТНИК — тот, кто взял мир, и тот, у кого его
 *    взяли** (решение владельца 2026-10-06). Чужой захват даже на мире, который я вижу, —
 *    раскрытие информации: «кто что захватил» игрок видит на карте перекраской, но не
 *    получает новостью — ни строкой журнала, ни всплывающим сообщением, ни в сводке
 *    возвращения (она собирается из тех же строк). Прежде здесь стояло общее правило
 *    журнала «чужое — на опознанном узле» (`eventVisibility.ts`), и строкой печатался любой
 *    захват в обзоре.
 *
 * 2. **Строка захвата несёт ЯКОРЬ на мир, а строка открытия — нет.** Захват это
 *    происшествие НА КАРТЕ, к которому игрок захочет прыгнуть камерой; исследование
 *    происходит нигде — прыгать некуда, и якорь на нём был бы кнопкой в пустоту.
 *
 * 3. **Вспышка захвата и память разведки идут по ВИДИМОСТИ, а не по участию.** Перекраска
 *    опознанного мира — наблюдение: её видно на карте и без строки, вспышка лишь отмечает
 *    момент, а память обязана записать нового владельца того, что игрок видел. За туманом
 *    не мигает ничего — иначе картинка выдавала бы то, что скрыл туман. Фог-вердикт общий
 *    для журнала (`eventVisibility.ts`, REFM-86); здесь он не переписан, а позван, потому
 *    что вторая копия фог-правила разойдётся с первой молча. Повторный захват
 *    перезапускает волну, а не копит вспышки: на карте важен последний владелец, а не
 *    история.
 *
 * 4. **Открытие слышит ТОЛЬКО исследователь.** Чужие технологии — разведданные, их
 *    добывают шпионажем; уведомление о них раздавало бы даром то, за что в игре платят.
 *
 * Правила 2–3 модуль ОБЪЯСНЯЕТ, но не реализует: фог-вердикт даёт `eventVisibility.ts`,
 * а якорь и вспышка — по одной строке на месте вызова, и заводить обёртку ради них
 * значило бы прятать однострочник за именем. Здесь живут те три решения, которые
 * ломаются молча: кто слышит захват, кто слышит открытие и что перерисовывается
 * независимо от этого.
 *
 * 5. **Перерисовка идёт ВНЕ проверки адресата — и это не оплошность.** Счётчик провинций
 *    в ростере и доступность узлов в дереве меняются оттого, что событие СЛУЧИЛОСЬ, а не
 *    оттого, что игрок о нём услышал: захват за туманом всё равно сдвигает счёт держав, и
 *    открытый игроку список технологий обязан совпадать с состоянием, даже когда строки
 *    в ленте не было.
 */

/**
 * Слышит ли игрок о захвате: только участник — новый владелец (`owner`) или прежний
 * (`from`), правило 1. Безымянная сторона — не я (fail-secure): захват ничейного мира
 * слышит один захвативший.
 */
export function captureHeard(owner: unknown, from: unknown, me: string): boolean {
  return owner === me || from === me;
}

/** Слышит ли игрок об открытии: только тот, кто его сделал (правило 4). */
export function researchHeard(playerId: unknown, me: string): boolean {
  return playerId === me;
}

/** Что перерисовать после события — независимо от того, услышал ли игрок строку. */
export interface GainRepaint {
  /** Ростер держав: счётчик провинций сдвинулся. */
  roster: boolean;
  /** Дерево технологий: доступность узлов сдвинулась. */
  techTree: boolean;
}

/**
 * Перерисовка по виду приобретения (правило 5). Отдельная функция, а не два `if` по
 * месту: именно её независимость от адресата легко потерять при следующей правке.
 */
export function gainRepaint(kind: 'capture' | 'research'): GainRepaint {
  return { roster: kind === 'capture', techTree: kind === 'research' };
}
