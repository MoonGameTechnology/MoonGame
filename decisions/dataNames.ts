/**
 * Как id игровых ДАННЫХ превращается в имя для игрока (MIG-3).
 *
 * Правило неочевидное, и знать его обязаны оба клиента одинаково — иначе один и тот же
 * корабль подписан в прототипе «Разведдрон», а в новом клиенте «scout_drone».
 *
 * 1. **Имя данных — это msgid, а не ключ.** `tData()` строит из имени слаг (`dataKey()`):
 *    нижний регистр, а каждая группа символов вне `[a-z0-9]` становится дефисом. Поэтому
 *    на вход подаётся английское имя из `data/*.json`, а русский текст живёт в локали
 *    под `data.*` — `Scout Drone` → `data.scout-drone`.
 * 2. **Подчёркивания в id заменяются пробелами.** Id пишутся `scout_drone`, имя в
 *    каталоге — `Scout Drone`. Слаг у них совпадёт и без замены (`_` тоже вне класса и
 *    тоже станет дефисом), но замена оставлена намеренно: она делает ЯВНЫМ, что обе
 *    записи обязаны сойтись к одному ключу, а не полагается на совпадение двух правил.
 * 3. **У здания имя берут из каталога, если оно есть.** Там оно уже человеческое
 *    (`Metal Mine`), и id — лишь запасной путь для записи без имени.
 *
 * Текста здесь нет (правило папки) — только обращение к рантайму локализации, и
 * импорт идёт из `core`, а НЕ из `runtime`: второй подключает все локали сразу, что
 * верно для прототипа и сломало бы клиенту LOC-6 («ровно одна локаль на загрузку»).
 */
import { tData } from '../localization/core';

/** Имя юнита по его id (правила 1–2). */
export function displayUnit(unit: string): string {
  return tData(unit.replace(/_/g, ' '));
}

/** Имя здания: из каталога, иначе — по id (правило 3). */
export function buildingName(name: string | undefined, id: string): string {
  return tData(name ?? id);
}
