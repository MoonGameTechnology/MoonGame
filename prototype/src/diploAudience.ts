/**
 * Кому адресована дипломатия в СОЛО (REFM-182).
 *
 * Сетевой путь эти решения уже принимает в `diploDelivery.ts` (REFM-174) — там события
 * добываются сравнением снимков, потому что дипломатия не проходит фог-фильтр сервера.
 * Соло получает те же новости событиями ядра, и решения о них стояли прямо в свитче,
 * тремя разными `if`. Собраны сюда — и сравнение с сетевым путём вскрыло два расхождения,
 * описанные в конце шапки. Поведение НИ ОДНО из них здесь не меняет.
 *
 * 1. **Слышно только то, где я — сторона.** Две ИИ-державы, меняющие отношения между
 *    собой, не часть моего разговора: у треда ровно две стороны, и чужой паре в нём места
 *    нет. В ленту это тоже не идёт — иначе она превратилась бы в сводку чужой политики,
 *    в которой мои собственные объявления войны потерялись бы.
 *
 * 2. **У войны свой текст.** Остальные сдвиги игрок читает как переговоры, а война — это
 *    начало боевых действий; спрятать её за общим «отношения изменились» значит сообщить
 *    о нападении тем же тоном, что о потеплении.
 *
 * 3. **Входящее предложение считается непрочитанным, исходящее — нет.** Собственное
 *    действие игрок и так помнит, и бейдж «есть новое» на нём просто врал бы; а вот
 *    предложение от другой стороны без счётчика останется незамеченным — лента коротка и
 *    переполняется боем.
 *
 * 4. **Своё исходящее предложение объявляется, только если ответа надо ЖДАТЬ.** Бот
 *    отвечает в той же пачке событий (согласие или отказ приезжает следом), так что
 *    строка «отправлено» у бота живёт долю секунды и читается как сбой; у человека же
 *    ответа можно ждать часами, и без этой строки игрок не будет уверен, что предложение
 *    вообще ушло.
 *
 * 5. **Отказ читает только тот, кто предлагал.** Отклонившему сообщать нечего: он
 *    сам только что нажал «отказать», и уведомление о собственном решении — шум.
 *
 * **РАСХОЖДЕНИЕ 1 — два текста для одного события (вопрос владельцу).** Соло и сеть
 * говорят об одном и том же РАЗНЫМИ ключами: соло `log.diplo.war` / `log.diplo.stance`,
 * сеть `comms.war-declared` / `comms.stance-changed`. Один игрок в одном матче видит одну
 * формулировку, в сетевом — другую. Свести их — смена текста, а значит смена поведения.
 *
 * **РАСХОЖДЕНИЕ 2 — тред со СМОЙ СОБОЙ.** Ядро издаёт `diplomacy.changed` как
 * `{ a: инициатор, b: цель }`, а соло кладёт реплику в тред с ключом `b`. Когда сторону
 * `b` занимает сам игрок (то есть отношения меняет НЕ он, а ему), реплика уходит в
 * переписку, ключом которой стоит его собственное место, а не место собеседника. Сетевой
 * путь такого не допускает: он всегда пишет в тред `ev.other`. Строка ленты при этом
 * приходит правильно — расходится только адрес треда. Починка меняет поведение, поэтому
 * здесь сохранено как есть; `stanceThread` существует ровно для того, чтобы у этого адреса
 * было ОДНО место, когда до починки дойдут руки.
 */

/** Касается ли меня событие: я — одна из двух сторон (правило 1). */
export function diploConcernsMe(a: unknown, b: unknown, me: string): boolean {
  return a === me || b === me;
}

/** Ключ строки о смене стойки: у войны свой (правило 2). */
export function stanceKey(stance: unknown): 'log.diplo.war' | 'log.diplo.stance' {
  return stance === 'war' ? 'log.diplo.war' : 'log.diplo.stance';
}

/**
 * Куда положить реплику о смене стойки и от чьего имени.
 * Сегодня — тред `b`, автор `a`; см. РАСХОЖДЕНИЕ 2 в шапке.
 */
export function stanceThread(a: string, b: string): { key: string; from: string } {
  return { key: b, from: a };
}

/** Что делать с предложением: я адресат, я отправитель и ответа стоит ждать, или молчим. */
export type OfferAudience = 'incoming' | 'sent' | 'silent';

/**
 * Кому адресовано предложение (правила 3–4). `targetIsBot` — отвечает ли адресат
 * немедленно: у бота ответ приезжает в той же пачке, и «отправлено» показывать незачем.
 */
export function offerAudience(
  from: unknown,
  to: unknown,
  me: string,
  targetIsBot: boolean,
): OfferAudience {
  if (to === me) return 'incoming';
  if (from === me && !targetIsBot) return 'sent';
  return 'silent';
}

/** Считать ли событие непрочитанным: только входящее предложение (правило 3). */
export function offerUnread(audience: OfferAudience): boolean {
  return audience === 'incoming';
}

/** Отказ читает только предлагавший (правило 5). */
export function declineHeard(from: unknown, me: string): boolean {
  return from === me;
}
