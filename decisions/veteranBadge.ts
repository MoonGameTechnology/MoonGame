//
// ЧТО ЗДЕСЬ, А ЧТО НЕ ЗДЕСЬ. Сколько именно даёт выслуга — ПРАВИЛО МИРА, оно в ядре
// (`veteranFactor`/`veteranHull`, `packages/shared-core/src/state/veterancy.ts`) и сюда
// приезжает уже посчитанным. Здесь только клиентская половина: как назвать и когда молчать.
//
// VET-6: выслуга даёт не только урон, но и корпус — и только там, где хост дал ветерану
// силу (Sector Zero). В сетевой партии оба числа не приходят вовсе, и значок молчит тем же
// правилом, что у необстрелянных сил.
import { t } from '../localization/core';

/** Глиф — ТОТ ЖЕ вымпел, что у медали «Выслуга» в строке состава (`unitMedals.ts`).
 *  Это одна механика, показанная в двух местах: значок на корабле говорит «этот стек
 *  воевал», строка в окне боя — «вот сколько это сейчас даёт». Разные символы заставили
 *  бы игрока связывать их самому, и большинство не связало бы. */
const GLYPH = '⚑';

/** Готовая к отрисовке надбавка: глиф, короткая надпись и подпись. */
export interface VeteranBadge {
  glyph: string;
  /** Видимая надпись — только числа: `+8%`, а когда урон и корпус разошлись — `+8%/+4%`.
   *  Слов здесь нет намеренно, они в `title` (тот же приём, что у медалей: в узкую строку
   *  имя степени не влезает). */
  text: string;
  /** Локализованная подпись — что это за проценты и откуда взялись. */
  title: string;
  /** Округлённые проценты урона. Отдаются наружу, чтобы тест и вёрстка не парсили `text`. */
  percent: number;
  /** Округлённые проценты прочности корпуса (VET-6); 0 — корпуса выслуга не даёт. */
  hullPercent: number;
}

/**
 * Значок надбавки по множителю урона стороны и её очкам корпуса, либо `null` —
 * «показывать нечего».
 *
 * `null` во всех случаях, и это одно и то же для игрока: надбавки нет (`undefined`, `1`
 * и `0`), механика выключена данными или хостом, ИЛИ надбавка есть, но округляется в
 * ноль. Последнее — не придирка: типичная выслуга это один бой на юнит, а половина сил
 * обычно необстреляна, так что множители вида 1.004 — обычное дело. Значок «+0%» занял
 * бы место в строке и не сказал бы ничего.
 *
 * Корпус считается в тех же процентах, что урон: пул R значит «держит в 1 + R раз
 * больше». При равных ставках числа совпадают, и надпись остаётся одним числом.
 */
export function veteranBadge(
  factor: number | undefined,
  hull?: number,
): VeteranBadge | null {
  const percent = factor !== undefined && factor > 1 ? Math.round((factor - 1) * 100) : 0;
  const hullPercent = hull !== undefined && hull > 0 ? Math.round(hull * 100) : 0;
  if (percent <= 0 && hullPercent <= 0) return null;
  const text =
    percent > 0 && hullPercent > 0 && percent !== hullPercent
      ? `+${percent}%/+${hullPercent}%`
      : `+${Math.max(percent, hullPercent)}%`;
  const title =
    percent > 0 && hullPercent > 0
      ? t('battle.win.veteran-both', { n: percent, h: hullPercent })
      : percent > 0
        ? t('battle.win.veteran', { n: percent })
        : t('battle.win.veteran-hull', { h: hullPercent });
  return { glyph: GLYPH, text, percent, hullPercent, title };
}
