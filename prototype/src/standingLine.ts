/**
 * Живое положение игрока в верхней строке: место, счёт и когда строка перерисовывается
 * (REFM-191).
 *
 * Итоговый экран уже считает место вынесенной формулой (`placementOf` в `endScreen.ts`), а
 * кадр до сих пор считал его ВТОРОЙ раз вручную — та же сортировка, тот же `indexOf`,
 * набранные заново. Правила ниже собирают строку в одном месте; каждое чинит поломку,
 * которая ошибается ТИХО — интерфейс не падает, он показывает не то.
 *
 * 1. **Место берётся из ТОЙ ЖЕ формулы, что и на итоговом экране.** Две рукописные копии
 *    одной сортировки расходятся молча: живая строка говорит «3-е из 5», а конец матча
 *    объявляет другое место, и игрок не понимает, которой верить.
 * 2. **Пустая таблица очков — НЕТ строки места.** `indexOf` не нашёл себя ⇒ место 0, и
 *    напечатать его значило бы объявить «1-е из 0» до старта матча. Молчание честнее.
 * 3. **«Нужно ещё» не уходит в минус.** Перебор очков сверх порога — это победа, а не
 *    «нужно −40»; отрицательный остаток нечего показывать и не с чем сравнивать.
 * 4. **Порог достигнут ровно при нуле остатка.** Признак победы выводится из того же
 *    остатка, что показан игроку, а не из отдельного сравнения со счётом: два сравнения
 *    разъезжаются на округлении, и подсветка «победа» загорается не тогда.
 * 5. **Позывной падает на имя ДОМА, а не в пустоту.** Соло-места названы домом
 *    (`buildSetupConfig`), и пустое поле ввода оставило бы командира без имени вовсе.
 * 6. **Подпись перерисовки несёт КАЖДОЕ показываемое поле.** Это ключ кэша: поле, которое
 *    видно на экране, но не попало в подпись, замораживает строку на прошлом значении —
 *    и виноватым выглядит что угодно, кроме подписи.
 * 7. **Поля в подписи разделены символом, которого не бывает в тексте.** Без разделителя
 *    позывной «3» с местом 5 неотличим от позывного «35» без места: разные состояния дают
 *    одну подпись, и строка снова застывает.
 */
import { placementOf } from './endScreen';

/** Разделитель полей подписи: управляющий символ, недостижимый в позывном и числах. */
const FS = '\u0001';

export interface Standing {
  /** Место среди тех, у кого есть счёт; 0 — таблицы ещё нет (правило 2). */
  place: number;
  /** Сколько всего мест в таблице. */
  of: number;
  /** Мой счёт, округлённый до целого. */
  score: number;
  /** Сколько очков осталось до порога победы (правило 3). */
  need: number;
}

/** Правила 1 и 3: одна формула места с итоговым экраном + неотрицательный остаток. */
export function liveStanding(
  scores: Record<string, { total?: number } | undefined>,
  me: string,
  limit: number,
): Standing {
  const { place, of, total } = placementOf(scores, me);
  return { place, of, score: total, need: Math.max(0, limit - total) };
}

/** Правило 2: строку места печатаем, только когда место вообще есть. */
export function standingShown(place: number): boolean {
  return place >= 1;
}

/** Правило 4: порог взят ровно тогда, когда показанный остаток обнулился. */
export function atLimit(need: number): boolean {
  return need === 0;
}

/** Правило 5: позывной → имя дома → пусто. */
export function callsign(typed: string, seatName: string | undefined): string {
  return typed.trim() || seatName || '';
}

/** Правила 6–7: ключ кэша верхней строки — все её видимые поля через разделитель. */
export function topSignature(
  nick: string,
  place: number,
  of: number,
  score: number,
  day: number,
  eta: string,
): string {
  return [nick, `${place}/${of}`, score, day, eta].join(FS);
}
