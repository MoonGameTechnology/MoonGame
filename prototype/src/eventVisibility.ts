/**
 * Что игрок вообще узнаёт из журнала событий (REFM-86).
 *
 * `handleEvents` разбирает поток доменных событий, и почти каждая ветка начинается с
 * вопроса «а видит ли это игрок». Ответ везде складывался руками — `p.attacker === ME ||
 * p.defender === ME || known(loc)`, — и варианты этого выражения разошлись: где-то туман
 * учитывался, где-то нет, где-то по одному концу дуги, где-то по обоим.
 *
 * 1. **Своё видно ВСЕГДА.** Игрок — участник события, туман тут ни при чём.
 * 2. **Чужое видно только на опознанном узле.** Драка ботов за туманом — не моя
 *    разведка, и в журнал она попасть не должна.
 * 3. **Бой, в котором я участвовал, виден до КОНЦА.** Узел может уйти под туман, пока
 *    бой идёт; без отдельной памяти о «своих» боях исход схватки, в которую игрок влез,
 *    молча пропадёт из журнала.
 * 4. **Выстрел по дуге виден, если опознан ХОТЬ ОДИН конец** — стреляющий или цель.
 *    Залп, чья цель у меня на виду, я замечаю, даже не зная, откуда бьют.
 * 5. **Местная симуляция обязана повторять серверный фильтр.** В сети события фогуются
 *    на сервере; покажи соло больше — игрок выучит неверную картину мира и в сети решит,
 *    что интерфейс сломался.
 */

/** Участвую ли я: любой из перечисленных — это я (правило 1). */
export function isMine(sides: ReadonlyArray<string | null | undefined>, me: string): boolean {
  return sides.some((s) => s === me);
}

/** Обычное правило журнала: своё всегда, чужое — только на опознанном узле (правила 1–2). */
export function seen(mine: boolean, nodeKnown: boolean): boolean {
  return mine || nodeKnown;
}

/** Хвост боя: узел, где я дрался, остаётся видимым до конца (правило 3). */
export function seenTail(tracked: boolean, nodeKnown: boolean): boolean {
  return tracked || nodeKnown;
}

/** Выстрел по дуге: хватит опознанного конца — любого (правило 4). */
export function seenArc(fromKnown: boolean, toKnown: boolean): boolean {
  return fromKnown || toKnown;
}
