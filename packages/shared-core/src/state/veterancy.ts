import type { GameData } from '../data/schemas';
import type { Battle, GameState, PlayerId } from './gameState';
import { sideUnits } from '../util/combat';

/**
 * БОЕВАЯ НАДБАВКА ВЕТЕРАНА (PERK-3.1) — правило, а не его копия.
 *
 * Функция ЧИСТАЯ и живёт в `state/`, а не внутри модуля, по той же причине, по которой
 * там живёт `medalsOf` (VET-3): читателей у неё двое и они в разных слоях — сам множитель
 * в бою (`modules/veteran.ts`, ядро) и окно боя, которое показывает игроку, сколько он
 * получает (`createBattleModel`, оба клиента). Правило обязано у них совпадать до
 * единицы: покажи панель «+8%», а редьюсер посчитай +4% — игрок не заметит расхождения
 * никогда, и никакой тест его не поймает, потому что каждая половина верна сама по себе.
 *
 * Именно этим окно боя отличается от карточки стека: стек показывает СВОЮ выслугу, а
 * множитель принадлежит СТОРОНЕ целиком и зависит от всего её состава.
 */

/**
 * Среднее число пережитых боёв НА ЮНИТ у сил игрока `owner` в этом бою.
 *
 * Развеска ПО ГОЛОВАМ, а не по доле в залпе: `creditBattle` начисляет бой ПЛОСКО — +1
 * каждому живому стеку стороны, стрелял он или вёз десант, — значит платить по калибру
 * означало бы развести начисление и выплату одной механики.
 *
 * Следствие принимается, а не обходится: долив свежих кораблей в заслуженный флот
 * надбавку разбавляет. Это ТА ЖЕ цена удобства, что записана в правиле слияния стеков
 * VET-2 («долив свежих разводит честь подразделения по новым»).
 *
 * Одного владельца в бою может представлять НЕСКОЛЬКО сторон (совместный штурм, MSB-4),
 * поэтому обходятся все его стороны, а не первая найденная. Порядок обхода — порядок
 * массива `sides` (порядок входа в бой), то есть детерминированный.
 */
export function servedPerUnit(state: GameState, battle: Battle, owner: PlayerId): number {
  let units = 0;
  let served = 0;
  for (const side of battle.sides) {
    if (side.owner !== owner) continue;
    const stacks = sideUnits(state, side.ref);
    if (!stacks) continue;
    for (const stack of stacks) {
      // Отдельной проверки «выбитый стек не в счёт» тут НЕТ, и это проверено порчей:
      // взвешивание по `count` И ЕСТЬ это правило — стек из нуля голов не добавляет ни к
      // числителю, ни к знаменателю. Написанная сначала проверка `count <= 0` порчу не
      // уронила ни одним тестом, потому что ронять было нечего (тот же мёртвый сторож,
      // что уже снимали в VET-4).
      units += stack.count;
      served += stack.count * (stack.battles ?? 0);
    }
  }
  return units > 0 ? served / units : 0;
}

/**
 * Во сколько раз силы `owner` бьют сильнее за выслугу: `1 + ставка × средняя выслуга`.
 *
 * `1` значит «надбавки нет» — и у необстрелянных сил, и когда механика выключена данными
 * (`damagePerBattle: 0`). Для показа игроку это одно и то же: показывать «×1.00» не нужно
 * ни в том, ни в другом случае.
 */
export function veteranFactor(
  state: GameState,
  battle: Battle,
  owner: PlayerId,
  data: Pick<GameData, 'veteran'>,
): number {
  const rate = data.veteran.damagePerBattle;
  if (rate <= 0) return 1;
  const served = servedPerUnit(state, battle, owner);
  return served > 0 ? 1 + rate * served : 1;
}
