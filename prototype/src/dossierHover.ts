/**
 * Досье под указателем: чей ключ показывать и когда его менять (REFM-82).
 *
 * Одно и то же досье живёт в трёх местах: всплывашка у курсора, пристыкованная справа
 * панель на узком экране и модалка тапа на телефоне. Правила «что под указателем» у
 * первых двух РАЗНЫЕ, и именно поэтому их стоит назвать вслух — иначе разница читается
 * как опечатка и её «чинят».
 *
 * 1. **Уровень здания живёт в самом ключе:** `b:<id>:<lvl>`. Заголовок дописывает его
 *    пометкой уровня, а у не-здания и у ключа без третьего сегмента уровня нет. Ключ
 *    разбирают все три места показа, и разъехаться им нельзя.
 * 2. **Всплывашка у курсора живёт, только пока объект ПОД указателем.** Ушёл курсор в
 *    промежуток — подсказку прячем, иначе она висит над пустотой и врёт, о чём она.
 * 3. **Пристыкованная панель — наоборот: промежуток показанное НЕ гасит.** Курсор идёт
 *    между строками через пустоту, и панель мигала бы пустой на каждом переходе.
 * 4. **Досье без тела показывает только заголовок.** Голые имена (ресурсы, простые
 *    юниты) тела не имеют, и пустой блок под заголовком — это дырка в вёрстке.
 *    Правило про ВСПЛЫВАШКУ: у пристыкованной панели раскладка фиксированная, она
 *    держит блок тела всегда.
 * 5. **Уход указателя и закрытие панели сбрасывают наведение.** Иначе панель, открывшись
 *    снова, покажет досье объекта, которого под курсором давно нет.
 */

/** Где показывается досье: у курсора или в пристыкованной панели. */
export type HoverMode = 'cursor' | 'docked';

/** Уровень здания из ключа досье: `b:<id>:<lvl>` → `lvl`, всё прочее → 0 (правило 1). */
export function dossierLevel(key: string): number {
  if (!key.startsWith('b:')) return 0;
  return Number(key.split(':')[2]) || 0;
}

/** Куда переходит наведение и надо ли перерисовывать (правила 2–3). */
export function nextHover(
  mode: HoverMode,
  key: string | null,
  cur: string | null,
): { changed: boolean; hover: string | null } {
  if (mode === 'docked' && key === null) return { changed: false, hover: cur };
  return { changed: key !== cur, hover: key };
}

/** Рисовать ли блок тела во всплывашке (правило 4). */
export function showsBody(body: string): boolean {
  return body !== '';
}
