/**
 * Масштаб интерфейса ПК (UIX-2.1): во сколько раз голографический интерфейс крупнее
 * базового.
 *
 * Голографический интерфейс — единственный на ПК — стоял в масштабе 1 на любом мониторе:
 * медиана текста партии 12 px и при 1366×768, и при 2560×1440, окно науки — 10 px. На
 * большом экране игрок сидит дальше, и тот же текст читается мельче. Основа — XAG 101: при
 * 1080p текст от 18 px высоты глифа.
 *
 * 1. **Растёт с высотой окна: высота / 864.** 1366×768 — масштаб 1 (ниже не мельчим:
 *    раскладка ноутбука проверена именно там), 1920×1080 — 1,25, 2560×1440 — 1,667.
 * 2. **Не больше 2.** На 4K двукратного хватает, дальше окна займут весь экран.
 * 3. **Ширине раскладки не дают стать уже 1366 px.** Под зумом раскладка видит окно
 *    уменьшенным: браузер на половине монитора 2560×1440 (1280×1440) по одной высоте
 *    получил бы 1,667, и раскладке осталось бы 768 px — широкие окна вылезли бы за край,
 *    хотя медиа-запросы видят настоящие 1280 и узких правил не включают. Для экранов 16:9
 *    правило ничего не меняет: у них ширина / 1366 больше, чем высота / 864.
 * 4. **Нечисловой размер — масштаб 1.** Замер окна, которого нет, не должен ронять зум в NaN.
 */

/** Высота окна, при которой интерфейс в масштабе 1. */
export const PC_SCALE_BASE_HEIGHT = 864;
/** Уже этого раскладку под зумом не сжимают: столько она видит у ноутбука 1366×768. */
export const PC_SCALE_MIN_WIDTH = 1366;
/** Потолок масштаба. */
export const PC_SCALE_MAX = 2;

/** Масштаб голографического интерфейса ПК для окна `width × height` (CSS px), 1..2. */
export function pcScale(width: number, height: number): number {
  const fit = Math.min(height / PC_SCALE_BASE_HEIGHT, width / PC_SCALE_MIN_WIDTH);
  if (!Number.isFinite(fit)) return 1;
  // Три знака: дробь длиннее только дёргала бы стиль на каждом пикселе ресайза.
  return Math.round(Math.min(PC_SCALE_MAX, Math.max(1, fit)) * 1000) / 1000;
}
