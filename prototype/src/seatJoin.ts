/**
 * Выбранное место → адрес входа в матч (REFM-152).
 *
 * Одиннадцатый срез сетевой секции. Окно выбора дома (`seatPicker.ts`, REFM-49) уже
 * решает, КАКОЕ место достаётся игроку; здесь — что происходит вокруг этого выбора:
 * когда кнопка «Играть» вообще что-то значит и во что превращается нажатие. Обе части
 * стояли внутри обработчиков окна, вперемешку с показом и скрытием разметки.
 *
 * 1. **Пока дом не выбран, «Играть» заперта.** Пустой выбор отправил бы игрока на сервер
 *    без места — сервер выдал бы любое свободное, и человек оказался бы не тем домом, за
 *    который собирался играть. Лучше неактивная кнопка, чем чужая фракция.
 * 2. **Каждый заход в окно начинается с ЧИСТОГО выбора.** Окно живёт в разметке между
 *    заходами, и уцелевший выбор оставил бы «Играть» включённой с местом из ПРОШЛОГО
 *    матча: один тап — и игрок улетел бы не туда.
 * 3. **Выбор уходит в АДРЕС, поэтому экранируется.** Идентификатор матча, слот и фракция
 *    склеиваются в ссылку `?join=…&slot=…&faction=…`, которую разбирает загрузочный блок;
 *    любой из них может нести символ, ломающий запрос (тот же довод, что у `matchQuery.ts`
 *    и `netDial.ts`).
 * 4. **Фракции может не быть — и тогда её нет и в адресе.** Пустой параметр `faction=`
 *    сервер прочитал бы как «фракция задана и она пустая»; отсутствие параметра честно
 *    значит «оставь ту, что идёт с местом».
 * 5. **Совет учёных едет тем же правилом** (ENTRY-4): выбран — уходит строкой через
 *    запятую, не выбран — параметра нет вовсе. Совет выбирается В ЭТУ сессию и попадает
 *    в заявку на месте (`seat.claim`), поэтому он часть адреса входа, а не отдельного
 *    запроса: иначе между «сел» и «выбрал» появилось бы окно, в котором место уже занято,
 *    а состав ещё нет.
 */

/** Можно ли уже входить (правило 1). */
export function startEnabled(selectedSlot: string | null): boolean {
  return selectedSlot !== null;
}

/** Ссылка входа с выбранным местом (правила 3–5). */
export function joinHref(
  pathname: string,
  matchId: string,
  slot: string,
  faction: string | null,
  scientists: readonly string[] = [],
): string {
  const factionParam = faction ? `&faction=${encodeURIComponent(faction)}` : '';
  // Совет — одной строкой через запятую (сервер её так и разбирает). Пустой совет
  // параметра не даёт вовсе: `sci=` сервер прочитал бы как «выбор сделан и он пуст»,
  // а это другое утверждение, чем «не выбирал» (тот же довод, что у faction в правиле 4).
  const sciParam = scientists.length
    ? `&sci=${scientists.map((s) => encodeURIComponent(s)).join(',')}`
    : '';
  return `${pathname}?join=${encodeURIComponent(matchId)}&slot=${encodeURIComponent(slot)}${factionParam}${sciParam}`;
}
