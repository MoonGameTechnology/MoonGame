/** Что клиент знает о чужом флоте этого кадра. */
export interface FleetSighting {
  /** Сетевой матч: мир клиента — проекция сервера (`visibleState`). */
  net: boolean;
  /** Живое окно шпионажа по флотам хозяина. */
  spied: boolean;
  /** Опознан ли флот по зрению, посчитанному клиентом: узел, бой, круг мины или патруля. */
  local: () => boolean;
}

/**
 * Опознан ли флот: показывать ли его и его состав, а не одну сигнатуру.
 *
 * Окно шпионажа `fleets` по контракту ядра открывает флоты цели целиком — позицию и состав
 * (`espionage.ts`), и проекция отдаёт их целиком. Поэтому флот под окном опознан и в соло,
 * и в сети.
 *
 * В сети мир клиента — уже проекция сервера. Чужой флот попадает в неё, только если сервер
 * его опознал или открыто окно шпионажа; радарный контакт приходит отдельной отметкой, а не
 * флотом. Опознаёт сервер по ПОЛНОМУ миру, в том числе глазами, которых проекция зрителю не
 * отдаёт: ракетная мина союзника видна лишь вблизи (`mineFleetVisible`), а её круг в блоке
 * зрения считается. Пересчёт по проекции такой флот терял: сервер его прислал, а карта
 * прятала. Поэтому в сети флот опознан самим присутствием.
 *
 * Соло видит полный мир, и зрение клиента совпадает с ядром.
 */
export function fleetIdentified(s: FleetSighting): boolean {
  return s.net || s.spied || s.local();
}
