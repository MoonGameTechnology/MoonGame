/**
 * Часы кадра: когда мир идёт и на сколько он продвигается (REFM-87).
 *
 * `frame` вызывается на кадр rAF (за меню — реже, правило 9) и решает три разных вопроса,
 * которые в коде стояли вперемешку: крутить ли местную симуляцию, на сколько сдвинуть игровое
 * время и правдоподобен ли вообще разрыв между кадрами.
 *
 * 1. **Местная симуляция крутится только в СОЛО.** В сети часы, бой, стройка и все
 *    соперники принадлежат серверу — клиент лишь рисует его снимки, и второй,
 *    «свой» ход времени немедленно разъехался бы с авторитетным.
 * 2. **Пауза и баннер останавливают мир, решённый матч — тоже.** Доигрывать партию с
 *    показанным итогом нечестно: счёт уже объявлен.
 * 3. **Игровое время растёт от РЕАЛЬНОГО, помноженного на скорость.** Не «тик на кадр»:
 *    при просадке FPS мир обязан идти с той же быстротой, иначе на слабом телефоне сутки
 *    длятся дольше, чем на сильном.
 * 4. **Абсурдный разрыв между кадрами не считается.** Вкладка ушла в фон — `dt` там
 *    секунды и минуты; пустить его в среднее FPS значит показать чушь, а в спин орбит —
 *    провернуть корабли на пол-оборота одним скачком. **Ход мира — тоже** (AUD-23): за
 *    один кадр мир идёт не дальше {@link FPS_GAP_MS} реального времени. Бот соперника и
 *    драйверы боя (авто-штурм, столкновения, цепочки приказов) работают раз в кадр ПОСЛЕ
 *    шага, поэтому длинный шаг — это часы игры, в которых Рой не начинает ни одного боя.
 *    Разрыв бывает и без `visibilitychange`, которым игра ставит забег на паузу: браузер
 *    замораживает rAF в iframe площадки, прокрученном за край окна, и вкладка при этом
 *    остаётся «видимой». Полчаса за краем двигали мир на 75 игровых часов и выигрывали
 *    главу без боя. Правилу 3 срез не мешает, пока устройство держит хотя бы кадр в секунду.
 * 5. **Орбитальный спин живёт по ходу МИРА, а не кадра.** На паузе корабли замирают на
 *    кольцах; иначе застывшая карта продолжает шевелиться и врёт, что время идёт.
 * 6. **Отдельному потоку расчёта мир отмеряется так же.** Поток идёт шагами, и шаг занимает
 *    несколько кадров, поэтому кадры копят игровое время к следующему шагу (правило 3), но
 *    шаг берёт не больше одного правдоподобного кадра (правило 4). Иначе устройство, которое
 *    считает мир медленнее, чем тот идёт, удлиняло бы каждый следующий шаг, и шаги росли бы
 *    без конца; с потолком мир на таком устройстве идёт медленнее выбранной скорости, а
 *    экран не ждёт.
 * 7. **Мир потока экран берёт не чаще раза в {@link ADOPT_EVERY_MS}.** Поток присылает мир
 *    после каждого шага, а взятый мир кадр разбирает заново: зрение, доход, радары, панели. На
 *    большой карте слабого телефона это около 10 мс, и платил их больше половины кадров, с
 *    открытой картой — почти каждый. Движение между мирами досчитывают часы картинки
 *    (`netViewClock.ts`), как в сети, где снимок сервера приходит раз в секунду. Шаги потока
 *    правило не трогает: следующий уходит, как только пришёл прошлый. Пока камера движется, мир
 *    берётся не чаще раза в {@link ADOPT_MOVING_MS}: кадр жеста упирается в растр карты, и глаз
 *    в жесте следит за картой, а не за числами панелей. Часы картинки получают время мира
 *    потока с приходом каждого шага, а не со взятием мира: поправки от редкого взятия копились
 *    бы, и картинка дёргалась бы.
 * 8. **Мир идёт только в партии.** За меню — хабом, экраном входа, настройкой партии, меню
 *    Sector Zero — он стоит: его там не видно, а шаг мира с ботами, зрением и задачами — самая
 *    дорогая часть кадра. До первой партии за меню шёл мир, собранный на старте страницы, и на
 *    эмуляции телефона (ЦП вчетверо медленнее) его ход занимал под хабом около 40% главного
 *    потока (замер 2026-10-30). Соло-партию хаб и так ставит на паузу, а сетевой мир идёт у
 *    сервера (правило 1).
 * 9. **За полноэкранным меню кадр идёт редко.** Экран входа, хаб, меню Sector Zero и
 *    настройка партии на телефоне закрывают карту целиком: мир стоит (правило 8), карта не
 *    рисуется, и кадру там почти нечего делать. Но кадр, заказанный на каждый кадр экрана, сам
 *    заставляет браузер собирать кадр главным потоком, а с ним пересчитывать стили анимаций
 *    меню — даже тех, что крутит композитор. Поэтому за меню следующий кадр ждёт
 *    {@link MENU_FRAME_MS}. Касание, клавиша и смена экрана будят кадр сразу: вход в партию не
 *    ждёт паузы, а Back взводится к первому кадру после нажатия. Кадры меню и первый кадр
 *    после него не идут в средний FPS: по нему карта отмеряет работу на кадр, а разрыв меню —
 *    пауза, а не медленный кадр. Второй кадр после меню начинает среднее заново: прежнее
 *    осталось от прошлой партии или от умолчания страницы, а карта за заставкой входа
 *    отмеряет себе работу по нему уже в первых кадрах.
 */

/** Разрыв больше этого — не кадр, а возвращение из фона. */
export const FPS_GAP_MS = 1000;

/** Правдоподобен ли разрыв между кадрами (правило 4). */
export function saneGap(dt: number): boolean {
  return dt > 0 && dt < FPS_GAP_MS;
}

/** Крутится ли местная симуляция (правила 1–2 и 8): `inMatch` — партия на экране, а не меню. */
export function simRuns(
  net: boolean,
  speed: number,
  banner: boolean,
  ended: boolean,
  inMatch: boolean,
): boolean {
  return inMatch && !net && speed > 0 && !banner && !ended;
}

/** Куда двигать игровое время: реальные миллисекунды × скорость (правило 3), но не больше
 *  одного правдоподобного кадра за раз (правило 4). Нулевой, отрицательный и нечисловой
 *  разрыв мир не двигает. */
export function advanceTarget(now: number, dt: number, speed: number, hourMs: number): number {
  if (!(dt > 0)) return now;
  return now + (Math.min(dt, FPS_GAP_MS) / 1000) * speed * hourMs;
}

/** Игровое время, накопленное к следующему шагу отдельного потока (правило 6): кадр
 *  добавляет столько же, сколько сдвинул бы мир сам, а всё вместе — не больше одного
 *  правдоподобного кадра. */
export function stepBacklog(backlog: number, dt: number, speed: number, hourMs: number): number {
  return Math.min(
    advanceTarget(backlog, dt, speed, hourMs),
    advanceTarget(0, FPS_GAP_MS, speed, hourMs),
  );
}

/** Чаще этого кадр мир отдельного потока не берёт (правило 7). */
export const ADOPT_EVERY_MS = 100;

/** Чаще этого кадр не берёт мир потока, пока камера движется (правило 7). */
export const ADOPT_MOVING_MS = 250;

/** Пора ли кадру взять присланный потоком мир (правило 7): прошлый он взял в `adoptedAt`,
 *  `moving` — камера движется. */
export function adoptDue(now: number, adoptedAt: number, moving: boolean): boolean {
  return now - adoptedAt >= (moving ? ADOPT_MOVING_MS : ADOPT_EVERY_MS);
}

/** Идёт ли мир для орбитального спина: сеть всегда, соло — пока не на паузе (правило 5). */
export function spinRuns(net: boolean, speed: number, banner: boolean): boolean {
  return net || (speed > 0 && !banner);
}

/** Сглаженный FPS: экспоненциальное среднее по разрыву кадра. */
export function fpsNext(ema: number, dt: number): number {
  return ema * 0.9 + (1000 / dt) * 0.1;
}

/** Пауза кадра за полноэкранным меню (правило 9). */
export const MENU_FRAME_MS = 200;

/** Через сколько мс заказать следующий кадр (правило 9): `covered` — карту закрывает
 *  полноэкранное меню. Ноль — к следующему кадру экрана. */
export function nextFrameDelay(covered: boolean): number {
  return covered ? MENU_FRAME_MS : 0;
}

/** Идёт ли разрыв в средний FPS (правила 4 и 9): `sinceMenu` — сколько кадров прошло с кадра
 *  за меню (0 — этот кадр сам за меню, 1 — первый после него). */
export function fpsCounts(dt: number, sinceMenu: number): boolean {
  return saneGap(dt) && sinceMenu >= 2;
}

/** Средний FPS после кадра (правила 4 и 9): второй кадр после меню начинает его заново. */
export function fpsAfter(ema: number, dt: number, sinceMenu: number): number {
  if (!fpsCounts(dt, sinceMenu)) return ema;
  return sinceMenu === 2 ? 1000 / dt : fpsNext(ema, dt);
}
