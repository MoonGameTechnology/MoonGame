/**
 * Совет научных руководителей для БОТОВОГО места (BAL-12).
 *
 * Посвящение совета — первый необратимый выбор игрока (GDD §5.2): он делается ДО точки
 * старта и внутри матча неизменен. Человеку его собирает окно `sciPick.ts`; боту —
 * никто, и до этого модуля ботовые места уезжали в матч вообще без совета. В self-play
 * оба места ботовые, поэтому `technologyLock` отбивал каждый `has_scientist`-узел кодом
 * `E_CONDITIONS_UNMET`, и целый слой дерева не попадал в измерение ни разу.
 *
 * Выбор — функция СИДА матча и id места, а не среза с начала каталога. Это инвариант
 * детерминизма (`CLAUDE.md` №1) в его практическом виде: партия обязана воспроизводиться
 * по сиду, поэтому перестановка двух записей в `data/scientists.json` не имеет права её
 * изменить. Отсюда хеш по всем трём частям и сортировка по нему: порядок входа влияет
 * только на ничьи, а те разрешаются по id.
 */
import { COUNCIL_SIZE } from './sciPick';

/** FNV-1a, 32 бита. `Math.random`/`Date.now` тут запрещены по построению задачи —
 *  случайность обязана приходить из сида, а не из окружения. */
function hash(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

/**
 * Кого бот посвятит в совет. Каталог короче совета — отдаёт что есть: ростер учёных
 * неполон by design (BAL-13), и мягкая деградация тут дешевле отказа.
 */
export function botCouncil(
  seed: string,
  seatId: string,
  scientistIds: readonly string[],
  size: number = COUNCIL_SIZE,
): string[] {
  return scientistIds
    .map((id) => ({ id, key: hash(`${seed}|${seatId}|${id}`) }))
    .sort((a, b) => a.key - b.key || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .slice(0, Math.max(0, size))
    .map((x) => x.id);
}
