/**
 * Что значит выделить флот и как выделение меняется по Ctrl-клику (REFM-163).
 *
 * Выделение — вход почти во все приказы, и правила у него были размазаны по трём
 * функциям `main.ts` (`setFleetSelection`, `toggleFleetInSelection`, `clearSelection`),
 * причём главное — почему «ровно один» и «несколько» это РАЗНЫЕ состояния — не было
 * записано нигде.
 *
 * 1. **Выделить можно только СВОЁ.** Чужой флот в наборе — это приказ, который ядро всё
 *    равно отклонит: фильтр на входе делает невыразимым то, чего не бывает, вместо того
 *    чтобы ловить это отказом на каждом приказе. (Осмотр чужого флота идёт другим путём —
 *    панель, `panelSelect.ts`; там владелец не проверяется намеренно.)
 * 2. **Ровно один флот — это ещё и «текущий флот».** У одиночного флота своя карточка со
 *    всеми приказами, у группы — список; выделив один, игрок ждёт именно карточку. И
 *    наоборот: держать «текущий» при группе значило бы, что приказ уходит одному флоту из
 *    нескольких выделенных — не тому, на который игрок смотрит.
 * 3. **Флот и мир не выделяются вместе.** Боковая панель одна, и приказ «сюда» при
 *    выделенных сразу флоте и мире читался бы двумя разными способами.
 * 4. **Ctrl-клик СКЛАДЫВАЕТ текущий одиночный флот в группу, а не заменяет его.** Иначе
 *    первый выбранный флот терялся бы ровно в тот момент, когда игрок собирает из него
 *    группу, — самый частый жест перед общим приказом.
 * 5. **Ctrl-клик по ЧУЖОМУ не трогает набор вовсе.** Не «добавить и отфильтровать»:
 *    иначе промах по чужому флоту молча схлопывал бы текущий одиночный в группу из
 *    одного — состояние сменилось бы, а игрок не просил ни о чём.
 */

/** Что выделено: подсвеченный набор и «текущий» флот, если он один (правило 2). */
export interface Selection {
  /** Все выделенные — ровно то, что подсвечено на карте. */
  picked: string[];
  /** Единственный выделенный, иначе `null`. */
  single: string | null;
}

/** Пустое выделение — им же гасится и выбор мира (правило 3). */
export const NO_SELECTION: Selection = { picked: [], single: null };

/** Выделение из списка: только своё (правило 1), «текущий» — если он один (правило 2). */
export function selectFleets(ids: readonly string[], mine: (id: string) => boolean): Selection {
  const picked = ids.filter(mine);
  return { picked, single: picked.length === 1 ? (picked[0] ?? null) : null };
}

/**
 * Набор после Ctrl-клика по `id` (правила 4–5): текущий одиночный складывается в группу,
 * `id` добавляется или убирается. `null` — по чужому флоту, набор не трогаем вовсе.
 */
export function toggleInSelection(
  current: Selection,
  id: string,
  mine: (id: string) => boolean,
): string[] | null {
  if (!mine(id)) return null; // правило 5
  const next = new Set(current.picked);
  if (current.single) next.add(current.single); // правило 4
  if (next.has(id)) next.delete(id);
  else next.add(id);
  return [...next];
}
