/**
 * Из чего складывается эмблема флота: что считается кораблём, а что грузом (REFM-115).
 *
 * У эмблемы три числа — корабли, ромбики крыла в хвосте груза и десант, — и все три
 * считались четырьмя выражениями подряд в кадровом цикле. Из них не читалось, что первые
 * два ВЗАИМНО ИСКЛЮЧАЮТ друг друга: одна и та же эскадрилья попадает то в боевой счёт,
 * то в груз, и решает это наличие корпусов.
 *
 * 1. **Эскадрильи НА БОРТУ — груз, а не боевая линия.** Пока во флоте есть хоть один
 *    корпус, эскадрильи уходят из счёта кораблей в хвост груза: боевой счёт обязан
 *    показывать, сколько корпусов встанет в линию, а не сколько всего единиц числится.
 *    Иначе носитель с полным трюмом читался бы как втрое больший флот, чем он есть.
 * 2. **Чистое крыло в полёте САМО ЕСТЬ флот.** Корпусов нет — значит эскадрильи и есть
 *    корабли: посчитай их грузом, и ударное крыло показало бы «0 кораблей» и перестало
 *    читаться как сила. Хвоста груза у него при этом нет — везти некому и не на чем.
 * 3. **Десант считается ОТДЕЛЬНО.** Он не корабль и не эскадрилья: у него своя цифра,
 *    потому что он решает не бой в космосе, а судьбу мира под ним.
 */

/** Стопка единиц: что и сколько. */
export interface UnitStack {
  unit: string;
  count: number;
}

/** Три числа эмблемы. */
export interface EmblemTally {
  /** Сколько кораблей показывает счётчик (правила 1–2). */
  ships: number;
  /** Сколько ромбиков крыла едет в хвосте груза (правила 1–2). */
  wingPips: number;
  /** Сколько десанта на борту (правило 3). */
  troops: number;
}

const sum = (stacks: readonly UnitStack[]): number => stacks.reduce((a, st) => a + st.count, 0);

/**
 * Разложить состав флота на числа эмблемы (правила 1–3). `isWing` отвечает, эскадрилья
 * ли эта единица — предикат приходит снаружи, чтобы модуль не зависел от игровых данных.
 */
export function emblemTally(
  units: readonly UnitStack[],
  landing: readonly UnitStack[],
  isWing: (unit: string) => boolean,
): EmblemTally {
  const all = sum(units);
  const wingAboard = sum(units.filter((st) => isWing(st.unit)));
  const hulls = all - wingAboard;
  // Развилка правил 1–2: корпуса есть — крыло едет грузом; корпусов нет — крыло и есть флот.
  return {
    ships: hulls > 0 ? hulls : all,
    wingPips: hulls > 0 ? wingAboard : 0,
    troops: sum(landing),
  };
}
