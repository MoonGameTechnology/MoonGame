/**
 * Когда лист перестраивается и что при этом нельзя потерять (REFM-188).
 *
 * `renderPanel` гоняется КАЖДЫЙ кадр, а разметку собирает целиком, поэтому вокруг неё
 * выросли четыре решения о кэше — и все четыре стояли отдельными присваиваниями в разных
 * концах функции. Инвалидация кэша ошибается тихо: панель не падает, она просто не
 * появляется или прыгает под пальцем, и виноватым выглядит что угодно, кроме кэша.
 *
 * 1. **Перестраиваем, только если разметка ИЗМЕНИЛАСЬ.** Безусловный `innerHTML` каждые
 *    16 мс рвал бы тап под пальцем (узел подменяется между нажатием и отпусканием) и
 *    сбрасывал бы прокрутку в начало.
 *
 * 2. **Тронул DOM листа — гаси кэш ДОСЬЕ.** `innerHTML` пересоздаёт узел `#pdesc`, и
 *    старый кэш «такое досье уже нарисовано» становится враньём про НОВЫЙ пустой узел:
 *    досье просто не появится, пока игрок не наведётся на другой объект. Гасить надо в
 *    ОБОИХ переходах — и при перестройке, и при закрытии, — а забывается это как раз во
 *    втором.
 *
 * 3. **Закрытый лист забывает ВСЁ.** Иначе при следующем открытии кэш скажет «такая
 *    разметка уже нарисована», а DOM пуст — и лист откроется пустым.
 *
 * 4. **Прокрутка переживает перестройку, но восстанавливается только НЕНУЛЕВАЯ.** Пока
 *    что-то строится, отсчёт меняет разметку постоянно, и без переноса позиции список
 *    прыгал бы наверх — прокрутить его было бы невозможно. Писать же ноль незачем: это
 *    не восстановление, а лишняя запись поверх того, что браузер и так сделал сам.
 *
 * Оговорка про область: `lastPanelHtml` гасится ещё примерно из полутора десятков мест
 * (после приказов, смены выделения, открытия окон) — там это «я поменял мир, перерисуй».
 * Модуль отвечает не за них, а за ДВА перехода внутри самой `renderPanel`, где кэш листа
 * и кэш досье обязаны двигаться вместе.
 */

/** Что нарисовано прямо сейчас: разметка листа и разметка досье. */
export interface PanelCache {
  panel: string;
  objDesc: string;
}

/** Кэш закрытого листа: пусто и там, и там (правила 2–3). */
export const FORGOTTEN: PanelCache = { panel: '', objDesc: '' };

/** Нужна ли перестройка: разметка отличается от нарисованной (правило 1). */
export function panelChanged(html: string, cached: string): boolean {
  return html !== cached;
}

/**
 * Кэш после перестройки: лист помнит новую разметку, досье ЗАБЫТО (правило 2).
 * Возвращается целиком, чтобы забыть досье было нельзя — оно в том же значении.
 */
export function afterRebuild(html: string): PanelCache {
  return { panel: html, objDesc: '' };
}

/** Восстанавливать ли прокрутку: только ненулевую (правило 4). */
export function keepScroll(prev: number): boolean {
  return prev > 0;
}
