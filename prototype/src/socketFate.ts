/**
 * Чей это сокет и что делать, когда он закрылся (REFM-143).
 *
 * У клиента в любой момент ровно ОДИН живой сокет матча, но старые не исчезают мгновенно:
 * игрок жмёт «Подключиться» ещё раз, срабатывает переподключение, сервер закрывает
 * прежнюю дверь с опозданием. Поэтому каждый обработчик начинался с одной и той же
 * проверки, а разбор «что значит это закрытие» стоял лесенкой условий прямо в нём.
 *
 * 1. **Устаревший сокет НЕ ТРОГАЕТ общее состояние.** Его позднее закрытие погасило бы
 *    таймеры уже живого соединения и выбросило оверлей поверх работающей игры; его
 *    снимок переписал бы состояние чужой сессией. Проверка нужна в КАЖДОМ обработчике —
 *    снимок, закрытие, ошибка, — потому что опоздать может любой из них.
 * 2. **«Сокет открылся» ещё НЕ значит «нас впустили».** Сервер может отвергнуть вход
 *    (место занято, матча нет), и открытие сокета об этом ничего не говорит: впустили
 *    нас только с первым снимком. Иначе отвергнутый вход мигнёт игроку картой.
 * 3. **Закрытие читается по трём вещам:** мы были в матче или нет, закрыл ли его САМ
 *    игрок, и успели ли нас впустить. Отсюда четыре разных исхода — и путать их нельзя:
 *    молча переподключаться после «выйти» значит не отпустить игрока из матча, а
 *    показать «отключено» на обрыве связи значит соврать, будто он вышел сам.
 * 4. **Отказ во входе НЕ стирает причину.** Если нас так и не впустили, в строке статуса
 *    уже лежит ответ сервера — трогать её нечем, иначе игрок останется без объяснения,
 *    почему он не в матче.
 */

/** Что известно о закрывшемся сокете. */
export interface CloseState {
  /** Это текущий сокет клиента (а не переживший своё старый). */
  current: boolean;
  /** Мы были В МАТЧЕ: сервер нас впустил и снимки шли. */
  inMatch: boolean;
  /** Закрытие затеял сам игрок (кнопка «выйти»). */
  userClosed: boolean;
  /** Идёт цикл переподключения. */
  reconnecting: boolean;
  /** Этот сокет успел получить приветственный снимок. */
  admitted: boolean;
}

/**
 * Что делать с этим закрытием (правила 1, 3–4):
 * — `ignore` — сокет устарел, не трогаем ничего;
 * — `closed-by-user` — игрок вышел сам: сказать об этом и показать экран подключения;
 * — `reconnect` — связь оборвалась в матче: молча переподключаться к своему месту;
 * — `retry-admit` — попытка переподключения не дошла до входа: отступить и повторить;
 * — `keep-reason` — нас не впустили: оставить ответ сервера в строке статуса.
 */
export type CloseAction = 'ignore' | 'closed-by-user' | 'reconnect' | 'retry-admit' | 'keep-reason';

export function closeAction(st: CloseState): CloseAction {
  if (!st.current) return 'ignore';
  if (st.inMatch) return st.userClosed ? 'closed-by-user' : 'reconnect';
  if (st.reconnecting && !st.admitted) return 'retry-admit';
  return 'keep-reason';
}

/** Наш ли это сокет (правило 1) — та же проверка для снимка, закрытия и ошибки. */
export function isCurrentSocket<T>(sock: T, current: T | null): boolean {
  return sock === current;
}
