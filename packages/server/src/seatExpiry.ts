import type { Action, GameState } from '@void/shared-core';

/**
 * Истечение неподтверждённой заявки на место (ENTRY-3, правило 7).
 *
 * Игрок открывает ссылку на сессию, выбирает мир, дом и совет — и может не прийти.
 * Заявка при этом уже записана, место числится занятым, и без окна оно стояло бы
 * запертым до конца партии: в матче на десять мест несколько таких «призраков» убивают
 * сессию, а браузер матчей показывает её полной.
 *
 * Место закрепляется за игроком не заявкой, а ПОПАДАНИЕМ НА КАРТУ (`seat.confirm`
 * ставит `seated` при реальном входе в мир). Всё, что заявлено, но не подтверждено
 * дольше окна, возвращается в оборот.
 *
 * 1. **Окно считается в РЕАЛЬНОМ времени.** Игровые часы бегут в `timeScale` раз
 *    быстрее, и на плейтестовом ×100 «сутки» прошли бы за пятнадцать реальных минут —
 *    человек не успел бы дойти до компьютера. Реальное выводится из игрового делением,
 *    ровно как считает окно входа (`MatchRegistry.entryOpen`): настенных часов в
 *    состоянии нет и быть не должно, иначе реплей станет невоспроизводимым.
 * 2. **Закреплённое место не отзывается никогда.** Дошёл до карты — кресло твоё, даже
 *    если потом ушёл спать на неделю; за отсутствующего играет Хранитель или серверный
 *    ИИ, а место остаётся. Отбирать его — отдельная механика с другими правилами.
 * 3. **Ровно на границе не отпускаем.** Строгое «больше окна»: на равенстве исход
 *    зависел бы от того, в какой момент тика мы посмотрели, а игрок не должен терять
 *    место из-за дребезга планировщика.
 * 4. **Порядок обхода стабилен.** Места сортируются по идентификатору: пачка действий
 *    должна быть одинаковой от прогона к прогону, иначе лог реплея зависит от обхода
 *    ключей объекта.
 */

/** Окно по умолчанию — сутки РЕАЛЬНОГО времени. */
export const SEAT_CLAIM_WINDOW_MS = 24 * 60 * 60 * 1000;

/** Сколько РЕАЛЬНОГО времени прошло с заявки (правило 1). */
function realElapsedMs(state: GameState, claimedAt: number, timeScale: number): number {
  const gameElapsed = state.time - claimedAt;
  // Шкала ≤0 бессмысленна и означала бы делённое на ноль «бесконечно давно»: считаем
  // такую партию идущей в реальном времени, а не отпускаем все места разом.
  return timeScale > 0 ? gameElapsed / timeScale : gameElapsed;
}

/** Места, чья заявка просрочена: их пора вернуть в оборот (правила 1–4). */
export function expiredSeatClaims(
  state: GameState,
  timeScale: number,
  windowMs: number = SEAT_CLAIM_WINDOW_MS,
): Array<{ playerId: string; action: Action }> {
  const out: Array<{ playerId: string; action: Action }> = [];
  for (const playerId of Object.keys(state.players).sort()) {
    const player = state.players[playerId];
    if (!player) continue;
    if (player.claimedAt === undefined) continue; // место не заявляли
    if (player.seated) continue; // правило 2
    if (realElapsedMs(state, player.claimedAt, timeScale) <= windowMs) continue; // правило 3
    out.push({
      playerId,
      // Идентификатор несёт момент заявки: две разные заявки на одно место (взяли,
      // отпустили, взяли снова) дают разные id, поэтому квитанции не сдедупят вторую
      // как повтор первой.
      action: {
        id: `seat-release:${playerId}:${player.claimedAt}`,
        type: 'seat.release',
        playerId,
        payload: {},
        issuedAt: state.time,
      },
    });
  }
  return out;
}
