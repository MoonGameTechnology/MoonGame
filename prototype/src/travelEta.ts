/**
 * Сколько ещё лететь: оценка времени в пути с учётом форс-марша (REFM-67).
 *
 * Одно и то же правило нужно в двух местах — в карточке флота (строка «в пути»,
 * `pn-eta`) и в таймлайне режима «Приказ» (когда флот начнёт исполнять план). Раньше
 * каждое считало его своими руками, и разъехаться они могли молча.
 *
 * 1. **ТЕКУЩИЙ ЛЕЙН АВТОРИТЕТЕН И ФОРС-МАРШЕМ НЕ УСКОРЯЕТСЯ.** Прибытие по нему уже
 *    расписано сервером в `arrivesAt`. Ускорь его на клиенте — и игрок увидит время,
 *    которого сервер не обещал; буст действует со СЛЕДУЮЩЕГО лейна.
 * 2. **Ускоряется только остаток маршрута** за текущим лейном — он ещё не расписан,
 *    и там форс-марш реально работает. Выключил буст — оценка честно удлиняется.
 * 3. **«Не знаю» — это не «мгновенно».** Маршрута нет (`null`) → `null`, а не ноль:
 *    иначе недостижимая цель выглядела бы как цель под боком.
 * 4. **Ожидание не бывает отрицательным.** Кадр может отстать от расписания (вкладка
 *    спала, сервер опередил) — просроченное прибытие это ноль, а не «минус два часа».
 */

/**
 * Остаток маршрута ЗА текущим лейном, в часах (правила 2–3). `rawRestH` — сырая оценка
 * (`null`, если маршрута нет); `mult` — множитель форс-марша, применяется только здесь.
 */
export function restRouteHours(rawRestH: number | null, boosted: boolean, mult: number): number {
  if (rawRestH == null) return 0; // маршрут за лейном не найден — считаем, что добавлять нечего
  return boosted ? rawRestH / mult : rawRestH;
}

/**
 * Часы до конца ВСЕГО перелёта: авторитетное прибытие по текущему лейну (правила 1, 4)
 * плюс остаток маршрута.
 */
export function arrivalHours(
  arrivesAt: number,
  now: number,
  hourMs: number,
  restH: number,
): number {
  return Math.max(0, (arrivesAt - now) / hourMs) + restH;
}

/** Оценка перелёта с бустом; `null` остаётся `null` — «не знаю» ≠ «мгновенно» (правило 3). */
export function marchHours(rawH: number | null, boosted: boolean, mult: number): number | null {
  if (rawH == null) return null;
  return boosted ? rawH / mult : rawH;
}
