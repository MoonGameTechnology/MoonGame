/**
 * Чем клиент представляется серверу при дозвоне в матч (REFM-142).
 *
 * Адрес сокета — это не «склеить строку»: в нём лежит СПОСОБ опознать игрока, и способов
 * два, взаимоисключающих. Собирался он прямо в `connect()` вперемешку с записью в
 * хранилище и показом статуса — а от того, что попадёт в адрес, зависит, впустят игрока
 * или отвергнут.
 *
 * 1. **Два способа представиться, и они НЕ СМЕШИВАЮТСЯ.** В режиме аккаунтов дозвон идёт
 *    с коротким токеном, выписанным на этот матч; позывной и билет места сервер там
 *    отвергнет. В режиме позывных наоборот: сервер сам сопоставляет имя с местом и
 *    возвращает его в приветствии. Послать оба — значит получить отказ вместо входа.
 * 2. **Билет места привязан к ТРОЙКЕ «сервер + матч + позывной».** Он выписан на
 *    конкретное место конкретного матча: храни его под общим ключом — и клиент предъявит
 *    билет от чужого матча, а сервер откажет, причём выглядеть это будет как «место
 *    занято».
 * 3. **Билет прикладывают, только если он есть.** Первый вход его ещё не получил, и
 *    пустой параметр в адресе сервер разбирал бы как «предъявлен пустой билет».
 * 4. **Всё, что уходит в адрес, ЭКРАНИРУЕТСЯ.** Позывной вводит человек: `&`, `?` или
 *    пробел в нём иначе расклеят адрес — и в лучшем случае игрок не войдёт, в худшем
 *    попадёт не в тот матч.
 */

/** Как игрок представляется: токеном (режим аккаунтов) или позывным с билетом места. */
export type DialIdentity =
  { kind: 'token'; token: string } | { kind: 'nick'; nick: string; ticket: string | null };

/**
 * Ключ хранилища для билета места (правило 2): билет годится только для той же тройки,
 * для которой был выписан.
 */
export function seatTicketKey(base: string, matchId: string, nick: string): string {
  return `void.ticket.${base}|${matchId}|${nick}`;
}

/** Адрес дозвона в матч (правила 1, 3–4). */
export function dialUrl(base: string, matchId: string, who: DialIdentity): string {
  const at = `${base}/matches/${encodeURIComponent(matchId)}`;
  if (who.kind === 'token') return `${at}?token=${encodeURIComponent(who.token)}`;
  const nick = `${at}?nick=${encodeURIComponent(who.nick)}`;
  return who.ticket ? `${nick}&ticket=${encodeURIComponent(who.ticket)}` : nick;
}

/**
 * Кем представляться при этом дозвоне (правило 1). Токен есть только в режиме аккаунтов и
 * только сразу после того, как его выписали, — иначе идём позывным.
 */
export function dialIdentity(
  accountsMode: boolean,
  joinToken: string | null,
  nick: string,
  ticket: string | null,
): DialIdentity {
  return accountsMode && joinToken
    ? { kind: 'token', token: joinToken }
    : { kind: 'nick', nick, ticket };
}
