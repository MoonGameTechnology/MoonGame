/**
 * Темп ЗАБЕГА — с какой скоростью идёт его мировой клок (PVR-2.2). Чистое решение
 * обоих клиентов.
 *
 * **Почему у забега своя скорость.** Соло-песочница открывается на ×10, и это верно для
 * неё: там играют в своё удовольствие, часами. Забег — другой продукт: решение владельца
 * (§0.3 `sector-zero-roadmap.md`) требует ПОЛНОГО прохождения за 25–35 минут, а
 * ускорение — вдвое быстрее обычного темпа (решение 2026-09-25: прежние ×1,5 на экране
 * почти не отличались от ▶). На ×10 тот же забег идёт около четырнадцати часов, то есть
 * дефолт песочницы делает его не «долгим», а несуществующим.
 *
 * **Откуда взялись именно эти множители.** Забег нельзя пройти быстрее, чем придёт
 * последняя волна: десять волн с шагом шесть игровых часов — это {@link RUN_SPINE_HOURS}
 * часов, и ниже этого числа не опускается никто. Сверху — хвост: удержание после
 * последней волны, {@link RUN_TAIL_HOURS} часов. Значит пройденный забег живёт
 * 60–72 игровых часа, и множители подобраны так, чтобы ВЕСЬ этот отрезок попал в
 * названные владельцем минуты. Проверено тестом рядом, а не на глаз.
 *
 * Здесь только числа и арифметика — ни DOM, ни таймеров: кто и как крутит часы, решает
 * клиент.
 */

/** Игровых часов до последней волны: 10 волн × 6 часов (`data/modes.json`). Пройти
 *  забег быстрее нельзя физически — это его хребет. */
export const RUN_SPINE_HOURS = 60;

/** Хвост после последней волны — УДЕРЖАНИЕ: столько часов игрок держит мир после
 *  десятой волны, и забег засчитан (PVR-2.5, решение владельца 2026-09-23 «победа —
 *  выстоять»). Это правило режима, а не оценка: число живёт в `data/modes.json`
 *  (`pve_waves.pve.holdHours`), а тест рядом не даёт им разойтись. Раньше здесь стояли
 *  25 часов «контратаки и зачистки улья» — оценкой, потому что пройти забег зачисткой
 *  не удавалось ни одному прогону. Зачистка осталась ранним финишем внутри того же
 *  отрезка. */
export const RUN_TAIL_HOURS = 12;

/** Обычный темп забега. */
export const RUN_SPEED_NORMAL = 150;

/** Ускорение ▶▶ — ровно вдвое быстрее обычного (решение владельца 2026-09-25: «скорость
 *  на второй стрелочке не сильно быстрее»). Прежние ×1,5 выводились из полос 25–35 и
 *  15–25 минут, но на экране читались как та же скорость; вдвое — пройденный забег за
 *  12–15 минут. */
export const RUN_SPEED_FAST = 300;

/** Дев-темп ▶▶▶ — только в дев-забеге дев-сборки (заказ владельца 2026-09-24): вдесятеро
 *  быстрее обычного, весь забег — меньше трёх минут. Нужен, чтобы проверять поздние волны и
 *  итоги, а не ждать их; игроку эта кнопка не достаётся, и в полосы владельца он не входит. */
export const RUN_SPEED_DEV = 1500;

/**
 * Во сколько раз в забеге быстрее летает ВСЁ на карте — флоты игрока и Роя, вылеты
 * челноков (PVR-2.3, решение владельца 2026-09-23).
 *
 * Темп часов забега ({@link RUN_SPEED_NORMAL}) ускорил мир целиком, но переход между
 * соседними мирами так и остался в игровых часах главы: обычный перегон — около 30 часов,
 * то есть 12 реальных минут из забега на 25–35. Для PvE такое «движение часами»
 * сомнительно (владелец). Множитель бьёт только по скорости, а не по часам: волны,
 * стройка и исследования идут в прежнем темпе, иначе сдвинулся бы хребет забега.
 *
 * Это правило МИРА (ядро считает по нему ноги), но число — решение продукта Sector Zero,
 * поэтому оно лежит здесь, рядом с темпом забега, а в ядро едет конфигом матча
 * (`MatchConfig.travelSpeedFactor`). Онлайн-партия на том же режиме `pve_waves` его не
 * получает.
 */
export const RUN_TRAVEL_SPEED = 5;

/**
 * Сколько РЕАЛЬНЫХ минут занимают `hours` игровых часов при множителе `mult`.
 *
 * Основание — `PLAY_BASE` прототипа: ×1 это настенные часы, то есть один игровой час за
 * один реальный. Отсюда вся арифметика темпа и берётся, и держать её здесь честнее, чем
 * пересчитывать в уме при каждой правке множителя.
 */
export function runMinutes(hours: number, mult: number): number {
  return (hours * 60) / mult;
}
