/**
 * Что значит «штурмовать» для каждого флота группы (REFM-167).
 *
 * Штурм — приказ с двумя исходами, как и слияние (`mergeOrders.ts`): кто уже у цели,
 * штурмует сейчас, остальные летят и штурмуют по прибытии. Но есть и третий, менее
 * очевидный слой — КОМУ и СКОЛЬКО РАЗ жаловаться, — и он стоял в `dispatchAssault`
 * одной переменной-защёлкой посреди цикла.
 *
 * 1. **Кто уже стоит у цели — штурмует НЕМЕДЛЕННО.** Тот же довод, что у слияния: делать
 *    сейчас то, что можно сделать сейчас. «У цели» значит и стоит там, И никуда не летит:
 *    отбывающий флот целью уже не владеет.
 * 2. **У стоящего спрашивают ЯДРО, а не проверяют десант руками.** Приказ издаётся сейчас,
 *    значит ядро может ответить точно и про всю связку запретов сразу (RULES-4); ручная
 *    проверка «есть ли десант» разошлась бы с настоящим набором причин отказа — и разошлась
 *    бы молча, в пользу более слабой проверки.
 * 3. **Летящему ядро ответить НЕ МОЖЕТ — флот ещё не там.** Поэтому для него это не отказ,
 *    а ПРЕДУПРЕЖДЕНИЕ: приказ всё равно уходит, потому что за время полёта десант можно
 *    погрузить. Отказать заранее значило бы запретить нормальный план «вылетаю сейчас,
 *    гружусь по дороге».
 * 4. **Жалоба ОДНА на всю группу, чья бы ветка её ни родила.** Пять флотов без десанта
 *    высыпали бы пять одинаковых строк в журнал, и настоящие события утонули бы. Защёлка
 *    общая для обеих веток: первая жалоба гасит остальные — в том числе жалобу другого
 *    рода, потому что важен не полный перечень бед, а то, что штурм не пошёл как задумано.
 *    Место жалобы в журнале тоже важно: она встаёт ПЕРЕД действием того флота, который её
 *    вызвал, а не в начало всей пачки, — иначе в журнале «не смог» оказывалось бы раньше
 *    приказов, которые на самом деле ушли до него.
 * 5. **Погибших в списке нет вовсе.** Тот же довод, что в `mergeOrders.ts` (правило 3):
 *    групповой приказ не отменяется из-за флота, которого больше нет.
 */

/** Флот глазами приказа на штурм. */
export interface AssaultFleetView {
  id: string;
  /** Стоит у цели и никуда не летит (правило 1). */
  parked: boolean;
  /** Отказ ядра — только у стоящих (правило 2); `null` — можно штурмовать. */
  refusal: string | null;
  /** Похоже, десанта нет — только у летящих (правило 3). */
  lacksTroops: boolean;
}

/** Что делать с одним флотом. */
export type AssaultStep =
  /** Штурмовать прямо сейчас (правило 1). */
  | { kind: 'storm'; id: string }
  /** Отправить к цели, штурм по прибытии (правило 3). */
  | { kind: 'send'; id: string }
  /** Ядро отказало — приказа не будет (правило 2). */
  | { kind: 'refused'; id: string; code: string };

/** Единственная жалоба на всю группу (правило 4). */
export type AssaultWarning =
  /** Ядро отказало стоящему — показываем его причину. */
  | { kind: 'refusal'; code: string }
  /** Летящему, похоже, нечем высаживаться. */
  | { kind: 'no-troops' };

export interface AssaultPlan {
  steps: AssaultStep[];
  /** `null` — жаловаться не на что. */
  warn: AssaultWarning | null;
  /** Перед каким по счёту шагом встаёт жалоба (правило 4); `null` — жалобы нет. */
  warnAt: number | null;
}

/** План штурма для группы (правила 1–4); погибшие в списке не передаются (правило 5). */
export function assaultPlan(fleets: readonly AssaultFleetView[]): AssaultPlan {
  const steps: AssaultStep[] = [];
  let warn: AssaultWarning | null = null;
  let warnAt: number | null = null;
  const жалоба = (w: AssaultWarning): void => {
    if (warn) return; // правило 4: первая гасит остальные
    warn = w;
    warnAt = steps.length; // перед шагом, который её вызвал
  };
  for (const f of fleets) {
    if (f.parked) {
      if (f.refusal !== null) {
        жалоба({ kind: 'refusal', code: f.refusal });
        steps.push({ kind: 'refused', id: f.id, code: f.refusal });
        continue;
      }
      steps.push({ kind: 'storm', id: f.id });
      continue;
    }
    if (f.lacksTroops) жалоба({ kind: 'no-troops' }); // правила 3–4
    steps.push({ kind: 'send', id: f.id });
  }
  return { steps, warn, warnAt };
}
