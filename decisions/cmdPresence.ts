/**
 * Какие команды ПОЯВЛЯЮТСЯ в ряду, а какие просто гаснут (REFM-185).
 *
 * Ряд команд говорит о недоступности НА ДВУХ РАЗНЫХ ЯЗЫКАХ, и в кадре они стояли
 * вперемешку: часть кнопок пряталась тернарником прямо в конкатенации разметки, часть
 * приходила серой пятым аргументом `cmdBtn`. Разница между ними — не оформление, а
 * смысл, и именно она теряется первой при следующей правке.
 *
 * 1. **Серая кнопка и отсутствующая кнопка значат РАЗНОЕ.** Серая говорит «команда у
 *    этого флота есть, сейчас её не сложить» — игрок ждёт и пробует снова. Отсутствие
 *    говорит «такой команды у такого флота не бывает вовсе». Перепутаешь — игрок либо
 *    ищет пропавшую кнопку, которая «только что была», либо давит серую в ожидании, что
 *    она когда-нибудь оживёт, хотя оживать нечему.
 *
 * 2. **Отсутствием показывается то, чего у выделения НЕТ ПО ПРИРОДЕ.** Остановка — когда
 *    ни один флот не принимает приказ «стой» (стоит на месте, в коридоре, в бою: ядро
 *    отвечает одной пробой, RULES-1/CMD-VIS). Способности — когда на борту нет флагмана
 *    с кастуемым.
 *
 * 3. **Гашением показывается то, что у флота ЕСТЬ, но сейчас не складывается** —
 *    деление, неподходящая цель штурма (слияние и десант ушли в правило 3б). Это состояния, а не природа:
 *    подлетел, набрал напарника, вышел из боя — и кнопка ожила там же, где была.
 *    Спрятать их значило бы заставить игрока гадать, куда делась команда, которой он
 *    пользовался минуту назад.
 *
 * 3а. **У ШТУРМА правило разделилось** (заказ владельца 2026-09-21: «кнопка штурм
 *    появляется только если есть во флоте кем штурмовать»). Раньше штурм целиком стоял
 *    в правиле 3 и гас. Но «нечем штурмовать» — это не состояние цели, а СОСТАВ
 *    выделения: высаживается десант, а не корпуса, и у эскадры из одних боевых кораблей
 *    такой команды не бывает вовсе, пока в трюм не сядут войска. Поэтому пустой трюм
 *    кнопку УБИРАЕТ (правило 2), а всё остальное у штурма — орбита, чужой ли мир,
 *    захватываемый ли сектор — по-прежнему её ГАСИТ (правило 3).
 *    **Взведённый штурм кнопку не теряет** — по той же причине, что и набор группы
 *    (правило 4): выделение можно сменить, не сняв прицел, и пропавшая кнопка забрала бы
 *    и единственную подпись о том, что прицел ещё взведён. Escape и Back снимают его и
 *    без кнопки, но игрок к тому моменту уже не знает, что снимать.
 *
 * 3б. **Слияние и десант — тоже по составу** (заказ владельца 2026-09-24: «Если сливать
 *    нечего, то и кнопки "слить" не должно отображаться», «то же самое с кнопкой
 *    десант»). Обе кнопки прежде гасли, и серая обещала действие, которого у выделения
 *    нет: сливать не с кем, грузить и высаживать некого. Теперь отсутствие:
 *    - «Слить» нет, когда напарника нет вовсе — одиночный флот у игрока, у которого флот
 *      один (`canMerge`);
 *    - «Десант» ⇅ нет, когда меню не из чего собрать: группа, флот в пути или в бою,
 *      на мире и в трюме нет войск, чужой мир без десанта на борту.
 *    Взведённое слияние (выбор напарника) и открытое меню десанта кнопку не теряют —
 *    по причине правила 3а: пропавшая кнопка унесла бы единственный след режима.
 *
 * 4. **Кнопка набора группы видна и под ☰, и когда набор УЖЕ включён.** Иначе выключить
 *    режим нечем: свернул ☰ — и остался в наборе без выхода. Это не украшение, а
 *    единственный путь наружу.
 *
 * 5. **Остальное из ☰ видно только раскрытым ☰.** Базовый ряд не должен пухнуть: он и
 *    так вплотную к краю экрана на телефоне, а редкие команды (форсаж, стоячие приказы)
 *    нужны раз в матч.
 */

/** Из чего решается состав ряда. Всё уже посчитано вызывающим — модуль не смотрит в мир. */
export interface CmdSelection {
  /** Хоть один флот принимает приказ «стой» (ответ ядра, а не догадка). */
  stoppable: boolean;
  /** Может ли ХОТЬ КТО-ТО в выделении стрелять издалека — от этого зависит обстрел. */
  /** Сколько СВОИХ флотов способны на дальний огонь — от этого зависит режим огня. */
  /** На борту есть флагман с кастуемыми способностями. */
  castHero: boolean;
  /** Есть ли в выделении десант — им и штурмуют (правило 3а). */
  troops: boolean;
  /** Взведён ли прицел штурма (правило 3а: взведённое не прячут). */
  assaultArmed: boolean;
  /** Есть ли с кем слиться (`canMerge`, правило 3б). */
  mergeable: boolean;
  /** Взведён ли выбор напарника для слияния (правило 3б: взведённое не прячут). */
  merging: boolean;
  /** Собирается ли меню десанта — есть что грузить или высаживать (правило 3б). */
  troopsMenu: boolean;
  /** Открыто ли меню десанта. */
  troopsOpen: boolean;
  /** Раскрыт ли ☰. */
  more: boolean;
  /** Включён ли набор группы. */
  picking: boolean;
}

/** Какие кнопки попадают в ряд (правила 2, 4, 5). */
export interface CmdShown {
  stop: boolean;
  cast: boolean;
  /** Штурм: команды не бывает у выделения без десанта (правило 3а). */
  assault: boolean;
  /** Слить: только когда есть с кем (правило 3б). */
  merge: boolean;
  /** Десант ⇅: только когда есть что грузить или высаживать (правило 3б). */
  troops: boolean;
  pick: boolean;
  /** Редкие команды из ☰ — форсаж, стоячие приказы. */
  extras: boolean;
}

/** Состав ряда команд по выделению. */
export function cmdShown(sel: CmdSelection): CmdShown {
  return {
    stop: sel.stoppable,
    cast: sel.castHero,
    assault: sel.troops || sel.assaultArmed,
    merge: sel.mergeable || sel.merging,
    troops: sel.troopsMenu || sel.troopsOpen,
    pick: sel.more || sel.picking,
    extras: sel.more,
  };
}
