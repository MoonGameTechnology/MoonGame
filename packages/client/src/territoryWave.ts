/**
 * M2.9 — ЖИВАЯ ГРАНИЦА: волна на краях провинций.
 *
 * Решение владельца (22 сентября), на вопрос «карта действительно будет такими сотами?»:
 * «Могут быть волнистыми, больше округлости, всё-таки космос. Там нет углов прямых и
 * прочих».
 *
 * Правило, ради которого этот модуль отдельный: **волна — это только РИСУНОК.** Соседство
 * по-прежнему выводится ядром из мозаики (M4.3), и граница остаётся той же гранью — она
 * просто рисуется не по линейке. Поэтому смещение накладывается ПОСЛЕ тесселяции и не
 * возвращается в правила.
 *
 * Три вещи, на которых здесь легко обжечься, и как они решены:
 *
 * 1. **Смещение — функция ТОЧКИ, а не грани.** Две соседние ячейки делят одну границу и
 *    обходят её в разные стороны. Сдвинь каждая по своей нормали — они разойдутся, между
 *    ними появится щель. Поле здесь зависит ТОЛЬКО от координат точки, поэтому обе ячейки
 *    двигают общую точку одинаково и остаются склеенными.
 * 2. **Волна детерминированная.** Никакого `Math.random()`: чистая тригонометрия от
 *    координат. Иначе карта «дышала» бы между кадрами.
 * 3. **Считается в ЛОКАЛЬНЫХ координатах мозаики** (`territoryGeometry` делит экранные на
 *    зум ещё до тесселяции), то есть изгиб не зависит от приближения и не ползёт при
 *    панораме. Посчитай его в экранных — и форма поплывёт на зуме, ровно как поплыла бы
 *    территория без правила 3 из `provinceMap.ts`.
 *
 * Дробление грани идёт по ДЛИНЕ, а не фиксированным числом: одну и ту же грань обе ячейки
 * разбивают одинаково, и точки совпадают.
 *
 * 4. **Край карты не волнуется** (замечание владельца 2026-09-24: «у провинций у края
 *    карты не должно быть своих волнистых краёв»). Край рисует сама карта — рамка
 *    голограммы или контур доски, — и провинция доходит до него ровно. Неподвижны точки
 *    грани края и обе её вершины; вершину, где граница двух провинций упирается в край,
 *    обе ячейки видят концом своей грани края и оставляют на месте одинаково — правило 1
 *    не нарушается.
 */
import { BOUNDARY, type TerritoryCell } from './territory';

/** Настройка волны. Единицы — те же, в которых пришли ячейки (локальные координаты
 *  мозаики), поэтому вызывающий переводит их из мировых сам. */
export interface WaveConfig {
  /** Наибольшее отклонение точки от прямой. 0 — волны нет. */
  amp: number;
  /** Длина волны: чем больше, тем длиннее и плавнее изгиб. */
  wavelength: number;
  /** Шаг дробления грани: примерно столько единиц на один отрезок. */
  segment: number;
}

/** Наименьшее и наибольшее число отрезков на грань. Нижняя граница держит форму у
 *  коротких граней, верхняя — цену у длинных. */
const MIN_STEPS = 2;
const MAX_STEPS = 16;

/**
 * Смещение точки — гладкое поле, зависящее ТОЛЬКО от её координат (см. правило 1 выше).
 * Сумма двух синусов по каждой оси: гладко, ограниченно и без периодической «клетки»,
 * которая выдала бы решётку ещё честнее, чем прямые углы.
 */
export function waveOffset(x: number, y: number, cfg: WaveConfig): [number, number] {
  const k = (2 * Math.PI) / cfg.wavelength;
  const dx = Math.sin(y * k + 0.7) * Math.cos(x * k * 0.61 + 2.1);
  const dy = Math.sin(x * k + 1.9) * Math.cos(y * k * 0.61 + 4.3);
  return [cfg.amp * dx, cfg.amp * dy];
}

/** Во сколько отрезков дробится грань длиной `len`. Считается от ДЛИНЫ, поэтому у общей
 *  границы обе ячейки получают одинаковые точки. */
export function edgeSteps(len: number, segment: number): number {
  if (!(segment > 0)) return MIN_STEPS;
  return Math.min(MAX_STEPS, Math.max(MIN_STEPS, Math.round(len / segment)));
}

/**
 * Та же мозаика, но грани — живые линии. Возвращает НОВЫЕ ячейки: полигон раздроблен и
 * смещён, а `tags` растянуты параллельно, чтобы каждый кусочек грани знал того же соседа,
 * что и грань целиком. Это важно не для красоты, а для правильности: по `tags` границы
 * классифицируются (своя / чужая / край карты), и разъехавшийся массив покрасил бы куски
 * одной границы в разные цвета.
 *
 * Заливка и обводка потом идут по ОДНОМУ и тому же полигону — иначе закрашенная
 * территория разошлась бы с линией, а вспышка захвата (она обрезается по нему же) вышла
 * бы за край.
 */
export function waveCells(cells: readonly TerritoryCell[], cfg: WaveConfig): TerritoryCell[] {
  if (!(cfg.amp > 0)) return cells as TerritoryCell[];
  return cells.map((cell) => {
    const n = cell.poly.length;
    if (n < 3) return cell;
    const poly: Array<[number, number]> = [];
    const tags: number[] = [];
    const edge = (k: number): boolean => (cell.tags[(k + n) % n] ?? BOUNDARY) === BOUNDARY;
    for (let k = 0; k < n; k++) {
      const p = cell.poly[k]!;
      const q = cell.poly[(k + 1) % n]!;
      const tag = cell.tags[k] ?? BOUNDARY;
      const len = Math.hypot(q[0] - p[0], q[1] - p[1]);
      const steps = edgeSteps(len, cfg.segment);
      // Конец грани НЕ добавляется: он же — начало следующей, и дубль замкнул бы
      // полигон сам на себя лишними нулевыми отрезками.
      for (let i = 0; i < steps; i++) {
        const t = i / steps;
        const x = p[0] + (q[0] - p[0]) * t;
        const y = p[1] + (q[1] - p[1]) * t;
        // Правило 4: грань края и её вершины (вершина k — конец грани k−1) стоят.
        const still = edge(k) || (i === 0 && edge(k - 1));
        const [dx, dy] = still ? [0, 0] : waveOffset(x, y, cfg);
        poly.push([x + dx, y + dy]);
        tags.push(tag);
      }
    }
    return { ...cell, poly, tags };
  });
}
