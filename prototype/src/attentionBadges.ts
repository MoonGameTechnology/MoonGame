/**
 * Значки внимания: что считается поводом позвать игрока и куда ложится цифра (REFM-189).
 *
 * В кадре три значка об одном и том же — «бои» на тревоге, «письма» на почте и общее
 * зеркало на гамбургере, когда панель инструментов закрыта. Правила ниже сидели прямо в
 * `frame()` россыпью условий; каждое чинит конкретную поломку, а не защищает от
 * невозможного.
 *
 * 1. **Бой мой, если я в нём сторона ИЛИ различаю его место.** Тревога — не только про
 *    свои потери: война у соседа, которую игрок ВИДИТ на карте, меняет обстановку вокруг
 *    него. Убрать проверку тумана — и наблюдаемый бой пропадёт из счётчика, хотя игрок
 *    смотрит прямо на него.
 * 2. **Ноль прячет значок, а не показывает «0».** Значок с нулём читается как «есть
 *    событие»: игрок тянется к нему и находит пустоту. После второго такого раза он
 *    перестаёт смотреть на значок вообще — включая тот единственный, который важен.
 * 3. **Внимание — это СУММА боёв и писем, а не большее из них.** По этой цифре игрок
 *    решает, открывать ли панель. Максимум соврал бы: при трёх боях и двух письмах писем
 *    из-под цифры «3» не видно вовсе.
 * 4. **Зеркало на гамбургере молчит, пока панель ОТКРЫТА.** У открытой панели свои значки
 *    на каждом инструменте; общий счётчик поверх них — вторая цифра о том же самом, и они
 *    расходятся уже на кадре, где одна обновилась, а другая нет. Зеркало нужно ровно за
 *    тем, чтобы уведомление было видно, когда панели не видно.
 * 5. **Зеркало отдаёт СТРОКУ, и пустая строка и есть «скрыть».** Видимость и текст
 *    выводятся из одного значения, поэтому разъехаться не могут: иначе скрытый значок
 *    остаётся в разметке с прошлым числом и всплывает с ним при следующем показе.
 */

/** Бой, сведённый к тому, по чему решается «мой ли он». */
export interface BattleLike {
  attacker: { owner: string | null };
  defender: { owner: string | null };
  location: string;
}

/** Правило 1: я сторона боя, либо его место различимо сквозь туман. */
export function battleConcernsMe(
  b: BattleLike,
  me: string,
  known: (id: string) => boolean,
): boolean {
  return b.attacker.owner === me || b.defender.owner === me || known(b.location);
}

/** Сколько боёв просится ко мне на тревогу. */
export function myBattleCount(
  battles: readonly BattleLike[],
  me: string,
  known: (id: string) => boolean,
): number {
  return battles.filter((b) => battleConcernsMe(b, me, known)).length;
}

/** Правило 2: значок показывается только при непустом счёте. */
export function countShown(count: number): boolean {
  return count > 0;
}

/** Правило 3: общий повод открыть панель. */
export function attentionTotal(battles: number, unread: number): number {
  return battles + unread;
}

/** Правила 4–5: текст зеркала на гамбургере ('' ⇒ скрыто). */
export function railBadge(attn: number, railOpen: boolean): string {
  return countShown(attn) && !railOpen ? String(attn) : '';
}
