import { randomUUID } from 'node:crypto';

/**
 * Какие партии хост поднимает на старте и как называется новая (ADDR-1).
 *
 * До этого набор партий прототипного хоста рождался из переменной окружения:
 * `MATCHES=N` → `proto`, `proto-2`, … `proto-N`, список собирался при старте процесса и
 * другого способа завести партию не было. Отсюда следовало неприятное: `?join=proto` —
 * это «комната №1 ЭТОГО процесса», а не «партия такая-то». Забукмаркал ссылку — вернулся
 * не в свою партию, а в первую комнату сервера, чем бы она к тому времени ни была; а
 * после конца партии ссылка указывает на её преемницу. Пока идентификатор выводится из
 * порядкового номера, постоянного адреса партии не существует физически.
 *
 * Канонический сервер (`packages/server/src/main.ts`) так не делает: у него есть
 * `createMatch`, и он чеканит `m-<uuid>`. Разъезд хостов ровно того же рода, что снял
 * блок CONV, только это не дубль, а пробел — поэтому решение вынесено сюда, в общее
 * место, и обоим хостам доступно одно.
 *
 * 1. **Источник истины — СТОР, а не переменная окружения.** Живые партии перечисляет
 *    `MatchStore.ongoingMatchIds()` (он для того и заведён: читает нормализованный
 *    `status`, не JSONB). Что durable — то и поднимается; переменная окружения
 *    описывает лишь ПЕРВЫЙ запуск.
 * 2. **Засев — только в пустой стор.** Иначе каждый рестарт добавлял бы ещё N комнат к
 *    уже существующим, и через неделю аптайма браузер матчей утонул бы в пустых.
 * 3. **Порядок стора не трогаем.** Сортировка здесь была бы выдумкой: у стора свой
 *    порядок, и менять его значит менять то, что игрок видит в браузере матчей.
 * 4. **Зажим сверху — только на ЗАСЕВ.** Найденное в сторе не обрезается: это живые
 *    партии с игроками внутри, и «не поднимать лишние» означало бы, что часть игроков
 *    не может войти в свою партию после рестарта.
 * 5. **Первая засеянная партия сохраняет исторический `proto`.** У неё уже есть
 *    durable-снапшот и выданные билеты на места; переименование обнулило бы и то, и другое.
 */

/** Сколько партий хост засевает максимум. Верхняя граница на ЗАСЕВ (правило 4). */
export const MAX_HOSTED_MATCHES = 16;

/** Исторический id первой партии (правило 5). */
export const LEGACY_FIRST_MATCH_ID = 'proto';

export interface BootRosterInput {
  /** Что стор считает живым: `MatchStore.ongoingMatchIds()`. */
  stored: readonly string[];
  /** Сколько партий завести, если стор пуст (`MATCHES=N`). */
  seedCount: number;
}

export interface BootRoster {
  /** Партии, которые хост поднимает: найденные в сторе либо только что засеянные. */
  raise: string[];
  /** Из них — те, которых до этого не было (их надо создать с нуля, а не восстановить). */
  seeded: string[];
}

/** Набор партий на старте хоста (правила 1–5). */
export function bootRoster(input: BootRosterInput): BootRoster {
  if (input.stored.length > 0) {
    // Правило 1 и 3: что durable — то и поднимаем, в порядке стора. Правило 4: не режем.
    return { raise: [...input.stored], seeded: [] };
  }
  const n = Math.max(1, Math.min(MAX_HOSTED_MATCHES, Math.floor(input.seedCount) || 1));
  const seeded = Array.from({ length: n }, (_, i) =>
    i === 0 ? LEGACY_FIRST_MATCH_ID : newMatchId(),
  );
  return { raise: [...seeded], seeded };
}

/** Идентификатор НОВОЙ партии.
 *
 *  Не выводится из порядкового номера в процессе — в этом весь ADDR-1: адрес партии
 *  должен пережить и её собственный конец, и рестарт хоста, и не начать указывать на
 *  чужую партию, занявшую освободившийся номер. Форма та же, что у канонического
 *  сервера (`m-<uuid>`), чтобы адреса не расходились между хостами. */
export function newMatchId(): string {
  return `m-${randomUUID()}`;
}
