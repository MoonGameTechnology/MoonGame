/**
 * Точка сбора мира-верфи в панели мира и на карте (RALLY-1, заказ владельца 2026-10-14
 * «как во всяких RTS»). Само правило — куда летят новостройки и когда точка действует —
 * в ядре (`autoRallyModule`, `rallyPointOf`); здесь только что показать и что отправить.
 *
 * 1. **Чужой мир не предлагает ничего** — это приказ владельца.
 * 2. **Задать точку предлагает только мир с верфью.** Без верфи кораблей там не строят, и
 *    кнопка обещала бы то, чего не будет.
 * 3. **Стоящую точку можно сменить и снять всегда**, даже если верфь разрушена: иначе
 *    игрок не уберёт точку, которую сам поставил.
 * 4. **Целью годится любой другой мир, кроме закрытой территории** (RALLY-2, владелец
 *    2026-11-12): закрыта территория того, с кем у игрока мир, — туда флот не пройдёт.
 *    «Закрыта» — по тому, что игрок ВИДИТ (`knownClosed` ядра): иначе отказ выдал бы
 *    хозяина мира под туманом. Тап мимо мира снимает прицел, тап по закрытому миру или
 *    по самому миру-верфи объясняет правило и тоже снимает.
 * 5. **Путь при выборе точки — тот, которым полетят корабли** (RALLY-2): маршрут по
 *    дорогам, оборванный перед первой видимой закрытой границей, — там они и встанут.
 */

/** Что панель мира показывает про точку сбора. */
export type RallyOffer =
  /** Ничего: чужой мир или мир без верфи и без точки. */
  | 'none'
  /** Точки нет — кнопка «Задать». */
  | 'set'
  /** Точка стоит — цель и кнопки «Сменить» и «Снять». */
  | 'change';

/** Правила 1–3. `hasPoint` — точка этого мира действует (`rallyPointOf` не `null`). */
export function rallyOffer(mine: boolean, buildsShips: boolean, hasPoint: boolean): RallyOffer {
  if (!mine) return 'none';
  if (hasPoint) return 'change';
  return buildsShips ? 'set' : 'none';
}

/** Чем кончается тап по карте с взведённой точкой сбора. */
export type RallyPick =
  /** Отправить приказ. */
  | 'order'
  /** Тап по самому миру-верфи — объяснить, что цель — другой мир. */
  | 'same'
  /** Тап по видимой закрытой территории — объяснить, что туда нет прохода. */
  | 'closed'
  /** Тап мимо мира — прицел снят. */
  | 'cancel';

/** Правило 4. `hit` — мир под пальцем (`null` — промах); `closed` — его территория
 *  закрыта игроку на ЕГО карте (`knownClosed`). */
export function rallyPick(from: string, hit: { id: string; closed: boolean } | null): RallyPick {
  if (!hit) return 'cancel';
  if (hit.id === from) return 'same';
  return hit.closed ? 'closed' : 'order';
}

/** Правило 5: какие хопы корабли пролетят — как курс ядра (`movement`, `stopAtBorder`).
 *  `route` — кратчайший маршрут без мира-верфи; `detour` — маршрут в обход закрытых миров
 *  (`null` — обхода нет); `closed` — видна ли закрытая территория в этом мире. Есть
 *  чистый обход — летят им; нет — путь обрывается перед границей, а граница первым же
 *  хопом даёт пусто: корабли не вылетят вовсе. */
export function rallyRouteHops(
  route: readonly string[],
  detour: readonly string[] | null,
  closed: (id: string) => boolean,
): string[] {
  const stop = route.findIndex(closed);
  if (stop < 0) return [...route];
  if (detour && !detour.some(closed)) return [...detour];
  return route.slice(0, stop);
}
