/**
 * ДЕЛЁЖ ЗАЛПА МЕЖДУ ВРАГАМИ (MSB-2) — решение владельца §0.0 №1 многостороннего боя.
 *
 * «Урон дробится на всех врагов стороны, а не уходит одной выбранной цели.» Выбора цели у
 * игрока нет — значит, не нужен и интерфейс выбора; и спрятаться за спину союзника нельзя,
 * ради чего выбор и сделан.
 *
 * Правило вынесено в отдельный файл, потому что читателей у него ДВА и они в разных
 * пакетах ответственности: живой раунд (`modules/combat.ts`, там же дипломатия и шина) и
 * ПРОГНОЗ (`state/previewBattle.ts`, чистый what-if без шины). Прогноз, считающий не тем
 * правилом, что бой, — это не неточность, а обещание игроку другого боя; на паре такое уже
 * случалось, и парность тут ни при чём: разойтись они могут на любом числе сторон.
 *
 * 1. **Делится РОВНО, а не пропорционально силе врагов.** Допущение, а не спрошенное
 *    решение (§0.0 №1, помечено ⚠️): пропорционально значило бы читать состав ВСЕХ сторон
 *    на каждый залп и делать свой урон зависимым от того, кто ещё стоит в бою — прогноз
 *    перестал бы быть линейным, а игрок не смог бы предсказать свой же выстрел. Меняется
 *    одной строкой здесь.
 * 2. **Один враг берёт всё.** Не частный случай «поделили на единицу», а требование
 *    MSB-1: на двух сторонах переход формы не имеет права изменить ни один исход.
 * 3. **Врагов нет — залп уходит в пустоту.** Ноль, а не «весь кому-нибудь»: сторона без
 *    врагов не стреляет вовсе, и деление на ноль тут не арифметическая ловушка, а
 *    содержательный случай (все помирились посреди боя).
 * 4. **Порядок врагов сохраняется.** Это порядок вступления в бой (`Battle.sides`), по
 *    которому MSB-4 решает, чей мир после совместного штурма. Делёж не имеет права его
 *    переставлять — иначе исход зависел бы от того, как список обошли.
 *
 * Кап линии огня (`COMBAT_UNIT_CAP`) здесь НЕ живёт и жить не должен: он применяется
 * раньше, когда считается сам залп стороны (`sideDamageBreakdown` → `cappedUnitBreakdown`), то есть уже
 * считается НА СТОРОНУ — второе допущение §0.0 №1 выполнено самим устройством кода, без
 * единой правки.
 */
import type { CombatantRef, PlayerId } from '../state/gameState';

/** Враг стороны: куда попадёт доля залпа и чей он. */
export interface VolleyTarget {
  ref: CombatantRef;
  owner: PlayerId | null;
}

/** Одна доля залпа — сколько и кому. */
export interface VolleyShare {
  to: CombatantRef;
  toOwner: PlayerId | null;
  damage: number;
}

/** Сколько достаётся ОДНОМУ врагу из залпа на `enemies` врагов (правила 1–3). */
export function volleyShare(volley: number, enemies: number): number {
  if (enemies <= 0) return 0; // правило 3
  return volley / enemies; // правила 1–2
}

/** Залп, разложенный по врагам в порядке их вступления в бой (правило 4). */
export function splitVolley(
  volley: number,
  enemies: readonly VolleyTarget[],
): VolleyShare[] {
  const share = volleyShare(volley, enemies.length);
  return enemies.map((e) => ({ to: e.ref, toOwner: e.owner, damage: share }));
}
