/**
 * Что происходит с выделением, когда тап выбрал объект (REFM-166).
 *
 * Кого выбрал тап, решают `tapTargets.ts` (кто попал под палец), `tapPriority.ts` (кто
 * забрал жест) и `tapCycle.ts` (перебор стопки). Осталось последнее звено: ЧТО из этого
 * следует. Три ветки стояли безымянным замыканием внутри `selectAt`, и различие между
 * ними — не техническое: у каждой свой ответ на вопрос «что теряет силу».
 *
 * 1. **Под тапом ничего — сбрасываем ВСЁ, включая незавершённые намерения.** Тап по
 *    пустому месту это «отменить», а слияние, деление и погрузка десанта привязаны к
 *    выделенному флоту: пережив сброс, они применились бы к следующему выбранному — то
 *    есть к другому флоту, и молча.
 * 2. **Флот — обычное выделение** (`fleetSelection.ts`): только своё, «ровно один» это
 *    ещё и «текущий», выбор мира при этом гаснет — панель одна.
 * 3. **Мир гасит флоты, но НЕ гасит намерения.** Так это работает сегодня, и правило
 *    записано КАК ЕСТЬ: у ветки «мир» свой набор сбросов, короче, чем у полного сброса из
 *    правила 1. Похоже на недосмотр (окно деления переживает выбор мира и остаётся висеть
 *    на флоте, который уже не выделен), но менять поведение молча нельзя — вопрос в
 *    карточке REFM-166.
 */

/** Что выбрал тап. */
export type Picked =
  | { kind: 'fleet'; id: string }
  | { kind: 'planet'; id: string };

/** Что сделать с выделением. */
export type PickEffect =
  /** Полный сброс: и выделение, и незавершённые намерения (правило 1). */
  | { kind: 'clear-all' }
  /** Выделить один флот (правило 2). */
  | { kind: 'fleet'; id: string }
  /** Выбрать мир: флоты гаснут, намерения — нет (правило 3). */
  | { kind: 'planet'; id: string };

/** Что следует из выбора (правила 1–3). */
export function pickEffect(pick: Picked | null): PickEffect {
  if (!pick) return { kind: 'clear-all' };
  return pick.kind === 'fleet' ? { kind: 'fleet', id: pick.id } : { kind: 'planet', id: pick.id };
}

/** Гаснут ли незавершённые намерения (слияние, деление, десант) при этом выборе. */
export function dropsIntents(effect: PickEffect): boolean {
  return effect.kind === 'clear-all';
}
