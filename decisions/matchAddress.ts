/**
 * Адрес партии против приглашения в неё (ADDR-2).
 *
 * Сегодня это одна ссылка, и она описывает ДЕЙСТВИЕ: `?join=…&slot=p2&faction=azure`
 * читается как «займи место p2 за такой-то дом». Адресом партии она работает почти
 * случайно — сервер игнорирует выбор, когда место уже за тобой (`joinSeat.ts`, правило 2),
 * — а вот приглашением она вредна: отдал ссылку другу, и он просит ТВОЁ место и ТВОЙ дом.
 * Место ему сервер не отдаст (резолвер откатится на свободное), а дом — отдаст: для него
 * это НОВЫЙ захват, и выбор применяется. Человек сядет играть за чужую фракцию, не поняв,
 * почему.
 *
 * Развести их — это два разных ответа на два разных вопроса:
 *
 * 1. **Адрес партии несёт ТОЛЬКО идентификатор.** Он для закладки и возврата, и жить он
 *    должен дольше одной партии: всё остальное в ссылке — намерение, которое сбывается
 *    один раз. Идентификатор экранируется, потому что приходит от сервера, а не из кода.
 * 2. **Параметры захвата вычищаются из строки ПОСЛЕ успешного входа.** Не раньше: пока
 *    вход не удался, они ещё нужны — например, игрок уходит логиниться и возвращается
 *    доигрывать заход. Тот же приём и та же причина, что у `?reset=<token>` (он не должен
 *    осесть в истории и referer'е), только здесь речь не о безопасности, а о том, что
 *    игрок копирует из адресной строки.
 * 3. **Чистка хирургическая.** Убираем ровно `slot`/`faction`/`sci`, остальное не трогаем:
 *    адрес может нести чужие параметры (язык, будущие флаги), и переписать его целиком
 *    значило бы молча их потерять. Мусор вместо адреса возвращается как есть — вход не
 *    должен падать из-за строки, которую мы не поняли.
 * 4. **Тому, кто уже сидит в партии, ссылка — просто адрес.** Даже если параметры в ней
 *    есть, намерения захвата у возврата нет: своё место у игрока уже занято, а стухшая
 *    закладка иначе просила бы место, давно отданное другому. Сервер это и так знает
 *    (правило 2 `joinSeat.ts`), но клиент не должен и слать — иначе адрес врёт о том, что
 *    произойдёт при переходе по нему.
 */

/** Параметры, которые описывают ЗАХВАТ, а не партию (правило 3). */
const CLAIM_PARAMS = ['slot', 'faction', 'sci'] as const;

/** Постоянный адрес партии — только идентификатор (правило 1). */
export function matchAddress(pathname: string, matchId: string): string {
  return `${pathname}?join=${encodeURIComponent(matchId)}`;
}

/** Что оставить в адресной строке после успешного входа (правила 2–3).
 *
 *  Возвращает `href` без параметров захвата. Строку, которую не удалось разобрать,
 *  отдаёт нетронутой: чистка адреса — удобство, а не условие входа. */
export function scrubClaimParams(href: string): string {
  let url: URL;
  try {
    url = new URL(href);
  } catch {
    return href;
  }
  let touched = false;
  for (const p of CLAIM_PARAMS) {
    if (url.searchParams.has(p)) {
      url.searchParams.delete(p);
      touched = true;
    }
  }
  return touched ? url.toString() : href;
}

/** Чего просит ссылка сверх самого адреса. */
export interface ClaimIntent {
  slot?: string;
  faction?: string;
  scientists?: string[];
}

/** Приглашение это или просто адрес (правила 1, 4).
 *
 *  `seated` — держит ли игрок место в ЭТОЙ партии; у сидящего намерения захвата нет,
 *  сколько бы параметров ни висело в ссылке. `null` = заходим по адресу, ничего не прося. */
export function claimIntent(params: URLSearchParams, seated: boolean): ClaimIntent | null {
  if (seated) return null; // правило 4
  const slot = (params.get('slot') ?? '').trim();
  const faction = (params.get('faction') ?? '').trim();
  const scientists = (params.get('sci') ?? '')
    .split(',')
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
  if (!slot && !faction && scientists.length === 0) return null;
  return {
    ...(slot ? { slot } : {}),
    ...(faction ? { faction } : {}),
    ...(scientists.length ? { scientists } : {}),
  };
}
