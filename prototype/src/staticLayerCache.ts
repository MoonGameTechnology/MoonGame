/**
 * Когда перепекать статический слой карты (REFM-60).
 *
 * Дорогая часть карты — заливка провинций и сеть лейнов — рисуется один раз в
 * закадровый холст и потом просто копируется каждый кадр. Значит нужен признак «а
 * изменилось ли что-нибудь», и составлен он должен быть честно.
 *
 * 1. **Подпись строится по ЗНАНИЮ игрока, а не по правде.** Владельца в неё кладёт
 *    вызывающий, и класть он обязан то, что игроку ИЗВЕСТНО. Читай подпись сырое
 *    состояние — карта перепекалась бы на скрытом захвате, и по одному факту
 *    перерисовки игрок узнал бы то, ради сокрытия чего туман и существует.
 * 2. **«Неизвестно» — отдельный маркер, а не пустая строка.** Иначе «мир ничей» и «мир
 *    за туманом» дают одну подпись, и смена одного на другое пройдёт незамеченной.
 * 3. **Размер вьюпорта и плотность пикселей — часть подписи.** После поворота экрана
 *    запеканка не того размера: её надо переснять, а не растянуть.
 * 4. **Сдвиг камеры — тоже повод перепечь.** Запеканка размером с экран; следовать за
 *    панорамой старой картинкой значит оставить открывшийся край пустым — смаз по краю
 *    вместо карты.
 */

/** Маркер «владелец неизвестен» — не совпадает ни с одним идентификатором игрока. */
export const UNKNOWN_OWNER = '·';

/**
 * Подпись владельцев по всем узлам карты. `knownOwner` возвращает то, что игроку
 * ИЗВЕСТНО (правило 1), `null` — «не знает» (правило 2).
 */
export function ownersSignature(
  ids: readonly string[],
  knownOwner: (id: string) => string | null,
): string {
  let out = '';
  for (const id of ids) out += (knownOwner(id) ?? UNKNOWN_OWNER) + ',';
  return out;
}

/** Из чего складывается подпись содержимого запеканки. */
export interface BakeContent {
  vw: number;
  vh: number;
  dpr: number;
  /** Чьими глазами смотрим — у другого игрока другая политическая карта. */
  me: string;
  /** Результат `ownersSignature`. */
  owners: string;
  /** Включён ли звёздный фон — графическая настройка меняет саму запеканку. */
  starfield: boolean;
}

/** Подпись содержимого: всё, от чего зависит картинка, кроме положения камеры. */
export function bakeSignature(c: BakeContent): string {
  return `${c.vw}x${c.vh}:${c.dpr.toFixed(2)}|${c.me}|${c.owners}|${c.starfield ? 1 : 0}`;
}

/** Состояние прошлой запеканки. */
export interface BakeState {
  signature: string;
  cam: { x: number; y: number; scale: number };
  /** Ширина холста запеканки в физических пикселях. */
  width: number;
}

/** Нужна ли перепечка. `prev` — `null`, если ещё ни разу не пекли. */
export function needsRebake(prev: BakeState | null, next: BakeState): boolean {
  if (!prev) return true;
  if (prev.width !== next.width) return true; // правило 3: холст не того размера
  if (prev.signature !== next.signature) return true;
  // Правило 4: камера сдвинулась — запеканка размером с экран больше не подходит.
  return (
    prev.cam.x !== next.cam.x || prev.cam.y !== next.cam.y || prev.cam.scale !== next.cam.scale
  );
}
