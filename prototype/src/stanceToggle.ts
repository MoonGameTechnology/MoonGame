/**
 * Постановка стоек «авто-штурм» и «дежурный вылет» (REFM-98; дежурство переехало на
 * БАЗУ в SHU-2.2).
 *
 * 1. **Стойка ставится ЕДИНООБРАЗНО на всю группу.** Кнопка задаёт состояние, а не
 *    переключает каждый флот: смешанный набор снапится в одно, иначе один тап оставлял
 *    бы группу такой же разнородной, какой она была.
 * 2. **Только СВОИ** — чужой стойки не имеет, и приказ по нему всё равно отскочит.
 * 3. **Уже в нужном состоянии — приказа НЕТ.** Иначе сеть получала бы пустой приказ на
 *    каждый тап, а соло дважды писало бы одно и то же.
 * 4. **Дежурить нечем — стойки нет.** У базы должна стоять в ангаре хоть одна машина.
 *
 * Чего здесь БОЛЬШЕ НЕТ и почему. Раньше дежурство армилось на ФЛОТ челноков, и правил
 * было шесть: добавлялись «только с прикола», «вне боя» (зеркало гейта редьюсера) и
 * «снятие — отдельный исход, иначе следующее включение выдаст бесплатный бак». С
 * переездом на базу все три отпали сами: порт не двигается и не воюет, а запас вылетов
 * принадлежит БАЗЕ (SHU-1.2) и включением-выключением дежурства не трогается вовсе —
 * бесплатной дозаправке взяться неоткуда.
 */

/** Что делать с авто-штурмом на конкретном флоте. */
export type AutoStance = 'set' | 'skip';

/** Что делать с дежурным вылетом базы. */
export type ScrambleStance =
  /** Поднять дежурство. */
  | 'set'
  /** Снять дежурство. */
  | 'clear'
  /** Ничего: чужая база, пустой ангар или уже в нужном состоянии. */
  | 'skip';

/** Нужно ли трогать авто-штурм этого флота (правила 1–3). */
export function autoStance(mine: boolean, current: boolean, want: boolean): AutoStance {
  if (!mine) return 'skip';
  return current === want ? 'skip' : 'set';
}

/** Что делать с дежурным вылетом этой БАЗЫ (правила 1–4). */
export function scrambleStance(
  mine: boolean,
  hasSquadron: boolean,
  current: boolean,
  want: boolean,
): ScrambleStance {
  if (!mine || !hasSquadron) return 'skip';
  if (current === want) return 'skip';
  return want ? 'set' : 'clear';
}
