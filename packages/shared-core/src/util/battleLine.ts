/**
 * ЛИНИЯ ФЛОТОВ ДЕРЖАВЫ (MSB-13, резолюция владельца 2026-11-19; заменила «одну линию на
 * державу» MSB-11).
 *
 * У предела линии два уровня, и это РАЗНЫЕ правила:
 *
 * - **Внутри флота** — по кораблям: `min(1, L/N)` (GDD §7.2), N — живые юниты самого флота,
 *   L — 10 кораблей или 20 наземных. Это правило было всегда и здесь не живёт
 *   (`cappedUnitBreakdown`).
 * - **В бою** — по флотам: у державы {@link FLEET_LINE} флотов бьют в полную силу; при M > 5
 *   каждый её флот бьёт на `5/M` — та же формула, что у кораблей. Шесть флотов — по 83%,
 *   десять — по половине.
 *
 * Почему так, а не «все корабли державы в одной линии» (MSB-11): флот, который получает
 * урон, теряет и силу, поэтому выгоден небольшой запас сверх десятка — он держит полный урон
 * дольше; а дробление армии требует контроля — привести флоты в один бой вовремя и держать
 * вместе. Пять флотов ограничивают выигрыш от дробления: в полную силу бьют не больше
 * 5 × 10 кораблей.
 *
 * 1. **Держава — это владелец.** Союзник делит бой, но не линию: у каждой державы свои пять.
 * 2. **Считается каждая живая сторона державы** — флот, десант, плацдарм, гарнизон, в том
 *    числе те, кому нечем стрелять (резолюция владельца: «считать»).
 * 3. **У стороны без хозяина (пираты, Рой) линия своя у каждой стороны**: это не игроки,
 *    дробиться ради выгоды им незачем, а общий «ничей» владелец слил бы чужие банды.
 *
 * Читателей трое: живой залп, ответ и разрядка заряда (`battleExchanges.ts`), цифры окна
 * боя (`state/battleReadout.ts`) и прогноз (`state/previewBattle.ts`, своими входами).
 */
import type { Battle, BattleSide, GameState } from '../state/gameState';
import { sideAlive } from './combat';
import { combatEfficiency } from './stacks';

/** Сколько флотов державы бьют в полную силу. */
export const FLEET_LINE = 5;

/** Доля силы каждого флота державы, у которой в бою `fleets` живых сторон. */
export function fleetLineShare(fleets: number): number {
  return fleets > FLEET_LINE ? combatEfficiency(fleets, FLEET_LINE) : 1;
}

/** Доля линии стороны `side` в бою `battle` (правила 1–3). */
export function battleLineShare(state: GameState, battle: Battle, side: BattleSide): number {
  if (side.owner === null) return 1;
  let fleets = 0;
  for (const other of battle.sides)
    if (other.owner === side.owner && sideAlive(state, other.ref)) fleets += 1;
  return fleetLineShare(fleets);
}
