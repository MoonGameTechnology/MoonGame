/**
 * Журнал окна «События» по дням (UIX-10.9). День назван один раз, у первой (самой свежей)
 * записи своего дня, а у остальных записей дня — только время суток: раньше каждая строка
 * начиналась с «День 5, 07:45 ·», и день повторялся в каждой строке своего дня. Отдельной
 * строкой-заголовком день не ставится: в редком журнале, где на день одна-две записи,
 * заголовки сделали бы окно выше прежнего.
 *
 * Правила:
 * 1. Записи приходят в порядке появления, ранние первыми; окно показывает свежие сверху. Поэтому
 *    дни идут от последнего к первому, а внутри дня записи — от поздней к ранней.
 * 2. Группа — это подряд идущие записи одного дня. День без записей не пишется.
 */

export interface LogDay<T> {
  readonly day: number;
  readonly rows: readonly T[];
}

/** Записи журнала по дням, свежие первыми (правила 1 и 2). */
export function logByDay<T>(entries: readonly T[], dayOf: (entry: T) => number): LogDay<T>[] {
  const days: { day: number; rows: T[] }[] = [];
  for (let i = entries.length - 1; i >= 0; i--) {
    const entry = entries[i]!;
    const day = dayOf(entry);
    const last = days[days.length - 1];
    if (last && last.day === day) last.rows.push(entry);
    else days.push({ day, rows: [entry] });
  }
  return days;
}
