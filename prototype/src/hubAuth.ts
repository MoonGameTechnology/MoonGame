/**
 * Когда вкладка хаба имеет право ходить в сеть от имени аккаунта (REFM-138).
 *
 * «Друзья», «Рейтинги», «Арсенал», «Медали» и «Корпорация» живут на сервере, и каждая
 * спрашивает у клиента одно и то же: есть ли сейчас авторизованный адрес. Ответ на этот
 * вопрос стоял в `main.ts` ПЯТЬЮ байт-в-байт одинаковыми копиями — по одной на вкладку.
 *
 * 1. **Условий три, и обязательны все.** Известен сервер, сервер подтвердил режим
 *    аккаунтов, есть живая сессия. Пропусти любое — вкладка либо стучится в никуда, либо
 *    шлёт запрос без токена и получает от сервера 401 вместо честного «войдите».
 * 2. **Режим аккаунтов ПРОБУЕТСЯ у сервера, а не предполагается.** Тот же адрес бывает
 *    поднят и без аккаунтов; без пробы вкладка звала бы входить туда, где входа нет.
 * 3. **Ради ПРОСМОТРА пароль не спрашивают.** Все три отказа читаются одинаково —
 *    гостевое состояние: вкладка показывает причину и ничего не грузит. Требовать вход,
 *    чтобы просто посмотреть доску или список друзей, значит выгонять игрока из хаба за
 *    любопытство; сессию сюда приносит вход, а не эти вкладки.
 * 4. **Пять вкладок — ОДИН ответ.** Разъедься копии хоть на условие, и одна вкладка
 *    покажет гостя, а соседняя полезет в сеть с мёртвым токеном — на одном и том же
 *    экране, в одну и ту же секунду.
 */

/** Адрес и ключ для запроса от имени аккаунта. */
export interface AuthorizedBase {
  base: string;
  token: string;
}

/** Что клиент уже выяснил к моменту вопроса. */
export interface AuthState {
  /** Выбранный сервер; `null` — не выбран (гость). */
  server: { base: string } | null;
  /** Сервер ПОДТВЕРДИЛ режим аккаунтов (правило 2). */
  accountsMode: boolean;
  /** Сохранённая сессия этого сервера; `null` — её нет или истекла. */
  token: string | null;
}

/**
 * Авторизованный адрес или `null` — гостевое состояние (правила 1, 3–4). Чистая функция:
 * пробу режима и чтение сессии делает вызывающий, здесь только решение.
 */
export function authorizedBase(
  st: AuthState,
  httpBase: (base: string) => string,
): AuthorizedBase | null {
  if (!st.server || !st.accountsMode || !st.token) return null;
  return { base: httpBase(st.server.base), token: st.token };
}
