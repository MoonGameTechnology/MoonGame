/**
 * Сколько шума даёт флот и как далеко слышит мир (REFM-170).
 *
 * Кто становится отметкой радара — `radarContacts.ts` (REFM-96), сам туман спрашивается
 * у ядра (`sensorCoverage`). Здесь ШКАЛА: во сколько оценивается флот, в какую ступень он
 * попадает и какую дальность даёт мир. Три мелких счёта, но каждый несёт правило, которое
 * иначе стоит в кадре безымянным числом.
 *
 * 1. **Шум флота — сумма по стопкам, а не число кораблей.** Отметка говорит про МАССУ:
 *    три транспорта и три линкора не одна и та же цель, и складывать их поштучно значило
 *    бы врать радару.
 * 2. **Неизвестный клиенту тип шумит за 1, неизвестное здание слышит на 0 — и то, и
 *    другое ПОВТОРЯЕТ умолчание схемы** (`signature: default(1)`, `radarRange: default(0)`
 *    в `schemas.ts`). Поэтому клиент и ядро не расходятся на данных, разъехавшихся со
 *    сборкой. Несимметрично это выглядит только на первый взгляд: обе подстановки идут в
 *    осторожную сторону — незнание НЕ прячет твой флот от чужого радара и НЕ выдаёт тебе
 *    дальности, которой ты не строил.
 * 3. **Ступеней три, и они грубые.** Радар состава не выдаёт — точное число рядом с
 *    отметкой игрок прочёл бы как разведданные, которых у него нет.
 * 4. **Пороги ступеней абсолютные, а не доля от флотов на карте.** Одна и та же эскадра
 *    обязана читаться одинаково на первом дне и на сотом: «крупный» — это про саму цель,
 *    а не про то, насколько она крупна по нынешним меркам.
 * 5. **Слух мира — ЛУЧШИЙ массив, а не сумма.** Две антенны не удваивают дальность, иначе
 *    обзор набирался бы количеством построек вместо уровня.
 * 6. **Дальность берётся по УРОВНЮ здания**, тем же `buildingLevel(...).radarRange`, что
 *    читает туман ядра. Копия «дальность = поле дефа» не знала бы про уровень, и
 *    прокачанный радар расширял бы туман ядра, но не круг на карте игрока.
 */
import {
  buildingLevel,
  type BuildingDef,
  type UnitDef,
} from '../../packages/shared-core/src/index';
import type { SigSize } from './radarContacts';

/** Ступень крупности: с неё начинается «крупный» (правило 4). */
export const SIG_LARGE = 13;
/** Ступень крупности: с неё начинается «средний» (правило 4). */
export const SIG_MEDIUM = 5;

/** Стопка состава: сколько единиц одного типа (правило 1). */
export interface SigStack {
  unit: string;
  count: number;
}

/** Шум флота: сумма `count × signature` по стопкам (правила 1–2). */
export function fleetSignature(
  stacks: readonly SigStack[],
  unitDef: (unit: string) => UnitDef | undefined,
): number {
  let sig = 0;
  for (const st of stacks) sig += st.count * (unitDef(st.unit)?.signature ?? 1);
  return sig;
}

/** Ступень, которой отметка называет свою крупность (правила 3–4). */
export function sigClass(sig: number): SigSize {
  return sig >= SIG_LARGE ? 'L' : sig >= SIG_MEDIUM ? 'M' : 'S';
}

/** Одно построенное здание мира: чем оно является и какого уровня. */
export interface RadarBuilding {
  type: string;
  level: number;
}

/** Дальность, которую мир слышит: лучший из его массивов, 0 — ни одного (правила 5–6). */
export function planetRadar(
  buildings: readonly RadarBuilding[],
  buildingDef: (type: string) => BuildingDef | undefined,
): number {
  let r = 0;
  for (const b of buildings) {
    const def = buildingDef(b.type);
    if (def) r = Math.max(r, buildingLevel(def, b.level).radarRange);
  }
  return r;
}
