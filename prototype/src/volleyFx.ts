/**
 * Расписание баллистического залпа: кто сейчас в полёте, а кто уже разорвался (REFM-111).
 *
 * Осадный залп — не одна вспышка, а ОЧЕРЕДЬ из нескольких снарядов: они уходят с
 * задержкой, летят по дуге и разрываются каждый в свой момент. Всё это считалось прямо
 * в кадровом цикле четырьмя выражениями с `age`, и из них не читалось главное — что
 * фазы СЦЕПЛЕНЫ: сдвинь одну, и вспышка оторвётся от снаряда, который её вызвал.
 *
 * Жизнь ОДНОЙ вспышки уже описана в `flashFx.ts` (REFM-70) — сюда она не копируется:
 * снятие отгоревшей записи по-прежнему делает `flashDone`, здесь только расписание,
 * которого у одиночной вспышки нет.
 *
 * 1. **Время жизни залпа СКЛАДЫВАЕТСЯ из фаз, а не задаётся числом.** Отдельная
 *    константа рано или поздно разойдётся с фазами: занизишь — последний снаряд исчезнет
 *    в воздухе, завысишь — мёртвая запись будет считаться каждый кадр после последнего
 *    разрыва.
 * 2. **Снаряды уходят С ЗАДЕРЖКОЙ, каждый по своим часам.** Залп обязан читаться как
 *    очередь; уйди они разом — на карте была бы одна жирная черта вместо стрельбы.
 * 3. **Снаряд виден строго В ПОЛЁТЕ.** До старта его ещё нет, после попадания он уже
 *    не снаряд, а разрыв: нарисованный за границей, он повис бы в цели поверх вспышки.
 * 4. **Разрыв начинается ТАМ ЖЕ, где кончается полёт своего снаряда.** Это не отдельные
 *    часы, а продолжение тех же: разъедутся — вспышка либо опередит снаряд, либо
 *    отстанет от него, и попадание перестанет читаться.
 * 5. **Углы искр — от СИДА залпа, а не от случайности.** Случайные углы дрожали бы
 *    каждый кадр (одно попадание выглядело бы десятком разных), а в этом проекте ещё и
 *    ломали бы правило детерминизма: картинка обязана повторяться при том же состоянии.
 *
 * ДУГА (REFM-130) — сюда же, а не в свой модуль: «когда» и «куда» у одного залпа
 * разъезжаться не должны, а живёт эта геометрия в том же кадровом цикле и теми же
 * `age`/`t`, что расписание выше.
 *
 * 6. **Лоб дуги поднимается ПО ЭКРАНУ, тем выше, чем дальше бьют, — но с полом и
 *    потолком.** Без пола выстрел в упор вырождается в прямую: навесной огонь перестаёт
 *    читаться как навесной и сливается с лучом зенитки. Без потолка дальний залп
 *    выгибается за край экрана, и вопрос «кто кого обстреливает» — ради которого дуга и
 *    рисуется — остаётся без ответа. Подъём именно ЭКРАННЫЙ: проекция карты неравномерна
 *    по осям, и в единицах карты одна и та же дуга смотрелась бы по-разному в разных
 *    частях экрана.
 * 7. **Подъём масштабируется вместе с артом узла.** Залп остаётся виден на схематичном
 *    зуме (бой — это сигнал), но на нём же он не должен накрывать собой провинцию.
 * 8. **След рисуется ЛОМАНОЙ ДО ГОЛОВНОГО снаряда, а не всей дугой сразу.** Трасса
 *    отвечает «куда снаряд УЖЕ долетел». Нарисуй её целиком с первого кадра — и она
 *    читается как линия связи между мирами, обещающая попадание, которого ещё нет.
 */

/** Из чего сложен залп. */
export interface VolleySpec {
  /** Сколько снарядов в очереди. */
  shells: number;
  /** Сколько миллисекунд снаряд проводит на дуге. */
  flightMs: number;
  /** Задержка между стартами соседних снарядов (правило 2). */
  staggerMs: number;
  /** Сколько живёт разрыв (правило 4). */
  burstMs: number;
}

/** Полное время жизни залпа — сумма фаз, а не своё число (правило 1). */
export function volleyLife(spec: VolleySpec): number {
  return spec.flightMs + spec.staggerMs * (spec.shells - 1) + spec.burstMs;
}

/**
 * Доля пути снаряда `index` в этом возрасте залпа, или `null`, если он ещё не стартовал
 * либо уже упал (правила 2–3). Границы исключены с обоих концов: на `0` снаряда ещё нет,
 * на `1` он уже разрыв.
 */
export function shellT(age: number, index: number, spec: VolleySpec): number | null {
  const t = (age - index * spec.staggerMs) / spec.flightMs;
  return t > 0 && t < 1 ? t : null;
}

/**
 * Доля жизни разрыва снаряда `index`, или `null`, если он ещё не долетел либо разрыв уже
 * отгорел (правило 4). Отсчёт продолжает полёт того же снаряда, а не идёт своими часами.
 */
export function burstK(age: number, index: number, spec: VolleySpec): number | null {
  const landed = age - (index * spec.staggerMs + spec.flightMs);
  return landed >= 0 && landed <= spec.burstMs ? landed / spec.burstMs : null;
}

/** Точка экрана — то немногое от неё, что нужно дуге. */
export interface Pt {
  x: number;
  y: number;
}

/** Доля дальности, уходящая в высоту лба, и его пол/потолок в единицах арта (правило 6). */
export const ARC_RISE = 0.24;
export const ARC_MIN_LIFT = 16;
export const ARC_MAX_LIFT = 64;
/** На сколько отрезков ломается дуга следа (правило 8). */
export const ARC_STEPS = 18;

/**
 * Высота лба дуги над хордой: доля дальности, зажатая полом и потолком, и всё это в
 * масштабе арта узла (правила 6–7). `scale` — тот же множитель, которым ужимается
 * остальная графика узла на схематичном зуме.
 */
export function arcLift(dist: number, scale: number): number {
  return Math.min(ARC_MAX_LIFT * scale, Math.max(ARC_MIN_LIFT * scale, dist * ARC_RISE));
}

/**
 * Точка на дуге в доле пути `t` — квадратичная кривая, у которой опорная точка стоит
 * над серединой хорды на `lift` (правило 6). `t=0` даёт стреляющего, `t=1` — цель.
 */
export function arcPoint(a: Pt, b: Pt, lift: number, t: number): Pt {
  const cx = (a.x + b.x) / 2;
  const cy = (a.y + b.y) / 2 - lift;
  const u = 1 - t;
  return {
    x: u * u * a.x + 2 * u * t * cx + t * t * b.x,
    y: u * u * a.y + 2 * u * t * cy + t * t * b.y,
  };
}

/**
 * Ломаная следа ОТ стреляющего ДО головного снаряда (правило 8) — без самой первой
 * точки: её вызывающий уже поставил, начиная путь. Пустой список значит «снаряд ещё не
 * ушёл», и рисовать нечего.
 */
export function arcPolyline(a: Pt, b: Pt, lift: number, lead: number, steps = ARC_STEPS): Pt[] {
  const out: Pt[] = [];
  for (let i = 1; i <= Math.ceil(steps * lead); i++) {
    out.push(arcPoint(a, b, lift, Math.min(lead, i / steps)));
  }
  return out;
}

/** Угол искры: чистая функция сида залпа, снаряда и номера искры (правило 5). */
export function sparkAngle(seed: number, shell: number, spark: number, arms: number): number {
  const step = (Math.PI * 2) / arms;
  return ((seed * 7 + shell * 5 + spark) % arms) * step + 0.35;
}
