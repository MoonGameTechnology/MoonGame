/**
 * ПО КОМУ БЬЁТ ПАТРУЛЬ (SHU-6.2) — выбор одной цели в круге висящей эскадры.
 *
 * Правило живёт отдельной чистой функцией, а не внутри тика патруля, потому что его
 * пережил прежний хозяин: здесь стоял дежурный вылет (CC-4), который база поднимала сама
 * навстречу опознанному врагу. Патруль заменил его целиком (SHU-6.6, резолюция владельца
 * 2026-10-04): «Держать патруль» поднимает эскадру снова событием ядра, без драйверов
 * хоста, и выбор цели у висящей эскадры остался один.
 *
 * 1. **Ближний раньше дальнего, при равной дистанции — меньший id.** Ровно то же правило,
 *    по которому выбирает цель ПЕРЕХВАТ (`shuttle.ts`, SHU-1.3): патруль и встречное
 *    звено поднимает одна и та же база из одного ангара, и два разных прицела у одного
 *    оружия объяснить игроку нечем. Сравнение по КВАДРАТУ расстояния — корень монотонен,
 *    а лишний `Math.sqrt` на каждом контакте не нужен.
 * 2. **Граница включительна** — та же мерка `withinRange`, по которой ядро пускает удар:
 *    цель, стоящая ровно на краю круга, достижима, иначе круг на карте обещал бы больше,
 *    чем бьёт патруль.
 * 3. **Нулевой радиус не бьёт вовсе.** Эскадры без круга в патруле не бывает, но если
 *    она там окажется, патруль обязан молчать, а не бить в упор.
 *
 * Кто попадает в список контактов (враждебность, видимость мин, живая позиция), решает
 * тик патруля: это чтение мира, а не правило выбора.
 */
import { withinRange } from './shuttle';

/** Точка на карте. */
export interface PatrolPoint {
  x: number;
  y: number;
}

/** Враждебный контакт — кандидат в цели. */
export interface PatrolContact {
  id: string;
  pos: PatrolPoint;
}

/** По кому бьёт патруль: ближайший контакт в круге (правила 1–3). `null` — бить некого. */
export function patrolTarget(
  center: PatrolPoint,
  radius: number,
  contacts: readonly PatrolContact[],
): string | null {
  if (radius <= 0) return null; // правило 3
  let bestId: string | null = null;
  let bestD2 = Infinity;
  for (const c of contacts) {
    if (!withinRange(center, c.pos, radius)) continue; // правило 2
    const dx = c.pos.x - center.x;
    const dy = c.pos.y - center.y;
    const d2 = dx * dx + dy * dy;
    // Правило 1: ближе — раньше; на равной дистанции побеждает меньший id.
    if (d2 < bestD2 || (d2 === bestD2 && bestId !== null && c.id < bestId)) {
      bestId = c.id;
      bestD2 = d2;
    }
  }
  return bestId;
}
