/**
 * Быстрый заказ стройки правым кликом по плитке (REFM-85).
 *
 * На ПК правая кнопка — игровой ввод: клик по плитке каталога ставит заказ СРАЗУ, минуя
 * окно подтверждения (левый клик по-прежнему открывает досье). Ускорение это приятное,
 * но оно обходит окно — а значит все проверки, которые окно делало, должны стоять здесь,
 * и ровно те же.
 *
 * 1. **Быстрый заказ идёт ТЕМ ЖЕ путём, что кнопка «Построить здесь»,** только без
 *    подтверждения. Два независимых набора проверок неизбежно разъедутся, и правый клик
 *    начнёт ставить то, чего кнопка не даёт.
 * 2. **Якорь плитки — пара `kind:id`.** Нет любой половины — приказа нет: обрезанный или
 *    пустой якорь не должен превращаться в заказ «чего-нибудь».
 * 3. **Заказ только на СВОЁМ мире.** Чужой мир чужой и для правого клика тоже.
 * 4. **Здание должно быть разрешено типом сектора** — иначе плитка обещает стройку,
 *    которую ядро отобьёт.
 * 5. **Занятое место повторно не заказывается** (построено, строится, в очереди,
 *    приостановлено). Без этого быстрый двойной правый клик успевает поставить вторую
 *    копию РАНЬШЕ, чем плитка перерисуется запертой.
 * 6. **Гейты 4–5 — про ЗДАНИЯ.** У юнитов нет лимита «одна копия на мир», у них своя
 *    очередь, и запирать их теми же проверками нельзя.
 *
 * Сам ПК-гейт (у пальца правой кнопки нет) остаётся на месте вызова: это свойство
 * устройства, а не правило стройки.
 *
 * **Про достижимость гейтов 4–5 на сегодня.** Якорь заказа выдаёт только каталог плиток
 * боковой панели, а он остался лишь у ЮНИТОВ: каталог зданий переехал в отдельное окно
 * `#buildwin`, которое живёт вне `#side` и своих якорей не ставит. То есть `kind ===
 * 'building'` сюда сейчас не приходит вовсе. Правила оставлены и описаны, потому что они
 * зеркалят кнопку «Построить здесь» (правило 1) и обязаны сработать, если плитки зданий
 * вернутся в панель, — но полагаться на них как на ЕДИНСТВЕННУЮ защиту от двойного
 * заказа нельзя: сейчас эту работу делает окно.
 */

/** Что заказывает плитка. */
export interface BuildOrder {
  kind: 'building' | 'unit';
  id: string;
}

/** Обстановка вокруг заказа. */
export interface QuickBuildGates {
  /** Владелец выбранного мира; `null` — мир не выбран. */
  worldOwner: string | null;
  /** Кто заказывает. */
  me: string;
  /** Разрешает ли тип сектора это здание. */
  sectorAllows: boolean;
  /** Место занято: построено / строится / в очереди / приостановлено. */
  locked: boolean;
}

/** Разбор якоря плитки `kind:id` (правило 2). */
export function parseBuildAnchor(raw: string | undefined): BuildOrder | null {
  const [kind, id] = (raw ?? '').split(':');
  if (!kind || !id) return null;
  if (kind !== 'building' && kind !== 'unit') return null;
  return { kind, id };
}

/** Приказ, который переживёт все гейты, или `null` (правила 2–6). */
export function quickBuildOrder(
  raw: string | undefined,
  gates: QuickBuildGates,
): BuildOrder | null {
  const order = parseBuildAnchor(raw);
  if (!order) return null;
  if (gates.worldOwner === null || gates.worldOwner !== gates.me) return null;
  if (order.kind === 'building' && (!gates.sectorAllows || gates.locked)) return null;
  return order;
}
