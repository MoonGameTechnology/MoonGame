/**
 * Фишка ресурса в верхней полосе: как число говорит правду (REFM-190).
 *
 * Всплывающая карточка за тапом уже вынесена (`resourceCard.ts`), а сама ФИШКА до сих пор
 * собиралась россыпью выражений в `frame()`. Каждое из правил ниже чинит конкретное враньё
 * — не падение, а именно неверное показание, по которому игрок принимает решения.
 *
 * 1. **Поток меньше единицы округляется до ДЕСЯТОЙ, а не до целого.** Содержание построек и
 *    армии даёт дренаж в доли за час сплошь и рядом; обычное округление превратило бы его в
 *    «0», и игрок увидел бы «ничего не происходит», пока запас утекает. Ровно эта причина
 *    записана у `round1` в `format.ts` — здесь живёт ВЫБОР между ним и целым.
 * 2. **Гаснет фишка, только когда пусто И НЕ ТЕЧЁТ.** Ноль на складе при живом притоке — это
 *    не «ресурс не участвует в матче», а «вот-вот появится»; погасить такую фишку значит
 *    спрятать ровно то, за чем игрок следит. Отсюда «И», а не «ИЛИ».
 * 3. **Долг вытесняет скорость.** При неоплаченном содержании скорость ВРЁТ: она считает
 *    производство, которое до игрока уже не доходит. Поэтому на месте цифры встаёт знак
 *    долга — то, что нужно чинить, а не то, что красиво считается.
 * 4. **Нулевой поток не пишется вовсе.** «+0/ч» — это шум на месте, где игрок ищет движение;
 *    пустое место читается быстрее, чем ноль, который надо ещё осмыслить.
 * 5. **`kfmt` только от единицы и выше.** Он округляет до целого ради «k» на тысячах, и на
 *    дроби стёр бы ту самую десятую из правила 1 — вернув «0», от которого она и спасает.
 * 6. **На телефоне скорость уходит с полосы в ЦВЕТ.** Места под цифры там нет: отрицательный
 *    поток красит сам запас, точная скорость живёт за тапом. Печатать её всё равно значило бы
 *    обрезать число на середине — это хуже, чем не печатать.
 */
import { round1 } from './format';

/** Правило 1: доли часа сохраняются, целые остаются целыми. */
export function flowRounded(raw: number): number {
  return Math.abs(raw) >= 1 ? Math.round(raw) : round1(raw);
}

/** Правило 2: фишка тускнеет, только если ресурс и пуст, и неподвижен. */
export function chipDead(stock: number, flow: number): boolean {
  return stock === 0 && flow === 0;
}

/** Правило 3: этот ресурс числится в неоплаченном содержании. */
export function chipShort(arrears: readonly string[], key: string): boolean {
  return arrears.includes(key);
}

/** Правила 4 и 6: печатать ли скорость рядом с запасом. */
export function flowShown(mobile: boolean, flow: number): boolean {
  return !mobile && flow !== 0;
}

/** Куда смотрит стрелка: класс подписи по знаку потока. */
export function flowSign(flow: number): 'up' | 'dn' {
  return flow > 0 ? 'up' : 'dn';
}

/** Правило 5: сокращать до «k» можно только то, что не потеряет десятую. */
export function flowDigits(flow: number, kfmt: (n: number) => string): string {
  return Math.abs(flow) >= 1 ? kfmt(flow) : String(flow);
}

/** Приток пишется со знаком: без «+» скорость читается как ещё одно показание запаса. */
export function flowPrefix(flow: number): string {
  return flow > 0 ? '+' : '';
}

/** Правило 6: на телефоне убыль красит сам запас. */
export function stockBleeds(mobile: boolean, flow: number): boolean {
  return mobile && flow < 0;
}
