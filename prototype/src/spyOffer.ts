/**
 * Что панель предлагает по шпионажу на этом мире (REFM-92).
 *
 * Кнопка «украсть окно разведки» и живой обратный отсчёт занимают одно место, и в
 * разметке это был тернарник внутри условия — из него не читается, почему у одних миров
 * предложения нет вовсе, а у других оно серое.
 *
 * 1. **Свой мир не шпионят.** Про него и так всё известно.
 * 2. **НИЧЕЙНЫЙ мир не шпионят тоже.** Красть сведения не у кого: у пустого узла нет
 *    хозяина, чью разведку можно вскрыть.
 * 3. **Пока окно живо — вместо кнопки ОТСЧЁТ.** Платить второй раз за то, что уже
 *    куплено, игроку предлагать нельзя.
 * 4. **Нехватка кредитов ГАСИТ кнопку, но не прячет:** цена должна остаться на виду,
 *    иначе непонятно, чего копить.
 * 5. **Остаток окна не бывает отрицательным.** Кадр приходит и после истечения, а
 *    «осталось −3ч» — это поломка, а не информация.
 */

/** Что показать в строке шпионажа. */
export type SpyOffer =
  /** Ничего: свой или ничейный мир. */
  | 'none'
  /** Окно уже куплено — показываем отсчёт. */
  | 'window'
  /** Можно купить. */
  | 'buy'
  /** Кнопка есть, но денег не хватает. */
  | 'buy-disabled';

/** Предложение по шпионажу (правила 1–4). */
export function spyOffer(
  mine: boolean,
  hasOwner: boolean,
  windowLive: boolean,
  affordable: boolean,
): SpyOffer {
  if (mine || !hasOwner) return 'none';
  if (windowLive) return 'window';
  return affordable ? 'buy' : 'buy-disabled';
}

/** Сколько часов осталось у окна; истёкшее — ноль, не минус (правило 5). */
export function windowLeftH(until: number, now: number, hourMs: number): number {
  return Math.max(0, until - now) / hourMs;
}
