/**
 * Чем кадр даёт ВЫЙТИ из матча и начать заново (REFM-193).
 *
 * Три разных места — кнопка в баннере, кнопка в полосе скорости и сама полоса — решают
 * один вопрос: есть ли у игрока прямо сейчас путь наружу. Стояли они россыпью в `frame()`,
 * и каждое ошибается ТИХО: ничего не падает, просто выход либо предлагается там, где его
 * предлагать нельзя, либо исчезает там, где он единственный.
 *
 * 1. **Кнопка перезапуска в баннере — только на НАСТОЯЩЕМ конце соло-матча.** Сетевые
 *    статус-баннеры («переподключаюсь», «жду игроков») выглядят так же, но матч там не
 *    кончился: кнопка на них увела бы игрока из ЖИВОЙ партии, которая вот-вот вернётся.
 * 2. **Баннер убран — кэш его разметки ЗАБЫВАЕТСЯ.** Иначе следующий баннер с той же
 *    разметкой не нарисуется: кэш скажет «такое уже нарисовано», а узел к тому моменту
 *    скрыт и пуст — сообщение просто не дойдёт.
 * 3. **Кнопка перезапуска в полосе скорости — только в песочнице БЕЗ ботов.** Там матчу
 *    нечем «кончиться», значит и баннера с кнопкой не будет; в остальных режимах это была
 *    бы вторая кнопка перезапуска рядом с первой — две правды об одном действии.
 * 4. **На ТЕЛЕФОНЕ узел полосы скорости не гасится НИКОГДА.** Ряд на телефоне раскрывает
 *    кнопка скорости (UIX-3.2, `phoneSpeed.ts`), а погашенный узел не раскрылся бы. Выхода ⌂
 *    в ряду нет: на телефоне выход — «Выход в меню» в листе «Ещё» (UIX-3.1).
 *    На ПК полоса видна, только когда ей есть что нести (управление временем или
 *    перезапуск): пустая коробка в углу карты читалась как сломанное меню.
 * 5. **В сети управления временем нет ни на ПК, ни на телефоне, ни в какой сборке.**
 *    Временем распоряжается сервер: пауза и множители там ничего не меняют, и кнопки,
 *    которые не работают, игрок видел в углу сетевой партии (плейтест 2026-10-17). В соло
 *    на телефоне они есть всегда, на ПК — по дев-выключателю.
 * 6. **В забеге Sector Zero полоса несёт паузу и ТЕМП забега — на ПК и на телефоне.** У
 *    забега своя пара «▶ обычный / ▶▶ ускоренный» (PVR-2.2, `decisions/runTempo.ts`), и
 *    ускорение — часть продукта: время прохождения владелец назвал и с ним. Поэтому на ПК
 *    полоса видна и без дев-выключателя. «‖» — пауза забега (`YAG-6.2`; в полосе с
 *    2026-09-24, решение владельца), в дев-забеге рядом ещё ▶▶▶. Множители в забеге
 *    спрятаны (класс `spd-run`, CSS): они перенастраивают пару на темп песочницы — ×1
 *    растянул бы забег на 60–72 реальных часа.
 * 7. **В обучении первого матча полоса несёт ×300 урока — на ПК и на телефоне.** Урок идёт
 *    на настоящих часах стройки, науки и полёта, ускоренных в 300 раз (заказ владельца
 *    2026-10-23: «и скорость ×300 добавь туда»), и игрок видит этот темп фишкой «×300»
 *    рядом с паузой, а не только тостом на старте. На ПК полоса видна без дев-выключателя.
 */

/** Забытый кэш баннера: пустая разметка и есть «на экране ничего нет» (правило 2). */
export const BANNER_FORGOTTEN = '';

/** Правило 1: настоящий конец СОЛО-матча, а не сетевой статус. */
export function bannerOffersRestart(net: boolean, matchStatus: string | undefined): boolean {
  return !net && matchStatus === 'ended';
}

/** Правило 3: песочница без ботов — единственный режим, которому нужна кнопка в полосе. */
export function speedbarRestartShown(net: boolean, aiSeats: number): boolean {
  return !net && aiSeats === 0;
}

/** Правило 4: на телефоне узел живёт всегда — ряд раскрывает кнопка скорости; на ПК — пока
 *  ему есть что нести (управление временем, а с ним и темп забега по правилу 6, или перезапуск). */
export function speedbarShown(pcUi: boolean, timeControls: boolean, restart: boolean): boolean {
  return !pcUi || timeControls || restart;
}

/** Правило 5: в сети управления временем нет; в соло — дев-выключатель на ПК, всегда на
 *  телефоне. Правила 6 и 7 — в забеге и в обучении оно есть всегда. */
export function timeControlsShown(
  pcUi: boolean,
  devSpeedControl: boolean,
  net: boolean,
  run: boolean,
  lesson = false,
): boolean {
  return run || (!net && (lesson || (pcUi ? devSpeedControl : true)));
}

/** Значение `style.display` для узла, который либо показан, либо убран. */
export function displayOf(shown: boolean): '' | 'none' {
  return shown ? '' : 'none';
}
