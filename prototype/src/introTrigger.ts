/**
 * Когда действие игрока поднимает обучающую вставку ONB-3 (REFM-100).
 *
 * Вставки учат «на первом настоящем применении»: приказ принят — можно объяснить, что
 * только что произошло. Условие висело тремя одинаковыми строками подряд в
 * `playerOrder`, и в них терялось само правило: почему вставка молчит во время тура и
 * почему она привязана к ПРИНЯТОМУ приказу, а не к нажатию кнопки.
 *
 * 1. **Учим на первом НАСТОЯЩЕМ применении.** Вставка привязана к принятому приказу:
 *    отказ ядра ничему не научит, а объяснять заранее — значит рассказывать про то,
 *    чего игрок ещё не делал.
 * 2. **Во время ТУРА вставки молчат.** Экран принадлежит шагу тура, и вторая всплывашка
 *    поверх него перебила бы обучение — двум учителям одновременно игрок не внемлет.
 * 3. **Один тип приказа — одна вставка,** и приказы без своей вставки не поднимают
 *    ничего: список закрыт, а не «всё, что похоже на действие».
 * 4. **«Мир идёт без вас» — только в сетевой партии.** Вставка обещает, что флот летит
 *    часами реального времени и мир идёт, пока игрок офлайн. Это правда только в сети:
 *    соло-схватка на выходе замирает и пропущенное не догоняет, а забег Sector Zero без
 *    игрока встаёт на паузу (YAG-6.2) и летит секундами. Заказ владельца 2026-09-24 —
 *    убрать сообщение; там, где оно правда, оно осталось.
 */

/** Ключ обучающей вставки. */
export type IntroKey = 'asyncDelay' | 'retreat';

/** Какой приказ какую вставку объясняет (правило 3). */
const BY_ACTION: Record<string, IntroKey> = {
  'fleet.move': 'asyncDelay',
  'fleet.retreat': 'retreat',
};

/** Вставки, правдивые только в сетевой партии (правило 4). */
const NET_ONLY: ReadonlySet<IntroKey> = new Set(['asyncDelay']);

/**
 * Вставка, которую поднимает ПРИНЯТЫЙ приказ этого типа, или `null` — если у приказа
 * своей вставки нет, сейчас идёт тур или вставка не про этот режим (правила 1–4).
 * `net` — партия сетевая.
 */
export function introFor(actionType: string, tourActive: boolean, net: boolean): IntroKey | null {
  if (tourActive) return null;
  const key = BY_ACTION[actionType] ?? null;
  return key && NET_ONLY.has(key) && !net ? null : key;
}
