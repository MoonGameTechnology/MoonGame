/**
 * Куда попадает игрок, пришедший ПО ССЫЛКЕ на сессию (ADDR-5).
 *
 * Ссылку на партию пересылают, кладут в закладки и открывают через неделю — поэтому по
 * ней приходит кто угодно и когда угодно: участник, посторонний, вовсе не залогиненный
 * человек. Загрузочный блок вёл эту ветку так, будто вход всегда удаётся: прятал оверлей
 * (`showConnect(false)`) и НИ РАЗУ не показывал его обратно. Из-за этого и карточка
 * входа, и текст отказа выставлялись внутри скрытого экрана — игрок видел пустоту.
 *
 * 1. **Отказ никогда не оставляет пустой экран.** Что бы ни ответил сервер, игрок
 *    остаётся на ВИДИМОМ экране. Тупик здесь дороже обычного: по ссылке приходят в том
 *    числе те, кто видит игру впервые, и чёрный экран для них равен закрытой игре.
 * 2. **Куда именно — решает наличие сессии, а не код отказа.** Есть живая сессия →
 *    главное меню: человек уже свой, ему есть куда идти и что там делать. Нет сессии →
 *    стартовый экран с регистрацией/входом: главное меню без сессии всё равно пустое, а
 *    представиться нужно раньше всего остального.
 * 3. **Код отказа на посадку не влияет.** «Матча нет», «мест нет» и «вход закрыт» ведут
 *    в одно и то же место. Иначе ссылка превращается в оракул: по тому, КУДА тебя
 *    отправило, посторонний узнаёт, существует ли партия, — а знание идентификатора не
 *    должно давать даже такого ответа. Причина отказа при этом не теряется: её несут
 *    словами (`errorRoute.ts`, правило 4) на тот экран, куда игрок приземлился.
 * 4. **Сервер без аккаунтов пускает сразу.** LAN-харнесс не спрашивает пароль, сессии на
 *    нём нет по устройству, и требовать её значит запереть вход по ссылке на том самом
 *    сценарии, ради которого ссылку и дают, — «открой и играй».
 */

/** Где игрок окажется после перехода по ссылке. */
export type JoinLanding =
  /** Пробуем войти в матч (правило 4 либо живая сессия). */
  | 'match'
  /** Главное меню: сессия есть, но в матч не пустили (правило 2). */
  | 'hub'
  /** Стартовый экран — регистрация или вход (правило 2). */
  | 'welcome';

/** Что известно к моменту решения. */
export interface JoinAttempt {
  /** Сервер требует аккаунт (иначе LAN-харнесс без авторизации). */
  authRequired: boolean;
  /** Для этого сервера есть кэшированная сессия. */
  hasSession: boolean;
  /** Войти уже пробовали и не пустили (отказ ДО впуска в матч). */
  refused: boolean;
}

/** Куда вести игрока, пришедшего по ссылке (правила 1–4). */
export function joinLanding(a: JoinAttempt): JoinLanding {
  if (a.refused) return a.hasSession ? 'hub' : 'welcome';
  return a.authRequired && !a.hasSession ? 'welcome' : 'match';
}
