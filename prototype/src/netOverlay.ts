/**
 * Служебное наложение над картой: FPS, задержка до сервера и признак рассинхронизации
 * (REFM-192).
 *
 * Собиралось прямо в `frame()` вложенными `if`'ами. Ошибается оно ТИХО и именно тем
 * способом, который хуже отсутствия показания: строка либо не появляется там, где нужна,
 * либо остаётся висеть, когда её уже нечем подтвердить. Правила ниже — не защита от
 * невозможного, каждое чинит конкретную поломку.
 *
 * 1. **Десинк показывает наложение САМ, помимо галочки игрока.** Расхождение с сервером —
 *    единственное, о чём игрок должен уметь сообщить словами «у меня написано desync ✗ 4»;
 *    спрятать его за выключенной настройкой значит потерять этот отчёт целиком. Дев-хром
 *    (`DEV_UI`) включает наложение по той же причине — оно там рабочий инструмент.
 * 2. **Задержка и признак синхронизации существуют только в СЕТИ.** В соло сервера нет, и
 *    «0 ms · sync ✓» — не показание, а выдумка про несуществующий канал: игрок поверит, что
 *    связь проверена, хотя проверять было нечего.
 * 3. **Неизмеренная задержка пишется многоточием, а не нулём.** До первого замера «0 ms»
 *    соврало бы про идеальный канал; «· · ms» честно значит «ещё не знаю».
 * 4. **Счётчик расхождений НАКОПИТЕЛЬНЫЙ.** Одно расхождение бывает случайным, растущее
 *    число — уже отчёт о поломке; без числа игрок не отличит одиночный сбой от постоянного.
 * 5. **Красный цвет — только по десинку в сети.** Цвет здесь не украшение, а второй канал
 *    того же сообщения: он виден боковым зрением, когда цифры не читают. Просадка FPS им не
 *    красится — это не поломка связи, и красный на ней обесценил бы сигнал.
 * 6. **Условие ушло — наложение ОЧИЩАЕТСЯ.** Иначе последняя строка так и висит поверх
 *    карты, и мёртвое показание читается как живое: «60 FPS · 30 ms · sync ✓» после того,
 *    как соединение давно закрыто.
 */

/** Очищенное наложение: пустая строка и есть признак «на экране ничего нет» (правило 6). */
export const CLEARED = '';

/** Правило 1: своя галочка, дев-хром ИЛИ живой десинк в сети. */
export function overlayShown(
  optIn: boolean,
  devUi: boolean,
  net: boolean,
  desync: boolean,
): boolean {
  return optIn || devUi || (net && desync);
}

/** Правило 3: замер есть — миллисекунды, замера нет — многоточие. */
export function pingText(rtt: number | null): string {
  return rtt === null ? '· · ms' : `${Math.round(rtt)} ms`;
}

/** Правило 4: расхождение названо числом, согласие — галочкой. */
export function syncText(desync: boolean, count: number): string {
  return desync ? `desync ✗ ${count}` : 'sync ✓';
}

/** Правила 2–4: строка наложения целиком. Метка сборки дописывается, когда она есть. */
export function overlayText(
  fps: number,
  net: boolean,
  rtt: number | null,
  desync: boolean,
  count: number,
  buildTag: string,
): string {
  let text = `${Math.round(fps)} FPS`;
  if (net) text += ` · ${pingText(rtt)} · ${syncText(desync, count)}`;
  if (buildTag) text += ` · ${buildTag}`;
  return text;
}

/** Правило 5: тревожный цвет — ровно на сетевом десинке. */
export function overlayAlarm(net: boolean, desync: boolean): boolean {
  return net && desync;
}

/** Правило 6: чистить нужно только то, что на экране ещё есть. */
export function needsClearing(shown: string): boolean {
  return shown !== CLEARED;
}
