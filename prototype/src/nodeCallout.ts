/**
 * Подпись узла на карте: чем мир отличается от путевой точки (REFM-117).
 *
 * У каждого узла есть имя, а у опознанного — ещё строка телеметрии. Решений тут три, и
 * все они стояли вложенными тернарниками прямо в кадре: во что красить, каким кеглем и
 * показывать ли вторую строку. Из такой записи не читалось главное — что подписи ДЕЛЯТ
 * карту на «где играют» и «через что летают».
 *
 * 1. **Мир подписан ЯРЧЕ и крупнее прочих секторов.** Мир — приз, который захватывают;
 *    путевая точка и астероидное поле нужны только для маршрута. Сравняй подписи — и
 *    карта станет равномерным текстовым полем, по которому не видно, где играть.
 * 2. **Цвет подписи несёт ВЛАДЕЛЬЦА, но только у опознанного узла.** Цвет владельца и
 *    есть разведданные: покрась им неопознанный — и туман перестанет что-либо скрывать.
 * 3. **Ничейный опознанный узел красится СВОИМ оттенком** — не владельческим и не
 *    туманным. «Здесь никого» — это тоже сведение, добытое разведкой, и путать его с
 *    «не знаем» нельзя.
 * 4. **Строка телеметрии живёт только на детальном зуме.** На схематичном виде у узла
 *    остаётся одно имя: вторая строка там всё равно нечитаема, а место занимает.
 * 5. **У тихого сектора телеметрия показывается, только если в нём что-то есть.** Мир
 *    отчитывается всегда — по нему принимают решения; а «G:0 B:—» у пустой путевой точки
 *    это шум, повторяющий то, что и так видно по её виду.
 * 6. **Неопознанный узел говорит об этом СЛОВАМИ.** Пустое место под именем читалось бы
 *    как «разведан и пуст» — ровно наоборот к правде.
 *
 * _Замечено при выносе, НЕ чинил — правило 6 СЕЙЧАС НЕДОСТИЖИМО._ До подписи
 * неопознанный узел не доходит: выше по циклу отрисовки его перехватывает фог-маркер
 * (`view === 'remembered' | 'unexplored'` → `drawFogMarker` и `continue`), а пустой
 * узел — свой survey-маркер. Значит на подписи `identified` всегда истинно, и ветка
 * «нет телеметрии» вместе с туманными чернилами — мёртвый код. Правило перенесено
 * ДОСЛОВНО: убрать его значило бы менять поведение под предлогом выноса, а оживить —
 * решать за дизайн, показывать ли подпись сквозь туман. Заодно объяснилось, почему в
 * этой ветке до сих пор сидит английский литерал мимо `/localization`: его никто не
 * видел. Оба факта выписаны в `docs/backlog.md`.
 */

/** Насколько узел важен подписи. */
export type CalloutTier =
  /** Мир — приз, который захватывают (правило 1). */
  | 'world'
  /** Прочий сектор: путевая точка, поле, туманность. */
  | 'sector';

/** Чем красить имя узла. */
export type CalloutInk =
  /** Цветом владельца (правило 2). */
  | 'owner'
  /** Ничейный, но опознанный (правило 3). */
  | 'neutral'
  /** Неопознанный — нейтрально-серым (правило 2). */
  | 'fogged';

/** Что показывать второй строкой. */
export type CalloutLine =
  /** Ничего (правила 4–5). */
  | { do: 'none' }
  /** Гарнизон и постройки. */
  | { do: 'stats' }
  /** «Нет телеметрии» словами (правило 6). */
  | { do: 'unknown' };

/** Что известно про узел, когда рисуется его подпись. */
export interface CalloutSight {
  /** Опознан ли узел прямо сейчас. */
  identified: boolean;
  /** Уровень детализации: `0` — схематичный вид (правило 4). */
  detail: number;
  tier: CalloutTier;
  /** Сколько единиц в гарнизоне (правило 5). */
  garrison: number;
  /** Сколько построек (правило 5). */
  buildings: number;
}

/** Мир или прочий сектор (правило 1). */
export function calloutTier(sector: string): CalloutTier {
  return sector === 'planet' ? 'world' : 'sector';
}

/** Чем красить имя (правила 2–3; `fogged` сейчас недостижим — см. шапку). */
export function calloutInk(identified: boolean, hasOwner: boolean): CalloutInk {
  if (!identified) return 'fogged';
  return hasOwner ? 'owner' : 'neutral';
}

/** Что писать второй строкой (правила 4–6; `unknown` сейчас недостижим — см. шапку). */
export function calloutLine(sight: CalloutSight): CalloutLine {
  if (sight.detail <= 0) return { do: 'none' }; // правило 4
  if (!sight.identified) return { do: 'unknown' }; // правило 6
  // правило 5: мир отчитывается всегда, тихий сектор — только когда есть о чём
  if (sight.tier === 'world' || sight.garrison > 0 || sight.buildings > 0) return { do: 'stats' };
  return { do: 'none' };
}
