/**
 * Рисовать ли общую границу двух провинций как БАРЬЕР (M2.7 → M4.3).
 *
 * В мозаике соседство читается глазами по общей границе, поэтому граница, через
 * которую нет пути, молча обещает переход, которого не существует. Вопрос всегда был
 * не «врёт ли граница», а «откуда клиент это ЗНАЕТ».
 *
 * Сначала (M2.7) знать было неоткуда: мозаику рисовали по координатам, а список путей
 * писали руками, и расхождение этих двух графов ничего не значило — на песочнице
 * прототипа расходились 59% границ, и пометить их все значило превратить карту в
 * лабиринт из ничего. Поэтому барьер ставили только там, где мир его объясняет сам:
 * у непроходимого сектора.
 *
 * С M4.3 соседство ВЫВОДИТСЯ из мозаики, и ядро публикует `Planet.sealed` — границы,
 * которые закрыла местность. Это уже не расхождение, а решение мира: скопление
 * астероидов впускает один подход, ионные штормы не смыкаются. Такую границу рисовать
 * барьером не просто можно — нужно, иначе игрок видит соседа, к которому не дойти.
 *
 * Два правила пережили обе версии:
 *
 * 1. **Молчим, когда мир не объясняет.** Нет ни печати в состоянии, ни непроходимой
 *    стороны — барьера нет. Старые карты со своим списком путей (песочница прототипа)
 *    печатей не носят, и выдумывать их за них клиент не вправе.
 * 2. **Молчим, когда игрок не видел обе стороны.** Неразведанный подход — это
 *    «неизвестно», а не подтверждённо закрыто (правило §3.2 каталога местностей).
 *    Барьер — это знание, а туман войны его как раз и не даёт.
 */

/** Одна сторона границы — ровно то, что нужно знать о ней, чтобы решить. */
export interface SealSide {
  /** Идентификатор провинции. */
  id: string;
  /** Соседи, границы с которыми ЗАКРЫТЫ (`Planet.sealed`). */
  sealed?: readonly string[];
  /** Вид этой провинции непроходим (`traversable: false` в каталоге). */
  impassable: boolean;
  /** Игрок видит её сейчас или помнит по разведке. */
  seen: boolean;
}

/** Закрыта ли граница между `a` и `b` — и знает ли об этом игрок. */
export function isSealedBorder(a: SealSide, b: SealSide): boolean {
  // Печать двусторонняя по построению, но читаем обе стороны: состояние могло прийти
  // из старого снимка, где вторая половина ещё не проставлена.
  const declared = a.sealed?.includes(b.id) === true || b.sealed?.includes(a.id) === true;
  if (!declared && !a.impassable && !b.impassable) return false; // правило 1
  return a.seen && b.seen; // правило 2
}
