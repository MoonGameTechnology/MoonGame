/**
 * Отложенный вход в матч: намерение, пережившее экран логина (REFM-51).
 *
 * Игрок нажимает «Войти» на матче, выбирает дом и кресло — и упирается в карточку
 * входа, потому что сессии ещё нет. Пока он вводит пароль, выбор должен где-то жить,
 * а после успешного входа — доехать до входа в матч ЦЕЛИКОМ. Отсюда правила.
 *
 * 1. **Прочитать и забыть — ОДНО действие.** Намерение одноразовое: доехало — его
 *    больше нет, иначе следующий заход в хаб утащит игрока в позавчерашний матч. Пока
 *    это были три отдельные переменные, «забыть» и «прочитать» писались разными
 *    строками — и порядок разъехался: кресло с домом обнулялись ПЕРЕД чтением, так что
 *    после логина игрок садился не туда, куда выбрал. `take()` делает оба шага сразу,
 *    расходиться нечему.
 * 2. **Намерение — это матч ВМЕСТЕ с креслом и домом.** Хранить один `matchId` значит
 *    молча терять выбор: до карточки входа игрок уже прошёл окно выбора дома.
 * 3. **Пустая строка — это «не выбрано».** Адресная строка отдаёт `?slot=` пустым, и
 *    пустое значение, доехав до запроса, читается сервером как ЗАДАННОЕ кресло — отказ
 *    на месте, которого игрок не выбирал (то же правило, что в `joinRules.ts`).
 */

/** Матч, в который игрок собирался, вместе с его выбором. */
export interface PendingJoin {
  matchId: string;
  /** Кресло из окна выбора дома; `undefined` — «сажай куда есть». */
  slot?: string;
  /** Дом, выбранный отдельно от стартовой точки (BF-30). */
  faction?: string;
  /** Совет учёных В ЭТУ сессию (ENTRY-4). Хранится по той же причине, что место и дом:
   *  игрок уходит логиниться уже ПОСЛЕ выбора, и потеряй мы состав — он сел бы играть
   *  без совета, который только что собрал. */
  scientists?: string[];
}

/** Хранилище одноразового намерения войти в матч. */
export interface PendingJoinStore {
  /** Запомнить намерение. Пустой матч не запоминается, пустой выбор не хранится. */
  remember(
    matchId: string,
    slot?: string | null,
    faction?: string | null,
    scientists?: readonly string[] | null,
  ): void;
  /** Забрать намерение и сразу забыть его — правило 1. */
  take(): PendingJoin | null;
  /** Есть ли намерение. Не забывает — это вопрос, а не выдача. */
  has(): boolean;
}

export function createPendingJoin(): PendingJoinStore {
  let pending: PendingJoin | null = null;
  return {
    remember(matchId, slot, faction, scientists) {
      if (!matchId) return;
      pending = { matchId };
      if (slot) pending.slot = slot;
      if (faction) pending.faction = faction;
      if (scientists && scientists.length > 0) pending.scientists = [...scientists];
    },
    take() {
      const taken = pending;
      pending = null;
      return taken;
    },
    has() {
      return pending !== null;
    },
  };
}
