/**
 * Очередь «штурмовать по прилёте»: что стало с отложенным приказом (REFM-58).
 *
 * Игрок целится в чужой мир, флот туда ЛЕТИТ, и приказ ждёт прилёта. Пока он ждёт, с
 * флотом может случиться что угодно, и на каждый случай ответ свой.
 *
 * 1. **Перенаправленный вручную флот теряет приказ.** Игрок передумал и послал флот в
 *    другое место; довезти штурм «на всякий случай» значит ударить не туда и не тогда.
 * 2. **Бой по прилёте — это и ЕСТЬ путь к штурму, приказ ждёт.** Флот встретили на
 *    орбите; снять приказ здесь значит потерять штурм ровно там, где он нужен, — игроку
 *    пришлось бы отдавать его заново, глядя на уже идущий бой.
 * 3. **Припарковался не в цели — приказ протух.** Долетел не туда (сбит с курса,
 *    перехвачен, слит) — штурмовать нечего, и держать запись незачем.
 * 4. **Исчез флот — исчез и приказ.** Иначе очередь копит мусор на весь матч и однажды
 *    выстрелит по идентификатору, который переиспользовали.
 *
 * Решает здесь только «пора ли спрашивать ядро». Сам вопрос «пройдёт ли штурм» — к ядру
 * (`canOrderAll`), и его ответ приказ снимает в любом случае: одно понятное сообщение
 * вместо цикла отказов.
 */

/** Флот в том виде, в каком его различает очередь. */
export interface QueuedFleet {
  /** Куда летит; `null`/`undefined` — стоит. */
  movement?: { destination?: string | null; to?: string | null } | null;
  /** Где стоит. */
  location?: string | null;
  /** Идёт бой — у флота есть его идентификатор. */
  battleId?: string | null;
}

/** Что делать с отложенным приказом прямо сейчас. */
export type AssaultOrderState =
  | 'gone' // флота нет — снять
  | 'redirected' // послан в другое место — снять
  | 'in-transit' // ещё летит к цели — ждать
  | 'in-battle' // бой по прилёте — ждать
  | 'lapsed' // встал не в цели — снять
  | 'ready'; // на месте и цел — спрашивать ядро

/** Снимается ли приказ в этом состоянии (всё, кроме ожидания и готовности). */
export function dropsOrder(state: AssaultOrderState): boolean {
  return state === 'gone' || state === 'redirected' || state === 'lapsed';
}

/**
 * Разобрать состояние отложенного приказа. `fleet` — `null`/`undefined`, если флота
 * больше нет. Цель приказа — `destId`.
 */
export function assaultOrderState(
  fleet: QueuedFleet | null | undefined,
  destId: string,
): AssaultOrderState {
  if (!fleet) return 'gone'; // правило 4
  if (fleet.movement) {
    // Правило 1: куда флот летит НА САМОМ ДЕЛЕ — конечная цель маршрута, а не
    // ближайший узел (`to`), иначе транзитная остановка выглядела бы отменой.
    const goingTo = fleet.movement.destination ?? fleet.movement.to ?? null;
    return goingTo === destId ? 'in-transit' : 'redirected';
  }
  if (fleet.battleId) return 'in-battle'; // правило 2
  if (fleet.location !== destId) return 'lapsed'; // правило 3
  return 'ready';
}
