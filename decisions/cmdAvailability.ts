/**
 * Кому какая команда положена — доступность кнопок командной полосы (REFM-78).
 *
 * Полоса рисуется от ВЫДЕЛЕНИЯ, и правила здесь не косметические: кнопка, обещающая
 * невозможное, стоит игроку хода, а команда, разосланная на группу вместо одного флота,
 * рассылает приказы с разной арифметикой.
 *
 * 1. **«Слить» — групповая, «Разделить» и «Десант» — строго ОДНОФЛОТОВЫЕ.** Гарнизон и
 *    трюм у каждого флота свои; один клик на группу разослал бы разные приказы под общей
 *    кнопкой.
 * 2. **Слияние доступно и одиночке — если во флоте игрока есть с кем сливаться.** Иначе
 *    кнопка вооружает выбор цели, которой не существует.
 * 3. **Делить можно флот с двумя и более кораблями вне боя** — стоит он, летит или ждёт
 *    на линии (замечание владельца 2026-09-25: «флот делить можно в любой момент»). В бою
 *    состав не режут, а из одного корабля нового флота не выйдет.
 * 4. **Захватить можно только чужой захватываемый мир с ближней орбиты** (мобильная
 *    ветка): пустой космос не берут, свой мир штурмовать незачем, с дальней орбиты
 *    десанту не дотянуться.
 * 5. **Общий режим огня показывается только при ЕДИНОГЛАСИИ.** При разнобое кнопка
 *    обязана быть нейтральной, иначе она врёт про часть флотов выделения.
 * 6. **Штурм спрашивает ДЕСАНТ, а не корабли** (заказ владельца 2026-09-21: «кнопка
 *    штурм появляется только если есть во флоте кем штурмовать»). Высаживается десант,
 *    а не корпуса (`dockedActions.ts`, правило 4): эскадре из одних боевых кораблей
 *    высаживать НЕКОГО, на защищённом мире ядро ответит `E_NO_TROOPS`, и кнопка обещала
 *    бы заведомый отказ. Командная кнопка наводится на мир ПОСЛЕ нажатия, поэтому про
 *    оборону цели в момент отрисовки не известно ничего — спрашивается только состав.
 *    Захват пустого мира порожняком от этого не пропадает: он законен (`dockedActions`,
 *    правило 4), и предлагает его карточка пристыкованного флота — там мир уже известен.
 */

/** Слияние: группа сливается в один тап, одиночка вооружает выбор напарника (правило 2). */
export function canMerge(selectedCount: number, ownFleetTotal: number): boolean {
  return selectedCount >= 2 || (selectedCount === 1 && ownFleetTotal >= 2);
}

/** Флот глазами однофлотовых команд. */
export interface LoneFleet {
  location?: string | null;
  movement?: unknown;
  battleId?: string | null;
  ships: number;
}

/** Деление: один флот с 2+ кораблями не в бою — стоит он или летит (правила 1, 3). */
export function canSplit(lone: LoneFleet | null): boolean {
  return splitBlock(lone) === null;
}

/**
 * ПОЧЕМУ делить нельзя — ключ подсказки, или `null`, когда можно (правила 1, 3).
 *
 * Серая кнопка без объяснения читается как сломанная (сообщение владельца 2026-09-24:
 * «кнопка деления флотов не работает»): флот в пути или в бою — а в Sector Zero это
 * большая часть забега, — и кнопка просто молчит. На ПК причина жила только в подсказке
 * мыши, на телефоне её не было вовсе. Порядок проверок — от того, что игрок исправит
 * быстрее: выбрать один флот, дождаться конца боя.
 */
export function splitBlock(lone: LoneFleet | null): string | null {
  if (!lone) return 'cmd.split.why.one';
  // В пути делить можно (замечание владельца 2026-09-25: «флот делить можно в любой
  // момент»): ядро ведёт отделённую часть тем же курсом.
  if (lone.battleId) return 'cmd.split.why.battle';
  if (lone.ships < 2) return 'cmd.split.why.single';
  return null;
}

/** Мир глазами штурма с орбиты. */
export interface AssaultSpot {
  orbit?: string;
  location?: string | null;
  /** Владелец мира под флотом; `null` — ничей. */
  worldOwner: string | null;
  /** Можно ли вообще захватывать такой сектор (пустой космос — нельзя). */
  capturable: boolean;
}

/** Штурм с орбиты (мобильная ветка): чужой захватываемый мир с ближней орбиты (правило 4). */
export function canAssaultFromOrbit(spot: AssaultSpot, fleetOwner: string): boolean {
  return (
    spot.orbit === 'near' && !!spot.location && spot.worldOwner !== fleetOwner && spot.capturable
  );
}

/** Есть ли в выделении КЕМ штурмовать (правило 6). `landing` — размер десанта каждого
 *  выделенного флота. Это вопрос о СОСТАВЕ, а не о цели, поэтому он и решает ПОКАЗ
 *  кнопки (`cmdPresence.ts`, правило 3), тогда как пригодность цели её гасит. */
export function canAssaultAim(landing: readonly number[]): boolean {
  return landing.some((n) => n > 0);
}

/**
 * Единогласный режим выделения или `null` при разнобое (правило 5). Пустой вход — тоже
 * `null`: показывать нечего.
 */
export function uniformMode<T>(modes: readonly T[]): T | null {
  const set = new Set(modes);
  return set.size === 1 ? [...set][0]! : null;
}
