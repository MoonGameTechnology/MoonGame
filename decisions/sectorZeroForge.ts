/**
 * Попытка улучшения в Sector Zero — мастерская и академия (SZE-0.3).
 *
 * Механика одна на оба места: звезда модуля и звезда навыка — это уровень заточки
 * `EC-2.1` под своим именем, и вторую лестницу заводить запрещено (§0.2
 * `sector-zero-economy-roadmap.md`). Отличается только предмет.
 *
 * ## Почему бросок тут не случайный
 *
 * `EC-2.1` требует СЕРВЕРНЫЙ seed ради аудита. В Sector Zero сервера нет: продукт
 * одиночный и обязан работать без сети (`yandex-games-roadmap.md`). Наивное
 * `Math.random()` в игре с сохраняемым профилем — это приглашение перекрутить неудачу
 * перезагрузкой страницы: игрок жмёт F5 до нужного исхода, и вся экономика попыток
 * перестаёт что-либо стоить.
 *
 * Поэтому исход **выводится** из того, что уже записано в профиле: сид профиля, номер
 * попытки, предмет и текущая звёздность. Та же попытка всегда даёт тот же результат —
 * перезагрузка не перекатывает, а следующая попытка отличается номером. Приём не новый:
 * `PVR-3.3` уже дедупит награду по СЕРИЙНОМУ номеру попытки, а не по игровому времени,
 * ровно потому, что время повторяется, а номер — нет.
 *
 * Ни `Math.random()`, ни `Date.now()` здесь нет и быть не должно.
 *
 * ## ⚠️ Номер попытки — ПОИМЁННЫЙ, и это защита, а не бухгалтерия
 *
 * Бросок — чистая функция от ключа, а игрок в офлайновой игре может посчитать её сам:
 * алгоритм уезжает к нему в сборке. Помешать этому нельзя. Можно другое — сделать так,
 * чтобы **подкрутка стоила ровно столько же, сколько честная попытка**.
 *
 * Из этого следует форма счётчика. Будь он общим на профиль, открылся бы обход: жечь
 * ДЕШЁВЫЕ попытки на дешёвом модуле (20 ⌖), пока номер не встанет на удачный для
 * дорогой ступени (360 ⌖). Поимённый счётчик это закрывает: единственный способ сдвинуть
 * бросок предмета — заплатить цену ЭТОГО предмета.
 *
 * Вызывающий обязан передавать сюда число попыток, потраченных НА ЭТОТ ПРЕДМЕТ
 * (`SectorZeroProgress.forgeTries[id]`), и увеличивать его на КАЖДОЙ попытке, удачной
 * или нет.
 *
 * ## Инвариант провала
 *
 * Неудача сжигает ВЛОЖЕННОЕ (цену попытки), но **никогда не снижает достигнутую
 * звёздность** — резолюция владельца 2026-09-20 (`economy-roadmap.md`). Поэтому у
 * результата нет ветки «звезда потеряна»: её не существует как состояния.
 */

/** Ступень лестницы: шанс успеха и цена попытки. Форма совпадает с `data/sectorZeroStars.json`. */
export interface ForgeStep {
  chance: number;
  warrants: number;
  /** Доля собственного вклада предмета, которую добавляет ступень (SZE-1.1). */
  bonus?: number;
  /** Потолок попыток на ступени (`EC-2.2`): попытка с этим номером не бросает, а удаётся.
   *  Ноль = гарантии нет. См. {@link ForgeAttempt.shards}. */
  pity?: number;
}

/** Лестница звёздности целиком. */
export interface ForgeLadder {
  cap: number;
  guaranteed: number;
  steps: readonly ForgeStep[];
}

/** Что именно и от чьего имени улучшают. */
export interface ForgeAttempt {
  /** Сид профиля Sector Zero — постоянный для игрока. */
  seed: string;
  /** Сколько попыток уже потрачено НА ЭТОТ предмет (`forgeTries[target]` профиля) —
   *  поимённо, а не сквозным счётчиком профиля: см. шапку про подкрутку. */
  attempt: number;
  /** Идентификатор предмета: модуль или навык. */
  target: string;
  /** Текущая звёздность предмета: 0 = ни одной звезды. */
  star: number;
  /** Осколки — сколько попыток на ТЕКУЩЕЙ ступени уже сгорело (`EC-2.2`). Копятся при
   *  неудаче и обнуляются, когда звезда взята: гарантия принадлежит ступени, а не
   *  предмету навсегда. В ключ броска НЕ входит — иначе накопление меняло бы бросок,
   *  и «до порога честный бросок» превратилось бы в «до порога другой бросок». */
  shards: number;
}

/** Почему улучшать нельзя. `null` в {@link ForgeOutcome.reason} = можно. */
export type ForgeRefusal = 'E_FORGE_AT_CAP' | 'E_FORGE_NO_STEP' | 'E_FORGE_NOT_ENOUGH';

/** Исход попытки — полностью выводимый, без скрытого состояния. */
export interface ForgeOutcome {
  /** Разрешена ли попытка вообще. */
  allowed: boolean;
  /** Удалась ли она. Всегда `false`, когда `allowed === false`. */
  success: boolean;
  /** Звёздность ПОСЛЕ попытки. При неудаче равна прежней — провал не отнимает. */
  star: number;
  /** Шанс ЭТОЙ попытки — его показывают игроку ДО подтверждения (`EC-2.3`). На гарантии
   *  (низ лестницы или набранный pity) равен `1`, а не номинальному шансу ступени:
   *  показать «30%» там, где бросок уже не делается, значит соврать ровно в том месте,
   *  ради честности которого требование и написано. */
  chance: number;
  /** Сколько Варрантов спишется. Сгорает и при неудаче. */
  warrants: number;
  /** Код отказа или `null`. */
  reason: ForgeRefusal | null;
}

/**
 * Детерминированный бросок в [0, 1) из параметров попытки — FNV-1a по строке ключа.
 *
 * Взят именно хеш, а не «сид + счётчик»: счётчик пришлось бы хранить и синхронизировать,
 * а хеш выводится из того, что в профиле уже есть. Смена любого из четырёх полей даёт
 * другой бросок, повтор тех же — тот же.
 *
 * Экспортируется ради тестов и отладки: показать игроку, что исход не подкручен, проще
 * всего умея его воспроизвести.
 *
 * Сам хеш вынесен в {@link hashUnit}: ротация витрины магазина (`SZE-3.2`) выводится из
 * своего ключа тем же приёмом, и вторая копия FNV в репозитории не нужна — разойдясь,
 * копии дали бы два «детерминированных» правила с разным поведением.
 */
export function hashUnit(key: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < key.length; i++) {
    hash ^= key.charCodeAt(i);
    // FNV-1a: умножение на 16777619 через сдвиги, чтобы остаться в 32 битах без переполнения.
    hash = (hash + ((hash << 1) + (hash << 4) + (hash << 7) + (hash << 8) + (hash << 24))) >>> 0;
  }
  return hash / 0x100000000;
}

export function forgeRoll(a: ForgeAttempt): number {
  return hashUnit(`${a.seed}\u0000${a.attempt}\u0000${a.target}\u0000${a.star}`);
}

/**
 * Исход попытки улучшения. Чистая функция: одни и те же аргументы → один и тот же ответ.
 *
 * `warrants` — сколько есть у игрока; при нехватке попытка не разрешается и ничего не
 * списывается. Проверка здесь, а не у вызывающего, чтобы «сколько стоит» и «хватает ли»
 * не разъехались двумя копиями цены.
 */
export function forgeOutcome(
  a: ForgeAttempt,
  ladder: ForgeLadder,
  warrants: number,
): ForgeOutcome {
  const deny = (reason: ForgeRefusal, chance = 0, cost = 0): ForgeOutcome => ({
    allowed: false,
    success: false,
    star: a.star,
    chance,
    warrants: cost,
    reason,
  });

  if (a.star >= ladder.cap) return deny('E_FORGE_AT_CAP');
  const step = ladder.steps[a.star];
  if (!step) return deny('E_FORGE_NO_STEP');
  if (warrants < step.warrants) return deny('E_FORGE_NOT_ENOUGH', step.chance, step.warrants);

  // Гарантированные ступени не бросают вовсе — не «бросают с шансом 1», а именно не
  // бросают: иначе правка вероятности молча превратила бы гарант в лотерею.
  //
  // Второй источник гарантии — накопленные осколки (`EC-2.2`): `pity` попыток на ступени
  // и есть её потолок. Без него серия неудач упирается в бесконечность, и игрок может
  // лить валюту без предела — это и есть то, за что штрафуют сторы, а не сам бросок.
  const pity = step.pity ?? 0;
  const sure = a.star < ladder.guaranteed || (pity > 0 && a.shards >= pity - 1);
  const success = sure || forgeRoll(a) < step.chance;
  return {
    allowed: true,
    success,
    star: success ? a.star + 1 : a.star, // провал не отнимает достигнутое
    chance: sure ? 1 : step.chance,
    warrants: step.warrants,
    reason: null,
  };
}
