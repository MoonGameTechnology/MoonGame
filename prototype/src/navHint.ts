/**
 * Подсказка «как пользоваться картой» — первый шаг обучения (ONB-11).
 *
 * Заказ владельца по живому наблюдению: краткое обучение объясняет, ЧТО делать (шахта,
 * корабль, курс), но нигде не сказано, как вообще управлять картой. «Нуб из нубов даже не
 * догадывается, что карту можно приблизить» — и вся дальнейшая цепочка идёт вслепую.
 *
 * 1. **Подсказка подстраивается под УСТРОЙСТВО, а не под язык или сборку.** На ПК у игрока
 *    колесо и правая рука на мыши, на телефоне — два пальца; текст про колесо на телефоне
 *    бесполезен ровно так же, как текст про щипок на ПК. Гейт — тот же `pcUi()`, на котором
 *    висит вся ПК-раскладка (`graphicsPrefs.ts`): «широкий экран + точный указатель +
 *    наведение», то есть настоящая мышь, а не просто широкое окно.
 * 2. **Никаких проверок: шаг закрывается кнопкой «Далее».** Жесты нельзя «сдать» — камера
 *    не часть игрового состояния, а гонять новичка «покрути колесо, я проверю» значит
 *    держать его на шаге, из которого не выйти, если жест не распознался.
 * 3. **Экран НЕ запирается — пробовать можно прямо сейчас.** Это единственный шаг, где
 *    польза именно в том, чтобы подёргать карту, пока подсказка на виду; модальный шаг
 *    заставил бы прочитать, закрыть и вспоминать по памяти. «Далее» никуда не денется.
 * 4. **Подсказка стоит ПЕРВОЙ, до всех дел.** Она объясняет не задачу, а сам способ
 *    смотреть на мир: после неё осмысленны и «тапните свой мир», и «задайте курс» — а
 *    до неё игрок не знает даже, что мир можно приблизить.
 */

/** Ключ подсказки по способу ввода (правило 1). */
export function navHintKey(mouse: boolean): string {
  return mouse ? 'onb.tour.first.nav.mouse' : 'onb.tour.first.nav.touch';
}
