/**
 * Как отдаётся приказ ШТУРМА (REFM-141).
 *
 * Штурм издаётся из двух мест: когда игрок бьёт по цели, у которой флот уже стоит
 * (`dispatchAssault`), и когда прилетел флот с отложенным приказом «штурмовать по
 * прибытии» (`pumpAssaultOrders`). Обе выписывали одно и то же своими руками.
 *
 * 1. **Годность штурма спрашивают у ЯДРА, а не проверяют руками.** Ядро одним ответом
 *    закрывает и «нет десанта», и «мир уже свой», и «его нельзя захватить», и чужой
 *    идущий штурм. Рукописный список условий отстанет от ядра на первом же новом правиле
 *    — и отстанет молча: игрок увидит кнопку, которая ничего не делает.
 * 2. **Штурмуют с БЛИЖНЕЙ орбиты, поэтому приказ идёт ПАРОЙ.** Перед штурмом флот
 *    переводится на ближнюю орбиту — и только если он не там. Разорви пару, и ядро
 *    откажет: игрок получит «штурм не начался» без всякой причины.
 * 3. **Перевод орбиты — не отдельное действие игрока.** Он часть штурма, поэтому и
 *    отменять его отдельно нечего: одна просьба — одна связка приказов.
 */

/** Приказы, которые надо издать, чтобы этот флот пошёл на штурм (правила 2–3). */
export type AssaultStep = 'orbit-near' | 'assault';

/** Что издать для флота, стоящего у цели: пару или только штурм. */
export function assaultSteps(orbit: string | undefined): AssaultStep[] {
  return orbit === 'near' ? ['assault'] : ['orbit-near', 'assault'];
}
