/**
 * Кого спрашивать про войну перед приказом (REFM-57).
 *
 * Ход или штурм через территорию игрока, с которым ты в мире, ядро не пропустит: сперва
 * нужна война. Клиент вместо отказа показывает окно «это объявит войну …», и собрать
 * его надо ровно из тех флотов и тех виновников, которые к делу относятся.
 *
 * 1. **Ход в мир, где флот УЖЕ стоит, — не ход.** Такие флоты отсеиваются заранее,
 *    иначе окно войны спросит про перелёт, которого не будет, и игрок объявит войну
 *    ради ничего.
 * 2. **Штурм — НЕ ход, и отсев «уже там» к нему не применяется.** Флот, стоящий у цели,
 *    штурмует с места: выкинь его — и приказ, ради которого всё затевалось, не уйдёт.
 * 3. **Виновники собираются со ВСЕХ флотов и без повторов.** Пять флотов, упирающихся в
 *    одного соседа, — это одно объявление войны, а не пять строк об одном и том же.
 * 4. **Порядок виновников стабилен** (порядок обнаружения), иначе текст окна пляшет
 *    между открытиями на одном и том же приказе.
 * 5. **У штурма есть СВОЙ виновник — владелец цели.** Даже по свободному маршруту
 *    нельзя высадиться на мир невраждебного игрока, и спросить об этом ядро заранее
 *    нельзя: флот ещё не там. Поэтому владелец цели проверяется отдельно.
 */

/** Флот в том виде, в каком его различает сборка окна. */
export interface FleetLike {
  id: string;
  /** Узел, в котором флот стоит; `null` — в пути. */
  location: string | null;
}

/** Кто полетит по приказу «ход»: все выбранные, кроме уже стоящих в цели (правило 1). */
export function moveMovers(fleets: readonly FleetLike[], destId: string): string[] {
  return fleets.filter((f) => f.location !== destId).map((f) => f.id);
}

/** Кто пойдёт на штурм: ВСЕ выбранные — стоящий у цели штурмует с места (правило 2). */
export function assaultMovers(fleets: readonly FleetLike[]): string[] {
  return fleets.map((f) => f.id);
}

/**
 * Собрать виновников со всех флотов: без повторов, в порядке обнаружения (правила 3–4).
 * `blockersOf` — вердикт по одному флоту; пустой список означает «этот пройдёт».
 */
export function collectBlockers(
  fleetIds: readonly string[],
  blockersOf: (fleetId: string) => readonly string[],
): string[] {
  const seen = new Set<string>();
  for (const id of fleetIds) {
    for (const blocker of blockersOf(id)) seen.add(blocker);
  }
  return [...seen];
}

/**
 * Виновник, которого добавляет сам штурм: владелец цели, если он не ты и проход к нему
 * не открыт (правило 5). `null` — высадка законна.
 *
 * `freePassage` — тот же предикат прохода, которым живёт ядро: он истинен там, где
 * высадка уже разрешена (идёт война), и ложен для мира, с которым ты в мире.
 */
export function assaultTargetBlocker(
  owner: string | null | undefined,
  me: string,
  freePassage: (owner: string) => boolean,
): string | null {
  if (owner == null || owner === me) return null;
  return freePassage(owner) ? null : owner;
}
