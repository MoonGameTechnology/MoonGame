/**
 * Кнопки, которые работают УДЕРЖАНИЕМ: подтверждение необратимого и автоповтор «±».
 *
 * Жизнь самого нажатия (взвод, «поехавший палец», съеденный завершающий тап) общая с
 * картой и каталогом и живёт в `holdPress.ts`. Здесь только то, что удержание делает на
 * кнопке.
 *
 * Подтверждение удержанием (приём из sl-ui-library, MIT):
 *
 * 1. **Необратимое подтверждают удержанием, а не вторым тапом.** Второй тап ложится
 *    ровно туда, куда лёг первый, поэтому случайный двойной тап расформировывал
 *    корпорацию или исключал участника. Удержание за одно движение не случается.
 * 2. **Короткий тап только показывает вопрос.** Игрок видит, что именно произойдёт, и
 *    решает, держать ли. Короткий тап по уже показанному вопросу его не исполняет.
 * 3. **Клик без нажатия работает по-старому, в два шага.** Экранный диктор и
 *    программный `click()` не умеют держать; первый такой клик показывает вопрос, второй
 *    исполняет. Палец и клавиатура всегда приходят с нажатием и сюда не попадают.
 * 4. **Срабатывает в момент, когда полоса дошла до конца,** а не на отпускании: игрок
 *    видит, что всё случилось, и тап после этого съедается (`holdPress.ts`, правило 4).
 *
 * Автоповтор (приём оттуда же):
 *
 * 5. **Тап меняет на один шаг, удержание повторяет шаг.** Заказ 20 кораблей больше не
 *    требует 19 тапов по «+».
 * 6. **Повтор начинается не сразу и разгоняется.** Пауза перед первым повтором отличает
 *    удержание от неторопливого тапа, а разгон даёт и точность в начале, и скорость на
 *    больших числах.
 * 7. **После повтора завершающий тап съедается,** иначе отпускание добавит лишний шаг.
 */

/** Сколько держать кнопку необратимого действия (правило 1). */
export const HOLD_CONFIRM_MS = 1000;

/** Пауза перед первым повтором «±» (правило 6). */
export const REPEAT_START_MS = 400;

/** Самый быстрый шаг повтора: 20 шагов в секунду (правило 6). */
export const REPEAT_FASTEST_MS = 50;

/**
 * Пауза перед повтором номер `n` (с единицы): первый ждёт `REPEAT_START_MS`, дальше
 * 150 мс и разгон на 15 мс за шаг до `REPEAT_FASTEST_MS` (правило 6).
 */
export function repeatDelay(n: number): number {
  if (n <= 1) return REPEAT_START_MS;
  return Math.max(REPEAT_FASTEST_MS, 150 - (n - 2) * 15);
}

/** Что сделать с кликом по кнопке подтверждения. */
export type HoldConfirmClick =
  /** Удержание уже исполнило действие: клик съесть (правило 4). */
  | 'eat'
  /** Показать вопрос, ничего не исполняя (правило 2). */
  | 'arm'
  /** Исполнить: клик без нажатия по уже показанному вопросу (правило 3). */
  | 'confirm';

/**
 * Судьба клика. `matured` — удержание дошло до конца; `fromPress` — клику
 * предшествовало нажатие пальцем, мышью или клавишей; `armed` — вопрос уже показан.
 */
export function holdConfirmClick(s: {
  matured: boolean;
  fromPress: boolean;
  armed: boolean;
}): HoldConfirmClick {
  if (s.matured) return 'eat';
  if (s.fromPress) return 'arm';
  return s.armed ? 'confirm' : 'arm';
}
