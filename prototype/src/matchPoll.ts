/**
 * Когда переопрашивать список матчей и что при этом писать в строку статуса (REFM-153).
 *
 * Двенадцатый срез сетевой секции. У сборки игрока нет кнопки «Обновить список» — экран
 * держит себя свежим сам, тихим переопросом раз в десять секунд. Два решения этого
 * переопроса — «тикать ли вообще» и «мигать ли строкой статуса» — стояли двумя голыми
 * условиями в таймере и одним `if (!quiet)` внутри загрузчика, и связь между ними
 * («тихий» — это про МИГАНИЕ, а не про молчание о беде) нигде не была записана.
 *
 * 1. **Тикает только список НА ЭКРАНЕ.** Переопрос существует ради списка, на который
 *    игрок СЕЙЧАС смотрит. Поверх закрытого оверлея (игрок в матче или в ставке) и на
 *    приветственном шаге он тратил бы трафик телефона и лимит запросов сервера на список,
 *    который никто не читает, — а главное, писал бы результат в ту же строку `#cstatus`,
 *    которой пользуются другие шаги: фоновая неудача проштамповала бы «сервер недоступен»
 *    поверх экрана, где игрок про сервер и не спрашивал.
 * 2. **Фоновый переопрос НЕ мигает «загрузкой».** Список уже показан; если каждые десять
 *    секунд подменять строку на «загрузка матчей…», неподвижный экран выглядит вечно
 *    перезагружающимся. Строку меняет только настоящая смена состояния.
 * 3. **Но молчать о беде тихий переопрос не имеет права.** Устаревший список, который
 *    выглядит живым, — это ложь: игрок жмёт «Войти» в матч, которого уже нет. И буквально:
 *    строку статуса читает `renderMatches` как признак «сервер не ответил»
 *    (`browserFallback.ts`, правило 3) — промолчав, тихая неудача не подняла бы даже
 *    экран-заглушку, а оставила бы старые строки как есть.
 * 4. **Удачный переопрос ГАСИТ строку.** Сервер ожил; оставленное «сервер недоступен»
 *    держало бы поднятым признак из правила 3 — браузер продолжал бы рисовать заглушку
 *    «сервер не ответил» поверх только что загруженных живых матчей.
 */

/** Что делает тик таймера. */
export type PollTick =
  /** Список на экране — переспрашиваем (правило 1). */
  | 'poll'
  /** Списка не видно — молчим (правило 1). */
  | 'skip';

/** Где находится переопрос по времени запроса. */
export type PollPhase =
  /** Запрос уходит. */
  | 'start'
  /** Список получен. */
  | 'loaded'
  /** До сервера не дошли или он ответил отказом. */
  | 'failed';

/** Что сделать со строкой статуса. */
export type LineUpdate =
  /** Не трогать: там уже стоит то, что нужно (правило 2). */
  | { kind: 'keep' }
  /** Очистить (правило 4). */
  | { kind: 'clear' }
  /** Написать текст по ключу (правила 2–3). */
  | { kind: 'text'; key: 'browser.loading' | 'acc.server-down' };

export interface PollWhen {
  /** Сетевой оверлей открыт (иначе игрок в матче или в ставке). */
  overlay: boolean;
  /** Показан именно браузер матчей, а не приветственный шаг. */
  browser: boolean;
}

/** Уместен ли фоновый переопрос прямо сейчас (правило 1). */
export function pollTick(w: PollWhen): PollTick {
  return w.overlay && w.browser ? 'poll' : 'skip';
}

/** Что переопрос делает со строкой статуса (правила 2–4). */
export function pollLine(phase: PollPhase, quiet: boolean): LineUpdate {
  if (phase === 'loaded') return { kind: 'clear' };
  if (phase === 'failed') return { kind: 'text', key: 'acc.server-down' };
  return quiet ? { kind: 'keep' } : { kind: 'text', key: 'browser.loading' };
}
