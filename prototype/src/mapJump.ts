/**
 * Переход камеры к точке карты: две дороги, разные правила (REFM-108).
 *
 * К одному и тому же миру игрока приводят два непохожих жеста, и они НЕ
 * взаимозаменяемы. «Прыжок» (тап по всплывашке, строке журнала-разбора, пингу в
 * диплоокне) — это «покажи мне ЭТО МЕСТО»: игрок пришёл из текста, карты перед
 * глазами у него сейчас нет. «Переход по ссылке» (цель в очереди приказов, мир из
 * окна интела) — это «покажи, ГДЕ это»: карта уже перед ним, он читает панель и
 * хочет только сориентироваться. Различия стояли двумя самостоятельными функциями
 * (`jumpToPing` / `focusWorld`), и из них не читалось, что расхождения — намеренные,
 * а не разный возраст кода.
 *
 * 1. **По мёртвой ссылке не двигаемся вовсе.** Мир мог исчезнуть между тем, как
 *    строку нарисовали, и тем, как по ней ткнули; камера у пустого места и сброшенное
 *    выделение были бы хуже, чем ничего.
 * 2. **Прыжок ПРИБЛИЖАЕТ всегда, переход НЕ ОТДАЛЯЕТ.** Прыжок берёт фиксированный
 *    масштаб: пришедший из текста вида не выбирал, и общий план ему бесполезен.
 *    Переход берёт не меньше порога, но и не меньше текущего масштаба — игрок уже
 *    настроил вид, и отъезд был бы отобранной у него работой.
 * 3. **Прыжок ПЕРЕКЛЮЧАЕТ выделение на мир, переход его НЕ ТРОГАЕТ.** Прыжок ведёт
 *    к месту, а оставленный выделенным флот показывал бы свою карточку вместо
 *    карточки места. Переход же вызывают ИЗ панели, которая обязана остаться
 *    открытой под пальцем.
 * 4. **Смена выделения сбрасывает кэш разметки панели.** Патчер сравнивает с прошлым
 *    HTML и без сброса оставил бы старую карточку.
 * 5. **Прыжок закрывает диплоокно.** Оно во весь экран и перекрыло бы ровно ту карту,
 *    ради которой прыгали. Переход его не закрывает сам: единственная его дорога
 *    изнутри окна (мир из интела) закрывает окно у себя, а из панели приказов
 *    закрывать нечего.
 * 6. **Точку отмечает вспышка только у перехода.** Прыжок показывает место сменой
 *    выделения — мир подсвечен и расписан в карточке; переходу же выделение трогать
 *    нельзя (правило 3), так что кольцо остаётся его единственным способом сказать
 *    «вот здесь».
 *
 * _Замечено при выносе, НЕ чинил._ Второй вход перехода — «цель приказа в очереди как
 * ссылка на карту» (`[data-goto]`) — мёртв: атрибут во всём репозитории только ЧИТАЕТСЯ,
 * эмитента у него нет. Обработчик живой и правильный, не хватает самой разметки в строке
 * плана; дописывать рендер очереди приказов — не задача кирпича про камеру.
 */

/** Откуда пришёл переход: из текста (`ping`) или из панели (`goto`). */
export type JumpKind = 'ping' | 'goto';

/** Масштаб прыжка из текста: вида игрок не выбирал, показываем крупно (правило 2). */
export const PING_ZOOM = 3;
/** Нижний порог перехода из панели — приближаем, только если сейчас мельче (правило 2). */
export const GOTO_MIN_ZOOM = 2.5;

/** Что сделать по этому переходу. */
export type JumpStep =
  /** Ничего: мира нет (правило 1). */
  | { do: 'none' }
  | {
      do: 'jump';
      /** Масштаб, к которому вести камеру. */
      scale: number;
      /** Переключить выделение на мир и снять флоты (правило 3). */
      select: boolean;
      /** Закрыть диплоокно (правило 5). */
      closeDiplo: boolean;
      /** Отметить точку короткой вспышкой-кольцом (правило 6). */
      ring: boolean;
    };

/** Судьба перехода к точке карты (правила 1–3, 5, 6). */
export function jumpStep(kind: JumpKind, exists: boolean, camScale: number): JumpStep {
  if (!exists) return { do: 'none' }; // правило 1
  if (kind === 'ping')
    return { do: 'jump', scale: PING_ZOOM, select: true, closeDiplo: true, ring: false };
  return {
    do: 'jump',
    scale: Math.max(camScale, GOTO_MIN_ZOOM), // правило 2: не отдаляем
    select: false,
    closeDiplo: false,
    ring: true,
  };
}
