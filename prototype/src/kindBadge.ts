/**
 * Голографический бейдж типа провинции: метка сектора, ВИСЯЩАЯ над узлом (REFM-121).
 *
 * У каждого сектора своё искусство — планета с орбитами, россыпь астероидов, туманность,
 * поле обломков. Тип при этом обязан читаться отдельно от этого искусства, поэтому над
 * узлом висит голограмма: капсула со знаком типа, подсвеченная цветом сектора. Вся её
 * геометрия стояла в кадре голыми числами (`c.y - R - 6 - brad - 6 + bob`), и из них не
 * читалось ни зачем бейдж вообще оторван от узла, ни зачем к нему тянется луч.
 *
 * 1. **Бейдж ВИСИТ НАД узлом, а не лежит на нём.** Положи метку типа поверх собственного
 *    искусства сектора — и она сольётся с ним ровно там, где нужна: на пёстрой карте,
 *    где игрок глазами ищет, куда лететь.
 * 2. **Раз висит — нужен ЛУЧ ПРОЕКТОРА от узла к бейджу.** На плотной карте бейдж
 *    оказывается между двумя узлами, и без луча непонятно, ЧЕЙ он. Луч идёт от КРАЯ узла
 *    до НИЗА капсулы, а не между их центрами: иначе он прошьёт насквозь и узел, и саму
 *    капсулу, превратившись из проекции в перечёркивающую черту.
 * 3. **Покачивание фазируется КООРДИНАТАМИ узла.** С общей фазой все бейджи экрана
 *    качались бы синхронно, и карта читалась бы как одна деталь, дрожащая целиком, а не
 *    как набор независимых проекций. Фаза берётся из координат, а не из случайного числа:
 *    она обязана быть одинаковой в каждом кадре и после перезахода в матч.
 * 4. **Нет знака типа — нет и бейджа.** Пустая капсула над узлом обещала бы тип, которого
 *    у сектора нет.
 * 5. **Бейдж — деталь, и он растворяется вместе с LOD.** На схематичном виде это лишний
 *    ярус поверх и без того тесного узла — то же правило, что у подписи узла
 *    (`nodeCallout.ts`).
 *
 * Замечено при выносе: радиус самой капсулы НЕ масштабируется вместе с узлом (узел идёт
 * `R × artScale`, капсула — постоянные 11). Так было и до выноса; на схематичном виде
 * бейдж уходит не размером, а прозрачностью (правило 5).
 */

/** Радиус голографической капсулы. */
export const BADGE_R = 11;

/** Зазор: между краем узла и низом капсулы, и столько же над ней. */
export const BADGE_GAP = 6;

/** Размах покачивания в пикселях (правило 3). */
export const BADGE_BOB = 2.4;

/** Рисовать ли бейдж (правила 4–5). */
export function badgeShown(hasGlyph: boolean, detail: number): boolean {
  return hasGlyph && detail > 0;
}

/**
 * Смещение покачивания для узла в точке `(x, y)` карты (правило 3). Координаты — в
 * МИРОВЫХ единицах узла, а не экранных: экранные меняются при каждом сдвиге камеры, и
 * бейдж дёргался бы от панорамирования.
 */
export function badgeBob(now: number, x: number, y: number): number {
  return Math.sin(now / 700 + x * 0.021 + y * 0.017) * BADGE_BOB;
}

/** Центр капсулы: над ВЕРХОМ узла, через зазор (правило 1). */
export function badgeCenterY(nodeTopY: number, bob: number): number {
  return nodeTopY - BADGE_GAP - BADGE_R - BADGE_GAP + bob;
}

/** Луч проектора: от края узла до низа капсулы (правило 2). */
export function badgeTether(nodeTopY: number, centerY: number): { from: number; to: number } {
  return { from: nodeTopY, to: centerY + BADGE_R };
}

/** Как выглядит голограмма — одной записью, чтобы ярусы не разъехались по кадру. */
export interface BadgeLook {
  /** Радиус кэшированного ореола вокруг капсулы и его сила. */
  glowRadius: number;
  glowAlpha: number;
  /** Пунктир луча проектора и его прозрачность. */
  tetherDash: readonly [number, number];
  tetherAlpha: number;
  /** Заливка капсулы, её ободок и внутреннее «сканирующее» кольцо. */
  fillAlpha: number;
  rimAlpha: number;
  rimWidth: number;
  scanInset: number;
  scanAlpha: number;
  /** Знак типа: свечение и прозрачность. */
  glyphBlur: number;
  glyphAlpha: number;
}

const LOOK: BadgeLook = {
  glowRadius: BADGE_R + 9,
  glowAlpha: 0.5,
  tetherDash: [2, 3],
  tetherAlpha: 0.16,
  fillAlpha: 0.12,
  rimAlpha: 0.6,
  rimWidth: 1.2,
  scanInset: 3,
  scanAlpha: 0.26,
  glyphBlur: 5,
  glyphAlpha: 0.95,
};

/** Вид голограммы. */
export function badgeLook(): BadgeLook {
  return LOOK;
}
