/**
 * Отметка боя на карте: где он идёт и как выглядят его две фазы (REFM-118).
 *
 * Бой — единственное событие, которое случается НЕ В УЗЛЕ: перехват на полпути идёт
 * между мирами. И он двухфазный: сначала небо, потом земля. Оба факта решались прямо в
 * кадре — поиском первого воюющего флота и парой тернарников по `phase`, — и из них не
 * читалось ни почему якорь берётся у флота, ни почему фазы обязаны быть НЕПОХОЖИМИ.
 *
 * 1. **Якорь — позиция ВОЮЮЩЕГО ФЛОТА, и только если её нет — узел.** Перехват
 *    происходит там, где корабли встретились, а не в ближайшем мире; поставь кольцо на
 *    узел — и карта соврёт о месте схватки, которое игрок как раз и ищет глазами.
 * 2. **Бой под туманом не показывается.** Кольцо в неразведанном пространстве выдавало
 *    бы чужие столкновения, то есть работало бы разведкой, за которую никто не платил.
 * 3. **Две фазы — две РАЗНЫЕ картинки, а не разный цвет одной.** Аудит нашёл их
 *    неразличимыми: орбитальная — широкие красные кольца (бой в пустоте), наземная —
 *    тугой янтарный пунктир, прижатый к поверхности. Игрок обязан видеть, на какой
 *    стадии захват, потому что от этого зависит, чем помогать: флотом или десантом.
 * 4. **Кольца идут волной со сдвигом на треть оборота.** Одно кольцо читалось бы как
 *    мигание; три со сдвигом — как расходящаяся волна, то есть как продолжающийся бой.
 * 5. **Таймер раунда показывается, только если ядро назначило следующий раунд.**
 *    Отсчёт без назначенного времени врал бы игроку о том, когда ударят.
 * 6. **Подпись и таймер живут только на детальном зуме** — на схематичном виде это
 *    нечитаемый текст поверх и без того тесного узла.
 */

/** Фаза боя: небо или земля. */
export type BattlePhase = 'orbital' | 'ground';

/**
 * Точка схватки: первая живая позиция воюющего флота, иначе позиция мира (правило 1).
 * `null` — рисовать нечего.
 */
export function clashPoint<P>(fighting: readonly (P | null)[], world: P | null): P | null {
  for (const at of fighting) if (at) return at;
  return world;
}

/** Что показать у отметки боя. */
export type BattleMark =
  /** Ничего: туман или нет точки (правила 1–2). */
  | { do: 'none' }
  | {
      do: 'draw';
      /** Рисовать ли подпись фазы и таймер (правило 6). */
      label: boolean;
      /** Есть ли что показывать таймером (правило 5). */
      timer: boolean;
    };

/** Что известно про бой в момент отрисовки. */
export interface BattleSight {
  /** Опознан ли узел боя (правило 2). */
  identified: boolean;
  /** Нашлась ли точка схватки (правило 1). */
  hasPoint: boolean;
  /** Уровень детализации: `0` — схематичный вид (правило 6). */
  detail: number;
  /** Время следующего раунда, назначенное ядром; `undefined` — не назначено (правило 5). */
  nextRoundAt: number | undefined;
}

/** Судьба отметки боя (правила 1–2, 5–6). */
export function battleMark(sight: BattleSight): BattleMark {
  if (!sight.identified || !sight.hasPoint) return { do: 'none' };
  const label = sight.detail > 0;
  return { do: 'draw', label, timer: label && typeof sight.nextRoundAt === 'number' };
}

/** Как выглядит фаза боя (правила 3–4). */
export interface PhaseLook {
  /** Цвет колец и подписи. */
  color: string;
  /** Пунктир колец; `null` — сплошные. */
  dash: readonly [number, number] | null;
  /** Радиус кольца в начале волны. */
  from: number;
  /** На сколько кольцо вырастает за оборот волны. */
  grow: number;
  /** Рисовать ли полосу фронта под миром — только у наземной фазы (правило 3). */
  frontLine: boolean;
}

const LOOKS: Record<BattlePhase, PhaseLook> = {
  // Бой в пустоте: широкие красные кольца, расходящиеся далеко от точки.
  orbital: { color: '#ff5a4d', dash: null, from: 18, grow: 24, frontLine: false },
  // Бой за поверхность: тугой янтарный пунктир, прижатый к миру, плюс полоса фронта.
  ground: { color: '#f0b429', dash: [5, 4], from: 14, grow: 12, frontLine: true },
};

/** Вид фазы — одной записью, чтобы фазы не сползлись обратно к «одному цвету». */
export function phaseLook(phase: BattlePhase): PhaseLook {
  return LOOKS[phase];
}

/** Сколько колец в волне (правило 4). */
export const BATTLE_RINGS = 3;

/** Доля жизни `i`-го кольца волны: сдвиг на треть оборота (правило 4). */
export function ringPhase(wave: number, index: number): number {
  return (wave + index / BATTLE_RINGS) % 1;
}

/** Радиус кольца по его доле (правила 3–4). */
export function ringRadiusAt(look: PhaseLook, k: number): number {
  return look.from + k * look.grow;
}
