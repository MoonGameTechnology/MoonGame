/**
 * РЯД ПРИКАЗОВ ЭСКАДРЫ — плитками, как у флота (заказ владельца 2026-11-09: «кнопки
 * управления как для флота»). Здесь только то, какие плитки видны на свёрнутом листе
 * телефона; что предлагать, решают карточки эскадры.
 *
 * 1. **До трёх приказов — все на виду.** Кнопка «Ещё» спрятала бы ровно одну плитку.
 * 2. **Больше трёх — две первые и «Ещё»**, как «Курс · Атака · Ещё» у флота. Первые две —
 *    главные приказы карточки (удар и патруль, когда эскадра готова).
 * 3. **«Ещё» открывает остальные на месте**, раскрытый лист показывает их сам. На ПК места
 *    хватает, там видны все плитки сразу.
 */

export interface WingOrderRow {
  /** Сколько первых плиток видно на свёрнутом листе. */
  main: number;
  /** Нужна ли плитка «Ещё». */
  more: boolean;
}

export function wingOrderRow(count: number): WingOrderRow {
  return count <= 3 ? { main: count, more: false } : { main: 2, more: true };
}
