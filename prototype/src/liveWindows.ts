/**
 * Как часто перерисовывается ОТКРЫТОЕ окно и почему сроки у окон разные (REFM-194).
 *
 * Четыре окна прототипа живут, пока открыты: дерево технологий (полоса исследования),
 * «Верфь» (законченная стройка переворачивает строку), «Хранитель» (обратный отсчёт до
 * возврата управления) и вкладка «Шпионаж» в дипломатии. Условия их перерисовки стояли
 * четырьмя почти одинаковыми `if`'ами в `frame()`. Ошибаются они тихо в обе стороны:
 * лишняя перерисовка ест кадр, недостаточная — показывает игроку вчерашнее число.
 *
 * 1. **Перерисовывается только ОТКРЫТОЕ окно.** Закрытое перерисовывать — работа впустую
 *    шестьдесят раз в секунду; проверка «открыто» и есть то единственное, что держит цену.
 * 2. **У «Шпионажа» проверка ДВОЙНАЯ: диалог открыт И игрок на ТОЙ вкладке.** Диалог
 *    дипломатии один на несколько вкладок; на любой другой таймеры шпионажа не видны, и
 *    перерисовка рисует то, чего никто не смотрит.
 * 3. **Дроссель считает РЕАЛЬНОЕ время, а не игровое.** Игровое идёт с множителем (до
 *    ×7200) и стоит на паузе, поэтому по нему дроссель ломается в обе стороны: на разгоне
 *    порог пробивается каждым кадром и дросселировать перестаёт вовсе, на паузе не
 *    пробивается никогда и окно замирает.
 * 4. **Полсекунды у окон с ПРОГРЕССОМ, пять секунд у разведки.** Полоса исследования и
 *    обратный отсчёт читаются как непрерывные: реже полусекунды они дёргаются. Таймеры
 *    «Шпионажа» тикают ЧАСАМИ — за полсекунды в них не меняется ничего, и частая
 *    перерисовка рисовала бы ту же самую картинку.
 * 5. **У каждого окна СВОЙ отсчёт.** Отметка приходит аргументом именно затем, чтобы окна
 *    не делили одну: с общей перерисовка одного отодвигала бы срок другого, два открытых
 *    окна обновлялись бы вдвое реже, и виноватым выглядело бы «тормозит», а не таймер.
 */

/** Окна с прогрессом: полоса и обратный отсчёт должны читаться как непрерывные. */
export const PROGRESS_MS = 500;

/** Разведка: её таймеры идут часами, чаще обновлять нечего. */
export const INTEL_MS = 5000;

/** Правила 1 и 3: открытое окно, срок которого истёк по РЕАЛЬНЫМ часам. */
export function repaintDue(open: boolean, now: number, last: number, everyMs: number): boolean {
  return open && now - last > everyMs;
}

/** Правило 2: таймеры «Шпионажа» видны, только когда открыта именно эта вкладка. */
export function intelVisible(diploOpen: boolean, tab: string): boolean {
  return diploOpen && tab === 'intel';
}
