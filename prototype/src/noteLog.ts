/**
 * Как сообщение попадает в журнал матча (REFM-101).
 *
 * Одна запись расходится сразу в три места — строка журнала, структурированная память
 * ONB-5 и всплывающий тост, — и перед этим проходит защиту от повторов. Всё это лежало
 * в теле `note` вперемешку, поэтому не читалось, почему защита меряет РЕАЛЬНОЕ время, а
 * метка ставится ИГРОВОЕ, и почему у двух лент разные пределы.
 *
 * 1. **Повтор подряд глушится на две секунды РЕАЛЬНОГО времени.** Цикл приказа,
 *    отскакивающий каждый кадр, иначе застрочит журнал и тосты пулемётом. Мерить
 *    игровым временем нельзя: на 120× двухчасовой зазор пролетает мгновенно, и защита
 *    перестала бы работать ровно там, где она нужнее всего.
 * 2. **Глушится только ТОТ ЖЕ текст.** Другое сообщение внутри тех же двух секунд —
 *    это другое событие, и молчать о нём нельзя.
 * 3. **Метка времени — ИГРОВАЯ, день и час мира:** игрок читает журнал как хронику
 *    матча, а не как системный лог, и «D3 07h» говорит ему больше, чем настенные часы.
 * 4. **Обе ленты ОГРАНИЧЕНЫ и режутся с головы.** Экранных строк девять, записей
 *    памяти восемьдесят: показывать нужно последнее, а дайджест возвращения читает
 *    ленту длиннее экрана — отсюда разные пределы, а не один общий.
 */

/** Сколько реального времени глушится дословный повтор. */
export const NOTE_DEDUPE_MS = 2000;
/** Сколько строк держит экранный журнал. */
export const LOG_LINES = 9;
/** Сколько записей держит структурированная память событий (ONB-5). */
export const EVENT_LOG_MAX = 80;

/** Считается ли сообщение повтором и должно быть отброшено (правила 1–2). */
export function isRepeat(
  msg: string,
  lastMsg: string,
  nowMs: number,
  lastAtMs: number,
  windowMs = NOTE_DEDUPE_MS,
): boolean {
  return msg === lastMsg && nowMs - lastAtMs < windowMs;
}

/** Метка «день и час мира» перед текстом записи (правило 3). */
export function stamp(gameTime: number, dayMs: number, hourMs: number): string {
  const d = Math.floor(gameTime / dayMs) + 1;
  const h = Math.floor((gameTime % dayMs) / hourMs);
  return `D${d} ${String(h).padStart(2, '0')}h`;
}

/** Дописать в ленту, срезав с головы всё сверх предела (правило 4). */
export function pushBounded<T>(list: T[], item: T, max: number): void {
  list.push(item);
  while (list.length > max) list.shift();
}
