# Ключи `server.env` — ОДИН источник правды для установки и для обновления.
#
# Зачем отдельный файл. Список ключей жил только в `install-ubuntu.sh`, а он пишет
# `server.env` РОВНО ОДИН РАЗ — при первой установке — и с тех пор бережно его
# сохраняет (иначе смена сгенерированного пароля рассыпала бы уже созданный том
# Postgres). `update.sh` файл только ЧИТАЕТ. Итог: ключ, добавленный в установщик
# позже, до уже развёрнутой машины не доезжает НИКОГДА, и она молча продолжает жить
# в старой постуре.
#
# Это не теория: на живом сервере так потерялись сразу два ключа. `TIME_SCALE` — и мир
# шёл в реальном времени, где самая дешёвая постройка готова через три часа, поэтому
# на плейтесте «ничего не происходило». И `AUTH_JWT_SECRET` — а без него сервер
# поднимается БЕЗ АККАУНТОВ, то есть место в партии берёт любой, кто знает позывной.
# Ровно та же болезнь, что уже описана в установщике про `update-dev.sh`: механизм
# обновления не доносил до машины собственные исправления.
#
# Правила, которым подчиняется добор:
#
#  1. **Существующее значение НЕПРИКОСНОВЕННО.** Оператор мог настроить его руками, и
#     обновление не вправе это переписывать. Добор трогает только ОТСУТСТВУЮЩИЙ ключ.
#  2. **Добор громкий.** Молча менять постуру работающего сервера нельзя: каждый
#     дописанный ключ печатается вместе с последствием.
#  3. **Асимметрия по цене ошибки.** Секрет подписи, если его нет, генерируется: цена
#     бездействия — открытый сервер. А `ALLOWED_ORIGINS` угадывать НЕЛЬЗЯ, хотя дыра
#     там тоже реальная: неверный allowlist отбивает рукопожатие у всех, то есть
#     «починка» превращается в полный отказ. Про него — предупреждение, а не догадка.
#  4. **`POSTGRES_PASSWORD` не генерируется.** Том базы уже создан с тем паролем,
#     который действовал в момент создания; новый случайный пароль означал бы
#     `28P01 password authentication failed` на живых данных. Если ключа нет, стек
#     работает на дефолте compose — его и закрепляем, ничего не меняя по существу.

# Значение по умолчанию для ключа, которого нет в файле. Пустая строка = «дефолта нет,
# только предупредить» (см. правило 3).
env_default_for() {
  case "$1" in
    PORT) echo '8788' ;;
    TIME_SCALE) echo '100' ;;
    MATCHES) echo '1' ;;
    GATE) echo '1' ;;
    SEAT_LOCK) echo '1' ;;
    # Тот же дефолт, что подставляет compose (`${POSTGRES_PASSWORD:-void}`) — правило 4.
    POSTGRES_PASSWORD) echo 'void' ;;
    AUTH_JWT_SECRET) openssl rand -hex 32 ;;
    *) echo '' ;;
  esac
}

# Чем грозит отсутствие ключа — печатается рядом с добором (правило 2).
env_why_for() {
  case "$1" in
    TIME_SCALE) echo 'без него мир шёл в реальном времени: постройки по 3–24 часа' ;;
    AUTH_JWT_SECRET) echo 'без него сервер стоял БЕЗ АККАУНТОВ — место брал любой, кто знает позывной' ;;
    GATE) echo 'без него принимались голые действия, без валидации конвертов' ;;
    SEAT_LOCK) echo 'без него любой позывной занимал любое свободное место' ;;
    *) echo '' ;;
  esac
}

# Ключи, которые обязаны быть в файле. Порядок — как в установщике, чтобы дописанное
# читалось в том же порядке, что и написанное изначально.
ENV_REQUIRED_KEYS="PORT TIME_SCALE MATCHES POSTGRES_PASSWORD GATE SEAT_LOCK AUTH_JWT_SECRET"

# Ключи без безопасного дефолта: о них только предупреждаем (правило 3).
ENV_WARN_ONLY_KEYS="ALLOWED_ORIGINS"

# Дописать в $1 всё, чего в нём нет. Возвращает 0 всегда: отсутствие ключей — не повод
# валить обновление, иначе машина застрянет на старом образе из-за конфигурации.
ensure_env_keys() {
  local file="$1"
  [ -f "$file" ] || return 0
  local added=""

  for key in $ENV_REQUIRED_KEYS; do
    # Якорь на начало строки: `PORT=` не должен находиться внутри `INTERNAL_PORT=`.
    grep -qE "^${key}=" "$file" && continue
    local value
    value="$(env_default_for "$key")"
    [ -n "$value" ] || continue
    printf '\n# Дописано обновлением (ключа не было в этом файле).\n%s=%s\n' "$key" "$value" >> "$file"
    added="$added $key"
  done

  for key in $ENV_WARN_ONLY_KEYS; do
    grep -qE "^${key}=" "$file" && continue
    echo "[!] В server.env нет ${key} — Origin-allowlist выключен (риск CSWSH)."
    echo "    Значение угадать нельзя: неверное отобьёт рукопожатие у ВСЕХ игроков."
    echo "    Впишите адрес, с которого игроки открывают игру, например:"
    echo "    echo 'ALLOWED_ORIGINS=http://<адрес>:<порт>' >> $file"
  done

  [ -n "$added" ] || return 0
  echo "[*] В server.env дописаны недостающие ключи:$added"
  for key in $added; do
    local why
    why="$(env_why_for "$key")"
    [ -n "$why" ] && echo "    ${key} — ${why}"
  done
  echo "    Существующие значения не тронуты; перезапуск ниже применит дописанное."
  return 0
}
