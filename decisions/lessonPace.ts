/**
 * Темп урока первого матча (ревизия обучения 2026-11-20).
 *
 * Урок идёт в ускоренном времени ×300: стройка, наука и полёты настоящие, но игрок не ждёт
 * их вживую. После подорожания построек и войск только ожидание таймеров заняло около 117
 * игровых часов, то есть ~23 минуты реального времени, — урок превратился в просмотр часов.
 *
 * 1. **Шаг, где игрок только ждёт, идёт на ×3600.** Ждёт он там, где подсказке не на что
 *    указать: нет ни кнопки, ни точки карты, ни строки списка, а засчитывает шаг сам мир
 *    (шахта выросла, флот долетел). На ×3600 те же 117 часов — около двух минут.
 * 2. **Шаг с действием идёт на ×300.** Пока игрок ищет кнопку, мир не убегает вперёд.
 * 3. **Шаг «Далее»** (приветствие, итог) — не ожидание: его закрывает игрок.
 *
 * Чистое правило: как темп ставится и возвращается, решает полоса скорости
 * (`prototype/src/matchTopBar.ts`).
 */

/** Темп урока на шагах с действием. */
export const LESSON_SPEED = 300;
/** Темп урока, пока игрок только ждёт таймер. */
export const LESSON_WAIT_SPEED = 3600;

/** То, что правилу нужно знать о шаге подсказки. */
export interface PacedStep {
  target: string | null;
  anchor?: unknown;
  selector?: unknown;
  advance: { on: string };
}

/** Игрок на этом шаге только ждёт: указать не на что, засчитает сам мир (правило 1). */
export function lessonWaits(step: PacedStep | null | undefined): boolean {
  return (
    !!step && step.target === null && !step.anchor && !step.selector && step.advance.on === 'state'
  );
}
