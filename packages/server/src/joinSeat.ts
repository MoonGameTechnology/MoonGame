/**
 * Что вход делает с МЕСТОМ и ДОМОМ игрока (ENTRY-1).
 *
 * `POST /matches/:id/join` несёт два независимых пожелания — `slot` (где начинаешь) и
 * `faction` (кем играешь). Их разделение — решение BF-30, и оно намеренное: дом не
 * привязан к стартовой точке, поэтому сводить их в одно поле нельзя.
 *
 * Прототипный хост (`prototype/netserver.ts`) это реализует, канонический сервер — нет:
 * его `join` принимал ТРИ параметра вместо пяти, объявленных `MatchApiDeps`, и два
 * последних отбрасывал. Ни ошибки, ни предупреждения: функция с меньшим числом
 * параметров совместима с более широкой сигнатурой, поэтому TypeScript такое пропускает,
 * а тестов у хостовой обвязки не было. Решение вынесено сюда именно поэтому — чтобы у
 * него был тест, который ловит потерю аргумента, а не только happy path.
 *
 * 1. **Место из AvA-ростера не обсуждается.** Рострованный аккаунт играет ФИКСИРОВАННОЕ
 *    место, и дом ему определён тем же ростером. Пожелание игрока здесь не применяется
 *    вовсе: иначе участник войны переобувался бы в другой дом на входе, и расклад,
 *    под который корпорации собирали состав, менялся бы после блокировки.
 * 2. **Дом переписывается только при НОВОМ захвате.** На возврате в свой матч выбор
 *    игнорируется: игрок уже сыграл под этим домом — бонусы дома учтены в его экономике,
 *    флоты построены, войны объявлены. Смена дома на реконнекте переписала бы историю
 *    матча задним числом.
 * 3. **Нет свободного места — отказ, а не «посадим куда-нибудь».** Резолвер уже учёл
 *    пожелание по слоту (и сам откатился на любое свободное, если занято); если он
 *    вернул пусто — сажать некуда.
 */

/** Что известно к моменту решения. */
export interface JoinSeatInput {
  /** Фиксированное место из AvA-ростера — если это AvA-матч (правило 1). */
  avaPlayerId?: string | undefined;
  /** Что вернул обычный резолвер мест: место и признак первого захвата. */
  resolved?: { playerId: string; isNew: boolean } | null | undefined;
  /** Дом, который выбрал игрок (`faction` из запроса). */
  preferredFaction?: string | undefined;
}

/** Чем кончается вход. */
export interface SeatClaim {
  /** Место, которое достаётся игроку. */
  playerId: string;
  /** Переписать ли дом этого места выбором игрока (правила 1–2). */
  applyFaction: boolean;
}

/** Какое место достаётся и переписывать ли дом (правила 1–3). `null` — сажать некуда. */
export function seatClaim(input: JoinSeatInput): SeatClaim | null {
  if (input.avaPlayerId !== undefined) {
    return { playerId: input.avaPlayerId, applyFaction: false };
  }
  const resolved = input.resolved;
  if (!resolved) return null;
  return {
    playerId: resolved.playerId,
    applyFaction: Boolean(input.preferredFaction) && resolved.isNew,
  };
}
