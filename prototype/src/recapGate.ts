/**
 * RECAP-FOG — что вообще имеет право попасть в мой журнал (а значит, и в сводку
 * возвращения `buildRecap`, и в пуш).
 *
 * Правило вынесено сюда чистой функцией по одной причине: это правило БЕЗОПАСНОСТИ, а
 * `main.ts` — DOM-вход без юнит-харнеса. В виде `if` внутри свитча событий оно
 * проверялось бы только глазами ревьюера; здесь его проверяет гейт.
 *
 * Классы событий:
 *  · `own` — событие про МОЮ экономику. Чужое той же природы не показывается вовсе:
 *    стройка, улучшение и производство юнитов противника — это разведданные, их
 *    добывают шпионажем, а не получают уведомлением. Именно этим сводка утекала.
 *  · `seen` — событие КАРТЫ. Своё вижу всегда, чужое — только там, где мир опознан
 *    (тот же фог-гейт, что у зенитного огня): взрыв или вылет на наблюдаемом мире
 *    это наблюдение, а не раскрытие.
 */
export type RecapPolicy = 'own' | 'seen';

/** Политика по типу события. Тип, которого здесь нет, обрабатывается вызывающим по
 *  месту (диалоги, бой, дипломатия — у них своя логика видимости). */
export const RECAP_POLICY: Readonly<Record<string, RecapPolicy>> = {
  'building.constructed': 'own',
  'building.upgraded': 'own',
  'unit.built': 'own',
  'building.destroyed': 'seen',
  'fleet.launched': 'seen',
};

/**
 * Пускать ли событие в журнал. `owner` — владелец из полезной нагрузки события,
 * `visible` — опознан ли узел события прямо сейчас.
 *
 * Fail-secure: неизвестный владелец (`undefined`/`null`) — это НЕ «моё», поэтому
 * `own`-событие без владельца отсекается, а `seen`-событие решается видимостью.
 */
export function recapAdmits(
  type: string,
  owner: string | null | undefined,
  me: string,
  visible: boolean,
): boolean {
  const policy = RECAP_POLICY[type];
  if (policy === undefined) return true; // не наш класс — решает вызывающий
  if (owner === me) return true;
  return policy === 'seen' && visible;
}
