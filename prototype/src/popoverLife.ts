/**
 * Время жизни всплывающих меню командного ряда (REFM-84).
 *
 * У ряда команд три поповера — 🔥 режим огня, ✨ способности флагмана, ⇅ десант, — и
 * каждый открыт ПОД что-то: под артиллерию в выделении, под живого героя, под конкретный
 * флот с его трюмом. Выделение при этом меняется постоянно: флоты сливаются, гибнут,
 * игрок тапает следующий. Проверки жили четырьмя отдельными строчками в разных концах
 * `renderCmdBar`, и одинаковы они были только на вид.
 *
 * 1. **Поповер живёт ровно пока живо его ОСНОВАНИЕ.** Ушла из выделения артиллерия —
 *    гаснет 🔥; не стало флагмана с применимой способностью — гаснет ✨.
 * 2. **⇅ привязан к КОНКРЕТНОМУ флоту, а не к «какому-нибудь одиночному».** Иначе меню,
 *    набранное на одном флоте, всплывёт над другим — и отправит чужой гарнизон.
 * 3. **Пустое выделение гасит всё разом** — и поповеры, и прицелы. Поповер всплыл бы над
 *    СЛЕДУЮЩИМ выбранным флотом, а прицел ждал бы тапа, который уже некому исполнить.
 * 4. **Набор группы держит ряд живым при нуле выделенных:** кнопка ⊕ обязана остаться
 *    достижимой, иначе опустевшая группа запирает игрока в режиме без выхода.
 *
 * Режим «Приказ» сюда не входит: он держит свои `fleetIds` и живёт вообще без выделения,
 * поэтому его ветка стоит в `renderCmdBar` ДО этой проверки.
 */

/** Под что открыты поповеры прямо сейчас. */
export interface PopoverBases {
  /** Сколько флотов выделено. */
  selected: number;
  /** Включён режим набора группы. */
  picking: boolean;
  /** Арт-флотов в выделении. */
  artillery: number;
  /** Есть ли флагман с хотя бы одной применимой способностью. */
  castHero: boolean;
  /** Есть ли что показать ⇅-меню. */
  troopsInput: boolean;
  /** Одиночный флот выделения; `null` — выделен не один. */
  loneId: string | null;
}

/** Какие поповеры игрок открыл. */
export interface OpenPopovers {
  fire: boolean;
  cast: boolean;
  /** Флот, под который набран план десанта; `null` — меню закрыто. */
  troopsFleetId: string | null;
}

/** Что остаётся на экране. */
export interface PopoverState {
  /** Держится ли ряд команд. Ложь — гаснут ещё и все прицелы: это одно событие. */
  bar: boolean;
  fire: boolean;
  cast: boolean;
  troops: boolean;
}

/**
 * Держится ли ряд команд (правила 3–4). Вынесено отдельно, потому что спрашивается
 * РАНЬШЕ, чем известны основания поповеров: пустое выделение гасит ряд вместе с
 * прицелами, не доходя до подсчёта артиллерии и трюмов.
 */
export function barStays(selected: number, picking: boolean): boolean {
  return selected > 0 || picking;
}

/** Что переживает текущее выделение (правила 1–4). */
export function popoverLife(bases: PopoverBases, open: OpenPopovers): PopoverState {
  const bar = barStays(bases.selected, bases.picking);
  if (!bar) return { bar, fire: false, cast: false, troops: false };
  return {
    bar,
    fire: open.fire && bases.artillery > 0,
    cast: open.cast && bases.castHero,
    troops: open.troopsFleetId !== null && bases.troopsInput && open.troopsFleetId === bases.loneId,
  };
}
