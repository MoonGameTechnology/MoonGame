/**
 * Откуда ⇅-меню десанта берёт типы и числа (REFM-81).
 *
 * Меню показывает, сколько наземных частей стоит в гарнизоне мира и сколько лежит в
 * трюме флота. Что именно считать источником — правило игры, а не деталь разметки.
 *
 * 1. **На СВОЁМ мире источников два — гарнизон и трюм.** Игрок и поднимает, и высаживает.
 * 2. **На союзном мире поднимать нечего:** чужой гарнизон не твой, ядро отобьёт погрузку.
 *    Поэтому и типы, и «в гарнизоне» берутся ТОЛЬКО из трюма — счётчик выходит
 *    односторонним («только высадить») сам собой, без отдельного режима меню.
 * 3. **Типы идут в порядке первого появления и без повторов** — иначе строки меню
 *    прыгали бы от перерисовки к перерисовке.
 * 4. **Стеков одного типа может быть несколько** (побитый + целый): «всего» складывает
 *    их ВСЕ, а поднять или высадить ядро даст только здоровый. Эти два числа обязаны
 *    считаться порознь, иначе меню обещает больше, чем ядро исполнит.
 * 5. **Нет наземных типов — меню не открывается.** Пустое меню хуже отсутствующего.
 */

/** Стопка частей одного типа. */
export interface Stack {
  unit: string;
  count: number;
}

/** Откуда брать типы и числа: свой мир — гарнизон и трюм, чужой — только трюм (правила 1–2). */
export function troopSources(
  mine: boolean,
  garrison: readonly Stack[],
  landing: readonly Stack[],
): Stack[] {
  return mine ? [...garrison, ...landing] : [...landing];
}

/** Наземные типы по порядку первого появления, без повторов (правило 3). */
export function groundTypes(
  stacks: readonly Stack[],
  isGround: (unit: string) => boolean,
): string[] {
  const types: string[] = [];
  for (const st of stacks) if (isGround(st.unit) && !types.includes(st.unit)) types.push(st.unit);
  return types;
}

/** Сколько частей этого типа ВСЕГО — со всеми побитыми стопками (правило 4). */
export function totalOf(stacks: readonly Stack[], unit: string): number {
  return stacks.reduce((n, st) => (st.unit === unit ? n + st.count : n), 0);
}

/** Открывать ли меню вообще (правило 5). */
export function hasTroops(types: readonly string[]): boolean {
  return types.length > 0;
}
