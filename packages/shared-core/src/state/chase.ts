/**
 * ПОГОНЯ ЗА ДВИЖУЩЕЙСЯ ЦЕЛЬЮ (SHU-4.4) — геометрия одного пересчёта.
 *
 * До этого кирпича удар наводился ОДИН раз, в момент вылета: `ShuttleStrike.to` был
 * снимком, и цель, идущая по линии, не бралась вовсе — `fleetWorldPos` модуля челноков
 * не знал про `Fleet.movement` и отбивал приказ кодом `E_NO_TARGET_POSITION`. Модель
 * владельца (§0.4 роадмапа): у цели небольшой радиус, эскадра регулярно пересчитывает
 * её координаты и правит курс к центру радиуса; попадание засчитывается, когда на
 * очередном пересчёте эскадра оказалась ВНУТРИ радиуса.
 *
 * Здесь живёт ровно эта арифметика — без состояния, без времени, без данных мира.
 * «Когда пересчитывать» и «где сейчас цель» решает модуль: у него есть отрезок
 * `time.advanced` и карта. Разделение не косметическое — шаг погони обязан быть
 * воспроизводимым по одним своим аргументам, иначе реплей разъедется с матчем.
 *
 * 1. **Курс правится КАЖДЫЙ пересчёт.** Эскадра идёт не по линии, снятой на вылете, а
 *    на текущий центр радиуса. Это и есть погоня; без правки курса получилось бы
 *    «упреждение», от которого цель уходит одним поворотом.
 * 2. **Перелёта не бывает.** Шаг обрезается остатком дистанции: эскадра встаёт НА цели,
 *    а не проскакивает мимо. Без обрезки быстрая эскадра при редких пересчётах
 *    «протыкала» бы радиус между шагами и гналась бы вечно — а частота пересчёта не
 *    должна менять исход.
 * 3. **Попадание — по ФАКТУ на пересчёте**, включительно по границе: та же мерка
 *    `withinRange`, по которой ядро пускает сам удар. Круг на карте и круг в правиле
 *    обязаны быть одним кругом.
 * 4. **Уже внутри радиуса — догнала, не дёргаясь.** Проверка идёт ДО шага: цель,
 *    подошедшая к эскадре сама, считается настигнутой там, где эскадра есть.
 * 5. **Радиус берётся по САМОЙ ТУПОЙ машине соединения** — тем же правилом «слабое
 *    звено решает», что дальность по самой короткой руке (`squadronReach`) и скорость
 *    по самой медленной машине. Эскадра идёт вместе, и подходить ближе всех обязана
 *    вся.
 * 6. **Нет стата в данных — нет захвата.** `chaseRadius: 0` значит «догнать можно
 *    только точку в точку», то есть стоящую цель. Числа механики живут в данных, и
 *    подстановка молчаливого дефолта из кода спрятала бы недозаполненный юнит.
 */
import type { GameData } from '../data/schemas';
import type { UnitStack } from './gameState';

/** Точка на карте (мировые координаты). */
export interface ChasePoint {
  x: number;
  y: number;
}

/** Насколько близко соединение обязано подойти, чтобы удар засчитался (правила 5–6). */
export function chaseRadius(units: readonly UnitStack[], data: GameData): number {
  let tightest = Infinity;
  for (const st of units) {
    if (st.count <= 0) continue; // правило 5: списанная машина радиус не правит
    tightest = Math.min(tightest, data.units[st.unit]?.stats.chaseRadius ?? 0);
  }
  return Number.isFinite(tightest) ? tightest : 0;
}

/** Итог одного пересчёта: где эскадра теперь и догнала ли она цель. */
export interface ChaseStep {
  at: ChasePoint;
  caught: boolean;
}

/**
 * Один пересчёт погони (правила 1–4): `travel` — сколько карты эскадра проходит за этот
 * шаг, `radius` — её радиус захвата, `aim` — центр радиуса цели НА ЭТОТ МОМЕНТ.
 */
export function chaseStep(
  at: ChasePoint,
  aim: ChasePoint,
  travel: number,
  radius: number,
): ChaseStep {
  const gap = Math.sqrt((aim.x - at.x) ** 2 + (aim.y - at.y) ** 2);
  if (gap <= radius) return { at, caught: true }; // правило 4
  const move = Math.min(Math.max(0, travel), gap); // правило 2
  if (move <= 0) return { at, caught: false };
  const next: ChasePoint = {
    x: at.x + ((aim.x - at.x) / gap) * move, // правило 1
    y: at.y + ((aim.y - at.y) / gap) * move,
  };
  const left = gap - move;
  return { at: next, caught: left <= radius }; // правило 3
}
