/**
 * Очередь одной линии производства над её каталогом: когда будет готов каждый заказ,
 * что прятать в свёрнутом виде и можно ли нажать «продолжить» у приостановленного.
 *
 * 1. **У ждущего заказа есть срок.** Линия строит по одному, ждущий стартует, когда
 *    кончится предыдущий, — значит, готов он через сумму длительностей перед ним и свою.
 *    Срок неизвестен (у героя нет длительности) — дальше по очереди его тоже нет:
 *    угадывать хуже, чем промолчать.
 * 2. **Свёрнутая очередь — одна строка идущего.** Шесть заказов строками съедают
 *    экран телефона над каталогом; остальные прячутся за «+N», который показывает,
 *    когда освободится вся линия. Две строки и меньше не сворачиваются: строка «+1»
 *    заняла бы столько же места, сколько сам заказ.
 * 3. **«Продолжить» — только на свободной линии.** Ядро отвечает `E_LANE_BUSY` на
 *    возобновление, пока линия занята (BLD-1: возобновление — это старт, в очередь оно
 *    не встаёт). Кнопка, которая всегда отвечает отказом, — поломка, а не подсказка.
 */

/** Заказ линии: идущий знает, когда закончится (`at`); ждущий — сколько длится. */
export interface LaneQueueJob {
  at?: number;
  duration?: number;
}

/** Когда будет готов каждый заказ, в порядке очереди (правило 1). */
export function laneReadyTimes(now: number, jobs: readonly LaneQueueJob[]): (number | undefined)[] {
  let end: number | undefined = now;
  return jobs.map((job) => {
    if (job.at !== undefined) {
      end = end === undefined ? undefined : Math.max(end, job.at);
      return job.at;
    }
    end = end !== undefined && job.duration !== undefined ? end + job.duration : undefined;
    return end;
  });
}

/** Сколько строк очереди видно (правило 2): всё — раскрытой или короткой, одна — свёрнутой. */
export function laneVisibleRows(rows: number, open: boolean): number {
  return open || rows <= 2 ? rows : 1;
}

/** Можно ли возобновить приостановленный заказ (правило 3): линия ничего не строит. */
export function laneCanResume(jobs: readonly LaneQueueJob[]): boolean {
  return !jobs.some((job) => job.at !== undefined);
}
