// VET-5: ЧТО ПОКАЗАТЬ ИГРОКУ ПРО МЕДАЛИ СТЕКА.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ДВЕ ВЁРСТКИ. Медали есть у каждого стека в списке состава,
// а список состава рисуют оба клиента своими руками (`panelKit.unitRows` в прототипе,
// `matchHud` в `packages/client`). Если каждый соберёт значок сам, они разойдутся в
// глифе, в порядке и — что хуже — в том, ЧТО считается подписью: один возьмёт имя
// степени, другой номер, и игрок, перешедший с прототипа на клиент, увидит другую игру.
//
// ЧТО ЗДЕСЬ, А ЧТО НЕ ЗДЕСЬ. Правило «сколько заслуги на какую степень» — ПРАВИЛО МИРА,
// оно в ядре (`medalsOf`, `packages/shared-core/src/state/medals.ts`) и здесь только
// ВЫЗЫВАЕТСЯ, а не повторяется: выплата в конце матча считается тем же правилом, и
// расхождение между «что показали» и «за что заплатили» было бы худшим из возможных —
// молчаливым. Здесь живёт ровно клиентская половина: какой глиф у линии и какой текст
// под ним.
//
// ГЛИФ, А НЕ ИКОНКА. Строка состава на телефоне узкая, и картинка в неё не влезет рядом с
// иконкой корпуса, числом и именем. Один символ на линию — это всё, что можно показать,
// не отобрав место у самого состава; имя степени уезжает в подпись (`title`), где его
// увидит тот, кому интересно.
import { medalsOf, type MedalAward, type MedalLine } from '../packages/shared-core/src/index';
import type { GameData, UnitStack } from '../packages/shared-core/src/index';
import { t } from '../localization/core';

/** Глиф линии. Разведены ОБРАЗНО, как и имена: доблесть — звезда (огонь), выслуга —
 *  вымпел (корабль). Игрок различит их раньше, чем прочитает подпись. */
const LINE_GLYPH: Readonly<Record<MedalLine, string>> = {
  valour: '✦',
  service: '⚑',
};

/** Значок медали, готовый к отрисовке: глиф, подпись и класс степени для цвета. */
export interface MedalBadge {
  line: MedalLine;
  grade: number;
  glyph: string;
  /** Локализованная подпись: «Доблесть: Багровая звезда». Собирается ЗДЕСЬ, чтобы два
   *  клиента не изобрели двух разных форматов. */
  title: string;
}

/**
 * Значки медалей стека — в порядке линий из ядра, без степеней и без нулей.
 *
 * Пустой массив значит «медалей нет», и это ЕДИНСТВЕННЫЙ способ сказать «нет»: у стека
 * без заслуги вид строки не меняется ни на пиксель. Показать «нет медалей» отдельно
 * значило бы занять место под сообщение, которое верно для трёх четвертей списка.
 */
export function medalBadges(stack: UnitStack, data: GameData): MedalBadge[] {
  return medalsOf(stack, data).map((award: MedalAward) => ({
    line: award.line,
    grade: award.grade,
    glyph: LINE_GLYPH[award.line],
    title: `${t(`medal.${award.line}`)}: ${t(award.key)}`,
  }));
}
