/**
 * Как из набранного игроком получается адрес сервера (REFM-162).
 *
 * Первая часть остатка секции `meta-progression`: `resolveServer()` — вход в сеть для
 * ВСЕГО клиента (дозвон, браузер матчей, проба режима аккаунтов, восстановление доступа),
 * и до сих пор он держал в себе шесть решений подряд, из которых четыре — правки чужого
 * ввода. Каждая из них закрывает СВОЙ молчаливый провал: адрес выглядит принятым, а
 * соединение не открывается и в консоли пусто.
 *
 * 1. **Пустой адрес называют вслух, пустой позывной — молча.** Реакция разная не по
 *    прихоти: адрес игрок вводит сам и осознанно, а `resolveServer()` зовут ещё и из
 *    загрузочного блока (проба `/auth/status`) ДО того, как человек что-то напечатал, —
 *    жалоба «введите позывной» висела бы под свежеоткрытой приветственной карточкой. Оба
 *    случая одинаково НЕ пускают дальше, разница только в том, говорить ли об этом.
 * 2. **`http(s)://` принимается и переводится в `ws(s)://`.** Адрес сервера игрок копирует
 *    из адресной строки браузера, где стоит `https://`. Отвергнуть такой ввод — значит
 *    требовать от человека знания, что игра ходит по веб-сокету.
 * 3. **Голый `host:port` дополняется схемой СТРАНИЦЫ.** Без схемы адрес не разберётся
 *    вовсе, а угадывать между `ws` и `wss` неоткуда: страница по HTTPS почти наверняка
 *    подаётся тем же сервером, что и сокет.
 * 4. **На HTTPS-странице `ws://` поднимается до `wss://`.** Смешанное содержимое браузер
 *    режет сам: сокет не открывается, окна с ошибкой нет — игрок видит вечное
 *    «подключение» и не может понять, что не так. Правка делает то, что браузер всё равно
 *    потребует.
 * 5. **Путь и запрос отбрасываются, остаются схема и хост.** Скопированный вместе с
 *    адресом `/matches` превратил бы сокет в запрос к несуществующей странице.
 * 6. **Неразбираемый адрес — отказ С ПРИЧИНОЙ, а не молчание.** Опечатка в адресе — самая
 *    частая беда при заходе на чужой сервер; молчаливый отказ не даёт её найти.
 */

/** Чем кончился разбор того, что набрано в полях. */
export type AddressStep =
  /** Поле адреса пустое — сказать вслух (правило 1). */
  | { kind: 'need-address'; key: 'net.need-address' }
  /** Адрес не разобрался — сказать вслух (правило 6). */
  | { kind: 'bad-address'; key: 'net.bad-address' }
  /** Позывной ещё не введён — молча не пускать (правило 1). */
  | { kind: 'need-nick' }
  /** Всё есть: нормализованный адрес сокета и позывной. */
  | { kind: 'ok'; base: string; nick: string };

export interface TypedIn {
  /** Содержимое поля адреса, как есть. */
  server: string;
  /** Содержимое поля позывного, как есть. */
  nick: string;
  /** Страница открыта по HTTPS (правила 3–4). */
  pageHttps: boolean;
}

/**
 * Адрес сокета из того, что набрано: схема правится (правила 2–4), путь отбрасывается
 * (правило 5). `null` — разобрать не удалось.
 */
export function socketBase(typed: string, pageHttps: boolean): string | null {
  let raw = typed.replace(/^http(s?):\/\//i, 'ws$1://'); // правило 2
  if (!/^wss?:\/\//i.test(raw)) raw = (pageHttps ? 'wss://' : 'ws://') + raw; // правило 3
  if (pageHttps && raw.startsWith('ws://')) raw = 'wss://' + raw.slice('ws://'.length); // правило 4
  try {
    const url = new URL(raw);
    return `${url.protocol}//${url.host}`; // правило 5
  } catch {
    return null;
  }
}

/** Полный разбор полей входа (правила 1–6). */
export function resolveAddress(typed: TypedIn): AddressStep {
  const server = typed.server.trim();
  if (!server) return { kind: 'need-address', key: 'net.need-address' };
  const base = socketBase(server, typed.pageHttps);
  if (base === null) return { kind: 'bad-address', key: 'net.bad-address' };
  const nick = typed.nick.trim();
  if (!nick) return { kind: 'need-nick' };
  return { kind: 'ok', base, nick };
}
