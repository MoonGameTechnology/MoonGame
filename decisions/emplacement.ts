/**
 * Космическая крепость на карте — неподвижный космический юнит (сообщение владельца
 * 2026-10-03: «Крепость после постройки должна появляться на точке, где её построили, в
 * виде неподвижного космического юнита „космическая крепость“, который не летает по
 * орбите»).
 *
 * В ядре крепость воюет отрядом орудий (`fortress_guns`, FORT-5.4): это флот, и до этой
 * правки клиент рисовал его как любой флот — шевроном на орбитальном кольце, который
 * кружит вокруг узла, корпусом «по архетипу» и с кнопками «Курс», «Слить», «Разделить»,
 * на которые ядро отвечает отказом. Правила ниже отличают такой отряд и говорят, как его
 * показать.
 *
 * 1. **Отряд-сооружение — флот, в котором ВСЕ живые юниты `immobile`, и это не мина.**
 *    По трейту, а не по id отряда: id крепостного отряда — внутренняя договорённость
 *    модуля `station`, а неподвижность — данные. Мина тоже `immobile`, но у неё свой знак
 *    и своё окно (SM-3.6), поэтому она исключена здесь же.
 * 2. **Сооружение стоит В ТОЧКЕ, где его поставили, носом вверх.** Не на орбитальном
 *    кольце и не в строю боя: оно не облетает узел и не разворачивается к врагу.
 * 3. **Чужой слот на кольце оно не занимает** — веер флотов на орбите считается без него.
 * 4. **Приказов у него нет.** Ядро не двигает, не сливает и не делит неподвижное
 *    (`E_FLEET_IMMOBILE`, `E_EMPLACEMENT`), значит выбор сооружения — осмотр, как у мины,
 *    а не выбор под приказ: кнопки, которые всегда откажут, игроку не показываются.
 */
import type { Fleet, GameData } from '../packages/shared-core/src/index';
import { defHasTrait } from '../packages/shared-core/src/index';

/** Нос сооружения на карте: вверх, как у силуэта в каталоге (правило 2). */
export const EMPLACEMENT_HEADING = -Math.PI / 2;

/** Флот — неподвижное сооружение (правило 1). Пустой флот — не сооружение. */
export function isEmplacementFleet(fleet: Pick<Fleet, 'units'>, data: GameData): boolean {
  const live = fleet.units.filter((st) => st.count > 0);
  return (
    live.length > 0 &&
    live.every((st) => defHasTrait(data.units[st.unit], 'immobile')) &&
    !live.some((st) => defHasTrait(data.units[st.unit], 'mine'))
  );
}
