/**
 * Что окно выбора места показывает вместо списка домов и что написано в строке дома
 * (REFM-155).
 *
 * Четырнадцатый срез сетевой секции. `seatPicker.ts` (REFM-49) группирует места в дома,
 * `seatJoin.ts` (REFM-152) превращает выбор в адрес входа — а между ними оставалось само
 * окно: чем оно занято, пока список едет, что показывает, если не доехал, и из чего
 * состоит строка дома. Всё это стояло внутри `openSeatPicker` вперемешку со сборкой
 * разметки — две заглушки разной раскраски и две подписи, собранные по месту.
 *
 * 1. **Окно поднимается СРАЗУ, ещё до ответа сервера.** Игрок нажал «Войти»; окно,
 *    которое ждёт ответа за кулисами, выглядит как проваленный тап — человек жмёт ещё
 *    раз и открывает второй запрос вместо того, чтобы дождаться первого. Поэтому пустое
 *    место занимает честная заглушка «Загрузка…».
 * 2. **Каждый заход начинается с заглушки, а не с домов ПРОШЛОГО матча.** Окно живёт в
 *    разметке между заходами (тот же довод, что у `seatJoin.ts`, правило 2), и уцелевшие
 *    строки выглядят настоящим выбором: игрок выберет дом, которого в ЭТОМ матче нет.
 * 3. **Ожидание и беда различаются не только словами, но и цветом.** Заглушка занимает
 *    одно и то же место, читают её мельком, и приглушённое «Загрузка…» от красного «не
 *    удалось» на глаз должно отличаться раньше, чем игрок дочитает строку.
 * 4. **Строка дома говорит и словом, и счётом.** «Свободно» отвечает на вопрос «пустят
 *    ли», счёт «1/2» — на следующий, «сколько там уже сидит»; в доме мест несколько
 *    (`seatPicker.ts`, правило 2), так что одного слова не хватает.
 *
 * ⚠️ Отказ сервера и обрыв связи это окно показывает ОДИНАКОВО — «не удалось загрузить
 * слоты». Это расхождение с правилом 3 `matchQuery.ts` («сервер ответил отказом» и «до
 * сервера не дошли» — разные беды, и повторять стоит только вторую). Поведение оставлено
 * как было; вопрос записан владельцу.
 */

/** Где находится окно по времени запроса мест. */
export type SeatPhase =
  /** Окно только что открыли, запрос ушёл (правила 1–2). */
  | 'opening'
  /** Места получены. */
  | 'loaded'
  /** Сервер ОТВЕТИЛ отказом. */
  | 'refused'
  /** До сервера не дошли или ответ не разобрался. */
  | 'unreachable';

/** Что стоит на месте списка домов. */
export type SeatView =
  /** Заглушка: ключ текста и тон (правило 3). */
  | { kind: 'placeholder'; key: 'seatpick.loading' | 'seatpick.load-failed'; tone: 'dim' | 'bad' }
  /** Сам список домов. */
  | { kind: 'houses' };

/** Что показать в окне на этом шаге (правила 1–3 и оговорка про отказ/обрыв). */
export function seatView(phase: SeatPhase): SeatView {
  if (phase === 'loaded') return { kind: 'houses' };
  if (phase === 'opening') return { kind: 'placeholder', key: 'seatpick.loading', tone: 'dim' };
  return { kind: 'placeholder', key: 'seatpick.load-failed', tone: 'bad' };
}

/** Подписи строки дома: слово о занятости и счёт мест (правило 4). */
export function houseLine(house: { free: number; total: number; full: boolean }): {
  statusKey: 'browser.free' | 'browser.taken';
  count: string;
} {
  return {
    statusKey: house.full ? 'browser.taken' : 'browser.free',
    count: `${house.free}/${house.total}`,
  };
}
