/**
 * Приветственный снимок: вход в матч, а не просто «пришло состояние» (REFM-144).
 *
 * Продолжение `socketFate.ts`: там решалось, ЧЕЙ сокет и что значит его закрытие, здесь —
 * что значит первый пришедший по нему снимок. Разбор стоял внутри `connect()` одной
 * ветвью `if (!admitted)`, вперемешку с полутора десятками присваиваний глобальным
 * переменным, и три отдельных правила в ней были не видны.
 *
 * 1. **Вход подтверждает ПЕРВЫЙ снимок, а не открытие сокета** (обратная сторона правила 2
 *    из `socketFate.ts`), и обработать его можно ровно ОДИН раз на сокет. Второй снимок —
 *    обычное обновление мира; повтори он вход, игрок каждые полсекунды получал бы фанфару,
 *    сброшенный выбор и вычищенные черновики прямо посреди игры.
 * 2. **Переподключение — это НЕ новый матч.** Фанфара звучит только при ПЕРВОМ входе.
 *    Отличить их даёт живой цикл переподключения: признак «нас впустили» умирает вместе с
 *    сокетом и на реконнекте снова ложен, а флаг цикла переживает обрыв именно для этого.
 *    Иначе каждый провал связи объявлял бы игроку начало матча, которого не было.
 * 3. **Приветственный снимок ЗАКРЫВАЕТ цикл переподключения.** Счётчик попыток обнуляется
 *    (иначе следующий обрыв начнёт отсчёт с максимальной задержки — как будто связь уже
 *    долго не даётся), а баннер переподключения снимается: он врал бы поверх работающей игры.
 * 4. **Баннер снимает тот, кто его поставил.** Вход гасит СВОЙ баннер и не трогает чужие
 *    («ждём хоста», итог матча): безусловная очистка стёрла бы сообщение, о котором вход
 *    ничего не знает. Канал баннера различается по метке в начале строки.
 * 5. **Вход НЕ ПЕРЕНОСИТ хвосты прошлой сессии** — выбор флотов, черновик цепочки, очередь
 *    грузов, экран итога. Идентификаторы прошлой сессии в новом мире либо не существуют,
 *    либо принадлежат другому игроку, а экран итога прошлого матча поверх нового объявил
 *    бы поражение в только что начатой игре. Сброс идёт и на переподключении тоже —
 *    пришедший снимок сервера и есть новая истина о мире (см. правило 2: молчит там только
 *    фанфара, а не сам вход).
 */

/** Метка баннера переподключения — по ней вход узнаёт СВОЙ баннер (правило 4). */
export const RECONNECT_MARK = '⟳';

/** Что известно к моменту прихода снимка. */
export interface WelcomeState {
  /** Этот сокет уже получал приветственный снимок. */
  admitted: boolean;
  /** Жив цикл переподключения (обрыв был, места мы ещё не заняли). */
  reconnecting: boolean;
  /** Текущий баннер поверх карты. */
  banner: string | null;
}

/** Что делать с этим снимком. */
export interface WelcomePlan {
  /** Это вход: занять место, сбросить хвосты прошлой сессии, завести таймеры (правила 1, 5). */
  admit: boolean;
  /** Играть фанфару начала матча (правило 2). */
  fanfare: boolean;
  /** Каким остаётся баннер (правила 3–4). */
  banner: string | null;
}

/** Наш ли это баннер переподключения (правило 4). */
export function isReconnectBanner(banner: string | null): boolean {
  return !!banner && banner.startsWith(RECONNECT_MARK);
}

/** Что значит пришедший снимок (правила 1–5). */
export function welcomePlan(st: WelcomeState): WelcomePlan {
  if (st.admitted) return { admit: false, fanfare: false, banner: st.banner };
  return {
    admit: true,
    fanfare: !st.reconnecting,
    banner: isReconnectBanner(st.banner) ? null : st.banner,
  };
}
