/**
 * Семантический зум карты: что растворяется на схематичном виде (REFM-93).
 *
 * Общий mapLod.ts вычисляет детализацию по расстоянию между узлами в CSS-пикселях.
 * На общем плане остаются плоские маркеры, территории, пути, флоты и пульсы боя.
 * Здесь — законы размеров и прозрачности для возвращающихся при приближении слоёв.
 *
 * 1. **Схема и детализация — КРОСС-ФЕЙД, а не порог.** Между `LOD_FROM` и концом полосы
 *    доля детализации растёт плавно: скачком карта бы моргала на каждом щипке.
 * 2. **Доля ЗАЖАТА в [0,1].** Ею умножают `globalAlpha`, а он вне этого отрезка либо
 *    молча обрезается, либо роняет кадр — «чуть-чуть отрицательная» прозрачность это
 *    поломка, а не бледная картинка.
 * 3. Арт узла и залп осады используют один масштаб: от 45% до 100%. На общем плане
 *    отдельный коэффициент mapLod.art полностью исключает дорогой арт узла.
 * 4. **СВОЙ мир подписан ВСЕГДА** — не ниже 0.9 даже на полной схеме: это якорь игрока
 *    на любом зуме, как название города на глобусе. Чужая подпись уходит вместе с
 *    детализацией.
 * 5. **Шеврон и полная выкладка флота — ВСТРЕЧНЫЙ кросс-фейд:** их непрозрачности в
 *    сумме всегда единица, поэтому в середине перехода не бывает ни двойной картинки,
 *    ни пустого места.
 * 6. Яркость видимой сферы зависит от нормализованного масштаба и имеет пол 0.3.
 *    На общем плане сфера и её свечение вообще не рисуются.
 */

/** Порог подписей и анимации в нормализованном масштабе (расстояние / 64 CSS px). */
export { LOD_FROM, LOD_SPAN, detailAt } from '../../packages/client/src/mapLod';

/** Множитель размера арта узла и залпа осады: 45% на схеме → 100% на детали (правило 3). */
export function artScale(detail: number): number {
  return 0.45 + 0.55 * detail;
}

/** Непрозрачность подписи узла; ноль значит «не рисовать вовсе» (правило 4). */
export function calloutAlpha(detail: number, mineWorld: boolean): number {
  if (mineWorld) return Math.max(detail, 0.9);
  return detail;
}

/** Непрозрачность схематичного шеврона флота — встречная к выкладке (правило 5). */
export function chevronAlpha(detail: number): number {
  return 1 - detail;
}

/** Яркость голографической сферы планеты: своя шкала от масштаба, с полом (правило 6). */
export function sphereBloom(scale: number): number {
  return Math.max(0.3, Math.min(1, 0.3 + (scale - 1) * 0.7));
}
