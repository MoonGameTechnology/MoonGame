/**
 * Ритм кольца цели задачи на карте забега. Заказы владельца: 2026-09-24 «сделай анимацию
 * кружка миссии на карте», 2026-09-25 «Пунктир сделай анимированным по примеру пингов».
 *
 * Кольцо живёт, как метка на голографической карте (`drawHolographicPing`), и каждый слой
 * говорит одно — «тебе сюда»:
 *  - сам пунктир уходит наружу волнами, как сонар метки: копия кольца отрывается от него,
 *    растёт на {@link WAVE_REACH} и тает за {@link WAVE_MS};
 *  - волн всегда ДВЕ со сдвигом в полпериода: пока одна гаснет у предела, другая уже
 *    родилась, и кольцо не замирает между всплесками (одиночная волна оставляла полпериода
 *    пустоты — на загруженной карте кольцо читалось неподвижным);
 *  - у каждой цели своя фаза ({@link missionRingPhase}) — соседние цели не мигают в унисон;
 *  - пунктир бежит по кругу, яркость и свечение дышат.
 *
 * Часы — визуальные (`hologramTime` хоста): стоят на паузе и при отключённой анимации.
 * Без анимации (`motion = false`) кольцо неподвижно: пунктир на месте, волн нет, яркость
 * средняя — метка остаётся видимой, но не мигает.
 */

/** Период жизни одной волны, мс, — как у метки на голографической карте. */
export const WAVE_MS = 3000;
/** Сдвиги пары волн в долях периода. */
export const WAVE_OFFSETS: readonly number[] = [0, 0.5];
/** Радиус самого кольца на карте, px. */
export const RING_R = 24;
/** Толщина пунктира кольца, px. Волна рождается такой же и к пределу тоньше вдвое. */
export const RING_W = 1.8;
/** На сколько волна уходит от кольца, px: гаснет там же, где эхо метки (58 от центра). */
export const WAVE_REACH = 34;
/** Прозрачность волны при рождении — как у кольца метки; к пределу тает до нуля. */
export const WAVE_ALPHA = 0.62;
/** Полный оборот фазы на столько единиц карты по X — у метки оборот на ~125 px экрана. */
const PHASE_SPAN = 125;
/** Скорость бега пунктира: мс часов на пиксель. */
const DASH_MS_PER_PX = 60;
/** Период дыхания яркости. */
const BREATH_MS = 520;

export interface MissionWave {
  /** Радиус волны, px. */
  r: number;
  /** Прозрачность. */
  alpha: number;
  /** Толщина штриха, px. */
  width: number;
  /**
   * Во сколько раз волна больше кольца. Во столько же длиннее её штрихи и сдвиг пунктира:
   * уходит само кольцо, а не новый, всё более мелкий узор.
   */
  scale: number;
}

export interface MissionRingFrame {
  /** 0..1 — яркость и свечение кольца. */
  breath: number;
  /** Смещение пунктира кольца (`lineDashOffset`), px. */
  dashOffset: number;
  /** Волны пунктира; пусто — анимация выключена. */
  waves: MissionWave[];
}

/**
 * Своя фаза цели, доли периода 0..1, — от места мира на КАРТЕ. У метки фаза берётся от
 * экранного X и потому плывёт при панораме; у кольца цели она от панорамы и зума не
 * зависит. Двойной модуль держит результат в [0, 1) и при отрицательной координате.
 */
export function missionRingPhase(pos: { x: number; y: number }): number {
  return (((pos.x / PHASE_SPAN) % 1) + 1) % 1;
}

/** Волна на доле жизни `k` (0 — у кольца, 1 — у предела). */
function wave(k: number): MissionWave {
  const scale = 1 + (k * WAVE_REACH) / RING_R;
  return { r: RING_R * scale, alpha: WAVE_ALPHA * (1 - k), width: RING_W * (1 - k / 2), scale };
}

export function missionRingFrame(clock: number, motion: boolean, phase = 0): MissionRingFrame {
  if (!motion) return { breath: 0.5, dashOffset: 0, waves: [] };
  return {
    breath: 0.5 + 0.5 * Math.sin(clock / BREATH_MS + phase * 2 * Math.PI),
    dashOffset: -clock / DASH_MS_PER_PX,
    waves: WAVE_OFFSETS.map((off) => wave((((clock / WAVE_MS + phase + off) % 1) + 1) % 1)),
  };
}
