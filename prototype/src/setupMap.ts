/**
 * Мини-карта экрана сетапа: где стартовать (REFM-45).
 *
 * Мини-карта рисуется SVG'ом, и в ней есть три вещи, которые ломаются молча.
 *
 * 1. **Каждая трасса рисуется ОДИН раз.** Связи в данных двусторонние: узел A знает
 *    про B, а B — про A. Пройди по ним в лоб, и половина карты получит по две линии
 *    друг на друге: полупрозрачные штрихи сложатся и станут ярче соседних, будто там
 *    важная магистраль. Правило «рисуем ребро, только когда встретили его младший
 *    конец» и есть то, что держит вид карты честным.
 * 2. **Кандидаты идут ПОСЛЕДНИМИ.** Кружок стартовой точки крупнее обычного узла, и
 *    если нарисовать его раньше, обычные узлы лягут сверху и перекроют цель тапа —
 *    экран будет выглядеть кликабельным, но не отзываться.
 * 3. **Рамка с отступом.** Без него узлы у края обрезаются ровно наполовину, а
 *    выбранный кандидат — он ещё крупнее — тем более.
 *
 * ТАП ПО МИНИ-КАРТЕ (REFM-126) — сюда же, потому что попасть по кандидату можно только
 * в той системе координат, в которой эта карта и разложена.
 *
 * 4. **Тап переводится в координаты viewBox, а не читается с экрана.** SVG растягивается
 *    с `preserveAspectRatio=meet`: единый масштаб по МЕНЬШЕЙ стороне плюс центрирование
 *    по большей. Считай тап в пикселях экрана — и снап промахнётся тем сильнее, чем
 *    сильнее вытянуто окно, причём в одну сторону: на широком экране мимо по горизонтали,
 *    на узком — по вертикали. Ровно эта арифметика и стояла в обработчике россыпью.
 * 5. **Промах засчитывается БЛИЖАЙШЕМУ кандидату.** Кружок кандидата на телефоне около
 *    восьми пикселей: требовать прямого попадания значит требовать снайперской точности
 *    от пальца, а выбор старта — первое, что игрок делает в партии. Радиус снапа задан в
 *    единицах viewBox, тех же, что координаты узлов; в экранных он «плыл» бы с размером
 *    окна, и на телефоне ловил бы совсем не так, как на мониторе.
 * 6. **Прямое попадание по кружку важнее снапа** — если игрок попал точно, гадать не о
 *    чем. Это правило живёт в вызывающем: там оно и есть сам поиск элемента под тапом.
 *
 * 7. **`lanes()` обслуживает ОБЕ карты (REFM-127).** Имя файла историческое: то же
 *    правило «каждая трасса один раз» нужно и БОЛЬШОЙ карте матча, где сеть путей
 *    печётся в статический слой, — и там стоял свой цикл с тем же сравнением
 *    идентификаторов. Причина одна на обе карты и одинаково невидимая: штрихи
 *    полупрозрачные (на большой карте 0.34), поэтому дважды нарисованная дорога просто
 *    становится ярче соседних — не ошибка, не артефакт, а «магистраль», которой в данных
 *    нет. Разъедься копии — и одна карта показывала бы одну сеть, а вторая другую.
 */

/** Узел карты в том виде, в каком его держит `map.ts`. */
export interface MapNodeLike {
  id: string;
  x: number;
  y: number;
  links: readonly string[];
}

/** Отрезок трассы между двумя узлами. */
export interface Lane<T extends MapNodeLike = MapNodeLike> {
  from: T;
  to: T;
}

/** Рамка мини-карты: охватывает все узлы плюс отступ, чтобы края не срезались. */
export function mapViewBox(
  nodes: readonly MapNodeLike[],
  pad: number,
): { x: number; y: number; w: number; h: number } {
  if (nodes.length === 0) return { x: -pad, y: -pad, w: pad * 2, h: pad * 2 };
  const xs = nodes.map((n) => n.x);
  const ys = nodes.map((n) => n.y);
  const minX = Math.min(...xs);
  const maxX = Math.max(...xs);
  const minY = Math.min(...ys);
  const maxY = Math.max(...ys);
  return { x: minX - pad, y: minY - pad, w: maxX - minX + pad * 2, h: maxY - minY + pad * 2 };
}

/**
 * Трассы без повторов: ребро берётся только со стороны МЛАДШЕГО конца (см. шапку).
 * Ссылки в никуда пропускаются — карта не обязана быть согласованной, чтобы рисоваться.
 */
export function lanes<T extends MapNodeLike>(nodes: readonly T[]): Array<Lane<T>> {
  const byId = new Map(nodes.map((n) => [n.id, n]));
  const out: Array<Lane<T>> = [];
  for (const n of nodes) {
    for (const id of n.links) {
      const m = byId.get(id);
      if (!m || m.id < n.id) continue;
      out.push({ from: n, to: m });
    }
  }
  return out;
}

/** Порядок рисования узлов: сначала фон, потом стартовые кандидаты поверх него. */
export function drawOrder<T extends MapNodeLike>(
  nodes: readonly T[],
  candidates: readonly string[],
): { plain: T[]; candidates: T[] } {
  const cand = new Set(candidates);
  const byId = new Map(nodes.map((n) => [n.id, n]));
  return {
    plain: nodes.filter((n) => !cand.has(n.id)),
    // Порядок кандидатов — как в списке стартовых точек, а не как на карте:
    // список и есть то, по чему игрок их перебирает.
    candidates: candidates.flatMap((id) => {
      const n = byId.get(id);
      return n ? [n] : [];
    }),
  };
}

/** Прямоугольник элемента на экране — та часть `DOMRect`, что нужна для перевода. */
export interface ScreenRect {
  left: number;
  top: number;
  width: number;
  height: number;
}

/** Рамка SVG в том виде, в каком её держит `viewBox`. */
export interface ViewBoxRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

/**
 * Точка тапа в координатах viewBox (правило 4). `null` — карта ещё не разложена
 * (нулевая ширина рамки или элемента), и переводить нечего.
 */
export function viewBoxPoint(
  rect: ScreenRect,
  vb: ViewBoxRect,
  clientX: number,
  clientY: number,
): { x: number; y: number } | null {
  if (!(vb.width > 0) || !(rect.width > 0)) return null;
  // preserveAspectRatio=meet: масштаб один на обе оси — по меньшей стороне.
  const scale = Math.min(rect.width / vb.width, rect.height / vb.height);
  return {
    x: vb.x + (clientX - rect.left - (rect.width - vb.width * scale) / 2) / scale,
    y: vb.y + (clientY - rect.top - (rect.height - vb.height * scale) / 2) / scale,
  };
}

/** Радиус снапа в единицах viewBox — примерно три радиуса кружка кандидата (правило 5). */
export const SNAP_REACH = 90;
