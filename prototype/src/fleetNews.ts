/**
 * Кому есть дело до флотских новостей (REFM-181).
 *
 * Четыре события про флоты и одно про рынок отвечали на вопрос «а услышит ли это игрок»
 * каждое по-своему, прямо в свитче: где-то `p.owner === ME`, где-то фог-гейт, где-то
 * вообще ничего. Решения собраны сюда, чтобы их можно было прочитать рядом и сравнить —
 * именно сравнение и вскрыло расхождение соло с сетью, снятое правилом 4.
 *
 * 1. **Вылет — событие КАРТЫ, и его судьбу решает `recapGate`** (`fleet.launched` стоит
 *    там в политике `seen`). Здесь его нет намеренно: держать одно правило в двух местах
 *    — верный способ развести их, а гейт `recapGate.test.ts` требует, чтобы каждый
 *    экономический case проходил через `admits()` буквально.
 *
 * 2. **Слияние и деление слышно ТОЛЬКО своё.** Чужая реорганизация игроку не наблюдаема
 *    в принципе: на карте видно значок флота, а не то, что два соединения свели в одно.
 *    Объявить её значило бы выдать за наблюдение то, что наблюдать нечем.
 *
 * 3. **Сделка на рынке слышна ОБЕИМ сторонам, и формулировка зависит от стороны.**
 *    Рынок анонимен для посторонних, но свою сделку игрок обязан увидеть — иначе списание
 *    казны выглядит пропажей денег. Покупка и продажа различаются не знаком числа, а
 *    словом: «купил» и «продал» — разные события в голове игрока, и одна строка с минусом
 *    заставила бы его вычислять, что произошло.
 *
 * 4. **Гибель флота слышит только его ВЛАДЕЛЕЦ** (решение владельца 2026-10-06: чужое
 *    «флот уничтожен» — раскрытие информации). Так же работает сеть, и это пункт 5
 *    доктрины `eventVisibility.ts` (REFM-86): `combat.ts` издаёт `fleet.destroyed` с
 *    полезной нагрузкой `{ fleetId, owner }`, БЕЗ места, и `MatchRoom.eventVisibleTo`
 *    отдаёт событие только владельцу погибшего флота (ветка по `fleetId` к этому моменту
 *    уже не срабатывает — флота в состоянии нет). Прежде соло объявляло гибель ВСЕМ,
 *    включая драку двух ботов за туманом, и рассказывало больше сети. Исход своего боя
 *    игрок узнаёт строкой итога и ведомостью потерь (`battleLog.ts`), а не новостью о
 *    чужом флоте. Исключение одно — боеприпас, чей конец уже объявлен своей строкой
 *    (`spent`): израсходованная мина (SM-3.6) и ракета — попала, перехвачена ПРО или сбита
 *    челноками (SM-3.7b). «☠️ флот уничтожен» следом читалось бы как потеря флота, которой
 *    не было.
 */

/** Вид реорганизации: свести флоты в один или разделить один на два. */
export type ReorgKind = 'merged' | 'split';

/** Слияние и деление — новость только для владельца (правило 2). */
export function reorgHeard(owner: unknown, me: string): boolean {
  return owner === me;
}

/** Ключ строки журнала для реорганизации. */
export function reorgKey(kind: ReorgKind): 'log.fleet.merged' | 'log.fleet.split' {
  return kind === 'merged' ? 'log.fleet.merged' : 'log.fleet.split';
}

/**
 * Слышна ли гибель флота: только владельцу, и не боеприпаса с пометкой `spent` (правило 4).
 * Безымянный владелец — не я (fail-secure).
 */
export function destroyHeard(p: Readonly<Record<string, unknown>>, me: string): boolean {
  return p.owner === me && p.spent !== true;
}

/** Сделка слышна тому, кто в ней участвовал — с любой стороны (правило 3). */
export function tradeHeard(buyer: unknown, seller: unknown, me: string): boolean {
  return buyer === me || seller === me;
}

/** С какой стороны сделки стоит игрок — от этого зависит слово в строке (правило 3). */
export function tradeSide(buyer: unknown, me: string): 'log.market.buy' | 'log.market.sell' {
  return buyer === me ? 'log.market.buy' : 'log.market.sell';
}
