/**
 * Что значит приказ «слить флоты» (REFM-165).
 *
 * Слияние — единственный приказ, у которого ДВА разных исхода на одно нажатие: рядом
 * стоящие флоты сливаются сразу, а разнесённые сперва летят к якорю и сливаются по
 * прибытии. Обе ветки стояли одним циклом внутри `orderMerge`, вперемешку с отправкой
 * приказов и записью намерений, и ни одно из шести решений не объясняло себя.
 *
 * 1. **Якорь — только СВОЙ и живой.** Слить в чужой флот (или в тот, что уже погиб)
 *    нельзя: приказ отскочит от ядра отказом, а игрок к тому моменту уже увидел бы
 *    «слито» и считал бы флоты объединёнными.
 * 2. **Сам в себя не сливается.** Якорь в списке сливаемых — не ошибка игрока: рамка
 *    выделения захватывает и его. Молча пропустить его правильнее, чем слать приказ
 *    «слить A в A», который ядру нечем исполнить.
 * 3. **Чужие и погибшие среди сливаемых просто пропускаются.** Групповой приказ не должен
 *    отменяться целиком из-за одного флота, которого больше нет: остальные-то живы.
 * 4. **Стоят там же и никто не летит — сливаем НЕМЕДЛЕННО.** Это уже «вместе»; гонять их
 *    куда-то значит откладывать то, что можно сделать сейчас. Важно, что проверяются ОБА:
 *    летящий якорь через минуту будет в другом месте, и «слияние на месте» промахнулось бы.
 * 5. **Иначе — «долететь и слиться», и точка встречи берётся у якоря:** где он стоит, а
 *    если местоположения уже нет (он в пути) — конец его пути (`location ?? movingTo`).
 *    Без второй половины флот, отправленный к якорю в перелёте, шёл бы в никуда: у такого
 *    якоря текущей точки просто нет. Кто уже стоит в точке встречи, никуда не летит —
 *    приказ на движение ему не нужен, но намерение слиться записывается и ему.
 * 6. **У одного флота не может быть двух «во что слиться».** Новое намерение вытесняет
 *    прежнее: игрок передумал, и старая запись слила бы флот не туда — причём молча, уже
 *    по прибытии, когда объяснить это будет нечем.
 */

/** Флот глазами приказа на слияние. */
export interface MergeFleet {
  owner: string;
  /** Где стоит; `null` — в пути. */
  location: string | null;
  /** Куда летит; `null` — стоит. */
  movingTo: string | null;
}

/** Что делать с одним сливаемым флотом. */
export type MergeStep =
  /** Слить прямо сейчас — уже вместе (правило 4). */
  | { kind: 'now'; mover: string }
  /** Запомнить намерение; `sendTo` — куда лететь, `null` — уже там или лететь некуда. */
  | { kind: 'route'; mover: string; sendTo: string | null };

export interface MergePlan {
  /** Точка встречи: где якорь стоит или окажется (правило 5). */
  dest: string | null;
  steps: MergeStep[];
  /** Сколько флотов полетит — столько же намерений будет записано (правило 6). */
  queued: number;
}

/**
 * План слияния (правила 1–6). `null` — якорь не годится, и тогда НЕ происходит ничего:
 * ни приказов, ни смены выделения.
 */
export function mergePlan(
  fleets: Readonly<Record<string, MergeFleet | undefined>>,
  movers: readonly string[],
  anchorId: string,
  me: string,
): MergePlan | null {
  const anchor = fleets[anchorId];
  if (!anchor || anchor.owner !== me) return null; // правило 1
  const dest = anchor.location ?? anchor.movingTo ?? null; // правило 5
  const steps: MergeStep[] = [];
  let queued = 0;
  for (const mover of movers) {
    if (mover === anchorId) continue; // правило 2
    const m = fleets[mover];
    if (!m || m.owner !== me) continue; // правило 3
    const together = !!m.location && m.location === anchor.location && !m.movingTo && !anchor.movingTo;
    if (together) {
      steps.push({ kind: 'now', mover }); // правило 4
      continue;
    }
    steps.push({ kind: 'route', mover, sendTo: dest && m.location !== dest ? dest : null });
    queued++;
  }
  return { dest, steps, queued };
}
