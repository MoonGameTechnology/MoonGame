/**
 * Что написано в запросе «объявить войну?» и что написано на его кнопках (REFM-168).
 *
 * Запрос поднимается по двум РАЗНЫМ поводам, и текст с подписями кнопок у них тоже разный.
 * Выбор стоял двумя тернарниками прямо в сборке разметки `renderWarPrompt`, и из них не
 * читалось главное: игрок в этих двух случаях отвечает на разные вопросы.
 *
 * 1. **Повод решает, ЧТО написано.** Транзит — «маршрут идёт через миры того, с кем у вас
 *    мир»; штурм — «это мир дружественной фракции». Разные новости: в первом случае война
 *    объявится ПОПУТНО, по дороге к цели, во втором она и есть цель. Одинаковый текст
 *    заставил бы игрока гадать, за что он подписывается.
 * 2. **Подписи кнопок идут в паре с поводом.** У штурма это прямой вопрос — «ДА» / «НЕТ».
 *    У транзита кнопка называет ПОСЛЕДСТВИЕ («ОБЪЯВИТЬ ВОЙНУ»), а отказ — «ОТМЕНА»: игрок
 *    просил не войну, а перелёт, и «ДА» на такой вопрос читалось бы как «да, лететь», то
 *    есть согласием не на то, что произойдёт.
 * 3. **Заголовок один на оба повода.** Что бы ни привело сюда, решается одно и то же —
 *    объявлять ли войну; разный заголовок сделал бы из одного решения два разных окна.
 * 4. **Имена виновников экранируются.** Это имена игроков и домов, то есть чужой ввод в
 *    разметке (`esc` — та же дисциплина, что и в остальных панелях).
 */

/** Почему поднялся запрос. */
export type WarReason =
  /** Штурм мира невраждебного игрока — война и есть цель. */
  | 'assault'
  /** Маршрут пересекает чужие владения — война попутная. */
  | 'transit';

/** Ключи текстов запроса (правила 1–3). */
export interface WarPromptText {
  title: 'war.confirm.title';
  body: 'war.confirm.friendly' | 'war.confirm.transit';
  yes: 'war.confirm.yes' | 'war.confirm.go';
  no: 'war.confirm.no' | 'war.confirm.cancel';
}

/** Что показать в запросе (правила 1–3). */
export function warPromptText(reason: WarReason): WarPromptText {
  return reason === 'assault'
    ? {
        title: 'war.confirm.title',
        body: 'war.confirm.friendly',
        yes: 'war.confirm.yes',
        no: 'war.confirm.no',
      }
    : {
        title: 'war.confirm.title',
        body: 'war.confirm.transit',
        yes: 'war.confirm.go',
        no: 'war.confirm.cancel',
      };
}

/** Повод по флагу запроса — `assault: true` ставит только штурм (`selectAt`). */
export function warReason(assault: boolean | undefined): WarReason {
  return assault ? 'assault' : 'transit';
}
