/**
 * Номер партии на экране и в поле «Войти по номеру» (плейтест 2026-10-17).
 *
 * Владелец попросил вместо адресов в меню показывать номер партии из цифр, который можно
 * скопировать, — как у Bytro. Сервер чеканит такие номера сам (`packages/server/src/
 * matchId.ts`); здесь — как номер выглядит и как его читают обратно.
 *
 * 1. **На экране — номер, а не адрес.** Адрес `https://…/game/<id>` занимал три строки
 *    карточки и читался как служебная информация; номер короток и его диктуют голосом.
 * 2. **Старые партии называются своим id.** До номеров партии получали `m-<uuid>` и
 *    `proto`; они живут, пока не кончатся, и называть их иначе, чем сервер, нельзя —
 *    иначе по показанному «номеру» в партию не войти.
 * 3. **Поле прощает то, что люди вставляют.** «№ 48 219 370», «#48219370» и целиком
 *    скопированный адрес партии читаются как один и тот же номер. Мусор — `null`: вход не
 *    пытается звонить по строке, которую не понял.
 */

/** Сколько символов id ещё похоже на партию: UUID с префиксом — 38. */
const ID_MAX = 64;

/** Правила 1–2: что показать на месте адреса. */
export function matchNumberText(matchId: string): string {
  return `№ ${matchId}`;
}

/** Правило 3: номер (или id старой партии) из того, что игрок ввёл; `null` — не понял. */
export function parseMatchNumber(input: string): string | null {
  let raw = input.trim();
  const onPath = /\/game\/([^/?#\s]+)/.exec(raw);
  if (onPath) {
    try {
      raw = decodeURIComponent(onPath[1]!);
    } catch {
      return null;
    }
  }
  raw = raw.replace(/^(№|#)\s*/, '');
  if (/^[0-9][0-9\s]*$/.test(raw)) raw = raw.replace(/\s+/g, '');
  return raw.length > 0 && raw.length <= ID_MAX && /^[A-Za-z0-9-]+$/.test(raw) ? raw : null;
}
