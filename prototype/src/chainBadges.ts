/**
 * Какие планы показывать на карте и как свести их в ◎-бейджи (REFM-73).
 *
 * Слой планов рисует ОТПРАВЛЕННЫЕ приказы своих флотов. Правила отбора и группировки
 * решают, что игрок увидит, и раньше жили внутри цикла отрисовки.
 *
 * 1. **Только СВОИ планы.** Чужой приказ — это разведданные, которых у игрока нет;
 *    показать его значит выдать чужие намерения даром.
 * 2. **Редактируемый план исключён из отправленных.** Иначе он нарисуется дважды —
 *    бледным «отправленным» и ярким черновиком — и прочитается как два разных приказа.
 * 3. **Обход в устойчивом порядке (по id флота).** Бейджи не должны переставляться
 *    местами от кадра к кадру: их порядок задаёт и номер в стопке, и содержимое хита.
 * 4. **Группировка по ЯКОРЮ — конечной точке маршрута.** Несколько флотов, идущих в
 *    один мир, дают ОДИН бейдж со счётчиком, а не стопку одинаковых значков.
 * 5. **План без якоря бейджа не получает** — рисовать его негде (это решает группировка,
 *    поэтому якорь считается только для тех планов, что вообще показываются).
 * 6. **Счётчик появляется только при двух и более:** «1» на бейдже — шум.
 */

/** Отправленный план глазами отбора: чей он. */
export interface OrderOwner {
  fleetId: string;
  owner: string | null | undefined;
}

/** Показываемый план с посчитанным якорем. */
export interface AnchoredOrder {
  fleetId: string;
  /** Конечная точка маршрута; `null` — плану негде встать. */
  anchor: string | null;
}

/**
 * Планы, которые слой рисует: свои и не редактируемые сейчас (правила 1–2). Якорь тут
 * не нужен — он считается уже для выживших, чтобы не тратить кадр на чужие планы.
 * Порядок входа сохраняется: вызывающий подаёт его отсортированным (правило 3).
 */
export function shownOrders<E extends OrderOwner>(
  entries: readonly E[],
  me: string,
  editing: ReadonlySet<string>,
): E[] {
  return entries.filter((e) => e.owner === me && !editing.has(e.fleetId));
}

/**
 * Планы по якорю: мир → флоты, идущие в него, в порядке входа (правило 4). Порядок
 * САМИХ якорей — порядок их первого появления, чтобы бейджи не прыгали.
 */
export function groupByAnchor(entries: readonly AnchoredOrder[]): Map<string, string[]> {
  const byWorld = new Map<string, string[]>();
  for (const e of entries) {
    if (e.anchor === null) continue;
    const arr = byWorld.get(e.anchor);
    if (arr) arr.push(e.fleetId);
    else byWorld.set(e.anchor, [e.fleetId]);
  }
  return byWorld;
}

/** Подпись счётчика на бейдже; `null` — не рисовать (правило 6). */
export function badgeCount(n: number): string | null {
  return n > 1 ? String(n) : null;
}

/** Бейдж висит над миром, выше булавки метки. */
export const BADGE_DY = -29;

/** Пульс бейджа: 0.55…1.0, свой период — план дышит медленнее метки. */
export function badgePulse(now: number): number {
  return 0.55 + 0.45 * Math.sin(now / 260);
}
