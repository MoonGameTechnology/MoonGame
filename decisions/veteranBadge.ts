import { t } from '../localization/core';

/** Глиф — ТОТ ЖЕ вымпел, что у медали «Выслуга» в строке состава (`unitMedals.ts`).
 *  Это одна механика, показанная в двух местах: значок на корабле говорит «этот стек
 *  воевал», строка в окне боя — «вот сколько это сейчас даёт». Разные символы заставили
 *  бы игрока связывать их самому, и большинство не связало бы. */
const GLYPH = '⚑';

/** Готовая к отрисовке надбавка: глиф, короткая надпись и подпись. */
export interface VeteranBadge {
  glyph: string;
  /** Видимая надпись — только число: `+8%`. Слов здесь нет намеренно, они в `title`
   *  (тот же приём, что у медалей: в узкую строку имя степени не влезает). */
  text: string;
  /** Локализованная подпись — что это за проценты и откуда взялись. */
  title: string;
  /** Округлённые проценты. Отдаются наружу, чтобы тест и вёрстка не парсили `text`. */
  percent: number;
}

/**
 * Значок надбавки по множителю стороны, либо `null` — «показывать нечего».
 *
 * `null` во всех трёх случаях, и это одно и то же для игрока: надбавки нет (`undefined`
 * или `1`), механика выключена данными, ИЛИ надбавка есть, но округляется в ноль.
 * Последнее — не придирка: типичная выслуга это один бой на юнит, а половина сил обычно
 * необстреляна, так что множители вида 1.004 — обычное дело. Значок «+0%» занял бы
 * место в строке и не сказал бы ничего.
 */
export function veteranBadge(factor: number | undefined): VeteranBadge | null {
  if (factor === undefined || !(factor > 1)) return null;
  const percent = Math.round((factor - 1) * 100);
  if (percent <= 0) return null;
  return { glyph: GLYPH, text: `+${percent}%`, percent, title: t('battle.win.veteran', { n: percent }) };
}
