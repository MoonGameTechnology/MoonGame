/**
 * Как дышит метка на карте и как расходятся её сонарные кольца (REFM-72).
 *
 * Метка — это «смотри сюда» через полкарты, поэтому её анимация несёт смысл, а не
 * украшает: она обязана быть заметной в поле других меток и не должна ронять кадр.
 *
 * 1. **Фаза берётся от X метки — соседние не мигают в унисон.** Иначе поле меток
 *    превращается в одну общую мигалку и перестаёт указывать на что-то конкретное.
 * 2. **Двойной модуль держит прогресс кольца ПОЛОЖИТЕЛЬНЫМ.** У метки за левым краем
 *    экрана `x < 0`, а JS-остаток сохраняет знак делимого: отрицательный прогресс даёт
 *    отрицательный радиус, и `arc()` роняет кадр исключением.
 * 3. **Кольца идут парой со сдвигом в полпериода** — волна «капает» вдвое чаще, чем
 *    живёт одно кольцо, и метка не выглядит замершей между всплесками.
 * 4. **Молодое кольцо вспыхивает заливкой** первые 18% жизни: без этого волна не
 *    рождается, а просто возникает из ниоткуда.
 * 5. **Кольцо растёт и утончается от ОДНОГО прогресса** — радиус, толщина и прозрачность
 *    берутся из него же, а не из своих таймеров, иначе они разъедутся.
 */

/** Период жизни одного кольца. */
export const RING_PERIOD_MS = 2200;

/** Период «дыхания» самой булавки. */
export const PULSE_PERIOD_MS = 360;

/** Сдвиги пары колец в долях периода (правило 3). */
export const RING_OFFSETS: readonly number[] = [0, 0.5];

/** Доля жизни, пока кольцо вспыхивает заливкой (правило 4). */
export const DROP_IN = 0.18;

/** Собственная фаза метки по её X (правило 1). */
export function pingPhase(x: number): number {
  return x * 0.05;
}

/** Дыхание булавки: 0.7…1.0. */
export function pinPulse(now: number, phase: number): number {
  return 0.7 + 0.3 * Math.sin(now / PULSE_PERIOD_MS + phase);
}

/**
 * Прогресс кольца 0 → 1 за период. Двойной модуль — не украшение: он и держит
 * результат в [0, 1) при отрицательной фазе (правило 2).
 */
export function ringProgress(now: number, phase: number, offset: number): number {
  return (((now / RING_PERIOD_MS + offset + phase) % 1) + 1) % 1;
}

/** Радиус кольца: от узла наружу (правило 5). */
export function ringRadius(k: number): number {
  return 6 + k * 40;
}

/** Толщина кольца: тает вместе с ним (правило 5). */
export function ringWidth(k: number): number {
  return 3.2 - k * 2.2;
}

/** Прозрачность самого кольца. */
export function ringAlpha(k: number): number {
  return (1 - k) * 0.8;
}

/** Заливка «капли» у молодого кольца; после `DROP_IN` — ноль (правило 4). */
export function dropInAlpha(k: number): number {
  return k < DROP_IN ? (1 - k / DROP_IN) * 0.28 : 0;
}
