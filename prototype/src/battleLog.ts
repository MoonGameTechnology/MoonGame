/**
 * Что игрок узнаёт о бое — от начала до итога (REFM-179).
 *
 * ПУСКАТЬ ли строку решает видимость события — `eventVisibility.ts` (REFM-86): начало
 * судится общим правилом тумана, а ИТОГ — «хвостовым» (`seenTail`), потому что свой бой
 * помнится по месту и его исход обязан доехать до журнала, даже если узел уйдёт под туман
 * по ходу схватки. Здесь остальное: чем именно названы обе строки.
 *
 * 1. **Фаза называется всегда.** Орбита и десант — разные бои с разными войсками; «бой у
 *    X» без фазы не говорит игроку, кого туда слать и успеет ли он.
 * 2. **Итог — победитель ИЛИ ничья, третьего нет.** Молчание вместо исхода читалось бы как
 *    «бой ещё идёт», а бой уже кончился.
 * 3. **Потери приписываются, только если они есть.** Пустой хвост «· потери:» — строка ни
 *    о чём, она удлиняет запись и обесценивает соседние цифры.
 * 4. **Потери сводятся ПО ИГРОКУ, а не по типам.** В одной строке журнала важно, кто
 *    сколько потерял; поштучный разбор по типам живёт в разборе боя, и здесь он превратил
 *    бы одну строку в абзац.
 * 5. **Порядок в сводке — порядок, в котором стороны попали в учёт.** Пересортировать
 *    было бы честнее по алфавиту, но тогда одна и та же битва читалась бы по-разному на
 *    разных языках; порядок появления одинаков для всех.
 */

/** Потери: игрок → тип юнита → сколько. */
export type BattleLosses = Record<string, Record<string, number>>;

/** Ключ названия фазы (правило 1). */
export function battlePhaseKey(
  phase: string | undefined,
): 'log.battle.phase.ground' | 'log.battle.phase.orbit' {
  return phase === 'ground' ? 'log.battle.phase.ground' : 'log.battle.phase.orbit';
}

/** Чем назван итог: победа кого-то или ничья (правило 2). */
export function battleOutcome(winner: string | undefined | null): {
  key: 'log.battle.win' | 'log.battle.draw';
  /** Нужна ли подстановка имени победителя. */
  named: boolean;
} {
  return winner ? { key: 'log.battle.win', named: true } : { key: 'log.battle.draw', named: false };
}

/** Сводка потерь одной строкой; пустая — приписывать нечего (правила 3–5). */
export function lossTally(
  losses: BattleLosses | undefined,
  name: (id: string) => string,
): string {
  if (!losses) return '';
  return Object.entries(losses)
    .map(([who, units]) => {
      const total = Object.values(units).reduce((a, b) => a + b, 0);
      return `${name(who)} −${total}`;
    })
    .join(', ');
}
