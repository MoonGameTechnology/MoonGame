// NETA2-4: сторож сменил предмет охраны — и переехал к тому, что охраняет.
//
// Жил в `packages/client/src/`, потому что стерёг клиентские копии; теперь копий нет, а
// предмет охраны — отношение между пакетами, поэтому файл лежит у контракта.
//
// Прежде здесь стояли Mutual-ассерты (`[A] extends [B] ? [B] extends [A]`) между
// рукописной клиентской копией wire-типов и серверным оригиналом: компилятор ронял гейт,
// когда две декларации расходились. Тест работал, но лечил симптом — сами копии он
// оставлял на месте, и каждая новая пара полей требовала третьей записи в ассертах.
//
// Теперь декларация ОДНА (`@void/protocol`), и проверять «совпадают ли копии» стало
// тавтологией: клиент реэкспортирует ровно те типы, что импортировал. Поэтому сторож
// охраняет то, что тавтологией не является, — что копии НЕ ВЕРНУЛИСЬ: `multiplayer.ts`
// не объявляет своих версий протокольных типов, а получает их из пакета. Проверка идёт по
// исходнику, потому что структурная типизация TypeScript по определению не отличит копию
// от оригинала, пока они совпадают, — а отличить нужно ДО того, как они разойдутся.
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';

const source = readFileSync('packages/client/src/multiplayer.ts', 'utf8');

/** Типы, чья форма принадлежит контракту, а не клиенту. */
const WIRE_TYPES = ['PingKind', 'PingAnchor', 'ChatChannel'] as const;

describe('NETA2-4 — wire-контракт объявлен ОДИН раз', () => {
  it('клиент берёт протокольные типы из пакета, а не объявляет свои', () => {
    expect(source).toMatch(/import type \{[^}]*\} from '@void\/protocol'/s);
  });

  for (const name of WIRE_TYPES) {
    it(`\`${name}\` не объявлен в клиенте заново`, () => {
      // Ловим именно ОБЪЯВЛЕНИЕ (`export type X =` / `export interface X`), а не
      // упоминание: импорт и реэкспорт того же имени — законны и обязаны проходить.
      expect(source).not.toMatch(new RegExp(`export (type ${name} =|interface ${name}\\b)`));
    });
  }

  it('клиентские имена остались публичными — переименования UI не потребовалось', () => {
    // `MultiplayerPing`/`MultiplayerChatMessage` — поверхность клиента, её читает весь UI.
    // Контракт переехал, имена нет; если реэкспорт снимут, это сломает не только сборку,
    // но и договор с прототипом, поэтому проверяем явно.
    expect(source).toMatch(/export type \{[^}]*MultiplayerPing[^}]*\}/s);
    expect(source).toMatch(/export type \{[^}]*MultiplayerChatMessage[^}]*\}/s);
  });
});
