/**
 * Что клиент кладёт в запрос к `/auth` и какой ответ считает пропуском (REFM-156).
 *
 * Четырнадцатый срез сетевой секции. Проверку логина с паролем и разбор кодов ответа
 * держит `authRules.ts` (REFM-47), но три решения ПЕРЕД запросом и одно ПОСЛЕ него
 * оставались выражениями по месту внутри `ensureSession` — а каждое из них выбирает
 * между вариантами, которые легко перепутать местами.
 *
 * 1. **Пароль берут из того поля, которое игрок реально заполнил.** Полей два —
 *    приветственная карточка (первый вход) и строка в браузере матчей (свой сервер), — и
 *    лежат они в разметке ОДНОВРЕМЕННО. «Главного» среди них нет, есть заполненное:
 *    взять всегда одно и то же значит потребовать пароль, который игрок ввёл не туда, и
 *    отказать при верном пароле.
 * 2. **Явно переданный пароль не перебивается полями — даже ПУСТОЙ.** Вызов, который его
 *    передал (вход с карточки, восстановление доступа), знает свой контекст лучше обоих
 *    полей. Пустая строка от такого вызова обязана дойти до проверки и получить внятное
 *    «пароль слишком короткий»; молча подставить вместо неё содержимое чужого поля — это
 *    войти не тем паролем, который человек только что видел на экране.
 * 3. **Почта уходит ТОЛЬКО в регистрацию и только если её ввели.** Входу почта не нужна —
 *    лишнее поле в теле запроса это данные, отправленные без надобности. А `email: ''`
 *    вместо отсутствия поля записал бы на учётку пустой адрес: восстановление доступа
 *    потом упрётся в него как в «адрес уже задан».
 * 4. **Пропуск берут у ВХОДА, регистрация — только вторая попытка.** Порядок здесь и есть
 *    смысл «первый вход создаёт учётку»: сперва пробуем войти в существующую, и лишь
 *    неизвестный логин уводит в регистрацию. Перепутать порядок значит заводить вторую
 *    учётку тому, у кого она уже есть.
 */

/** Ответ `/auth/login` или `/auth/register` в том виде, в каком его читает клиент. */
export interface TokenReply {
  token?: string;
}

/** Какой пароль уходит в запрос (правила 1–2). */
export function passwordFrom(
  passed: string | undefined,
  welcomeCard: string,
  browserField: string,
): string {
  if (passed !== undefined) return passed; // правило 2: даже пустой
  return welcomeCard || browserField;
}

/** Что добавить к телу РЕГИСТРАЦИИ сверх логина и пароля (правило 3). */
export function registerExtra(email: string | undefined): Record<string, string> {
  return email ? { email } : {};
}

/** Пропуск из пары ответов: вход первым, регистрация — вторая попытка (правило 4). */
export function mintedToken(login: TokenReply, register?: TokenReply): string | null {
  return login.token ?? register?.token ?? null;
}
