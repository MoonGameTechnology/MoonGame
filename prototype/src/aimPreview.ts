/**
 * Превью взведённого приказа «Ход»: КУДА идёт линия и что она обещает (REFM-196).
 *
 * Радиус захвата и поиск ближайшего уже вынесены (`tapPriority.ts`, `pointerPick.ts`),
 * маршрут считает ядро (`planRoute`), срок — `estimateTravelHours`. Неразобранной
 * оставалась СБОРКА: из чего складывается линия, до чего она обязана дотянуться и что
 * написано у острия. Каждое правило ниже чинит враньё превью — а превью врёт тихо: игрок
 * принимает по нему решение и узнаёт правду, когда флот уже вышел.
 *
 * 1. **Мир важнее дороги: дорога ищется, только если узла рядом НЕТ.** Мир — это цель, а
 *    точка на дороге — «припарковаться по пути»; предложить дорогу рядом с миром значило бы
 *    отобрать у игрока очевидную цель, по которой он и целился.
 * 2. **Нет цели — остриё падает на сам указатель.** Линия обязана дотянуться до пальца,
 *    иначе взведённый прицел выглядит сломанным: игрок ведёт палец, а линия стоит.
 * 3. **Путь рисуется по МАРШРУТУ через центры провинций, а не прямой.** Прямая соврала бы
 *    про дорогу: армия пойдёт не туда, куда указывает линия, и игрок посчитает время и риск
 *    по несуществующему пути.
 * 4. **У цели-ДОРОГИ маршрут ведёт до точки ВХОДА, и лишь потом отрезок к точке на дороге.**
 *    Армия физически входит на дорогу через её конец; линия, режущая напрямик к середине
 *    дороги, обещала бы проход там, где его нет.
 * 5. **Маршрут строится, только если известны ОБА конца и они РАЗНЫЕ.** Путь из узла в себя
 *    пуст, и просить его — лишняя работа ради пустого ответа.
 * 6. **Маршрута не вышло — линия идёт прямо к острию.** Иначе не рисуется ВООБЩЕ ничего, и
 *    игрок читает это как «прицел не взведён», хотя он взведён.
 * 7. **Метка у точки на дороге МЕНЬШЕ, чем у мира.** Мир — тело с площадью, точка на дороге
 *    площади не имеет; кольцо мирового размера захватывало бы то, что целью не является.
 * 8. **Срок печатается только КОНЕЧНЫЙ, а меньше часа — в минутах и ВВЕРХ.** Бесконечность
 *    и `NaN` значат «маршрута нет», и «~Infinityh» хуже молчания; «~0.0h» не значит ничего;
 *    а округление вверх потому, что обещать МЕНЬШЕ, чем займёт, хуже, чем обещать больше.
 */

/** Точка на экране. */
export interface Point {
  x: number;
  y: number;
}

/** Правило 1: дорога ищется, только когда узла под указателем нет. */
export function laneSought(targetId: string | null): boolean {
  return targetId === null;
}

/** Правило 2: остриё линии — цель, а без цели сам указатель. */
export function aimTip(target: Point | null, pointer: Point): Point {
  return target ?? pointer;
}

/** Правило 4: у цели-дороги маршрут ведёт к её точке входа, а не к самой цели. */
export function routeViaLane(hasLaneTarget: boolean, standingAt: string | null): boolean {
  return hasLaneTarget && standingAt !== null;
}

/** Правило 5: маршрут имеет смысл только между двумя РАЗНЫМИ известными узлами. */
export function routeNeeded(from: string | null, endId: string | null): boolean {
  return from !== null && endId !== null && endId !== from;
}

/** Правила 3, 4 и 6: точка старта, центры провинций маршрута, точка на дороге, запасное остриё. */
export function aimPath(
  anchor: Point,
  hops: readonly Point[],
  lanePoint: Point | null,
  tip: Point,
): Point[] {
  const pts: Point[] = [anchor, ...hops];
  if (lanePoint) pts.push(lanePoint);
  if (pts.length === 1) pts.push(tip);
  return pts;
}

/** Правило 7: кольцо у мира и точка на дороге — разного размера. */
export function targetPipRadius(onLane: boolean): number {
  return onLane ? 9 : 16;
}

/** Правило 8: бесконечный и нечисловой срок не печатается вовсе. */
export function etaShown(hrs: number | null): boolean {
  return hrs != null && Number.isFinite(hrs);
}

/** Правило 8: от часа — десятые часа, меньше часа — целые минуты вверх. */
export function etaText(hrs: number): string {
  return hrs >= 1 ? `~${hrs.toFixed(1)}h` : `~${Math.ceil(hrs * 60)}m`;
}
