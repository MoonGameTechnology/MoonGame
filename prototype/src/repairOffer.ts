/**
 * Какие кнопки ремонта показывать на карточке флота (REFM-90).
 *
 * Ремонтов два, и они НЕ взаимозаменяемы: дешёвый экспресс за металл у своего дока и
 * ненавязчивый платный за кредиты где угодно. Условия у них разные, но общая часть —
 * «свой, не в бою, есть что чинить» — в коде складывалась в одну цепочку, из которой
 * непонятно, какое условие чьё.
 *
 * 1. **Чинить можно только СВОЙ флот.** Чужой чинит его владелец; предлагать кнопку —
 *    обещать приказ, который ядро отобьёт.
 * 2. **В бою ремонта нет.** Латать корпуса под огнём нельзя, и кнопка посреди схватки
 *    только сбивает с толку.
 * 3. **Нечего чинить — нечего и предлагать.** Нулевая цена значит полный корпус: кнопка
 *    на здоровом флоте выглядит как неисправность интерфейса.
 * 4. **Экспресс за металл — ТОЛЬКО у своего дока.** Это его смысл: дешевизна платится
 *    привязкой к месту, иначе платный ремонт за кредиты никому не нужен.
 * 5. **Док не отменяет платного.** У дока показываются ОБА: игрок выбирает, чем платить —
 *    металлом или кредитами, — а не получает решение за себя.
 */

/** Общая часть обоих ремонтов: свой, вне боя, есть что чинить (правила 1–3). */
export function canRepair(mine: boolean, inBattle: boolean, cost: number): boolean {
  return mine && !inBattle && cost > 0;
}

/** Экспресс за металл: та же общая часть плюс свой док (правило 4). */
export function canDockRepair(repairable: boolean, atOwnDock: boolean): boolean {
  return repairable && atOwnDock;
}
