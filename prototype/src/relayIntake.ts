/**
 * Что делать с РЕТРАНСЛИРОВАННОЙ строкой ленты — меткой на карте и репликой чата
 * (REFM-148).
 *
 * Седьмой срез сетевой секции. `orderRoute.ts` разобрал исходящее (приказ), здесь —
 * обратный поток по тем же двум каналам, что видит игрок: метка провинции и сообщение.
 * Оба обработчика (`onPingAdded`, `onChatMessage`) вели один и тот же разбор двумя
 * копиями коротких `if`-ов, и общее правило за ними было не видно.
 *
 * 1. **Личность строки назначает СЕРВЕР.** В сетевом матче клиент не кладёт свою метку
 *    в ленту сам: он шлёт намерение, а строка появляется от ЭХА сервера. Иначе одна и та
 *    же метка жила бы у автора под своим идентификатором, а у союзников под серверным, и
 *    «снять метку» убрало бы её только у части людей.
 * 2. **Своё эхо не удваивает строку.** Эхо приходит и автору тоже, а при входе в матч
 *    сервер вдобавок переигрывает историю — без сверки по серверному id одна метка легла
 *    бы в ленту дважды: живая строка и её повтор при подключении.
 * 3. **Строку, которую нечем показать, не берём.** Маркеры прототипа привязаны к
 *    провинции: метка без узла не нарисуется ни на карте, ни в ленте — это молчаливый
 *    мусор, а не сообщение, и место в ленте он занимал бы зря.
 * 4. **Снимается строка по серверному id, а не по тексту или автору.** Тексты
 *    повторяются («сюда», «внимание»), один игрок ставит десятки меток; уникален только
 *    id, и лишь по нему снимется ровно та метка, которую сняли у всех остальных.
 */

/** Что сделать с пришедшей строкой. */
export type Intake =
  /** Положить в ленту. */
  | 'add'
  /** Эта строка уже есть — эхо своей же или повтор при входе (правило 2). */
  | 'skip-duplicate'
  /** Показать нечем: метка без провинции (правило 3). */
  | 'skip-unshowable';

export interface RelayLine {
  /** Строка с таким серверным id уже лежит в ленте. */
  known: boolean;
  /** Есть чем показать строку (для метки — провинция, к которой она привязана). */
  showable: boolean;
}

/** Брать ли пришедшую строку (правила 2–3). */
export function relayIntake(line: RelayLine): Intake {
  if (!line.showable) return 'skip-unshowable';
  return line.known ? 'skip-duplicate' : 'add';
}

/** Куда уходит СВОЯ метка (правило 1). */
export type PingRoute =
  /** Сеть: намерение серверу, в ленту строка придёт эхом. */
  | 'server'
  /** Соло: своя лента и есть истина. */
  | 'local';

export function pingRoute(net: boolean, hasClient: boolean): PingRoute {
  return net && hasClient ? 'server' : 'local';
}
