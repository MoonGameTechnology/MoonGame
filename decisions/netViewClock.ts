/**
 * Часы КАРТИНКИ в сетевой партии: какое игровое время рисовать между снимками сервера.
 *
 * В сети мир двигает только сервер, а клиент получает его снимок, когда в мире что-то
 * случилось, и не реже раза в секунду (пульс `HEARTBEAT_MS` в `clockDriver.ts`). Пока
 * карта рисовала `state.time` снимка как есть, флоты, вылеты и мины стояли на месте весь
 * промежуток и перескакивали вперёд с приходом следующего: при ровных 60 кадрах картинка
 * двигалась раз в секунду — «FPS нормальный, но дёргается». Эти часы досчитывают время
 * снимка до текущего кадра.
 *
 * 1. **Картинка идёт вперёд от последнего снимка со скоростью мира.** Скорость меряется
 *    по самим снимкам (сколько игрового времени прошло за реальное между двумя), а не
 *    берётся константой: сервер волен крутить мир быстрее стены (`timeScale` плейтеста),
 *    и поставленная на паузу партия присылает снимки с тем же временем — скорость ноль.
 * 2. **Досчёт ограничен.** Сервер замолчал (обрыв, спящая вкладка на его стороне) —
 *    картинка проходит не больше {@link LEAD_MS} реального времени сверх снимка и
 *    останавливается, а не уводит флоты туда, где их, может быть, уже нет.
 * 3. **Новый снимок не дёргает картинку назад.** Досчитанное время почти всегда чуть
 *    расходится с присланным (сеть приносит снимки неровно). Невязку не выбрасывают
 *    скачком, а гасят за {@link BLEND_MS}, и гасят не быстрее хода мира — картинка лишь
 *    придерживается, но назад не едет.
 * 4. **Время назад или сменившийся матч — начать заново.** Снимок раньше прошлого бывает
 *    только при переподключении или входе в другую партию: старая скорость и невязка там
 *    ничего не значат.
 *
 * Модуль не решает, ЧТО рисовать: позиции по-прежнему считает ядро (`legT`,
 * `fleetPositionAt`) — ему лишь дают другое «сейчас», и оно само держит флот в пределах
 * его отрезка пути.
 */

/** Сколько реального времени картинка вправе досчитывать без нового снимка (правило 2):
 *  два пульса сервера — один опоздавший снимок не останавливает движение. */
export const LEAD_MS = 2000;

/** За сколько реального времени гасится невязка между досчётом и снимком (правило 3). */
export const BLEND_MS = 400;

/** Короче этого промежутка между снимками скорость не меряют: сетевой разброс там
 *  сравним с самим промежутком, и оценка прыгала бы. */
export const MIN_SAMPLE_MS = 150;

/** Вес свежего замера в сглаженной скорости. */
const RATE_WEIGHT = 0.3;

export interface NetViewClock {
  /** Игровое время последнего снимка; `null` — снимков ещё не было. */
  readonly t: number | null;
  /** Реальный момент (`performance.now()`), когда этот снимок пришёл. */
  readonly at: number;
  /** Скорость мира: игровых мс на реальную мс; 0 — пауза или ещё не измерена. */
  readonly rate: number;
  /** Реальный момент снимка, по которому мерили скорость в последний раз. */
  readonly sampledAt: number;
  /** Игровое время того снимка. */
  readonly sampledT: number;
  /** Досчитанное время минус время снимка в момент его прихода — гасится (правило 3). */
  readonly err: number;
}

/** Часы до первого снимка. */
export const NET_VIEW_IDLE: NetViewClock = { t: null, at: 0, rate: 0, sampledAt: 0, sampledT: 0, err: 0 };

/** Какое игровое время рисовать в реальный момент `now`. До первого снимка — `fallback`. */
export function netViewAt(clock: NetViewClock, now: number, fallback: number): number {
  if (clock.t === null) return fallback;
  const since = Math.max(0, now - clock.at);
  const ahead = Math.min(since, LEAD_MS) * clock.rate;
  const fade = since >= BLEND_MS ? 0 : 1 - since / BLEND_MS;
  return clock.t + ahead + clock.err * fade;
}

/** Пришёл снимок с игровым временем `t` в реальный момент `now`. */
export function netViewSnapshot(clock: NetViewClock, t: number, now: number): NetViewClock {
  if (clock.t === null || t < clock.t) return { t, at: now, rate: 0, sampledAt: now, sampledT: t, err: 0 };
  let { rate, sampledAt, sampledT } = clock;
  const span = now - sampledAt;
  if (span >= MIN_SAMPLE_MS) {
    const measured = (t - sampledT) / span;
    // Пауза — сразу ноль (иначе сглаживание ещё долго гнало бы картинку вперёд);
    // первый замер берётся как есть.
    rate = measured <= 0 ? 0 : rate === 0 ? measured : rate + (measured - rate) * RATE_WEIGHT;
    sampledAt = now;
    sampledT = t;
  }
  // Невязка не больше, чем мир проходит за время гашения: тогда картинка между снимками
  // не едет назад (правило 3). Отставание гасится так же — догоняет, а не прыгает.
  const limit = rate * BLEND_MS;
  const shown = netViewAt(clock, now, t);
  const err = Math.min(limit, Math.max(-limit, shown - t));
  return { t, at: now, rate, sampledAt, sampledT, err };
}
