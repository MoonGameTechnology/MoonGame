/**
 * Какая кнопка ряда команд горит и почему (REFM-186).
 *
 * Подсветка (`on`) в ряду отвечает на ТРИ разных вопроса, и в кадре они выглядели
 * одинаково — тернарником в аргументе `cmdBtn`:
 *
 *  · **взведённый прицел** (⤳ движение, ⚔ штурм, 🎯 обстрел, ⛬ слияние, ⊟ деление) —
 *    «команда взведена, следующий тап по карте её исполнит»;
 *  · **раскрытый поповер** (✨ способности, 🔥 режим огня, ⇵ десант, ☰ ещё, ⊕ набор) —
 *    «под кнопкой сейчас открыто меню»;
 *  · **общее состояние ФЛОТОВ** (⚡ форсаж, ⚔ авто-штурм, 🛩 стоячий вылет) — «это уже
 *    включено», и вот здесь начинается единственное место, где легко соврать.
 *
 * 1. **Групповая подсветка требует ЕДИНОГЛАСИЯ, а не «хоть у кого-то».** На группе из
 *    десяти флотов один включённый форсаж покрасил бы кнопку, и игрок прочёл бы это как
 *    «вся группа разогнана» — а потом удивился, почему девять идут обычным ходом. Кнопка
 *    в ряду говорит о ВЫДЕЛЕНИИ целиком, значит и гореть обязана только за всех сразу.
 *
 * 2. **Пустое множество НЕ горит — хотя `every` на нём истинно.** Это та самая ловушка
 *    пустой истины: без явной проверки кнопка загоралась бы ровно тогда, когда управлять
 *    нечем. В кадре от неё защищались ДВУМЯ разными способами: у форсажа и авто-штурма
 *    стояла явная проверка `ids.length > 0`, а у стоячего вылета защита была НЕЯВНОЙ —
 *    кнопки просто нет, когда в выделении нет ни одного крыла. Второй способ держится на
 *    соседнем условии: вынеси кнопку из-под него, и она загорится на пустом множестве.
 *    Здесь обе ветки идут через одну проверку, так что защита перестаёт зависеть от
 *    того, где стоит кнопка. Поведение при этом не меняется: сегодня оба пути дают
 *    одинаковый ответ.
 *
 * 3. **Модуль спрашивает про КАЖДОГО, а не считает сам.** Форсаж, авто-штурм и патруль
 *    живут в разных местах прототипа (флаги марша, стоячие приказы, патрули крыльев);
 *    тащить их сюда значило бы связать подсветку со всеми тремя. Признак приходит
 *    функцией — модуль знает только правило «все или никто».
 */

/**
 * Горит ли групповой переключатель: включено у ВСЕХ и выделение не пусто (правила 1–2).
 * `has` спрашивается по одному элементу — источник признака модулю неизвестен (правило 3).
 */
export function allOn<T>(items: readonly T[], has: (item: T) => boolean): boolean {
  return items.length > 0 && items.every(has);
}
