/**
 * HERO-CORRIDOR-VIEW — что карта показывает про временные коридоры героев.
 *
 * Статический слой лейн рисуется из карты (`MAP`), а коридор живёт в СОСТОЯНИИ
 * (`state.tempLanes`) и до сих пор не рисовался вообще: игрок не видел ни того, что
 * коридор открыт, ни куда он ведёт, ни сколько ему осталось.
 *
 * Что показываем и почему по-разному:
 *  · ступень 1 (одноразовый) — таймера НЕТ и быть не может: коридор закрывается по
 *    прибытию армии героя, а не по часам. Показывать «осталось 6 ч» было бы враньём.
 *    Обозначение — пунктир, который МИГАЕТ: он вот-вот исчезнет, это не дорога.
 *  · ступень 2 (временный) — тот же личный проход, но у него есть срок, поэтому и
 *    таймер настоящий.
 *  · ступень 3 (общий) — по нему идут все, включая противника; он рисуется как дорога,
 *    а не как личная тропа, и его срок тоже показывается.
 *
 * Модель чистая: `main.ts` — DOM-вход без юнит-харнеса, а «что и когда показывать» —
 * решение, которое должно проверяться тестом, а не глазами.
 */
import type { GameState } from '../../packages/shared-core/src/index';

export interface CorridorLine {
  laneId: string;
  from: string;
  to: string;
  /** Ступень: 1 — одноразовый, 2 — временный, 3 — общий. */
  tier: number;
  /** Мой ли это коридор (свой и чужой красятся по-разному). */
  mine: boolean;
  /** Мигает ли линия — только одноразовый: он исчезнет с первым же проходом. */
  blink: boolean;
  /** Сколько миллисекунд осталось, или `null` — когда таймера НЕ должно быть. */
  msLeft: number | null;
}

/**
 * Коридоры, которые стоит нарисовать прямо сейчас.
 *
 * `visible` — фог-гейт: чужой коридор показывается только если ОБА его конца опознаны.
 * Иначе оверлей выдавал бы позицию чужого героя и его планы — то самое раскрытие,
 * которое мы вычищали в сводке.
 */
export function corridorLines(
  state: GameState,
  me: string,
  now: number,
  visible: (planetId: string) => boolean,
): CorridorLine[] {
  const out: CorridorLine[] = [];
  for (const lane of state.tempLanes ?? []) {
    const tier = lane.tier ?? 1;
    const mine = lane.owner === me;
    if (!mine && !(visible(lane.from) && visible(lane.to))) continue;
    out.push({
      laneId: lane.id,
      from: lane.from,
      to: lane.to,
      tier,
      mine,
      blink: tier === 1,
      // У одноразового таймера нет по определению: он закрывается прибытием, а не
      // часами. Срок в состоянии у него всё равно стоит (страховка от утечки лейна),
      // но показывать его игроку — врать.
      msLeft: tier === 1 ? null : Math.max(0, lane.expiresAt - now),
    });
  }
  out.sort((a, b) => (a.laneId < b.laneId ? -1 : a.laneId > b.laneId ? 1 : 0));
  return out;
}
