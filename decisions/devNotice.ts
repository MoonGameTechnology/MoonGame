/**
 * Предупреждение «игра в разработке» — показать ли окно согласия на старте.
 *
 * Заказ владельца: на всех экранах ненавязчивая надпись, что игра в разработке, а при
 * запуске — окно, где игрок подтверждает, что понимает это.
 *
 * 1. **Согласие запоминается на устройстве, а не спрашивается каждый запуск.** Окно,
 *    которое встречает игрока при каждом входе, быстро становится кнопкой «закрыть не
 *    читая» — и предупреждение перестаёт предупреждать.
 * 2. **Согласие привязано к ВЕРСИИ текста.** Поменялся смысл предупреждения (например,
 *    «прогресс может быть сброшен» после вайпа) — поднимаем {@link DEV_NOTICE_VERSION},
 *    и окно снова показывается всем, включая тех, кто уже соглашался со старым текстом.
 * 3. **Чужое значение в хранилище — не согласие.** Хранилище правит кто угодно (A05):
 *    согласием считается только ровно текущая версия; мусор, пустая строка и старая
 *    версия — повод спросить ещё раз. Ошибиться в сторону лишнего вопроса дешевле, чем
 *    в сторону пропущенного предупреждения.
 */

/** Ключ хранилища устройства, в котором лежит версия принятого текста. */
export const DEV_NOTICE_KEY = 'vd.dev-notice';

/** Версия текста предупреждения. Поднять — значит спросить всех заново (правило 2). */
export const DEV_NOTICE_VERSION = 1;

/** Значение, которое кладётся в хранилище после согласия. */
export function devNoticeAckValue(version: number = DEV_NOTICE_VERSION): string {
  return String(version);
}

/** Нужно ли показать окно: игрок ещё не соглашался с ЭТОЙ версией текста (правила 1–3). */
export function needsDevNotice(
  stored: string | null,
  version: number = DEV_NOTICE_VERSION,
): boolean {
  return stored !== devNoticeAckValue(version);
}
