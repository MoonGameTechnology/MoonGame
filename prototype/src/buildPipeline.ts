/**
 * Сборный флот мира: когда он перестаёт собирать свежепостроенные корабли (REFM-172).
 *
 * Здесь ЖИЛА и очередь стройки — правила «одна вещь в полосе», «полосы независимы»,
 * «голова ждёт только денег». Их больше нет не потому, что они отменены, а потому что
 * они переехали ТУДА, ГДЕ ИСПОЛНЯЮТСЯ: с BLD-1 очередь живёт в ядре
 * (`shared-core/modules/construction.ts`), одна на сеть и на соло. Здесь они были
 * правилами КЛИЕНТА и действовали только офлайн — в сети каждый тап заводил ещё одну
 * параллельную стройку, и на плейтесте это выглядело как «постройки заменяют друг
 * друга, ресурсы тратятся».
 *
 * 1. **Сбор закрывается, когда на мире не осталось ни идущей постройки корабля, ни
 *    очереди.** Флот с меткой `rally` глотает свежепостроенные корабли; пока мир
 *    строит, партия ещё не полна.
 * 2. **Закрытие — снятие МЕТКИ, а не роспуск флота.** Корабли остаются на месте, а
 *    следующий заказ откроет НОВЫЙ сборный флот: иначе одна эскадра росла бы весь матч
 *    и отделить свежую партию было бы нечем.
 * 3. **О летящем флоте решения не принимают.** У него нет мира под ногами — читать
 *    «строит ли ещё его мир» попросту не по чему, и метка ждёт возвращения.
 */

/** Метка сборного флота: он глотает свежепостроенные корабли своего мира. */
export const RALLY_TRAIT = 'rally';

/** Флот, о котором решают судьбу сбора. */
export interface RallyFleetView {
  mine: boolean;
  /** Мир под ногами; `null` — флот в пути (правило 8). */
  location: string | null;
  moving: boolean;
  traits: readonly string[] | undefined;
}

/** Закрывать ли сбор этому флоту (правила 1, 3). */
export function rallyCloses(
  f: RallyFleetView,
  stillBuilding: (planetId: string) => boolean,
): boolean {
  if (!f.mine || !f.location || f.moving) return false;
  if (!f.traits?.includes(RALLY_TRAIT)) return false;
  return !stillBuilding(f.location);
}

/** Метки флота без сбора — корабли при этом остаются на месте (правило 2). */
export function withoutRally(traits: readonly string[]): string[] {
  return traits.filter((t) => t !== RALLY_TRAIT);
}

/** Строит ли мир корабли прямо сейчас: идущая постройка ИЛИ непустая очередь (правило 1). */
export function shipsPending(activeBuild: boolean, queuedShips: number): boolean {
  return activeBuild || queuedShips > 0;
}
