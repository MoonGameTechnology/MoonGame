/**
 * Послесвечение радарной развёртки: что горит после прохода луча (REFM-113).
 *
 * По карте медленно ходят лучи — по одному на каждый свой радар. Когда луч пересекает
 * узел, тот вспыхивает и потом медленно гаснет: это и есть «засветка» контакта, главный
 * признак того, что радар РАБОТАЕТ. Яркость считалась циклом внутри `sweepGlow`, а отбор
 * узлов — четырьмя `continue` внутри кадра, и между ними терялось главное: почему
 * помнимый узел горит серым, а не цветом владельца.
 *
 * 1. **Яркость считается по УГЛУ ОТСТАВАНИЯ от луча, а не по расстоянию.** Только что
 *    пройденный контакт горит ярче всего и гаснет по мере ухода луча — засветка обязана
 *    показывать «когда его последний раз видели», а не «далеко ли он».
 * 2. **Угол приводится к неотрицательному.** `%` в JS сохраняет знак делимого, и узел,
 *    оказавшийся «позади» луча, получил бы отрицательную долю — вместо плавного затухания
 *    он вспыхивал бы на переходе через ноль. (Та же ловушка, что у сетки фона, REFM-110.)
 * 3. **Кривая квадратичная.** Линейная растягивает хвост на весь оборот, и момент
 *    ПЕРЕСЕЧЕНИЯ перестаёт читаться — экран просто равномерно светится.
 * 4. **Вне досягаемости луча узел не светится вовсе:** луч обрезан радиусом своего
 *    радара, и свечение за этой границей обещало бы обзор, которого нет.
 * 5. **Из нескольких лучей берётся САМЫЙ ЯРКИЙ, а не сумма.** Узел под двумя радарами
 *    иначе пересвечивался бы вдвое и читался как более важный, хотя он просто в двойном
 *    покрытии.
 * 6. **Кого вообще подсвечивать — выводится из `fogView.nodeView`, а не решается заново.**
 *    Пустой узел контакта не имеет, никогда не виденный не должен выдавать себя засветкой,
 *    а ПОМНИМЫЙ горит нейтрально: цвет владельца из памяти может быть устаревшим, и
 *    покрасить им значило бы выдать за свежую разведку то, что ею не является.
 * 7. **Слишком слабая засветка не рисуется.** Почти прозрачный диск не виден, но стоит
 *    полного круга отрисовки на каждый узел каждый кадр.
 *
 * _Замечено при выносе, НЕ чинил (нашёл тест)._ На ТОЧНОМ совпадении угла узла с углом
 * луча разность считается вычитанием и погрешность уводит остаток в минус — приведение
 * знака (правило 2) добавляет полный оборот, и узел на один кадр читается как «давно не
 * виденный» вместо самого яркого. Свойство исходной формулы, сохранено дословно и
 * закреплено тестом: точное попадание в этот угол практически недостижимо (луч идёт
 * непрерывным приращением), а «починка» сместила бы всю шкалу засветки.
 */

import type { NodeView } from './fogView';

/** Луч развёртки: где закреплён и докуда достаёт (экранные координаты). */
export interface SweepArm {
  x: number;
  y: number;
  /** Радиус досягаемости (правило 4). */
  r: number;
}

/** Ниже этого свечение не рисуем (правило 7). */
export const GLOW_MIN = 0.03;

/** Засветка от ОДНОГО луча в этой точке: 0 — не достаёт (правила 1–4). */
export function armGlow(
  arm: SweepArm,
  at: { x: number; y: number },
  sweepAng: number,
  tau: number,
): number {
  const dx = at.x - arm.x;
  const dy = at.y - arm.y;
  if (dx * dx + dy * dy > arm.r * arm.r) return 0; // правило 4
  let delta = (sweepAng - Math.atan2(dy, dx)) % tau;
  if (delta < 0) delta += tau; // правило 2
  const t = 1 - delta / tau; // правило 1
  return t * t; // правило 3
}

/** Засветка от всех лучей: самый яркий, а не сумма (правило 5). */
export function sweepGlow(
  arms: readonly SweepArm[],
  at: { x: number; y: number },
  sweepAng: number,
  tau: number,
): number {
  let best = 0;
  for (const arm of arms) {
    const g = armGlow(arm, at, sweepAng, tau);
    if (g > best) best = g;
  }
  return best;
}

/** Что делать с засветкой этого узла. */
export type SweepPaint =
  /** Не подсвечивать (правило 6). */
  | { do: 'skip' }
  /** Подсветить; `ownerColored` — цветом владельца или нейтрально. */
  | { do: 'paint'; ownerColored: boolean };

/** Подсвечивать ли узел и каким цветом — по его виду под туманом (правило 6). */
export function sweepPaint(view: NodeView): SweepPaint {
  if (view === 'full') return { do: 'paint', ownerColored: true };
  if (view === 'remembered') return { do: 'paint', ownerColored: false };
  return { do: 'skip' }; // пустой узел и никогда не виденный
}

/** Стоит ли вообще рисовать диск с такой засветкой (правило 7). */
export function sweepShows(glow: number): boolean {
  return glow > GLOW_MIN;
}
