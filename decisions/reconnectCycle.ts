/**
 * Цикл переподключения: когда дозваниваться снова и когда сдаться (REFM-145).
 *
 * Третий срез сетевой секции после `socketFate.ts` (чей сокет и что значит его закрытие) и
 * `netWelcome.ts` (что значит первый снимок). Расписание задержек уже вынесено в
 * `reconnect.ts` (NETA2-2), а вот ПОЛИТИКА вокруг него — сколько попыток жив цикл, что
 * видит игрок, пока он идёт, и чем всё кончается, если сервер так и не ответил — стояла
 * внутри `scheduleReconnect()` вперемешку с таймером и глобальными переменными.
 *
 * 1. **Одна назначенная попытка за раз.** К одному обрыву приходит НЕСКОЛЬКО сигналов:
 *    закрытие сокета, ошибка на нём, закрытие пережившего своё старого. Без этой проверки
 *    каждый завёл бы свой таймер, задержки перестали бы расти (все ждут параллельно), и
 *    весь бюджет сгорел бы за секунду — раньше, чем сервер вообще освободит место.
 * 2. **Счётчик попыток растёт СКВОЗЬ дозвоны.** Новый дозвон его не обнуляет: иначе бюджет
 *    начинался бы заново на каждой попытке и цикл не кончился бы никогда — клиент вечно
 *    долбил бы мёртвый сервер, а игрок вечно смотрел бы на баннер.
 * 3. **Бюджет кончился — сдаться ЧЕСТНО, а не молча:** цикл закрывается, счётчик
 *    обнуляется, баннер снимается, в строке статуса «войдите заново», сверху экран
 *    подключения. Молчаливая остановка оставила бы игрока перед замершим миром в
 *    уверенности, что связь есть.
 * 4. **Пока цикл идёт — висит баннер.** Мир на экране больше не обновляется; без баннера
 *    игрок принял бы застывшую картинку за настоящую и продолжил бы отдавать приказы,
 *    которые никуда не уходят.
 * 5. **В режиме аккаунтов дозвон начинается с ЧЕКАНКИ свежего join-токена.** Токен живёт
 *    минуты, а цикл — десятки секунд, так что к повторному дозвону прежний уже протух.
 *    А протухшая СЕССИЯ — не повод крутиться дальше: это экран входа с просьбой ввести
 *    пароль (fail-explicit), потому что молчаливые попытки с мёртвой сессией не кончатся
 *    ничем, кроме потраченного бюджета.
 */

import { reconnectDelayMs } from './reconnect';

/** Что делать с очередной попыткой переподключения. */
export type CycleStep =
  /** Попытка уже назначена — эту просьбу игнорируем (правило 1). */
  | { kind: 'busy' }
  /** Ждать `delayMs` и дозвониться снова; всё это время висит баннер (правила 2, 4). */
  | { kind: 'wait'; delayMs: number }
  /** Бюджет исчерпан — закрыть цикл и вывести игрока на экран входа (правило 3). */
  | { kind: 'give-up' };

/** Что известно к моменту, когда цикл просят продолжить. */
export interface CycleState {
  /** Уже есть назначенная попытка (таймер заведён). */
  timerPending: boolean;
  /** Сколько попыток УЖЕ сделано в этом цикле. */
  attempts: number;
}

/** Следующий шаг цикла (правила 1–3). */
export function nextCycleStep(st: CycleState): CycleStep {
  if (st.timerPending) return { kind: 'busy' };
  const delayMs = reconnectDelayMs(st.attempts + 1);
  return delayMs === null ? { kind: 'give-up' } : { kind: 'wait', delayMs };
}

/** С чего начинается повторный дозвон (правило 5). */
export type RedialPlan =
  /** Дозваниваться сразу: без аккаунтов клиента опознаёт позывной с билетом места. */
  | 'dial'
  /** Сначала выписать свежий join-токен по живой сессии. */
  | 'mint-token'
  /** Сессии нет — на экран входа, а не в новый круг попыток. */
  | 'sign-in-again';

export function redialPlan(accountsMode: boolean, hasSession: boolean): RedialPlan {
  if (!accountsMode) return 'dial';
  return hasSession ? 'mint-token' : 'sign-in-again';
}
