/**
 * Дыхание объектов на карте: почему у каждого своя фаза (REFM-137).
 *
 * Половина живых слоёв карты «дышит» — пульсирует прозрачностью или толщиной: метка
 * неопознанного контакта, свечение владельца под миром, двигатели флота, луч обстрела,
 * кольцо флота с планом. Формула у всех одна (`база + размах × sin`), а вот ФАЗА бралась
 * четырьмя разными способами: от координат (метка, свечение), от длины идентификатора
 * (двигатели) и никак (луч, кольцо плана).
 *
 * 1. **Фаза берётся от САМОГО объекта.** Без неё все экземпляры слоя мигают синхронно, и
 *    десяток живых объектов читается как один общий мигающий слой — карта «щёлкает»
 *    целиком вместо того, чтобы шевелиться.
 * 2. **Источник фазы обязан РАЗЛИЧАТЬ соседей.** Длина идентификатора его роль не
 *    выполняет: у `p1-1`, `p2-3` и `p9-7` она одинакова, значит все флоты матча получают
 *    одну фазу — правило соблюдено на вид, а на экране та же синхронная пульсация.
 *    Годятся координаты (у двух объектов они не совпадают) и хэш идентификатора.
 * 3. **Период и размах — дело СЛОЯ, а не этого модуля.** Двигатель частит (120 мс),
 *    свечение владельца дышит медленно (620 мс): это художественное решение каждого
 *    слоя, и сводить их к одному числу значит стереть разницу между «работает» и «живёт».
 * 4. **Хэш идентификатора должен быть УСТОЙЧИВЫМ.** Фаза, посчитанная заново каждый кадр,
 *    обязана совпадать сама с собой — иначе объект дёргается, а не дышит.
 */

/** Фаза (радианы) от места объекта: у двух разных объектов координаты не совпадают. */
export function phaseAt(x: number, y: number): number {
  return x * 0.011 + y * 0.017;
}

/**
 * Фаза (радианы) от идентификатора — устойчивый хэш строки (правила 2, 4). Нужен там,
 * где у объекта нет своего места на карте или оно меняется каждый кадр.
 */
export function phaseOfId(id: string): number {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) % 100_000;
  return (h % 6283) / 1000; // 0…2π с шагом в тысячную радиана
}

/** Из чего складывается дыхание слоя (правило 3). */
export interface Breath {
  /** Период колебания, мс. */
  period: number;
  /** Середина (значение при `sin = 0`). */
  base: number;
  /** Размах в обе стороны от середины. */
  amp: number;
  /** Фаза объекта — `phaseAt` / `phaseOfId`; 0 только для единственного в кадре слоя. */
  phase?: number;
}

/** Значение дыхания в этот момент: `base + amp · sin(now / period + phase)`. */
export function breath(now: number, b: Breath): number {
  return b.base + b.amp * Math.sin(now / b.period + (b.phase ?? 0));
}
