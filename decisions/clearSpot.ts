/**
 * Куда сдвинуть мир, который подсказка отметила на карте, если его закрыло окно (ONB-14).
 *
 * Подсказка обучения отмечает кольцом точку карты: «нажмите родной мир», «нажмите
 * подсвеченный мир». Мир при этом может лежать под окном флота, карточкой мира или самой
 * подсказкой. Кольцо рисуется поверх окна, а нажатие уходит в окно, и шаг не пройти.
 *
 * 1. **Сдвигается карта, а не окно.** Окно игрок открыл сам, и оно нужно ему на следующем
 *    шаге; камера же двигается и без обучения.
 * 2. **Место — ближайшее свободное.** Чем короче сдвиг, тем меньше игрок теряет, где он
 *    был. Кандидаты лежат сеткой с отступом от краёв: у края кольцо обрезалось бы.
 * 3. **Свободно ли место, решает экран, а не это правило.** Здесь только порядок, в котором
 *    места проверяются; что лежит поверх карты, знает тот, кто видит разметку.
 * 4. **Проверок не больше `limit`.** Если свободного места рядом нет (на телефоне лист
 *    открыт во весь экран), ответ «некуда», а не перебор всего экрана в одном кадре.
 */

export interface Spot {
  x: number;
  y: number;
}

export interface ClearSpotOptions {
  /** Отступ сетки от краёв экрана, px. */
  margin?: number;
  /** Шаг сетки, px. */
  step?: number;
  /** Сколько ближайших мест проверить, прежде чем сдаться. */
  limit?: number;
}

/** Ближайшее к `from` место сетки, где `clear` отвечает «свободно», или `null`. */
export function nearestClearSpot(
  from: Spot,
  view: { width: number; height: number },
  clear: (p: Spot) => boolean,
  { margin = 96, step = 48, limit = 400 }: ClearSpotOptions = {},
): Spot | null {
  const spots: Spot[] = [];
  for (let y = margin; y <= view.height - margin; y += step)
    for (let x = margin; x <= view.width - margin; x += step) spots.push({ x, y });
  const far = (p: Spot) => (p.x - from.x) ** 2 + (p.y - from.y) ** 2;
  spots.sort((a, b) => far(a) - far(b));
  return spots.slice(0, limit).find(clear) ?? null;
}
