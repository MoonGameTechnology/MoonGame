/**
 * Всплывающее уведомление над картой (REFM-105).
 *
 * Тост — единственная обратная связь, которую игрок видит НЕ открывая журнал, поэтому у
 * него четыре правила, и все они стояли числами и строками прямо в теле `toast`: сколько
 * их держать, сколько они живут и чем отличается тост с якорем.
 *
 * 1. **Обратная связь не живёт только в скрытом окне.** Журнал открыт не всегда, а
 *    отказ приказа и событие матча игрок должен заметить сразу — отсюда тост поверх
 *    карты, а не одна лишь строка в логе.
 * 2. **Не больше трёх разом.** Четвёртый вытесняет самый старый: стопка выше трёх
 *    перекрывает карту, ради которой всё и затевалось.
 * 3. **Живёт ~5 секунд и уходит САМ,** с отдельной короткой фазой затухания. Тост,
 *    который надо закрывать вручную, превращается в модальное окно.
 * 4. **Тост с ЯКОРЕМ ведёт к месту события и помечен стрелкой.** Иначе игрок знает,
 *    ЧТО произошло, но не знает ГДЕ; стрелка обещает переход, а класс включает вид
 *    кликабельного.
 */

/** Сколько тостов держится на экране разом (правило 2). */
export const TOAST_MAX = 3;
/** Сколько живёт тост до начала затухания, мс реального времени (правило 3). */
export const TOAST_LIFE_MS = 5200;
/** Длительность затухания перед снятием, мс (правило 3). */
export const TOAST_FADE_MS = 450;

/** Класс тоста: с якорем он выглядит кликабельным (правило 4). */
export function toastClass(anchored: boolean): string {
  return anchored ? 'toast jump' : 'toast';
}

/** Текст тоста: якорь помечается стрелкой перехода (правило 4). */
export function toastText(msg: string, anchored: boolean): string {
  return anchored ? `${msg} ↪` : msg;
}

/** Сколько самых старых тостов снять, чтобы влезть в предел (правило 2). */
export function toastOverflow(shown: number, max = TOAST_MAX): number {
  return Math.max(0, shown - max);
}
