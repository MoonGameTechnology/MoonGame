/**
 * «Мои партии» на главном экране (ADDR-4).
 *
 * Обозреватель матчей — это ПОИСК: там ищут, куда пойти играть, и туда же ушли фильтры
 * (`matchFilter.ts`, правило 1). Список СВОИХ партий отвечает на другой вопрос — «где я
 * уже играю и куда мне вернуться», — и в Bytro он не вкладка, а главный экран: игрок
 * заходит в игру, чтобы доиграть начатое, а не чтобы выбрать новое.
 *
 * Разделять их приходится ещё и потому, что вопросы расходятся в мелочах. Ниже — те, что
 * решены здесь; остальное (как выглядит строка, что писать вместо списка) живёт в UI.
 *
 * 1. **Моя партия — та, где у меня МЕСТО.** Это вкладка `active` read-model'а: сервер уже
 *    проецирует ленту на смотрящего (`MatchRegistry.list(nick)` — место ищется в
 *    `AccountStore`). Считать «моё» на клиенте значило бы завести второй ответ на
 *    вопрос, у которого уже есть серверный.
 * 2. **Архив — тоже мой, но УБРАННЫЙ С ГЛАЗ.** В список он не входит: иначе «убрал»
 *    ничего не значит — партия вернулась бы на главный экран, откуда игрок её только
 *    что унёс.
 * 3. **Живые впереди законченных.** Внутри группы порядок сервера сохраняется — он уже
 *    отсортирован по новизне. Без этого правила доигранная партия теснила бы ту, где
 *    идёт война, просто потому что её начали позже.
 * 4. **Главный экран — не второй браузер.** Больше горстки строк — и он перестаёт быть
 *    коротким ответом на «куда вернуться»; остаток честно считается числом, которое
 *    уводит в обозреватель.
 * 5. **Неизвестно ≠ пусто.** Пока лента не пришла, «у вас нет партий» — ложь, из-за
 *    которой игрок пойдёт заводить ещё одну поверх трёх идущих. Это отдельное состояние.
 * 6. **Пусто — не тупик** (тот же довод, что правило 1 `browserFallback.ts`): у списка
 *    своих партий пустота — нормальное начало, и она обязана звать туда, где партии
 *    берут, а не просто молчать.
 */

/** Сколько своих партий помещается на главный экран (правило 4). */
export const HUB_MY_MATCHES = 3;

/** Лента в том виде, в каком её отдаёт сервер: три вкладки, спроецированные на смотрящего.
 *  `null` — ленты ещё нет (правило 5). Вкладки необязательны: старый сервер мог не
 *  прислать какую-то, и это «нет таких», а не поломка. */
export interface ViewerLists<R> {
  active?: readonly R[];
  available?: readonly R[];
  archived?: readonly R[];
}

/** Что показать в разделе «Мои партии». */
export type MyMatchesView<R> =
  /** Ленты ещё нет — ничего не утверждаем (правило 5). */
  | { kind: 'unknown' }
  /** Лента есть, своих партий нет (правило 6). */
  | { kind: 'none' }
  /** Строки + сколько своих не поместилось (правило 4). */
  | { kind: 'list'; rows: R[]; more: number };

/** Строка ленты в объёме, который нужен ЭТОМУ решению: чем партия кончилась. Всё
 *  остальное (карта, день, места) читает UI прямо из своей строки. */
interface HasStatus {
  status?: string;
}

/** Свои партии для главного экрана (правила 1–6). */
export function myMatches<R extends HasStatus>(
  lists: ViewerLists<R> | null,
  limit: number,
): MyMatchesView<R> {
  if (!lists) return { kind: 'unknown' }; // правило 5
  const mine = lists.active ?? []; // правила 1–2: архив сюда не входит
  if (mine.length === 0) return { kind: 'none' };
  // Правило 3. Два прохода, а не сортировка: порядок сервера внутри группы сохраняется
  // по построению, без опоры на стабильность чужого алгоритма.
  const live = mine.filter((m) => m.status !== 'ended');
  const done = mine.filter((m) => m.status === 'ended');
  const ordered = [...live, ...done];
  // Кап не может обнулить список: «мои партии» без единой строки — это состояние
  // «их нет», а оно здесь уже разобрано и значит другое.
  const cap = Math.max(1, Math.floor(limit) || 0);
  return { kind: 'list', rows: ordered.slice(0, cap), more: Math.max(0, ordered.length - cap) };
}
