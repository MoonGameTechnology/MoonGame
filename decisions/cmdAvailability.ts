/**
 * Кому какая команда положена — доступность кнопок командной полосы (REFM-78).
 *
 * Полоса рисуется от ВЫДЕЛЕНИЯ, и правила здесь не косметические: кнопка, обещающая
 * невозможное, стоит игроку хода, а команда, разосланная на группу вместо одного флота,
 * рассылает приказы с разной арифметикой.
 *
 * 1. **«Слить» — групповая, «Разделить» и «Десант» — строго ОДНОФЛОТОВЫЕ.** Гарнизон и
 *    трюм у каждого флота свои; один клик на группу разослал бы разные приказы под общей
 *    кнопкой.
 * 2. **Слияние доступно и одиночке — если во флоте игрока есть с кем сливаться.** Иначе
 *    кнопка вооружает выбор цели, которой не существует.
 * 3. **Делить можно только СТОЯЩИЙ флот с двумя и более кораблями:** на ходу и в бою
 *    состав не режут, а из одного корабля нового флота не выйдет.
 * 4. **Захватить можно только чужой захватываемый мир с ближней орбиты** (мобильная
 *    ветка): пустой космос не берут, свой мир штурмовать незачем, с дальней орбиты
 *    десанту не дотянуться.
 * 5. **Общий режим огня показывается только при ЕДИНОГЛАСИИ.** При разнобое кнопка
 *    обязана быть нейтральной, иначе она врёт про часть флотов выделения.
 */

/** Слияние: группа сливается в один тап, одиночка вооружает выбор напарника (правило 2). */
export function canMerge(selectedCount: number, ownFleetTotal: number): boolean {
  return selectedCount >= 2 || (selectedCount === 1 && ownFleetTotal >= 2);
}

/** Флот глазами однофлотовых команд. */
export interface LoneFleet {
  location?: string | null;
  movement?: unknown;
  battleId?: string | null;
  ships: number;
}

/** Деление: только один стоящий флот с 2+ кораблями (правила 1, 3). */
export function canSplit(lone: LoneFleet | null): boolean {
  if (!lone) return false;
  return !!lone.location && !lone.movement && !lone.battleId && lone.ships >= 2;
}

/** Мир глазами штурма с орбиты. */
export interface AssaultSpot {
  orbit?: string;
  location?: string | null;
  /** Владелец мира под флотом; `null` — ничей. */
  worldOwner: string | null;
  /** Можно ли вообще захватывать такой сектор (пустой космос — нельзя). */
  capturable: boolean;
}

/** Штурм с орбиты (мобильная ветка): чужой захватываемый мир с ближней орбиты (правило 4). */
export function canAssaultFromOrbit(spot: AssaultSpot, fleetOwner: string): boolean {
  return (
    spot.orbit === 'near' && !!spot.location && spot.worldOwner !== fleetOwner && spot.capturable
  );
}

/**
 * Единогласный режим выделения или `null` при разнобое (правило 5). Пустой вход — тоже
 * `null`: показывать нечего.
 */
export function uniformMode<T>(modes: readonly T[]): T | null {
  const set = new Set(modes);
  return set.size === 1 ? [...set][0]! : null;
}
