/**
 * В чей трюм грузить эскадру из порта (SHU-5.1 + SHU-5.6).
 *
 * С общего трюма (SHU-5.1) шаттл везёт любой корабль с `cargoCapacity`, поэтому
 * кандидатов на погрузку у стоящего в порту бота обычно несколько. Порядок:
 *  1. флот с АВИАНОСЦЕМ (трейт `carrier`) — корпус, заведённый ровно под это;
 *  2. флот с РЕМОНТНЫМ АНГАРОМ (`repair` — темп `fleetHangarRepairRate` ядра, SHU-5.4):
 *     эскадры на его борту чинятся в походе, у остальных — только у дока;
 *  3. больше свободных мест;
 *  4. id — равенство решается детерминированно (инвариант №1).
 * Кандидаты — только флоты, куда эскадра уже ВЛЕЗАЕТ: отбирает их вызывающий, потому
 * что «влезает» зависит от того, какая эскадра стоит в порту под этим флотом. Лучший по
 * рангу, но полный флот иначе останавливал бы погрузку навсегда.
 */
export interface HoldCandidate {
  readonly id: string;
  /** Во флоте есть авианосец. */
  readonly carrier: boolean;
  /** Темп ремонта эскадр на борту (доля корпуса в час), 0 — ремонтного ангара нет. */
  readonly repair: number;
  /** Свободных мест в трюме. */
  readonly room: number;
}

export function pickHoldFleet<T extends HoldCandidate>(candidates: readonly T[]): T | undefined {
  return candidates
    .slice()
    .sort(
      (a, b) =>
        Number(b.carrier) - Number(a.carrier) ||
        b.repair - a.repair ||
        b.room - a.room ||
        (a.id < b.id ? -1 : a.id > b.id ? 1 : 0),
    )[0];
}
