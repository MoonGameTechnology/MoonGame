/**
 * REFM-200 — ЧТО КАРТОЧКА ПРИШВАРТОВАННОГО ФЛОТА ПРЕДЛАГАЕТ СДЕЛАТЬ.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Прогноз штурма и раздел «Наземные войска», а прежде и
 * доступность обстрела и штурма, решались россыпью условий прямо внутри сборки HTML.
 * Ошибается такой набор ТИХО и в самую дорогую сторону: он не падает, он ПРЕДЛАГАЕТ.
 * Кнопка выглядит доступной — игрок жмёт, ядро отказывает, а снаружи это «ничего не
 * произошло»; прогноз обещает бой, которого быть не может, и по нему принимают решение
 * посылать людей. Здесь ошибка стоит не пикселя, а хода.
 *
 * ПРАВИЛА И ПРИЧИНЫ:
 *
 * 1. Пришвартован = стоит У ТОЧКИ, НЕ в пути и НЕ в бою. В пути флот физически между
 *    узлами: предлагать штурм точки, до которой он ещё летит, значит обещать
 *    невозможное. В бою штатные действия заменяет карточка боя со своим единственным
 *    выходом — отступлением, и вторая колода кнопок рядом с ней только путала бы.
 *
 * 2. Удар — только по ЧУЖОЙ и ЗАХВАТЫВАЕМОЙ точке. Пустое пространство проходное,
 *    захватывать там нечего; на своей точке штурмовать некого. Нейтральная точка (без
 *    владельца) считается чужой — она не моя, и взять её можно. Здесь это решает, есть ли
 *    у листа прогноз штурма.
 *
 * 3–4. Обстрел и штурм с места отсюда ушли (заказ владельца 2026-11-01): их кнопки
 *    стоят в ряду команд и видны, только когда ядро их пропустит (`assaultHereTarget`,
 *    `bombardFleetsFor` в `groupOrders.ts`, правило 3г `cmdPresence.ts`). Рукописные
 *    предикаты повторяли ядро по частям — ближняя орбита, корабли для обстрела, орбитальный
 *    слой узла, десант на защищённом мире, флот из одних разведчиков, — а проба ядра
 *    отвечает на всё сразу и не отстаёт от следующего правила.
 *
 * 5. Прогноз боя показывается, только если ЕСТЬ И десант, И гарнизон. Прогноз пустого
 *    боя («ничья за 0 раундов») читается как настоящий расклад и врёт про исход именно
 *    там, где игрок ищет опору для решения.
 *
 * 6. Сводка наземных войск — только на СВОЕЙ точке. На чужой она перечислила бы
 *    гарнизон противника, то есть протекла бы туман: панель показала бы то, что игрок
 *    знать не должен.
 *
 * 7. Атака чужого ФЛОТА предлагается, когда он стоит здесь же и свободен. Это другое
 *    действие, чем удар по миру: цель — флот, и живёт кнопка отдельно от удара,
 *    потому что чужой флот может стоять и на нейтральной, и на моей точке.
 *    Ядро умеет этот приказ давно (`fleet.engage`), кнопки к нему не было: сцеплял
 *    флоты либо автомат прибытия, либо покадровый цикл СОЛО-прототипа — то есть в сети
 *    два стоящих флота могли не драться вовсе, и у игрока не было способа это
 *    исправить. Требование «свободен» (не в бою) — не косметика: ядро отвечает
 *    `E_IN_BATTLE`, и кнопка при живом бое снова обещала бы отказ.
 */

/** Стопка юнитов ровно в том объёме, который нужен этим правилам. */
export interface Stack {
  count: number;
}

/** Есть ли в наборе хоть кто-то живой (пустые стопки остаются в составе). */
function anyAlive(stacks: readonly Stack[]): boolean {
  return stacks.some((st) => st.count > 0);
}

/** Правило 1: флот действительно стоит у точки и свободен для действий. */
export function docked(atWorld: boolean, moving: boolean, inBattle: boolean): boolean {
  return atWorld && !moving && !inBattle;
}

/** Правило 2: предлагать ли раздел «Удар». */
export function strikeOffered(
  worldOwner: string | null,
  fleetOwner: string,
  capturable: boolean,
): boolean {
  return worldOwner !== fleetOwner && capturable;
}

/** Правило 5: показывать ли прогноз боя. */
export function forecastShown(landing: readonly Stack[], garrison: readonly Stack[]): boolean {
  return anyAlive(landing) && anyAlive(garrison);
}

/** Правило 6: показывать ли сводку наземных войск. */
export function groundSummaryShown(worldOwner: string | null, me: string): boolean {
  return worldOwner === me;
}

/** Правило 7: предлагать ли атаку чужого флота, стоящего здесь же. */
export function attackOffered(dockedNow: boolean, hostileFleetFree: boolean): boolean {
  return dockedNow && hostileFleetFree;
}
