/**
 * Правый клик по карте на ПК (UIX-9.2): «Курс сюда».
 *
 * Раньше правая кнопка на карте вела себя как левая — выбирала то, что под курсором, —
 * а курс задавался только через кнопку «Курс» и следующий клик. Привычка стратегий в
 * реальном времени другая: левой выбирают, правой посылают. Правила:
 *
 * 1. **Это правило только для правой кнопки мыши.** Остальные кнопки и пальцы идут прежней
 *    дорогой (`pass`): выбор, рамка, перетаскивание камеры.
 * 2. **Только раскладка ПК.** Долгое нажатие пальцем браузер тоже называет контекстным
 *    меню — оно не должно отправлять флот: у пальца для этого удержание и кнопка «Курс».
 * 3. **Взведённый приказ правой кнопкой не стреляет.** Прицел удара, слияния, десанта или
 *    плана ждёт левого клика по своей цели; правый клик посреди прицела увёл бы флот
 *    туда, куда игрок им не целился.
 * 4. **Правая кнопка не выбирает.** Нет своих флотов под приказ — клик ничего не делает:
 *    выбор остаётся за левой кнопкой, иначе один жест значил бы две разные вещи.
 * 5. **Иначе — курс выбранных флотов в точку под курсором:** в мир, а мимо миров — в
 *    точку дороги. Дальше это обычный приказ «Курс»: мирный договор на маршруте
 *    спрашивает про войну, путь и время прибытия рисуются у флота.
 */

/** Что известно про нажатие в момент правого клика. */
export interface RightClickInput {
  /** `MouseEvent.button`: 2 — правая кнопка. */
  button: number;
  /** Палец (или перо), а не мышь. */
  touch: boolean;
  /** Раскладка ПК (`pcUi`). */
  pc: boolean;
  /** Взведён ли приказ, которому принадлежат клики (курс, удар, слияние, план…). */
  armed: boolean;
  /** Сколько своих флотов под приказ выбрано. */
  movers: number;
}

/** `course` — курс выбранных в точку; `none` — ничего; `pass` — не наш жест. */
export type RightClickAct = 'course' | 'none' | 'pass';

export function rightClickAct(i: RightClickInput): RightClickAct {
  if (i.button !== 2 || i.touch) return 'pass'; // правило 1
  if (!i.pc) return 'none'; // правило 2
  if (i.armed) return 'none'; // правило 3
  if (i.movers <= 0) return 'none'; // правило 4
  return 'course'; // правило 5
}
