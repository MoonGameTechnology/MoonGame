/**
 * Список первых целей: подача и награда (REFM-183).
 *
 * ЧТО считается выполненным, решает `firstGoals.ts` (REFM-99) — там же база отсчёта и
 * порядок целей. Здесь следующий слой, до сих пор стоявший прямо в кадре: как список
 * выглядит, когда его перерисовывать и когда за него платят.
 *
 * 1. **Награда выдаётся РОВНО ОДИН раз.** `updateGoals` зовётся каждый кадр, пока список
 *    жив, и без защёлки XP доливался бы по разу на кадр — то есть счёт новичка улетел бы
 *    в тысячи за секунду после последней цели. Защёлка отдельная от «список выполнен»
 *    именно потому, что второе остаётся истинным навсегда, а первое обязано погаснуть.
 *
 * 2. **Перерисовка — только когда список ИЗМЕНИЛСЯ.** Панель собирается через
 *    `innerHTML`, и перезапись каждый кадр рвала бы тап по кнопке сворачивания: узел
 *    подменяется между `pointerdown` и `click`. Сравнивать достаточно ДЛИНУ: цели только
 *    добавляются, отменить выполненную нечем.
 *
 * 3. **Свёрнутый список — это ЛОТОК, а не спрятанные строки.** Смысл сворачивания —
 *    вернуть карте место; шапка во всю ширину с убранными под неё четырьмя рядами этого
 *    не даёт, она просто занимает столько же места молча. Поэтому свёрнутая подача — одна
 *    маленькая кнопка со значком и счётчиком.
 *
 * 4. **Счётчик «сделано/всего» стоит в ОБЕИХ подачах.** Свёрнутый вид иначе отвечал бы на
 *    другой вопрос, чем развёрнутый: игрок сворачивает список именно тогда, когда следить
 *    хочет одним взглядом, и «2/4» — единственное, ради чего лоток вообще нужен.
 *
 * 5. **Разметка собирается ЗДЕСЬ, а текст приходит готовым.** Модуль не знает ни локали,
 *    ни ключей: подписи и заголовки передаются уже переведёнными — та же граница, что у
 *    `catalogTile.ts`. Иначе пришлось бы тащить сюда рантайм локализации ради двух строк.
 */
import { esc } from './format';

/** Сколько опыта даётся за весь список — одной суммой, один раз (правило 1). */
export const GOALS_BONUS_XP = 40;

/** Изменился ли список выполненного — только тогда перерисовываем (правило 2). */
export function goalsChanged(before: number, after: number): boolean {
  return before !== after;
}

/** Пора ли платить: список выполнен И награда ещё не выдана (правило 1). */
export function rewardDue(complete: boolean, alreadyRewarded: boolean): boolean {
  return complete && !alreadyRewarded;
}

/** Счётчик «сделано/всего» — один и тот же в обеих подачах (правило 4). */
export function goalsCounter(done: number, total: number): string {
  return `${done}/${total}`;
}

/** Одна строка списка: подпись приходит уже переведённой (правило 5). */
export interface GoalRow {
  label: string;
  done: boolean;
}

/** Свёрнутая подача: лоток со значком и счётчиком (правила 3–4). */
export function goalsTrayHtml(title: string, done: number, total: number): string {
  return (
    `<button class="gl-tray" id="gl-tray" type="button" title="${esc(title)}">` +
    `◎ <span class="gl-count">${goalsCounter(done, total)}</span></button>`
  );
}

/**
 * Развёрнутая подача: заголовок, счётчик, кнопка сворачивания и сами строки.
 * Счёт выполненного приходит ЧИСЛОМ, а не выводится из строк: список выполненного
 * ведёт `firstGoals.ts`, и пересчитывать его здесь значило бы завести вторую истину
 * о том же — разойдутся они молча, а увидит это только игрок.
 */
export function goalsListHtml(
  title: string,
  collapseTitle: string,
  rows: readonly GoalRow[],
  done: number,
): string {
  const items = rows
    .map(
      (r) =>
        `<div class="gl-item${r.done ? ' done' : ''}"><span class="gl-ck">${r.done ? '✓' : '○'}</span>` +
        `<span>${esc(r.label)}</span></div>`,
    )
    .join('');
  return (
    `<div class="gl-box"><div class="gl-head"><b>${title}</b>` +
    `<span class="gl-count">${goalsCounter(done, rows.length)}</span>` +
    `<button class="gl-tg" id="gl-tg" type="button" title="${esc(collapseTitle)}">▾</button></div>` +
    `<div class="gl-list">${items}</div>`
  );
}
