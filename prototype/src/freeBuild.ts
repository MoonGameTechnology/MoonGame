/**
 * Когда песочница возвращает ресурсы за стройку (REFM-104).
 *
 * «Бесплатная стройка» сделана не скидкой в ядре, а откатом: перед приказом снимается
 * слепок кошелька, после успеха он кладётся обратно. Условия снятия и возврата стояли
 * двумя разными строками в `main.ts`, и из них не читалось, почему возврат привязан к
 * УСПЕХУ, а не просто к наличию слепка.
 *
 * 1. **В игроцкой сборке песочницы НЕТ ВОВСЕ.** Это инструмент разработчика; в сборке
 *    для игроков он не должен быть даже выключенным переключателем.
 * 2. **Нужны обе галочки — сама песочница И бесплатная стройка.** Включённая песочница
 *    сама по себе кошелёк не трогает.
 * 3. **Только приказы СТРОЙКИ.** Бесплатность обещана именно ей; распространить откат
 *    на прочие траты значило бы бесплатно раздать всё подряд.
 * 4. **Возврат ТОЛЬКО при успехе приказа.** Отскочивший приказ ресурсы и не тратил, а
 *    положить слепок поверх отказа значило бы затереть то, что за этот же шаг успели
 *    изменить другие правила (доход, содержание, чужие события).
 */

/** Снимать ли слепок кошелька перед этим приказом (правила 1–3). */
export function snapshotWallet(
  playerBuild: boolean,
  sandboxOn: boolean,
  freeBuildOn: boolean,
  isBuild: boolean,
): boolean {
  if (playerBuild) return false;
  return sandboxOn && freeBuildOn && isBuild;
}

/** Класть ли слепок обратно (правило 4). */
export function restoresWallet(hasSnapshot: boolean, orderOk: boolean): boolean {
  return hasSnapshot && orderOk;
}
