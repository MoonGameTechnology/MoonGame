/**
 * Припуск камеры под открытой панелью выбора (REFM-54).
 *
 * Панель выбора лежит ПОВЕРХ игрового поля и закрывает его часть. Камера ограничена
 * границами карты, поэтому без поправки миры, оказавшиеся под панелью, вытащить на
 * чистую часть экрана нельзя — вид оказывается заперт. Поправка = ровно та полоса,
 * которую панель закрыла: камере разрешается перелезть за край карты на её ширину.
 *
 * 1. **Решает ИЗМЕРЕННАЯ ширина панели, а не признак телефона.** Широкая панель
 *    (от 70% экрана) — это нижний лист, и закрыта полоса СНИЗУ; узкая — правая
 *    колонка, и закрыта полоса СПРАВА. Так обе раскладки работают одним правилом, без
 *    ветки «мобильный/настольный», которая разъедется с вёрсткой при первой же правке.
 * 2. **Схлопнутая панель припуска не даёт.** Нулевая ширина или высота — это «панели
 *    нет»: иначе камера получала бы слабину под тем, что ничего не закрывает.
 * 3. **Припуск не бывает отрицательным.** Панель, уехавшая за край экрана, закрывает
 *    ноль — а не «минус сколько-то», от чего ограничитель камеры съехал бы внутрь.
 */

/** Прямоугольник панели на экране — та часть `DOMRect`, которая здесь нужна. */
export interface PanelRect {
  left: number;
  top: number;
  width: number;
  height: number;
}

/** Насколько камере разрешено перелезть за край карты. Пустой — панели нет. */
export interface Slack {
  right?: number;
  bottom?: number;
}

/** Доля ширины экрана, с которой панель считается нижним листом, а не колонкой. */
export const SHEET_WIDTH_RATIO = 0.7;

/**
 * Припуск под панелью. `rect` — `null`, когда панели нет или она скрыта.
 * `vw`/`vh` — игровое поле в тех же координатах, что и прямоугольник.
 */
export function panelSlackFor(rect: PanelRect | null, vw: number, vh: number): Slack {
  if (!rect || rect.width <= 0 || rect.height <= 0) return {}; // правило 2
  // Правило 1: широкая панель — нижний лист, узкая — правая колонка.
  if (rect.width >= vw * SHEET_WIDTH_RATIO) return { bottom: Math.max(0, vh - rect.top) };
  return { right: Math.max(0, vw - rect.left) }; // правило 3 — обрезка по нулю
}
