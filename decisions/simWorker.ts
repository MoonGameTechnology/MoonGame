/**
 * Откуда поднять отдельный поток расчёта соло-мира (`prototype/src/simLink.ts`).
 *
 * 1. **Поток — свой файл сборки на том же сайте.** Сервер и сайт пускают в политике CSP
 *    только такие потоки (`worker-src 'self'`): поток из строки (`blob:`) пришлось бы
 *    разрешить отдельно, а вместе с ним и любой поток, собранный скриптом на странице.
 * 2. **Страница, открытая с диска, берёт исходник строкой.** С `file://` браузер не
 *    поднимает поток из файла, а политики у такой страницы нет. Исходник несёт только
 *    однофайловая дев-сборка (`build.mjs`): игрок с диска не играет.
 * 3. **`?sim=frame` оставляет мир в кадре.** Для замеров «с потоком и без» и на случай,
 *    если поток на чьём-то устройстве ведёт себя хуже кадра.
 * 4. **Нет ни файла, ни исходника — потока нет**, и мир идёт в кадре, как всегда. Так
 *    собран архив площадки: в нём нет соло-схватки, которую поток считал бы.
 */

/** Как поднять поток: из файла по адресу или из исходника строкой. */
export type SimWorkerScript = { url: string } | { source: string };

/** Что знает о себе страница: протокол адреса, флаг `?sim=` и что положила сборка. */
export interface SimWorkerBuild {
  protocol: string;
  query: string | null;
  url: string;
  source: string;
}

/** Откуда поднять поток; `null` — мир идёт в кадре. */
export function simWorkerScript(build: SimWorkerBuild): SimWorkerScript | null {
  if (build.query === 'frame') return null;
  if (build.protocol === 'file:') return build.source !== '' ? { source: build.source } : null;
  return build.url !== '' ? { url: build.url } : null;
}
