/**
 * Как назвать игроку отказ ядра или сервера (MIG-2, вынесено из `prototype/src/main.ts`).
 *
 * Оба клиента получают от сервера одно и то же: стабильный код вида `E_NO_CAPACITY` и
 * НИЧЕГО больше — деталь наружу не уходит намеренно (инвариант fail-secure). Значит
 * превратить код в человеческую фразу обязан клиент, и делать это оба клиента обязаны
 * ОДИНАКОВО: иначе один и тот же отказ читается по-разному в зависимости от того, через
 * какую сборку игрок зашёл.
 *
 * 1. **Ключ ВЫВОДИТСЯ из кода, а не берётся из таблицы.** `E_NO_CAPACITY` →
 *    `err.no-capacity`. Таблица кодов здесь означала бы второй список рядом с тем, что
 *    уже есть в `/localization`, — и забытая строка в нём показывала бы игроку сырой
 *    ключ при живом переводе. Новый код требует ровно одной правки: текста в локали.
 * 2. **Незнакомый код деградирует в САМ КОД, а не в ключ.** Перевода может не быть
 *    (код новый, локаль неполная) — тогда игрок видит `no capacity`: некрасиво, но
 *    читаемо и говорит правду. Показать `err.no-capacity` значило бы показать
 *    внутренний идентификатор и выглядеть поломкой.
 *
 * Текст сюда не кладётся (правило папки) — только ключ и обращение к рантайму
 * локализации. Импорт идёт из `core`, а НЕ из `runtime`: второй подключает ВСЕ локали
 * сразу, что верно для прототипа (один самодостаточный HTML) и неверно для клиента —
 * тот грузит ровно один язык (LOC-6), и потянуть через общий модуль остальные значило бы
 * незаметно вернуть игроку вес, который с него сняли.
 */
import { hasKey, t } from '../localization/core';

/** Ключ перевода для кода отказа (правило 1). */
export function refusalKeyOf(code: string): string {
  return `err.${code.replace(/^E_/, '').toLowerCase().replace(/_/g, '-')}`;
}

/** Человеческая фраза для кода отказа; нет перевода — сам код словами (правило 2). */
export function refusalText(code: string): string {
  const key = refusalKeyOf(code);
  return hasKey(key) ? t(key) : code.replace(/^E_/, '').toLowerCase().replace(/_/g, ' ');
}
