/**
 * Часы кадра: когда мир идёт и на сколько он продвигается (REFM-87).
 *
 * `frame` вызывается на каждый кадр rAF и решает три разных вопроса, которые в коде
 * стояли вперемешку: крутить ли местную симуляцию, на сколько сдвинуть игровое время и
 * правдоподобен ли вообще разрыв между кадрами.
 *
 * 1. **Местная симуляция крутится только в СОЛО.** В сети часы, бой, стройка и все
 *    соперники принадлежат серверу — клиент лишь рисует его снимки, и второй,
 *    «свой» ход времени немедленно разъехался бы с авторитетным.
 * 2. **Пауза и баннер останавливают мир, решённый матч — тоже.** Доигрывать партию с
 *    показанным итогом нечестно: счёт уже объявлен.
 * 3. **Игровое время растёт от РЕАЛЬНОГО, помноженного на скорость.** Не «тик на кадр»:
 *    при просадке FPS мир обязан идти с той же быстротой, иначе на слабом телефоне сутки
 *    длятся дольше, чем на сильном.
 * 4. **Абсурдный разрыв между кадрами не считается.** Вкладка ушла в фон — `dt` там
 *    секунды и минуты; пустить его в среднее FPS значит показать чушь, а в спин орбит —
 *    провернуть корабли на пол-оборота одним скачком. **Ход мира — тоже** (AUD-23): за
 *    один кадр мир идёт не дальше {@link FPS_GAP_MS} реального времени. Бот соперника и
 *    драйверы боя (авто-штурм, столкновения, цепочки приказов) работают раз в кадр ПОСЛЕ
 *    шага, поэтому длинный шаг — это часы игры, в которых Рой не начинает ни одного боя.
 *    Разрыв бывает и без `visibilitychange`, которым игра ставит забег на паузу: браузер
 *    замораживает rAF в iframe площадки, прокрученном за край окна, и вкладка при этом
 *    остаётся «видимой». Полчаса за краем двигали мир на 75 игровых часов и выигрывали
 *    главу без боя. Правилу 3 срез не мешает, пока устройство держит хотя бы кадр в секунду.
 * 5. **Орбитальный спин живёт по ходу МИРА, а не кадра.** На паузе корабли замирают на
 *    кольцах; иначе застывшая карта продолжает шевелиться и врёт, что время идёт.
 */

/** Разрыв больше этого — не кадр, а возвращение из фона. */
export const FPS_GAP_MS = 1000;

/** Правдоподобен ли разрыв между кадрами (правило 4). */
export function saneGap(dt: number): boolean {
  return dt > 0 && dt < FPS_GAP_MS;
}

/** Крутится ли местная симуляция (правила 1–2). */
export function simRuns(net: boolean, speed: number, banner: boolean, ended: boolean): boolean {
  return !net && speed > 0 && !banner && !ended;
}

/** Куда двигать игровое время: реальные миллисекунды × скорость (правило 3), но не больше
 *  одного правдоподобного кадра за раз (правило 4). Нулевой, отрицательный и нечисловой
 *  разрыв мир не двигает. */
export function advanceTarget(now: number, dt: number, speed: number, hourMs: number): number {
  if (!(dt > 0)) return now;
  return now + (Math.min(dt, FPS_GAP_MS) / 1000) * speed * hourMs;
}

/** Идёт ли мир для орбитального спина: сеть всегда, соло — пока не на паузе (правило 5). */
export function spinRuns(net: boolean, speed: number, banner: boolean): boolean {
  return net || (speed > 0 && !banner);
}

/** Сглаженный FPS: экспоненциальное среднее по разрыву кадра. */
export function fpsNext(ema: number, dt: number): number {
  return ema * 0.9 + (1000 / dt) * 0.1;
}
