/**
 * Один транспортный клиент на всё присутствие в матче — и как он переживает смену
 * сокета (NETA2-5).
 *
 * Седьмой срез сетевой секции; предыдущие разбирали чей сокет (`socketFate.ts`), что
 * значит первый снимок (`netWelcome.ts`), цикл переподключения (`reconnectCycle.ts`) и
 * куда уходит приказ (`orderRoute.ts`). Здесь — ЖИЗНЬ САМОГО КЛИЕНТА.
 *
 * 1. **Сокет умирает, клиент — нет.** У `MultiplayerClient` уже есть всё, что нужно на
 *    обрыве: `connectionLost()` переводит его в очередь, а реконнектный `welcome`
 *    сбрасывает `clientSeq` под новую сессию и досылает накопленное. Пересоздавая клиента
 *    на каждый дозвон, прототип выбрасывал эту очередь вместе с ним — и приказ, выданный
 *    в момент обрыва, оставалось только отвергнуть. Поэтому клиент переживает дозвоны, а
 *    меняется под ним ТОЛЬКО сокет.
 * 2. **Клиент привязан к МЕСТУ, а не к сокету.** Место — тройка «сервер + матч +
 *    позывной»: это то, что делает очередь осмысленной. Сменилось хоть одно поле — очередь
 *    прошлого места недоставима по построению (другая сессия, другой матч, другой игрок),
 *    и переносить её туда значило бы отправить приказ не в ту партию. Такой дозвон
 *    начинается с чистого клиента.
 * 3. **Ключ места экранируется.** Разделитель, который может встретиться внутри поля,
 *    склеил бы разные тройки в одну строку — и клиент чужого матча сошёл бы за свой.
 * 4. **Писать в момент обрыва некуда, и это не ошибка.** Между падением сокета и
 *    следующим `welcome` живого провода нет вовсе; клиент это знает (он очередит), но
 *    служебные сообщения — пинг, перф, чат — идут мимо очереди и в этот момент просто
 *    исчезают. Тихо, а не исключением: обрыв — штатное состояние, не сбой кода.
 */

/** Минимум, который транспортному клиенту нужен от сокета. */
export interface Wire {
  send(data: string): void;
  close(): void;
}

/** Что известно к моменту дозвона. */
export interface ClientContext {
  /** Клиент с прошлого подключения ещё жив. */
  hasClient: boolean;
  /** Дозваниваемся в ТО ЖЕ место (см. `seatKey`). */
  sameSeat: boolean;
}

/** Ключ места: тройка «сервер + матч + позывной» (правила 2–3). */
export function seatKey(base: string, matchId: string, nick: string): string {
  return [base, matchId, nick].map((part) => encodeURIComponent(part)).join('|');
}

/** Взять прежнего клиента с его очередью или завести нового (правила 1–2). */
export function clientPlan(ctx: ClientContext): 'reuse' | 'fresh' {
  return ctx.hasClient && ctx.sameSeat ? 'reuse' : 'fresh';
}

/**
 * Провод, который всегда смотрит на ТЕКУЩИЙ сокет (правила 1, 4). Клиент получает его
 * один раз при создании, а `current()` отдаёт тот сокет, который жив сейчас, — поэтому
 * после реконнекта тот же клиент пишет уже в новый сокет, ничего об этом не зная.
 */
export function liveSocket(current: () => Wire | null): Wire {
  return {
    send: (data: string) => current()?.send(data),
    close: () => current()?.close(),
  };
}
