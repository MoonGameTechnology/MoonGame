/**
 * Язык площадки → наша локаль (`YAG-1.3`).
 *
 * Требование площадки 2.14 — язык игры определяется автоматически через SDK, и это
 * обязательно для ВСЕХ игр, даже одноязычных. Язык приходит кодом ISO 639-1
 * (`ysdk.environment.i18n.lang`, 73 значения), локалей у нас меньше, поэтому нужен ответ
 * на вопрос «что показать игроку, чьего языка у нас нет».
 *
 * ## Резерв — площадки, а не наш
 *
 * Страница «Языки и домены» задаёт резервные языки: `ru` для `be`, `kk`, `uk`, `uz`, `en`
 * для всех прочих. Играть против этой схемы нельзя: площадка уже пообещала игроку язык,
 * и расхождение выглядит как недопереведённая игра. Поэтому незнакомый язык даёт
 * английский, кроме этой четвёрки.
 *
 * Кирпич когда-то формулировал иначе («незнакомый язык даёт русский») и полагал, что при
 * двух локалях расхождения с площадкой нет. Оно есть: турецкий игрок по той формулировке
 * получил бы русский, а площадка ждёт английский. Прежнее правило и так жило в рантайме
 * локализации (`detect()` в `localization/core.ts` отдаёт `en` всему, что не `ru`) — так
 * что для незнакомых языков меняется только четвёрка резерва.
 *
 * ## «Не знаю» ≠ «незнакомый язык»
 *
 * Нет строки, пустая строка, мусор вместо кода — это `null`, а не английский. Без
 * подсказки площадки остаётся выбор по языку браузера, и он лучше навязанного: английский
 * по мусору перебил бы верный выбор у русскоязычного игрока — ровно той аудитории, ради
 * которой мы на площадке.
 *
 * Новая локаль подхватывается сама: код, для которого есть `LocaleId`, берётся как есть.
 */
import { isLocaleId, type LocaleId } from '../localization/index';

/** Языки, для которых резерв площадки — русский (страница «Языки и домены»). */
export const RU_RESERVE_LANGUAGES: readonly string[] = ['be', 'kk', 'uk', 'uz'];

/** Код ISO 639-1 с необязательным региональным хвостом: `ru`, `en-US`, `ru_RU`. */
const LANGUAGE_TAG = /^([a-z]{2})(?:[-_][a-z0-9]{2,8})*$/;

/** Локаль по языку площадки; `null` — площадка ничего внятного не сообщила. */
export function platformLocale(lang: unknown): LocaleId | null {
  if (typeof lang !== 'string') return null;
  const code = LANGUAGE_TAG.exec(lang.trim().toLowerCase())?.[1];
  if (!code) return null;
  if (isLocaleId(code)) return code;
  return RU_RESERVE_LANGUAGES.includes(code) ? 'ru' : 'en';
}
