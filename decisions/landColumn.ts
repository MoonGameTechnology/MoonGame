/**
 * Колонка «Десант» в окне флота консолью (ПК и планшет): рисовать ли её вообще.
 *
 * Заказ владельца 2026-09-28: «если нет груза в трюме, то правую плашку необязательно
 * отрисовывать». Пустой трюм занимал треть окна строкой «0 / 6», таблицей гарнизона под
 * флотом и кнопкой погрузки, и всё это над картой, которую окно и так закрывает.
 *
 * 1. **Колонка есть, пока в трюме что-то есть**: войска на борту, погрузка в пути или
 *    машины в ангаре. Трюм у войск и челноков один (SHU-5.1), поэтому машины — тоже груз.
 * 2. **Пустой трюм колонку не прячет, если в ней стоят команды, которых в окне больше
 *    нигде нет**: удар по чужому миру под флотом и перегрузка челноков с порта. Спрятать
 *    их значило бы отнять приказ, а не освободить место.
 *
 * Погрузку ⇅ пустой трюм не прячет: без колонки она возвращается в «Приказы» (правило 3в
 * `cmdPresence.ts`). Пустой трюм — как раз тот случай, когда её жмут.
 */
export interface LandColumnInput {
  /** Трюм флота (`fleetHolds`): сколько занято и сколько уже грузится. */
  holds: ReadonlyArray<{ used: number; reserved: number }>;
  /** Под флотом чужой мир, по которому можно ударить (`strikeOffered`). */
  strike: boolean;
  /** Предлагается перегрузка челноков между флотом и портом (`transferOffer`). */
  wingTransfer: boolean;
}

export function landColumnShown(input: LandColumnInput): boolean {
  return (
    input.strike ||
    input.wingTransfer ||
    input.holds.some((h) => h.used > 0 || h.reserved > 0)
  );
}
