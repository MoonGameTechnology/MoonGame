/**
 * Военный счёт и ведомость потерь (REFM-180).
 *
 * Одно событие ядра — `unit.died` — кормит ДВА разных потребителя: личную статистику
 * матча («уничтожено / потеряно» в карточке итога) и ведомость, из которой `battleLog.ts`
 * (REFM-179) собирает хвост «· losses: …» в строке об окончании боя. Условия у них
 * РАЗНЫЕ, и инлайном это читалось как одна ветка с двумя похожими `if`.
 *
 * 1. **В счёт идут только бои, в которых я участвую.** Ядро издаёт `unit.died` по всей
 *    карте, и без этой проверки в мою статистику падали бы драки ботов между собой:
 *    цифра «уничтожено» росла бы сама, пока я строю шахты.
 *
 * 2. **Мои погибшие — «потеряно», ВСЕ остальные — «уничтожено».** Счёт ведётся от лица
 *    игрока, а не по парам сторон: в бою на три флота союзник и враг для этой цифры
 *    одинаковы. Разбор «кто чей» — это уже отчёт, которому в двух числах места нет.
 *
 * 3. **Событие без числа павших считается нулём.** Счёт — накопительная сумма; одно
 *    `undefined` превратило бы её в `NaN` до конца матча, и игрок увидел бы «NaN» вместо
 *    статистики — то есть один битый пакет сломал бы всю карточку, а не одну строку.
 *
 * 4. **Ведомость наполняется по ДРУГОМУ условию, чем счёт** (`seenTail`, а не «мой бой»).
 *    Счёт — личная статистика, и чужая драка в неё не входит (правило 1). Ведомость же
 *    питает строку ленты, а чужой бой на ОПОЗНАННОМ узле игрок видит и о его исходе
 *    читает — значит, и цену этого исхода надо знать. Сузить ведомость до «моих боёв»
 *    значит выдать «battle ended» без потерь там, где потери наблюдались.
 *
 * 5. **Безымянный владелец сводится в `?`.** Ключом ведомости служит идентификатор
 *    стороны, и `undefined` доехал бы до строки как «undefined −3»: `lossTally` печатает
 *    ключ, когда имени для него нет.
 *
 * 6. **Потери НАКАПЛИВАЮТСЯ, а не перезаписываются.** За один бой по одной стороне
 *    приходит много `unit.died` — по событию на тип юнита и на волну. Присваивание
 *    вместо сложения оставило бы в ведомости последнюю волну, и «−3» вместо «−17»
 *    выглядело бы правдоподобно — такую ошибку не видно, пока не пересчитаешь бой руками.
 */

/** Личная статистика матча: сколько уничтожил и сколько потерял сам. */
export interface KillStats {
  destroyed: number;
  lost: number;
}

/** Ведомость одного боя: сторона → тип юнита → сколько пало. */
export type BattleLosses = Record<string, Record<string, number>>;

/** Число павших из полезной нагрузки: нет числа — ноль (правило 3). */
export function deathCount(count: unknown): number {
  return typeof count === 'number' ? count : 0;
}

/** В какую графу счёта идёт погибший: мой — в «потеряно», чужой — в «уничтожено». */
export function scoreSide(owner: unknown, me: string): 'lost' | 'destroyed' {
  return owner === me ? 'lost' : 'destroyed';
}

/** Счёт после ещё одной гибели. Возвращает НОВЫЙ счёт — старый не трогает. */
export function tallyDeath(
  stats: KillStats,
  owner: unknown,
  me: string,
  count: unknown,
): KillStats {
  const side = scoreSide(owner, me);
  return { ...stats, [side]: stats[side] + deathCount(count) };
}

/** Ключ стороны в ведомости: безымянный владелец сводится в `?` (правило 5). */
export function lossOwner(owner: unknown): string {
  return typeof owner === 'string' ? owner : '?';
}

/**
 * Ведомость боя после ещё одной гибели. Возвращает НОВУЮ ведомость; порядок сторон
 * сохраняется — на него опирается правило 5 в `battleLog.ts` (порядок учёта, не алфавит).
 */
export function recordLoss(
  ledger: BattleLosses | undefined,
  owner: unknown,
  unit: string,
  count: unknown,
): BattleLosses {
  const who = lossOwner(owner);
  const perOwner = ledger?.[who] ?? {};
  return {
    ...ledger,
    [who]: { ...perOwner, [unit]: (perOwner[unit] ?? 0) + deathCount(count) },
  };
}
