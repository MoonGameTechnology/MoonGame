/**
 * Что показать игроку между волнами (PVR-1.4) — чистое решение обоих клиентов.
 *
 * Правила МИРА здесь нет: кому и сколько выборов должно, решает `pveModule`, а выдаёт
 * их действие `pve.boon`, которое ядро же и проверяет. Здесь только проекция: должен ли
 * экран сейчас что-то предлагать и что именно положить на карточки.
 *
 * Ни DOM, ни сети, ни таймеров — время приходит параметром вместе с состоянием.
 */

/** Что забег предлагает прямо сейчас. */
export type BoonOffer =
  | { kind: 'none' }
  | { kind: 'offer'; owed: number; choices: readonly string[] };

/** Ровно то, что решению нужно от состояния матча: долг по выборам и что уже взято. */
export interface BoonView {
  /** Невыбранные усиления этого места (`state.pve.boons[me]`). */
  owed: number;
  /** Пул режима (`data.modes[id].pve.boons`) — в порядке каталога. */
  pool: readonly string[];
  /** Технологии, уже завершённые у этого места. */
  completed: readonly string[];
}

/**
 * Предложение по состоянию.
 *
 * Показываются ВСЕ ещё не взятые усиления пула, а не случайная выборка из него. Так
 * решение остаётся чистым (тасовать нечем: `Math.random` запрещён, а сид ядра — не
 * клиентское знание) и честным: игрок видит, что у забега осталось, и выбирает, а не
 * угадывает. Пул кончился — предлагать нечего, и это `none`, а не пустой экран.
 */
export function boonOffer(view: BoonView): BoonOffer {
  if (view.owed <= 0) return { kind: 'none' };
  const taken = new Set(view.completed);
  const choices = view.pool.filter((id) => !taken.has(id));
  return choices.length === 0 ? { kind: 'none' } : { kind: 'offer', owed: view.owed, choices };
}
