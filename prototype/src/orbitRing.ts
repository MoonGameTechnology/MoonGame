/**
 * Геометрия орбитального кольца: когда оно открывается и куда садятся флоты (REFM-94).
 *
 * У мира ОДНО кольцо, и на нём стоят все негонящиеся флоты. Правил тут семь, и все они
 * висели на модульных `cam`/`orbitPhase` прямо в теле хелперов, поэтому ни порог, ни
 * потолок радиуса не читались как решения — только как числа `1.6`, `0.4`, `2.4`, `0.55`.
 *
 * 1. **Орбитальный слой ОТКРЫВАЕТСЯ только вблизи** (`ORBIT_ZOOM_IN`): один порог держит
 *    и ширину кольца, и вращение, и разворот шеврона. Иначе на общем виде крутились бы
 *    кольца, которых там всё равно не видно, — трата кадра без картинки.
 * 2. **Далеко кольцо ужато вдвое, вблизи распускается до 2.4×.** Полноразмерное кольцо на
 *    общем виде читается громоздко, а вблизи флотам нужно место обходить планету.
 * 3. **Кольцо НЕ ЗАЛЕЗАЕТ на соседа:** не шире 40% зазора до ближайшего СВЯЗАННОГО мира.
 *    Без этого потолка на телефоне при сильном зуме кольцо доставало до соседних узлов и
 *    карта превращалась в кашу.
 * 4. **Одинокому узлу потолок не нужен:** соседа нет, мерить не от чего — кольцо живёт
 *    по одному зуму, а не схлопывается в ноль.
 * 5. **Флоты разложены ВЕЕРОМ от «12 часов» и симметрично центру** — иначе шевроны
 *    налезали бы друг на друга, а веер уезжал бы вбок с ростом числа флотов.
 * 6. **Вращение идёт по ИГРОВОМУ времени** (накопленному `orbitPhase`, замирающему на
 *    паузе), а не по настенным часам: на паузе мир стоит, значит стоит и орбита.
 * 7. **Вблизи шеврон смотрит ПО КАСАТЕЛЬНОЙ, вдали — радиально.** Он летит по кольцу
 *    только пока кольцо живо; на неподвижной орбите нос по касательной читался бы как
 *    движение, которого нет.
 *
 * У КАКИХ УЗЛОВ КОЛЬЦО ВООБЩЕ ЕСТЬ (REFM-114) — здесь же, а не отдельным модулем: это
 * условие ОТКРЫВАЕТ всю геометрию выше, и второй дом означал бы, что «есть кольцо» и
 * «как оно выглядит» могут разойтись. Отбор стоял тройкой `continue` внутри кадра.
 *
 * 8. **Кольцо есть у типов-ГОРОДОВ; узел-развязка получает его только УКРЕПЛЁННЫМ.**
 *    Астероидное поле берут простым прибытием — вставать там негде и незачем. Но крепость
 *    или живой гарнизон делают узел таким, который приходится ШТУРМОВАТЬ, а штурм идёт с
 *    орбиты: кольцо — это обещание, что здесь есть куда встать.
 * 9. **Гарнизон считается ЖИВОЙ, только пока в нём есть кто-то.** Записи с нулевым
 *    счётом остаются в состоянии после потерь, и принять их за укрепление значило бы
 *    рисовать орбиту у выбитого досуха узла.
 * 10. **Пустая орбита не рисуется.** Кольцо — это сведение «здесь стоят», а не украшение
 *    узла; и считается оно по ВИДИМЫМ флотам, иначе кольцо выдало бы чужую стоянку,
 *    которую туман прячет.
 * 11. **На схематичном виде колец нет вовсе** — тот же LOD, что у остального узлового
 *    убранства: вдали они сливаются с самим узлом в пятно.
 */

/** Базовый радиус кольца в экранных px — до множителя зума. */
export const ORBIT_R = 31;
/** Ближе этого масштаба камеры орбитальный слой открывается (правило 1). */
export const ORBIT_ZOOM_IN = 1.6;
/** Скорость обхода кольца, рад/мс игрового времени. */
export const ORBIT_SPIN = 0.00052;

/** Живы ли кольца и вращение на текущем масштабе (правило 1). */
export function orbitsLive(scale: number): boolean {
  return scale >= ORBIT_ZOOM_IN;
}

/** Множитель радиуса от зума: 0.5 вдали → до 2.4 вблизи (правило 2). */
export function orbitBloom(scale: number): number {
  if (scale <= ORBIT_ZOOM_IN) return 0.5;
  return Math.max(0.5, Math.min(2.4, 0.5 + (scale - ORBIT_ZOOM_IN) * 1.2));
}

/** Радиус кольца в px: раздутый зумом, но зажатый зазором до соседа (правила 3–4).
 *  `nearestGap` — расстояние до ближайшего связанного мира в экранных px, `Infinity`
 *  если связей нет. */
export function orbitRadius(bloom: number, nearestGap: number): number {
  if (!Number.isFinite(nearestGap)) return ORBIT_R * bloom;
  return ORBIT_R * Math.min(bloom, (nearestGap * 0.4) / ORBIT_R);
}

/** Угол слота флота на кольце: веер от «12 часов» плюс ход вращения (правила 5–6). */
export function slotAngle(idx: number, nPeers: number, phase: number, live: boolean): number {
  const fan = -Math.PI / 2 + (idx - (nPeers - 1) / 2) * 0.55;
  return live ? fan + phase * ORBIT_SPIN : fan;
}

/** Куда смотрит нос шеврона: по касательной на живом кольце, радиально вдали (правило 7). */
export function chevronAngle(slot: number, live: boolean): number {
  return live ? slot + Math.PI / 2 : slot;
}

/** Что известно про узел, когда решается судьба его кольца (правила 8–11). */
export interface RingHost {
  /** Есть ли орбита у типа сектора — города её имеют, развязки нет (правило 8). */
  typeHasOrbit: boolean;
  /** Стоит ли крепость (правило 8). */
  starfort: boolean;
  /** Счётчики гарнизона как есть, вместе с нулевыми записями (правило 9). */
  garrison: readonly { count: number }[];
  /** Сколько ВИДИМЫХ флотов стоит здесь без движения (правило 10). */
  parked: number;
}

/** Укреплён ли узел: крепость или ЖИВОЙ гарнизон (правила 8–9). */
export function fortified(starfort: boolean, garrison: readonly { count: number }[]): boolean {
  return starfort || garrison.some((u) => u.count > 0);
}

/** Рисуется ли кольцо у этого узла (правила 8–11). `detail` — уровень LOD, 0 — схема. */
export function ringShown(host: RingHost, detail: number): boolean {
  if (detail <= 0) return false; // правило 11
  if (host.parked <= 0) return false; // правило 10
  return host.typeHasOrbit || fortified(host.starfort, host.garrison); // правила 8–9
}
