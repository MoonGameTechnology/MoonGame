/**
 * Что обучение позволяет нажимать на этом шаге (ONB-8).
 *
 * У подсветки три разных режима, и раньше их было два, выбираемых одной строкой
 * «шаг с „Далее“ → глушим всё, иначе → пропускаем всё». Средний случай — «нажимать
 * можно, но ТОЛЬКО подсвеченное место» — не выражался никак, и шаг вида «улучшите
 * Металлодобычу» оставлял новичку весь экран: он уходил нажимать что попало и терял нить.
 *
 * 1. **Шаг «Далее» — модальный.** Подтверждение и есть единственный ход; HUD на таком
 *    шаге трогать незачем, и случайный тап мимо кнопки не должен ничего заказывать.
 * 2. **Шаг с ЗАПЕРТЫМ местом пропускает нажатия только в подсвеченное окно.** Инструкция
 *    «нажмите сюда» без запрета читается как совет, а не как шаг обучения: игрок жмёт
 *    соседнее, получает другой экран и не понимает, почему подсказка не сменилась.
 * 3. **Запереть можно ТОЛЬКО пока место найдено.** Панель перерисовывается каждый кадр, и
 *    в кадре, где цели нет (список перестроился, вкладка сменилась), запертый экран запер
 *    бы игрока насмерть: нажимать негде, шаг не двигается, выйти можно только «Пропустить
 *    обучение». Нет прямоугольника — пропускаем всё, подсказка при этом остаётся.
 * 4. **Остальные шаги оставляют HUD свободным.** Там цель — не кнопка, а место, до
 *    которого ещё надо добраться (выбрать флот, открыть панель мира), и запрет на этом
 *    пути стал бы тупиком.
 */

/** Что overlay делает с нажатиями. */
export type OverlayMode =
  /** Глушим весь экран: ход один — «Далее» (правило 1). */
  | 'modal'
  /** Пропускаем только в подсвеченное окно, остальное глушим (правило 2). */
  | 'gate'
  /** Пропускаем всё: игрок сам ведёт HUD (правила 3–4). */
  | 'free';

export interface GateStep {
  advance: { on: 'tap' | 'action' | 'state' };
  /** Шаг запирает экран на своей цели: нажать можно только её. */
  gate?: boolean;
}

/** Режим нажатий для текущего шага (правила 1–4). */
export function overlayMode(step: GateStep, hasTarget: boolean): OverlayMode {
  if (step.advance.on === 'tap') return 'modal';
  return step.gate && hasTarget ? 'gate' : 'free';
}
