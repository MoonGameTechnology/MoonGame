/**
 * Постановка стоек «авто-штурм» и «дежурный вылет» на выбранные флоты (REFM-98).
 *
 * Обе стойки ставятся одной кнопкой ☰-ряда сразу на группу, и у обеих одинаковая
 * рамка отказов: чужой флот, уже выставленная стойка, неподходящее состояние. Условия
 * лежали внутри двух почти одинаковых циклов вперемешку с отправкой приказов, поэтому
 * не читалось, почему один флот в группе стойку получил, а сосед — нет.
 *
 * 1. **Стойка ставится ЕДИНООБРАЗНО на всю группу.** Кнопка задаёт состояние, а не
 *    переключает каждый флот: смешанный набор снапится в одно, иначе один тап оставлял
 *    бы группу такой же разнородной, какой она была.
 * 2. **Только СВОИ флоты** — чужой стойки не имеет, и приказ по нему всё равно отскочит.
 * 3. **Уже в нужном состоянии — приказа НЕТ.** Иначе сеть получала бы пустой приказ на
 *    каждый тап, а соло дважды писало бы одно и то же.
 * 4. **Дежурный вылет — только у флота с КРЫЛОМ:** дежурить нечем, если истребителей на
 *    борту нет.
 * 5. **Патруль встаёт только с ПРИКОЛА и вне боя** — это зеркало гейта редьюсера. Без
 *    него соло подняло бы патруль, который сеть отвергает (`E_CONDITIONS_UNMET`), и
 *    интерфейс предлагал бы действие, которого сервер не даёт.
 * 6. **Снятие дежурства — отдельный исход, а не «поставить false»:** при снятии нужно
 *    запомнить остаток вылета, иначе следующее включение выдаст бесплатный полный бак.
 */

/** Что делать с авто-штурмом на конкретном флоте. */
export type AutoStance = 'set' | 'skip';

/** Что делать с дежурным вылетом; отказы названы, чтобы вызывающий сказал игроку почему. */
export type ScrambleStance =
  /** Поднять патруль. */
  | 'set'
  /** Снять дежурство (с запоминанием остатка вылета). */
  | 'clear'
  /** Ничего: чужой, без крыла или уже в нужном состоянии. */
  | 'skip'
  /** Отказ: флот не пришвартован. */
  | 'need-dock'
  /** Отказ: флот занят (в пути или в бою). */
  | 'need-idle';

/** Нужно ли трогать авто-штурм этого флота (правила 1–3). */
export function autoStance(mine: boolean, current: boolean, want: boolean): AutoStance {
  if (!mine) return 'skip';
  return current === want ? 'skip' : 'set';
}

/** Что делать с дежурным вылетом этого флота (правила 1–6). */
export function scrambleStance(
  mine: boolean,
  hasWing: boolean,
  current: boolean,
  want: boolean,
  docked: boolean,
  idle: boolean,
): ScrambleStance {
  if (!mine || !hasWing) return 'skip';
  if (current === want) return 'skip';
  if (!want) return 'clear';
  if (!docked) return 'need-dock';
  if (!idle) return 'need-idle';
  return 'set';
}
