import type { PveState } from '../packages/shared-core/src/index';

/**
 * Что показать игроку про волны Роя (PVR-1.2).
 *
 * `PveState` нёс `waveNumber`, `totalWaves` и `nextWaveAt` с самого своего появления, а
 * последнее поле заведено в ядре дословно как «эхо для HUD» — и ни один клиент его не
 * читал. То есть штурм шёл, а игрок узнавал о нём только по флотам, вылезающим из улья.
 *
 * Решение отделено от рисования нарочно: обоим клиентам нужен один и тот же ответ, а
 * рисуют они по-разному (полоса статуса в прототипе, свой HUD в `packages/client`).
 *
 * 1. **Нет `state.pve` — показывать нечего.** Обычная партия не должна нести ни следа
 *    PvE: модуль в таком матче инертен, и HUD обязан быть таким же.
 * 2. **Счёт идёт ПРИШЕДШИМ волнам, с нуля.** `waveNumber` — это «сколько уже
 *    приземлилось», а не «какая сейчас идёт». До первой волны честно «0 из 10»:
 *    подрисовать единицу значило бы соврать, что первая волна уже здесь.
 * 3. **Отсчёт не уходит в минус.** Между наступлением срока и его обработкой миром
 *    остаток отрицателен; игроку показывают ноль — «вот-вот», а не «−3 часа».
 * 4. **Последняя волна — отдельный ответ, а не волна без отсчёта.** Модуль СНИМАЕТ
 *    `nextWaveAt`, когда новых поводов не осталось; для игрока это важная новость
 *    («больше не придут»), и звать её тем же именем, что идущий штурм, — потерять её.
 * 5. **Пропавший отсчёт при незаконченном штурме тоже читается как «волн не будет».**
 *    Такого состояния модуль не создаёт, но оно может приехать из сейва другой сборки.
 *    Ответ «показывать нечего» здесь был бы худшим из вариантов: HUD молча погас бы
 *    посреди PvE-матча.
 * 6. **После последней волны идёт отсчёт удержания, если режим его объявил (PVR-2.5).**
 *    Победа в забеге — выстоять (решение владельца 2026-09-23): срок `holdUntil` ядро
 *    ставит на последней волне, и это единственное, что игроку теперь нужно знать.
 *    «Волны кончились» без срока значило бы, что ждать нечего, — а ждать как раз есть
 *    чего. Режим без срока отвечает по-прежнему, правилом 4.
 */

/** Ответ: что рисовать. Текста здесь нет — он живёт в `/localization` по ключу. */
export type WaveReadout =
  /** Не PvE-матч — строки волн нет вовсе (правило 1). */
  | { kind: 'none' }
  /** Штурм идёт: `wave` уже пришло из `total`, следующая через `nextInMs` (правила 2–3). */
  | { kind: 'waves'; wave: number; total: number; nextInMs: number }
  /** Волны кончились — новых не будет (правила 4–5). */
  | { kind: 'cleared'; total: number }
  /** Волны кончились, до победы — удержание ещё `holdInMs` (правило 6). */
  | { kind: 'hold'; total: number; holdInMs: number };

/** `pve` — секция состояния матча (её нет в обычной партии), `now` — время МИРА. */
export function waveReadout(pve: PveState | undefined, now: number): WaveReadout {
  if (!pve) return { kind: 'none' };
  if (pve.nextWaveAt === undefined) {
    return pve.holdUntil === undefined
      ? { kind: 'cleared', total: pve.totalWaves }
      : { kind: 'hold', total: pve.totalWaves, holdInMs: Math.max(0, pve.holdUntil - now) };
  }
  return {
    kind: 'waves',
    wave: pve.waveNumber,
    total: pve.totalWaves,
    nextInMs: Math.max(0, pve.nextWaveAt - now),
  };
}
