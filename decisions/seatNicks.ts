/**
 * Ники игроков сетевой партии: кто сидит в каком кресле.
 *
 * Заказ владельца: «в дипломатии показывать ник игрока и сделать кликабельным, чтоб можно
 * было изучить его профиль». В состоянии мира ника нет: там имя ДОМА («Дом Кзар 2»), одно
 * на всех и одинаковое в каждой партии. Ник — это учётная запись, и её знает только
 * сервер, поэтому клиент берёт его из расклада мест (`GET /matches/:id/seats`, поле
 * `nick`). Участнику партии этот расклад отдают всегда, чужому — пока партия открыта для
 * входа (ADDR-6): вошёл бы — увидел бы то же самое.
 *
 * 1. **Ответ сервера — внешние данные.** Разбирается поштучно: кресло без строкового
 *    `playerId` или без непустого ника просто пропускается. Сломанный ответ даёт пустую
 *    карту, а не исключение: без ника строка дипломатии остаётся с именем дома.
 * 2. **Ник ограничен по длине.** Он уходит в разметку и в адрес профиля; разумный предел
 *    отсекает мусор, не трогая настоящих позывных.
 * 3. **Переспрашивать не чаще раза в {@link NICKS_REFRESH_MS}.** Новые игроки садятся в
 *    партию, пока она идёт, поэтому список обновляется при каждом открытии дипломатии, но
 *    частые открытия окна не должны превращаться в поток запросов.
 */

/** Предел длины ника (правило 2). */
export const NICK_MAX = 40;

/** Минимальный промежуток между запросами расклада (правило 3). */
export const NICKS_REFRESH_MS = 15_000;

/** Кресло → ник из ответа `/seats` (правило 1). */
export function nicksFromSeats(body: unknown): Record<string, string> {
  const out: Record<string, string> = {};
  const seats = (body as { seats?: unknown } | null)?.seats;
  if (!Array.isArray(seats)) return out;
  for (const seat of seats) {
    const { playerId, nick } = (seat ?? {}) as { playerId?: unknown; nick?: unknown };
    if (typeof playerId !== 'string' || typeof nick !== 'string') continue;
    const clean = nick.trim();
    if (clean === '' || clean.length > NICK_MAX) continue;
    out[playerId] = clean;
  }
  return out;
}

/** Пора ли переспросить расклад (правило 3). `last` — момент прошлого запроса или `null`. */
export function nicksRefreshDue(last: number | null, now: number): boolean {
  return last === null || now - last >= NICKS_REFRESH_MS;
}
