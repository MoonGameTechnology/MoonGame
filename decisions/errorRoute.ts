/**
 * Куда попадает отказ сервера: в тост поверх игры или в строку экрана подключения
 * (REFM-149).
 *
 * Восьмой срез сетевой секции и последняя из трёх её «развилок по обстоятельствам»:
 * `socketFate.ts` решал, чей сокет; `relayIntake.ts` — что делать с пришедшей строкой;
 * здесь — где игрок УВИДИТ отказ. Разбор стоял лесенкой `if`-ов внутри `onError`,
 * вперемешку с самим текстом сообщений.
 *
 * 1. **Отказ от устаревшего сокета — не наш.** Та же дисциплина, что у закрытия
 *    (`socketFate.ts`, правило 1): игрок нажал «Подключиться» второй раз, и опоздавший
 *    отказ первой попытки перетёр бы строку статуса уже живой сессии — человек прочёл бы
 *    приговор про матч, в котором он в этот момент играет.
 * 2. **Отказ ПОСЛЕ входа идёт тостом.** Экран подключения к этому времени скрыт, и
 *    написанное в его строку не прочитает никто: для игрока действие просто молча
 *    пропадёт. Тост — единственное место, которое видно поверх карты.
 * 3. **Отказ ДО входа идёт в строку экрана подключения.** Там игрок и ждёт ответа, а
 *    всплывшая и погасшая плашка поверх формы входа не объясняет, почему не пускают.
 * 4. **Причина называется словами, а не кодом.** Сервер довёл рукопожатие до конца
 *    именно ради объяснения («мест нет», «вход закрыт», «этим именем уже играют»);
 *    показать вместо этого `E_MATCH_FULL` — значит выбросить объяснение и оставить
 *    игрока гадать, сломан ли сервер.
 */

/** Где игрок увидит этот отказ. */
export type ErrorTarget =
  /** Нигде: отказ пришёл по чужому, уже смененному сокету (правило 1). */
  | 'ignore'
  /** Тост поверх карты: мы уже в матче (правило 2). */
  | 'toast'
  /** Строка экрана подключения: нас ещё не впустили (правило 3). */
  | 'status';

export interface ErrorContext {
  /** Отказ пришёл по ТЕКУЩЕМУ сокету. */
  current: boolean;
  /** Нас уже впустили в матч (пришёл приветственный снимок). */
  admitted: boolean;
  /** Код отказа (`E_*`). */
  code: string;
}

/** Куда показать отказ (правила 1–3). */
export function errorTarget(ctx: ErrorContext): ErrorTarget {
  if (!ctx.current) return 'ignore';
  // Тостом сейчас уходят только отказы чата — единственные, что приходят уже в матче
  // (флуд, недоступный адресат). Прочие коды после входа попадают в скрытую строку
  // статуса, то есть до игрока не доходят; это поведение сохранено как было и записано
  // отдельной строкой в backlog, а не переделано мимоходом.
  return ctx.admitted && ctx.code.startsWith('E_CHAT') ? 'toast' : 'status';
}

/** Ключ локализации для причины отказа, или `null` — причины под этот код нет (правило 4). */
export function refusalKey(code: string): string | null {
  switch (code) {
    case 'E_SLOT_TAKEN':
      return 'net.slot-taken';
    case 'E_UNKNOWN_PLAYER':
      return 'net.no-seat';
    case 'E_MATCH_FULL':
      return 'net.match-full';
    case 'E_ENTRY_CLOSED':
      return 'net.join-closed';
    default:
      return null;
  }
}
