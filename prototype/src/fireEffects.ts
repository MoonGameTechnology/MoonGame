/**
 * Куда рисовать вспышку залпа и сколько вспышек держать (REFM-178).
 *
 * ПУСКАТЬ ли залп на экран решает видимость события — `eventVisibility.ts` (REFM-86):
 * зенитку видно только на ОПОЗНАННОМ узле, а перестрелке артиллерии хватает одного
 * опознанного конца (залп по видимой цели замечаешь, не зная, откуда бьют). Здесь
 * оставшееся: КОНЦЫ дуги и предел очереди вспышек.
 *
 * 1. **Концы берутся СЕЙЧАС, а не при отрисовке.** Ядро издаёт событие ПОСЛЕ урона,
 *    поэтому флота-жертвы в состоянии может уже не быть — к моменту кадра тянуть дугу
 *    будет не к чему.
 * 2. **У зениток запасной конец — точка над орбитой своего мира.** Жертва погибла этим
 *    же залпом, и вспышка обязана всё равно случиться: беззвучно пропавший залп читается
 *    как «ПВО не сработало», хотя оно сработало наверняка.
 * 3. **У артиллерии запасной конец — узел, который прислало САМО событие.** Ядро знает,
 *    во что целились, даже когда цели уже нет; клиенту это знание не восстановить.
 * 4. **Нет ни одного конца — выстрела нет.** Дуга «из ниоткуда в никуда» хуже, чем её
 *    отсутствие: она сообщает игроку событие, но лжёт о месте.
 * 5. **Очередь вспышек ограничена по длине.** Эффект живёт секунды, а список рос бы весь
 *    матч; предел режет СТАРЫЕ, потому что свежая вспышка — та, которую игрок смотрит.
 */

/** Точка на карте. */
export interface XY {
  x: number;
  y: number;
}

/** Сколько зенитных вспышек держим (правило 5). */
export const AA_SHOTS_MAX = 40;
/** Сколько артиллерийских дуг держим (правило 5). */
export const SIEGE_SHOTS_MAX = 24;

/** Смещение запасной вспышки зениток от центра мира — «над орбитой» (правило 2). */
export const AA_ORBIT_OFFSET: XY = { x: 6, y: -14 };

/** Куда бьёт зенитка: в живую цель или над своей орбитой (правила 1–2). */
export function aaImpact(target: XY | null | undefined, planet: XY): XY {
  return target ?? { x: planet.x + AA_ORBIT_OFFSET.x, y: planet.y + AA_ORBIT_OFFSET.y };
}

/** Куда бьёт артиллерия: в живую жертву или в присланный узел; `null` — не рисуем
 *  (правила 1, 3, 4). */
export function siegeImpact(victim: XY | null | undefined, near: XY | null | undefined): XY | null {
  return victim ?? near ?? null;
}

/** Обрезать очередь вспышек до предела, выбрасывая САМЫЕ СТАРЫЕ (правило 5). */
export function capShots<T>(shots: T[], max: number): void {
  while (shots.length > max) shots.shift();
}
