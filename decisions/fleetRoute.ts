/**
 * Пунктирный маршрут идущего флота на карте (REFM-95).
 *
 * 1. **Виден только СВОЙ маршрут и только у идущего флота.** Чужой план — это разведка,
 *    которой у игрока нет (сервер её и не присылает), а у стоящего флота маршрута нет
 *    вовсе.
 * 2. **Сам путь считает ядро — `roadAhead` (ROADS-2).** Здесь он жил своей копией:
 *    опорные точки по узлам плюс доля остановки на последнем лейне. С дорогами путь
 *    идёт через развилки мимо миров, и какой дорогой пойдёт флот — это правило
 *    движения, а не рисунка: вторая копия пообещала бы дорогу, по которой флот не
 *    полетит. Заодно ушла ошибка, которую дороги внесли бы в копию: доля `endT < 1`
 *    теперь бывает и у ноги, кончающейся на развилке, а копия читала её как стоянку.
 * 3. **Выделенный маршрут ярче и толще** — среди десятка своих линий выбранная должна
 *    читаться сразу.
 */

/** Показываем ли маршрут этого флота (правило 1). */
export function routeShown(owner: string | null, me: string, moving: boolean): boolean {
  return moving && owner === me;
}

/** Начертание линии: выделенный маршрут ярче и толще (правило 3). */
export function routeStroke(selected: boolean): { alpha: number; width: number; blur: number } {
  return selected ? { alpha: 0.85, width: 1.8, blur: 8 } : { alpha: 0.32, width: 1.1, blur: 2 };
}
