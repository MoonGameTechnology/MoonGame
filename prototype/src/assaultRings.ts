/**
 * Какие миры обводятся на карте при взведённом ШТУРМЕ (REFM-106).
 *
 * Пока приказ штурма взведён, карта кольцует допустимые цели. Отбор стоял двумя
 * `continue` внутри цикла рисования, и из них не читалось, что кольцо — это ОБЕЩАНИЕ:
 * обвели мир, значит по нему ждут тап.
 *
 * 1. **Вне взведённого приказа колец нет вовсе.** Подсветка целей в обычном режиме
 *    читалась бы как «сюда можно всегда», а приказа за ней не стоит.
 * 2. **Свой мир не обводится** — штурмовать собственный тыл нечем и незачем.
 * 3. **НИЧЕЙНЫЙ мир не обводится тоже:** у пустого узла нет хозяина, чью оборону
 *    ломать, и кольцо обещало бы штурм там, где штурмовать некого.
 * 4. **Только ЗАХВАТЫВАЕМЫЙ сектор.** Астероидное поле или путевую точку не берут:
 *    обвести их значило бы предложить приказ, которого ядро не даст.
 *
 * _Замечено при выносе, НЕ чинил._ `cmdAvailability.canAssaultFromOrbit` считает
 * ничейный мир допустимой целью (`worldOwner !== fleetOwner` при `worldOwner === null`
 * истинно), а кольцо его не рисует — правило 3 строже кнопки. Приводить их к одному
 * означало бы менять поведение одной из сторон, а это не задача кирпича про рисование.
 */

/** Мир глазами прицела штурма. */
export interface RingTarget {
  owner: string | null;
  capturable: boolean;
}

/** Обводить ли этот мир при взведённом штурме (правила 2–4). */
export function ringed(target: RingTarget, me: string): boolean {
  if (target.owner == null || target.owner === me) return false;
  return target.capturable;
}

/** Рисуется ли слой колец вообще (правило 1). */
export function ringsShown(assaultArmed: boolean): boolean {
  return assaultArmed;
}
