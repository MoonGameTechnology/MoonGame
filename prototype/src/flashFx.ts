/**
 * Жизнь экранной вспышки: сколько её осталось и насколько она разошлась (REFM-70).
 *
 * Вспышек на карте три — кольцо «смотри сюда» у мира из строки плана, волна захвата
 * провинции и малое кольцо «готово» (UIX-4.1). Правила у них одни, а первые две считались
 * порознь и в РАЗНЫЕ стороны: одна вела отсчёт от «когда погаснет», другая от «когда
 * началась».
 *
 * 1. **Прогресс идёт по часам, а не по кадрам.** Иначе на медленной машине вспышка
 *    растянется, а на быстрой мигнёт — длительность обязана быть одинаковой у всех.
 * 2. **Прогресс ЗАЖАТ в [0, 1].** Кадр rAF приходит с меткой времени, которая может
 *    оказаться чуть РАНЬШЕ момента постановки вспышки: без клампа `k` уходит в минус,
 *    а отрицательный радиус роняет `arc()` исключением прямо в кадровом цикле.
 * 3. **Истёкшая вспышка СНИМАЕТСЯ, а не рисуется прозрачной.** Иначе список копится,
 *    и каждый кадр продолжает считать по мёртвой записи полную геометрию провинции.
 * 4. **Затухание — это тот же прогресс с другого конца** (`1 - k`), а не отдельная
 *    шкала: две шкалы разъезжаются, и волна перестаёт совпадать с гаснущей заливкой.
 */

/** Возраст вспышки в миллисекундах, никогда не отрицательный (правило 2). */
export function flashAge(now: number, at: number): number {
  return Math.max(0, now - at);
}

/** Прогресс 0 → 1 за время жизни, зажатый по обоим концам (правила 1–2). */
export function flashProgress(now: number, at: number, lifeMs: number): number {
  if (lifeMs <= 0) return 1;
  return Math.min(1, flashAge(now, at) / lifeMs);
}

/** Отгорела ли вспышка — её пора снять со списка (правило 3). */
export function flashDone(now: number, at: number, lifeMs: number): boolean {
  return now - at >= lifeMs;
}

/** Затухание 1 → 0: тот же прогресс с другого конца (правило 4). */
export function fadeOf(progress: number): number {
  return 1 - progress;
}

/** Радиус растущего кольца: от `base` и дальше на `grow` к концу жизни. */
export function growRadius(base: number, grow: number, progress: number): number {
  return base + grow * progress;
}

/**
 * Радиус волны: к концу жизни она уходит за дальний угол клетки на `overshoot`, чтобы
 * фронт ушёл ЗА границу, а не замер ровно на ней.
 */
export function waveRadius(progress: number, maxR: number, overshoot: number): number {
  return progress * maxR * overshoot;
}

/**
 * Малая вспышка (UIX-4.1, малый тир скилла `mobile-game-feel`): своя постройка готова, свой
 * флот прибыл. Кольцо расходится от `base` на `grow` и гаснет. Без движения оно не
 * расходится, а стоит на середине пути и только гаснет: уходит разлёт, а не сама вспышка.
 */
export function noticeRing(
  progress: number,
  motion: boolean,
  base: number,
  grow: number,
): { r: number; alpha: number } {
  return { r: growRadius(base, grow, motion ? progress : 0.5), alpha: fadeOf(progress) };
}
