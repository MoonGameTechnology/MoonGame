/**
 * Попал ли палец в ЗНАЧОК БОЯ, и в какой именно.
 *
 * Значок боя — единственная отметка на карте, которая уже несёт живые данные: фазу и
 * отсчёт до следующего раунда (`battleMark.ts`, REFM-118). До этого решения он был
 * только картинкой: посмотреть, КТО там дерётся и какими силами, можно было лишь выделив
 * СВОЙ флот в этом бою, — то есть про чужую схватку рядом узнать было нечем, а про свою
 * приходилось сперва попасть по кораблю.
 *
 * 1. **Фло́т и мир забирают тап первыми.** По кораблю тапают, чтобы ОТДАТЬ ПРИКАЗ, и
 *    отнять у него тап значило бы менять разбор боя на потерянный ход — худший размен из
 *    возможных. Значок берёт тап, только когда под пальцем больше ничего нет.
 * 2. **Радиус у значка МЕНЬШЕ узлового.** Кольцо висит над точкой схватки, и равный
 *    радиус позволил бы ему воровать тапы по самому миру — та же причина, по которой
 *    метка плана меньше узла (`tapPriority.ts`, REFM-64). У пальца радиус шире, чем у
 *    курсора: правило цели в 44 px.
 * 3. **Бой под туманом не тапается.** Кольца там нет вовсе (правило 2 `battleMark.ts`),
 *    и попасть в невидимое значило бы получить разведданные тапом по пустому месту.
 * 4. **Из нескольких боёв берётся БЛИЖАЙШИЙ.** Два боя рядом — обычное дело на плотной
 *    карте; обход по порядку отдал бы игроку не тот, в который он целился. Ничья по
 *    расстоянию разводится по `id`, иначе исход тапа зависел бы от порядка обхода.
 */

/** Бой в том виде, в каком его читает тап: где кольцо и опознан ли узел. */
export interface BattleTapTarget {
  id: string;
  /** Точка схватки на ЭКРАНЕ (уже спроецированная камерой), либо null — кольца нет. */
  at: { x: number; y: number } | null;
  /** Узел опознан игроком: под туманом кольца не рисуют и тапать нечего (правило 3). */
  identified: boolean;
}

/** Радиус попадания по значку боя: у пальца шире, чем у курсора (правило 2). */
export function battleTapRadius(byTouch: boolean): number {
  return byTouch ? 26 : 20;
}

/**
 * Какой бой забирает тап — или null, если никакой.
 *
 * `taken` — забрал ли тап кто-то более важный (флот, мир, вооружённый приказ). Правило 1:
 * значок стоит ПОСЛЕ них, поэтому занятый тап сюда даже не доходит.
 */
export function battleAtTap(
  battles: readonly BattleTapTarget[],
  point: { x: number; y: number },
  byTouch: boolean,
  taken: boolean,
): string | null {
  if (taken) return null; // правило 1
  const r = battleTapRadius(byTouch);
  let best: { id: string; d: number } | null = null;
  for (const b of battles) {
    if (!b.identified || !b.at) continue; // правило 3
    const dx = b.at.x - point.x;
    const dy = b.at.y - point.y;
    const d = Math.hypot(dx, dy);
    if (d > r) continue; // «в пределах», а не «ближе всех»
    // Правило 4: ближайший, ничья — по id, чтобы исход не зависел от порядка обхода.
    if (best === null || d < best.d || (d === best.d && b.id < best.id)) best = { id: b.id, d };
  }
  return best?.id ?? null;
}
