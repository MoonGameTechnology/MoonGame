/**
 * Сторож проводки «долгое нажатие на навык — описание» (заказ владельца 2026-09-25) —
 * статический, как соседние сторожа экрана: механика удержания живёт на DOM, и поднимать
 * её в vitest значило бы проверять мок. Живую проверку делает робот `smoke:sector-zero`.
 *
 * Что держит: навык ✨ командной полосы несёт ключ сводки `ab:` и подсказку, а удержание
 * знает навыки своей целью. Без первого удержанию нечего открыть, без второго оно навык
 * не видит вовсе и короткий тап остаётся единственным ответом кнопки.
 */
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

const MAIN = readFileSync(new URL('./main.ts', import.meta.url), 'utf8');

describe('навык в меню приказов: удержание открывает описание', () => {
  it('кнопка навыка ✨ несёт ключ сводки ab: и подсказку-описание', () => {
    expect(MAIN).toMatch(/data-cmd="castdo"[^`]*data-desc="ab:\$\{opt\.id\}"\$\{hint\}/);
  });

  it('навык — цель удержания', () => {
    expect(MAIN).toMatch(/const HOLD_TARGETS = '[^']*\[data-desc\^="ab:"\]'/);
  });

  it('пункт навыка меню точки «Приказа» получает описание из каталога', () => {
    expect(MAIN).toMatch(/ad\.description \? \{ desc: t\(ad\.description\) \}/);
  });
});
