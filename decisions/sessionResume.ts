/**
 * «Запомнить вход» (AC-0.2): что делать с сохранённой сессией, когда игрок вернулся.
 *
 * Сессия лежит в браузере неделю, но раньше стартовый экран её не замечал и каждый раз
 * просил пароль. Теперь на входе клиент меняет сохранённую сессию на свежую
 * (`POST /auth/refresh`): живая — хаб без пароля и ещё неделя впереди, мёртвая — карточка
 * входа. Отсюда три правила.
 *
 * 1. **Живая — это 2xx с токеном-строкой.** Новый токен ЗАМЕНЯЕТ старый в хранилище: срок
 *    сдвигается от этого захода, поэтому игрок, заходящий хотя бы раз в неделю, пароль не
 *    вводит. Дольше месяца с последнего ввода пароля сервер не продлевает — это его правило
 *    (`SESSION_REAUTH_SEC`), клиент его не дублирует: ответ просто придёт 401.
 * 2. **401 — сессии больше нет.** Вышли везде, сменили пароль, неделя без захода, месяц с
 *    пароля. Запись стирается (как у входа в матч, `joinRules.ts`, правило 1), иначе
 *    клиент так и будет предъявлять мёртвый пропуск.
 * 3. **Всё остальное — «не знаю», и оно ничего не решает.** Обрыв сети, 429, 5xx, ответ
 *    без токена: запись НЕ стирается — временный сбой не должен разлогинивать, — но и
 *    пропуском не считается. Куда вести при незнании, решает место вызова по прежнему
 *    правилу: стартовый экран показывает карточку входа, ссылка на партию идёт со старой
 *    сессией, а сервер на входе в матч скажет сам.
 */

/** Ответ сервера на продление; `null` — до сервера не дошли. */
export interface RefreshReply {
  status: number;
  /** Разобранное тело ответа (`null`, если не разобралось). */
  body: unknown;
}

/** Чем кончилась попытка продлить сессию. */
export type ResumeOutcome =
  /** Правило 1: сессия жива, `token` — её продлённая замена. */
  | { kind: 'live'; token: string }
  /** Правило 2: сессии нет, запись стереть. */
  | { kind: 'gone' }
  /** Правило 3: не знаем — запись не трогать, пропуском не считать. */
  | { kind: 'unknown' };

/** Разобрать ответ `POST /auth/refresh` (правила 1–3). */
export function resumeOutcome(reply: RefreshReply | null): ResumeOutcome {
  if (!reply) return { kind: 'unknown' };
  if (reply.status === 401) return { kind: 'gone' };
  const token = (reply.body as { token?: unknown } | null)?.token;
  if (reply.status >= 200 && reply.status < 300 && typeof token === 'string' && token !== '')
    return { kind: 'live', token };
  return { kind: 'unknown' };
}
