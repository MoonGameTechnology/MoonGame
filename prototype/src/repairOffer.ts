/**
 * Показывать ли кнопку ремонта на карточке флота (REFM-90).
 *
 * Кнопка одна — платный ремонт за кредиты (в забеге Sector Zero — за Суверены) где угодно
 * вне боя. Экспресс за металл у своего дока снят (заказ владельца 2026-11-01: «убрать
 * полное лечение кораблей за металл»): у дока корпус чинится сам, постепенно.
 *
 * 1. **Чинить можно только СВОЙ флот.** Чужой чинит его владелец; предлагать кнопку —
 *    обещать приказ, который ядро отобьёт.
 * 2. **В бою ремонта нет.** Латать корпуса под огнём нельзя, и кнопка посреди схватки
 *    только сбивает с толку.
 * 3. **Нечего чинить — нечего и предлагать.** Нулевая цена значит полный корпус: кнопка
 *    на здоровом флоте выглядит как неисправность интерфейса.
 */

/** Свой, вне боя, есть что чинить (правила 1–3). */
export function canRepair(mine: boolean, inBattle: boolean, cost: number): boolean {
  return mine && !inBattle && cost > 0;
}
