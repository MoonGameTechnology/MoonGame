/**
 * Из координат холста — в пиксели страницы, и как удержать плавающее меню на экране
 * (REFM-69).
 *
 * Проекция нужна везде, где DOM должен встать НАД точкой карты: меню точки режима
 * «Приказ», попап метки, e2e-проба. Все три считали её своими руками одинаковой
 * строкой — и одинаково молча разъехались бы при первой правке.
 *
 * 1. **Считаем от ИЗМЕРЕННОГО прямоугольника холста, а не от размера окна.** Холст
 *    бывает меньше окна (боковая панель, рамка, отступы страницы) — по окну меню
 *    уехало бы от своей точки тем сильнее, чем шире панель.
 * 2. **Масштаб по каждой оси свой.** Холст рисует в своих единицах `VW×VH`, а на
 *    странице занимает измеренные `width×height`; единый множитель разъехался бы по
 *    вертикали на нестандартном соотношении сторон.
 * 3. **Меню центрировано по точке и не должно уезжать за край:** его левый край
 *    зажимается на полширины плюс отступ. _Край случай:_ меню шире экрана — победит
 *    правая граница (`min` применяется последним); поведение сохранено как было.
 * 4. **Из-под верхнего хрома меню опускается на РАЗНИЦУ, а не ставится в абсолютные
 *    96 px.** Оно сдвинуто трансформом, поэтому css-`top` не равен измеренной кромке:
 *    абсолютная установка увела бы его вниз на величину этого сдвига.
 */

/** Измеренный прямоугольник холста на странице. */
export interface CanvasBox {
  left: number;
  top: number;
  width: number;
  height: number;
}

/** Точка в пикселях страницы. */
export interface ScreenPoint {
  x: number;
  y: number;
}

/** Координаты холста → пиксели страницы (правила 1–2). */
export function toScreen(
  pt: { x: number; y: number },
  box: CanvasBox,
  vw: number,
  vh: number,
): ScreenPoint {
  return {
    x: box.left + (pt.x / vw) * box.width,
    y: box.top + (pt.y / vh) * box.height,
  };
}

/** Зазор от края экрана до плавающего меню. */
export const MENU_GUTTER = 6;

/** Высота верхнего хрома: под ним меню не должно прятаться. */
export const TOP_CHROME = 96;

/** Левый край меню, зажатый по экрану (правило 3). */
export function clampMenuLeft(left: number, width: number, viewportW: number): number {
  const half = width / 2 + MENU_GUTTER;
  return Math.min(viewportW - half, Math.max(half, left));
}

/**
 * Новый css-`top` меню: если измеренная кромка залезла под хром, опустить ровно на
 * разницу (правило 4). Не залезла — оставить как есть.
 */
export function pushBelowChrome(styleTop: number, measuredTop: number): number {
  return measuredTop < TOP_CHROME ? styleTop + (TOP_CHROME - measuredTop) : styleTop;
}
