/**
 * Кому из выделенных флотов какой приказ по «Атаке» (ATK-1, ATK-3).
 *
 * 1. **Флот у цели атакует, флот вдали идёт маршем к её узлу.** Сцепку по прибытии заводит
 *    само ядро, поэтому марш и есть атака на расстоянии (ATK-1).
 * 2. **`fleet.engage` получает ОДИН флот у цели.** Бой «Атаки» втягивает всех свободных у
 *    мира, у кого в нём есть враг (ATK-3), значит, и остальные выделенные флоты у цели.
 *    Второй приказ получил бы `E_IN_BATTLE`, и игрок увидел бы отказ там, где всё
 *    получилось. Кандидаты идут по порядку: в соло отвергнутый приказ передаёт очередь
 *    следующему, в сети уходит первый.
 * 3. **Первыми идут свободные.** Флот, занятый боем, приказ отвергнет. Свободных у цели нет —
 *    приказ получает первый занятый, чтобы игрок увидел честный отказ один раз, а не по
 *    отказу на каждый флот.
 * 4. **Цель в пути — приказов нет.** Узла у неё нет: ни атаковать, ни идти некуда. Подсказка
 *    одна на весь приказ.
 */

/** Выделенный флот — то, что решению нужно из состояния. */
export interface EngageFleet {
  id: string;
  /** Узел, где флот стоит; `null` — в пути. */
  location: string | null;
  /** Корабли флота заняты боем (`shipsEngaged`). */
  engaged: boolean;
}

export interface EngageOrders {
  /** Кандидаты на `fleet.engage` по порядку; приказ получает первый принятый. */
  engage: string[];
  /** Кому марш к узлу цели. */
  march: string[];
  /** Цель в пути: приказов нет, нужна подсказка. */
  adrift: boolean;
}

/** Приказы выделенным флотам по цели на узле `target` (`null` — цель в пути). */
export function engageOrders(fleets: readonly EngageFleet[], target: string | null): EngageOrders {
  if (target === null) return { engage: [], march: [], adrift: fleets.length > 0 };
  const here = fleets.filter((f) => f.location === target);
  const free = here.filter((f) => !f.engaged);
  return {
    engage: (free.length ? free : here.slice(0, 1)).map((f) => f.id),
    march: fleets.filter((f) => f.location !== target).map((f) => f.id),
    adrift: false,
  };
}
