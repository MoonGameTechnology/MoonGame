// HUD-DOCK: низ экрана — это ДВА независимых fixed-элемента (лист `#side` и ряд команд
// `#cmdbar`), которые игрок читает как одну панель. Пока они не знают друг о друге,
// вылезают два дефекта, и оба заказаны владельцем одной фразой.
//
// 1. КАРТА КАК РАБОЧАЯ ПОВЕРХНОСТЬ. Взведённый «Курс» ждёт тапа по карте — а лист в это
//    время закрывает нижнюю половину экрана ровно там, куда надо тапнуть. Слияние,
//    набор группы и режим «Приказ» лист уже прятали; движение — нет, хотя это самый
//    частый приказ в игре. Признак один на всех: «ждём тап по карте».
//
// 2. РЯД ПРИВЯЗАН К ЛИСТУ. `#cmdbar` поднимался над листом на ДОГАДКУ (34vh на широком
//    экране, 50vh на телефоне), а лист растёт по содержимому при `max-height:34vh/50vh`.
//    Короткий лист (мир без построек, флот без груза) → догадка выше реальной высоты →
//    между рядом и листом зияет дыра в треть экрана. Высоту надо мерить и отдавать в
//    CSS-переменную; догадка остаётся только фолбэком до первого замера.

export interface DockState {
  /** «Курс» взведён — следующий тап по карте отправляет флот. */
  aiming: boolean;
  /** Ждём тап по дружественному флоту — цель слияния. */
  merging: boolean;
  /** Набор группы тапами (SEL-1). */
  picking: boolean;
  /** Режим «Приказ» — цепочка строится тапами по карте (CHAIN-UX). */
  chaining: boolean;
  /** Есть выделенный объект, которому вообще есть что показать в листе. */
  hasSelection: boolean;
}

/** Карта сейчас — рабочая поверхность: игрок целится, а не читает. */
export function mapIsWorkspace(st: DockState): boolean {
  return st.aiming || st.merging || st.picking || st.chaining;
}

/** Лист виден только когда игрок читает, а не целится. */
export function panelOpen(st: DockState): boolean {
  return st.hasSelection && !mapIsWorkspace(st);
}

/**
 * Значение `--sheeth` — измеренная высота листа. Уезжает прямо в `calc()`, поэтому
 * мусор здесь опаснее, чем кажется: невалидная переменная роняет ВСЁ правило, и ряд
 * команд прыгает к нулю экрана. Дробную высоту (девайсы с dpr 2.625) округляем —
 * пол-пикселя ряду не нужны, а мерцание на границе округления браузера — нужно ещё
 * меньше.
 */
export function sheetHeightVar(px: number): string {
  return `${Number.isFinite(px) && px > 0 ? Math.round(px) : 0}px`;
}
