/**
 * Чем оказалось нажатие на карту: выбор, рамка или удержание (REFM-55).
 *
 * На один и тот же жест претендуют три разные вещи, и разводить их надо в момент
 * НАЖАТИЯ — потом уже поздно: рамка, начатая с флота, съест клик по этому флоту.
 *
 * 1. **Shift над СВОИМ флотом — это «добавить в группу», а не рамка.** Привычка RTS:
 *    Shift-клик собирает флоты в одну группу. Открой здесь резинку — и клик пропадёт,
 *    а собрать группу шифтом станет нельзя вовсе. Рамку открывает Shift и ТОЛЬКО над
 *    пустым местом.
 * 2. **Добавляет к выбору любой из Ctrl/⌘/Shift, а рамку — только Shift.** Ctrl и ⌘
 *    живут на разных клавиатурах, и требовать «правильный» значило бы, что на половине
 *    машин добор в группу молча не работает.
 * 3. **Долгое нажатие — только палец и только пока приказ не вооружён.** Это
 *    телефонные стенд-ины Ctrl-клика и Shift-протяжки; в вооружённом режиме тапы
 *    принадлежат приказу, и удержание там сработало бы вслепую поверх прицела.
 * 4. **Что делает удержание, решает то, что под пальцем:** свой флот — переключить его
 *    в группе, пусто — растянуть рамку.
 *
 * Какие именно режимы считаются «вооружёнными», решает хозяин: набор режимов — его
 * хозяйство, а здесь важно лишь то, что при вооружённом приказе удержания нет.
 */

/** Что известно про нажатие в момент, когда палец (или кнопка) опустился. */
export interface PressInput {
  /** Палец, а не мышь: у пальца свои радиусы и своё удержание. */
  touch: boolean;
  shift: boolean;
  ctrl: boolean;
  meta: boolean;
  /** Под указателем — СВОЙ флот (радиус подбора уже применён вызывающим). */
  overOwnFleet: boolean;
  /** Вооружён ли приказ, которому принадлежат тапы (курс, слияние, залп, цепочка). */
  orderArmed: boolean;
}

/** Как разошлись претенденты на этот жест. */
export interface PressIntent {
  /** Добор к выбору вместо замены. */
  additive: boolean;
  /** Тянуть рамку выделения. */
  boxSelect: boolean;
  /** Заводить ли сторож удержания. */
  longPress: boolean;
}

export function pressIntent(i: PressInput): PressIntent {
  return {
    additive: i.ctrl || i.meta || i.shift, // правило 2
    boxSelect: i.shift && !i.overOwnFleet, // правило 1
    longPress: i.touch && !i.orderArmed, // правило 3
  };
}

/** Чем окажется сработавшее удержание — решает то, что под пальцем (правило 4). */
export type LongPressAction = 'toggle-fleet' | 'box-select';

export function longPressAction(overOwnFleet: boolean): LongPressAction {
  return overOwnFleet ? 'toggle-fleet' : 'box-select';
}
