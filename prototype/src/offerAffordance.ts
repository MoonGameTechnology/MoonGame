/**
 * REFM-201 — ЧЕЙ СЕЙЧАС ХОД В ПЕРЕГОВОРАХ.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Одна и та же формула была написана ОТ РУКИ ДВАЖДЫ — в чипе
 * стойки (`seatDiploActionsHtml`) и в кнопке обмена картами (`mapShareBtnHtml`). Обе
 * считают одно: висит ли встречное предложение и кто кого ждёт. Вторая рукописная копия
 * формулы — самый тихий способ развести поведение: копии расходятся по одной правке, и
 * никакой тест этого не ловит, потому что каждая по отдельности «работает».
 *
 * А ошибается этот вердикт дороже, чем выглядит. Он не рисует пиксель — он говорит
 * игроку, ЧЕЙ ХОД. Чип, сказавший «⏳ ждём их», когда на самом деле ждут МЕНЯ, не
 * падает и ничего не пишет в консоль: игрок просто не отвечает, а сделка умирает
 * молча — обе стороны сидят и ждут друг друга. Обратная ошибка не лучше: «✓ принять»
 * на СВОЁМ же предложении отправит дубликат вместо согласия.
 *
 * ПРАВИЛА И ПРИЧИНЫ:
 *
 * 1. Состояния ВЗАИМОИСКЛЮЧАЮЩИ и упорядочены. Одно и то же место экрана не может
 *    одновременно значить «прими» и «жди»: порядок решает, что игрок увидит, если
 *    встречные предложения оказались оба сразу.
 *
 * 2. ИХ предложение старше моего. Когда предложения встречные, ход за мной: моё уже
 *    отправлено, ждать его нечего, а их принимается одним тапом. Покажи панель «⏳» —
 *    и оба ждали бы друг друга.
 *
 * 3. Подавитель гасит ОБА предложения разом. Это то состояние, при котором предложения
 *    уже неактуальны (договор действует) или невозможны (бот в коалиции); показав
 *    аффорданс, кнопка предложила бы заключить заключённое или сделать невозможное.
 *    ЧТО именно подавляет — решает вызывающий: у двух чипов это РАЗНЫЕ вещи, и модуль
 *    нарочно не сводит их в одно (см. расхождение в карточке REFM-201).
 *
 * 4. Классы состояния накладываются НА базовый, а не заменяют его: разметку ищут по
 *    базовому классу (`.dp-act`, `.dp-map`), и потеряв его, кнопка перестала бы
 *    отзываться на нажатие вовсе — при том, что выглядела бы живой.
 *
 * 5. Своё отправленное предложение ЗАПЕРТО. Повторный тап послал бы то же самое
 *    второй раз: с той стороны это выглядит как новое предложение, а не как
 *    напоминание.
 *
 * 6. Запрет запирает кнопку НЕЗАВИСИМО от предложений — ядро всё равно отобьёт, и
 *    живая кнопка обещала бы действие, которого не будет.
 */

/** Что кнопка предлагает сделать прямо сейчас. */
export type OfferAffordance =
  /** Их предложение висит — тап ПРИНИМАЕТ (✓). */
  | 'accept'
  /** Моё предложение отправлено — ждём их (⏳), тап запрещён. */
  | 'waiting'
  /** Ничего не висит — обычная кнопка. */
  | 'plain';

/**
 * Вердикт (правила 1–3). `suppressed` — состояние, при котором предложения не считаются
 * вовсе; у чипа стойки это «нельзя по смыслу», у кнопки карт — «договор уже действует».
 */
export function offerAffordance(
  suppressed: boolean,
  theirOffer: boolean,
  myOffer: boolean,
): OfferAffordance {
  if (suppressed) return 'plain'; // правило 3
  if (theirOffer) return 'accept'; // правило 2
  if (myOffer) return 'waiting';
  return 'plain';
}

/** Классы кнопки поверх базового (правило 4). `active` — «уже действует/уже стоит». */
export function offerClass(base: string, active: boolean, a: OfferAffordance): string {
  return `${base}${active ? ' on' : ''}${a === 'accept' ? ' offer' : ''}${a === 'waiting' ? ' pend' : ''}`;
}

/** Заперта ли кнопка (правила 5–6). */
export function offerDisabled(a: OfferAffordance, barred: boolean): boolean {
  return barred || a === 'waiting';
}

/** Нужна ли подпись-пометка перед названием — и какая (текст даёт локаль, не модуль). */
export function offerMark(a: OfferAffordance): '✓' | '⏳' | null {
  if (a === 'accept') return '✓';
  if (a === 'waiting') return '⏳';
  return null;
}
