/**
 * Что игрок попросил, ткнув в дипломатическую кнопку (REFM-139).
 *
 * Дипломатия живёт на двух экранах сразу: КАРТОЧКА игрока (открывается тапом по нику в
 * чате) и полное ОКНО дипломатии со списком всех. Разметка кнопок у них общая — предложить
 * позицию, поделиться картой, заслать шпиона, написать письмо, — и разбор клика стоял
 * дважды, слово в слово, отличаясь лишь тем, что перерисовывалось после.
 *
 * 1. **НАМЕРЕНИЕ и ПЕРЕРИСОВКА — разные дела.** Что попросил игрок, читается из разметки
 *    одинаково; кто и что обновит потом — знает только экран: карточка перерисовывает
 *    себя, окно — весь список. Смешаешь их в одном месте — и получишь ровно то, что было:
 *    две копии разбора, которые обязаны меняться синхронно.
 * 2. **Место (`seat`) читается из САМОЙ кнопки, а не из открытого экрана.** У позиции и
 *    шпионажа это `data-seat`, у обмена картой `data-mapseat`, у письма `data-msgseat`:
 *    карточка показывает одного игрока, а окно — всех сразу, и «тот, кто сейчас открыт»
 *    там значит совсем разное.
 * 3. **Первое совпадение выигрывает.** Кнопки лежат в общих контейнерах, и клик может
 *    попасть под несколько правил; проверь все — одно нажатие сделает два действия.
 * 4. **Нет совпадения — нет намерения.** `null` возвращается честно, чтобы экран мог
 *    продолжить СВОЙ разбор: у окна дипломатии есть и свои кнопки (фильтры, окна
 *    интела, беседы), которых у карточки нет.
 */

/** Минимум от DOM-узла, нужный разбору: поиск ближайшего предка по селектору. */
export interface ClickTarget {
  closest(sel: string): { dataset: Record<string, string | undefined> } | null;
}

/** Что игрок попросил. */
export type DiploIntent =
  | { kind: 'stance'; seat: string; stance: string }
  | { kind: 'map'; seat: string }
  | { kind: 'spy'; seat: string; what: string }
  | { kind: 'message'; seat: string };

/**
 * Намерение по клику или `null`, если кнопка не дипломатическая (правила 2–4). Порядок
 * проверок — тот же, что был на обоих экранах: позиция, карта, шпион, письмо.
 */
export function diploIntent(tg: ClickTarget): DiploIntent | null {
  const act = tg.closest('.dp-act');
  if (act) return { kind: 'stance', seat: act.dataset.seat!, stance: act.dataset.stance! };
  const map = tg.closest('.dp-map');
  if (map) return { kind: 'map', seat: map.dataset.mapseat! };
  const spy = tg.closest('.dp-spy');
  if (spy) return { kind: 'spy', seat: spy.dataset.seat!, what: spy.dataset.spy! };
  const msg = tg.closest('.dp-msg');
  const msgseat = msg?.dataset.msgseat;
  if (msgseat) return { kind: 'message', seat: msgseat };
  return null;
}
