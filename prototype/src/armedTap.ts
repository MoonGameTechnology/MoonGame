/**
 * Судьба вооружённого приказа при тапе по карте (REFM-88).
 *
 * Прицельные режимы («иду сюда», «слить», «обстрел», «каст», «высадка героя», «штурм»)
 * ждут одного тапа. Что делать с прицелом ПОСЛЕ тапа, каждая ветка `selectAt` решала
 * сама — и одна из них решает иначе, чем остальные. Отличие настоящее и намеренное, но
 * пока оно не названо, оно читается как забытый `= false` и «чинится».
 *
 * 1. **Вооружённый приказ ОДНОРАЗОВЫЙ: тап его исполняет или снимает.** Прицел, переживший
 *    выстрел, уведёт флот не туда следующим же касанием.
 * 2. **Промах по пустоте — это отмена, а не «попробуй ещё».** Игрок ткнул мимо всего,
 *    значит передумал; держать карту заряженной после этого — ловушка.
 * 3. **ШТУРМ прощает неподходящую ЦЕЛЬ.** Свой мир, незахватываемый сектор, ничей узел —
 *    это промах по цели, а не отказ от приказа. Снимать прицел после каждого неточного
 *    тыка в скопление миров значит наказывать за меткость пальца, поэтому здесь режим
 *    остаётся взведённым и подсказывает, куда бить можно.
 * 4. **Пустота снимает даже прощающий режим** — правило 2 сильнее правила 3.
 */

/** Что оказалось под тапом. */
export type ArmedHit =
  /** Пустое место: ни цели, ни объекта. */
  | 'none'
  /** Годная цель — приказ исполним. */
  | 'valid'
  /** Объект есть, но приказу не годится. */
  | 'wrong';

/** Что делать с прицелом. */
export type ArmedOutcome =
  /** Исполнить приказ и снять прицел. */
  | 'fire'
  /** Снять прицел, ничего не исполняя. */
  | 'cancel'
  /** Оставить взведённым — пусть игрок выберет другую цель. */
  | 'keep';

/**
 * Судьба прицела (правила 1–4). `forgiving` — прощает ли режим неподходящую цель;
 * сегодня это только ШТУРМ.
 */
export function armedTap(hit: ArmedHit, forgiving: boolean): ArmedOutcome {
  if (hit === 'valid') return 'fire';
  if (hit === 'none') return 'cancel';
  return forgiving ? 'keep' : 'cancel';
}
