/**
 * ВЫЛЕТ НА КАРТЕ (остаток SHU-3.1) — где сейчас летящая эскадра и по какой линии.
 *
 * Первая половина кирпича дала игроку ангар и прицел, но САМ ВЫЛЕТ оставался невидим:
 * `state.strikes` не читал в прототипе никто. Игрок отправлял удар и узнавал исход из
 * журнала — не видя ни пути, ни того, что машины ещё в воздухе. Здесь живут решения
 * трассы; рисование (канва) остаётся в `main.ts`, как у маршрутов флотов.
 *
 * 1. **Своё видно, чужого на карте не бывает.** `visibleState` снимает чужие `strikes`
 *    целиком, а соло гоняет ПОЛНОЕ состояние и обязано повторить серверный фильтр сам —
 *    правило 5 `eventVisibility.ts`. Покажи соло больше, чем сеть, и игрок выучит
 *    неверную картину мира.
 * 2. **Концы берутся ЖИВЫЕ, а не из снимка.** База — её нынешняя точка: носитель волен
 *    уйти, пока челноки летят, и ядро на обратной ноге меряет путь ровно так же
 *    (`basePosition` в момент разворота). А вот точка удара — именно снимок
 *    (`strike.to`): вылет наводится и пускается, самонаведения у него нет, и трасса
 *    обязана вести туда, куда машины летят, а не туда, куда уехала цель.
 * 3. **Ход идёт по ВРЕМЕНИ МИРА** (`state.time`), а не по часам кадра: то же время, по
 *    которому ядро назначило прибытие, — иначе значок разъедется с моментом удара.
 * 4. **Нулевая длительность не делит на ноль**: вылет, которому ядро дало срок в один
 *    тик, стоит в конце пути, а не в NaN.
 * 5. **Нога решает НАПРАВЛЕНИЕ.** `out` идёт база → цель, `back` — цель → база. Без
 *    разворота значок на обратной ноге полз бы вспять: доля пройденного времени у обеих
 *    ног считается от своего `departedAt`.
 * 6. **Без живой базы трассы нет.** Порт снесли, носитель сбит — рисовать линию в
 *    никуда нечестно: у неё не будет второго конца. Машины при этом ещё летят, и их
 *    судьбу разберёт ядро на посадке (`shuttle.lost`).
 */
import type { ShuttleStrike, StrikeBase } from '../../packages/shared-core/src/index';

/** Точка на карте (мировые координаты). */
export interface XY {
  x: number;
  y: number;
}

/** Где сейчас база вылета. Передаётся снаружи: положение носителя в пути интерполирует
 *  рисующий (`fleetPos`), и второй копии этой математики здесь не нужно. */
export type BasePos = (base: StrikeBase) => XY | null;

/** Одна трасса: отрезок и значок эскадры на нём. */
export interface StrikeTrail {
  id: string;
  /** Начало ноги — с учётом разворота (правило 5). */
  from: XY;
  /** Конец ноги. */
  to: XY;
  /** Где эскадра в эту секунду. */
  at: XY;
  leg: 'out' | 'back';
  /** Сколько бортов идёт — подпись значка. */
  machines: number;
  /** id эскадры: позывной значка строится из него той же функцией, что имя карточки в
   *  порту, — одно соединение зовётся на карте и в панели одинаково. */
  squadronId: string;
}

/** Доля пройденного пути в [0,1] (правила 3–4). */
export function strikeProgress(strike: ShuttleStrike, now: number): number {
  const span = strike.arrivesAt - strike.departedAt;
  if (span <= 0) return 1;
  const k = (now - strike.departedAt) / span;
  return k < 0 ? 0 : k > 1 ? 1 : k;
}

/** Точка на отрезке по доле пути. */
function lerp(a: XY, b: XY, k: number): XY {
  return { x: a.x + (b.x - a.x) * k, y: a.y + (b.y - a.y) * k };
}

/** Трассы, которые карта имеет право показать этому игроку. */
export function strikeTrails(
  strikes: readonly ShuttleStrike[] | undefined,
  opts: { me: string; now: number; basePos: BasePos },
): StrikeTrail[] {
  const out: StrikeTrail[] = [];
  for (const st of strikes ?? []) {
    if (st.owner !== opts.me) continue; // правило 1
    const home = opts.basePos(st.base); // правило 2
    if (!home) continue; // правило 6
    const [from, to] = st.leg === 'back' ? [st.to, home] : [home, st.to]; // правило 5
    const k = strikeProgress(st, opts.now);
    out.push({
      id: st.id,
      from,
      to,
      at: lerp(from, to, k),
      leg: st.leg,
      machines: st.units.reduce((n: number, u) => n + Math.max(0, u.count), 0),
      squadronId: st.squadronId,
    });
  }
  return out;
}
