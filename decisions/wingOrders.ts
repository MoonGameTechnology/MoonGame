/**
 * Что такое ДЕЙСТВУЮЩЕЕ КРЫЛО — один ответ на панель и на обработчики (REFM-135).
 *
 * Крыло — отдельный флот, отколотый от носителя: у него есть база (`homeBase`), и оно
 * умеет бить в свободном пространстве, возвращаться на базу и вставать в патруль.
 * Условия этих трёх приказов панель и обработчики считали ПО-РАЗНОМУ: панель показывала
 * секцию по владельцу и наличию эскадрилий, а обработчики — только по наличию базы.
 * Расхождение видно игроку как кнопка, которая нажимается и ничего не делает.
 *
 * Решение переехало сюда из `prototype/src/squadron.ts` вместе со сведением хелперов
 * крыла в ядро (CONV-5): предикаты — сторона КЛИЕНТА (что предложить нажать), а не
 * правило мира, поэтому в ядро им нельзя, а в пакете прототипа их не видит
 * `packages/client`.
 *
 * 1. **Крыло — это флот с базой И с эскадрильями на борту.** Одной базы мало: у крыла,
 *    потерявшего эскадрильи в бою, база остаётся. Приказ от такого флота ядро всё равно
 *    отклонит (`E_NO_SHIPS`), но игрок получит ОТКАЗ вместо неактивной кнопки —
 *    интерфейс пообещал бы то, чего не может.
 * 2. **Чужим крылом не командуют.** Тап по чужому флоту тоже выделяет его, и без
 *    проверки владельца приказ ушёл бы за чужой флот — на сервере это отказ, на экране
 *    непонятное молчание.
 * 3. **Действовать крыло может только вне боя и вне перелёта** — в бою оно занято, в
 *    перелёте у него уже есть приказ, и второй его бы отменил незаметно для игрока.
 * 4. **Вернуться на базу можно только ИЗ свободного пространства.** Крыло, уже стоящее
 *    у носителя, слать домой незачем: ядро такой приказ примет (оно проверяет только
 *    базу и занятость), и получится приказ, который ничего не меняет.
 *
 * Признак «несёт эскадрильи» приходит ГОТОВЫМ, отдельным аргументом, а не считается
 * здесь: «какой юнит считается эскадрильей» — правило мира, оно живёт в каталоге данных
 * и в ядре (`fleetHasSquadron(fleet, data)`). Считать его тут значило бы завести вторую
 * версию того самого правила, ради сведения которого этот файл и появился.
 */

/** Что решению нужно знать о флоте. Намеренно уже, чем `Fleet` ядра: лишние поля
 *  сделали бы решение зависимым от формы состояния, которая его не касается. */
export interface WingFleet {
  owner: string;
  /** Носитель, от которого крыло откололось. Нет базы — это не крыло. `null` наравне
   *  с отсутствием поля: `Fleet` ядра допускает оба, и сузить здесь значило бы завести
   *  форму, в которую настоящий флот не пролезает. */
  homeBase?: string | null | undefined;
  /** Идёт бой — крыло занято. */
  battleId?: string | null | undefined;
  /** Летит в свободном пространстве — приказ уже есть. */
  freeMovement?: unknown;
  /** Стоит в свободном пространстве (не у носителя) — значит, есть откуда вернуться. */
  freePosition?: unknown;
}

/** Это крыло игрока `me` — флот с базой и с эскадрильями на борту (правила 1–2).
 *  `hasSquadron` считает вызывающий через `fleetHasSquadron(fleet, data)` ядра. */
export function isWing(f: WingFleet | undefined, me: string, hasSquadron: boolean): boolean {
  return !!f && f.owner === me && !!f.homeBase && hasSquadron;
}

/** Крыло свободно для приказа: не в бою и не в перелёте (правило 3). */
export function wingCanAct(f: WingFleet | undefined): boolean {
  return !!f && !f.battleId && !f.freeMovement;
}

/** Крылу есть откуда возвращаться: оно в свободном пространстве (правило 4). */
export function wingCanReturn(f: WingFleet | undefined): boolean {
  return wingCanAct(f) && !!f?.freePosition;
}
