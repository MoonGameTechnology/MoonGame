/**
 * «Выстрелил и забыл» с НАЗВАННЫМ исходом при отказе.
 *
 * Зачем отдельная функция, а не `void p` по месту. Node с 15-й версии убивает процесс на
 * необработанном отклонении промиса — значит незамеченная заминка базы в фоновом
 * сохранении уносит ВЕСЬ процесс, со всеми матчами и всеми подключёнными игроками. Ждать
 * такие промисы при этом нельзя: они фоновые по смыслу (сохранение, начисление, рассылка
 * «по возможности»). Остаётся третье — у каждого обязан быть назван исход при отказе.
 * Чтобы это было правилом, а не привычкой, за ним следит машина: `no-floating-promises`
 * в `eslint.config.js` не даёт оставить фоновый промис безымянным.
 *
 * `what` уходит в stderr вместе с ошибкой. Без него в логе остаётся голый стек, по
 * которому не понять, ЧТО именно не доехало, — а разбор падения на живом сервере и так
 * идёт в спешке.
 */
export function detach(what: string, work: Promise<unknown>): void {
  work.catch((err: unknown) => {
    process.stderr.write(`[detached] ${what}: ${String(err)}\n`);
  });
}
