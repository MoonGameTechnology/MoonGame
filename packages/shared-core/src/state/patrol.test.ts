/**
 * ДЕЖУРНЫЙ ВЫЛЕТ — по кому бьёт база (CC-4, переведён на порт в SHU-2.2).
 *
 * Решение чистое и живёт в ядре нарочно: его зовут ОБА драйвера — прототипный и
 * серверный, — а до SHU-2.2 у каждого была своя копия правила, и они уже разошлись
 * (сервер выбирал цель с меньшим id, прототип — тоже, но своим кодом).
 */
import { describe, expect, it } from 'vitest';
import { patrolTarget } from './patrol';

const at = (x: number, y: number) => ({ x, y });

describe('SHU-2.2 — выбор цели дежурного вылета', () => {
  it('БЛИЖНИЙ РАНЬШЕ ДАЛЬНЕГО — то же правило, что у перехвата (SHU-1.3)', () => {
    const pick = patrolTarget(at(0, 0), 100, [
      { id: 'far', pos: at(90, 0) },
      { id: 'near', pos: at(10, 0) },
    ]);
    expect(pick).toBe('near');
  });

  it('НА РАВНОЙ ДИСТАНЦИИ — МЕНЬШИЙ id: выбор обязан быть детерминирован', () => {
    const pick = patrolTarget(at(0, 0), 100, [
      { id: 'b', pos: at(0, 50) },
      { id: 'a', pos: at(50, 0) },
    ]);
    expect(pick).toBe('a');
  });

  it('ЗА РАДИУСОМ ЦЕЛИ НЕТ: дежурство стережёт круг, а не всю карту', () => {
    expect(patrolTarget(at(0, 0), 100, [{ id: 'far', pos: at(101, 0) }])).toBeNull();
  });

  it('ГРАНИЦА ВКЛЮЧИТЕЛЬНА — та же мерка `withinRange`, по которой ядро пускает удар', () => {
    expect(patrolTarget(at(0, 0), 100, [{ id: 'edge', pos: at(100, 0) }])).toBe('edge');
  });

  it('НУЛЕВОЙ РАДИУС НЕ БЬЁТ ВООБЩЕ: звена без дальности не бывает, но и обещать нечего', () => {
    expect(patrolTarget(at(0, 0), 0, [{ id: 'here', pos: at(0, 0) }])).toBeNull();
  });

  it('ПУСТОЙ СПИСОК — НЕ ОШИБКА: врагов в радиусе нет, вылета нет', () => {
    expect(patrolTarget(at(0, 0), 100, [])).toBeNull();
  });
});
