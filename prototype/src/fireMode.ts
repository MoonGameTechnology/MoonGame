/**
 * Режим огня артиллерии (🔥): чем он отличается от приказа и кому уходит (REFM-158).
 *
 * Это НЕ выстрел, а СТОЯЧЕЕ ПРАВИЛО: игрок задаёт, как артиллерия ведёт себя сама,
 * пока он смотрит в другую часть карты. Отсюда всё остальное в этом файле.
 *
 * 1. **У каждого режима есть вторая строка — само правило.** «Ответный» и
 *    «Стандартный» без пояснения просто слова, а выбирают тут поведение на часы
 *    вперёд, вслепую такое не ставят.
 * 2. **Подпись кнопки несёт режим ТОЛЬКО при единогласии выделения.** У разнородной
 *    группы общего режима нет; показать чей-то один — соврать про остальных. А ведь
 *    именно по этой подписи игрок решает, надо ли вообще открывать меню.
 * 3. **Незнакомый режим откатывается к нейтральной подписи, а не роняет ряд.**
 *    Режимы приходят из состояния флота, то есть в пределе — с сервера; кнопка
 *    команд не то место, где падать от незнакомого значения.
 * 4. **Текущий режим помечен в меню.** Меню стоячих правил обязано показывать, какое
 *    из них в силе, иначе выбор идёт вслепую.
 * 5. **Приказ уходит ТОЛЬКО тем, у кого режим другой.** Каждый приказ — круг через
 *    ядро с квитанцией; разослать «поставь standard» тем, у кого уже standard, значит
 *    заплатить за ничего.
 * 6. **Фильтр «свой и артиллерийский» стоит на ОТПРАВКЕ.** Кнопка рисуется по факту
 *    наличия артиллерии в выделении, но в самом выделении могут оказаться и обычные
 *    флоты; режима огня у них нет, а чужим не командуют вовсе.
 * 7. **Дефолт режима — один на весь клиент.** Он читается дважды: когда считается
 *    единогласие для подписи и когда сверяется «а не тот же ли режим уже стоит».
 *    Разъедься эти два места — кнопка показывала бы одно, а отправка сверялась бы с
 *    другим.
 */
import { t } from '../../localization/runtime';
import { esc } from './format';

/** Режим, который считается стоящим у флота без явного поля (правило 7). */
export const DEFAULT_FIRE_MODE = 'standard';

/**
 * Режимы огня в порядке нарастания инициативы (правило 1).
 *
 * Ключи стоят ЛИТЕРАЛАМИ, а не собираются из `id`: гейт локализации
 * (`i18n.test.ts`, «нет осиротевших переводов») ищет ключ как строку в исходнике, и
 * интерполяция сделала бы все восемь переводов невидимыми для него — опечатка в
 * одном перестала бы ловиться. Список закрытый и известен на сборке, так что
 * записи в `DYNAMIC` этот случай не заслуживает: тот шов для ключей из рантайм-данных.
 */
const FIRE_MODES = [
  { id: 'passive', labelKey: 'cmd.fire.passive', hintKey: 'cmd.fire.passive.hint' },
  { id: 'return', labelKey: 'cmd.fire.return', hintKey: 'cmd.fire.return.hint' },
  { id: 'standard', labelKey: 'cmd.fire.standard', hintKey: 'cmd.fire.standard.hint' },
  { id: 'aggressive', labelKey: 'cmd.fire.aggressive', hintKey: 'cmd.fire.aggressive.hint' },
] as const;

/** Идентификаторы режимов в том же порядке. */
export const FIRE_MODE_IDS = FIRE_MODES.map((m) => m.id) as readonly FireModeId[];

export type FireModeId = (typeof FIRE_MODES)[number]['id'];

/** Подпись кнопки 🔥: имя режима при единогласии, иначе нейтральная (правила 2–3). */
export function fireModeLabel(uniform: string | null): string {
  const hit = FIRE_MODES.find((m) => m.id === uniform);
  return hit ? t(hit.labelKey) : t('cmd.fire.title');
}

/** Поповер режимов над рядом команд: пункт на режим, ● у текущего (правила 1, 4). */
export function fireMenuHtml(uniform: string | null): string {
  const items = FIRE_MODES.map((m) => {
    const on = uniform === m.id;
    return (
      `<button data-cmd="fmset" data-mode="${m.id}"${on ? ' class="on"' : ''}>` +
      `<b>${on ? '● ' : ''}${esc(t(m.labelKey))}</b>` +
      `<span>${esc(t(m.hintKey))}</span>` +
      `</button>`
    );
  }).join('');
  return `<div class="cmdpop">${items}</div>`;
}

/** Флот глазами отправки приказа (правила 5–6). */
export interface FireModeFleet {
  id: string;
  owner: string;
  /** Есть ли на борту артиллерия — только у неё есть режим огня. */
  artillery: boolean;
  /** Режим прямо сейчас; пусто — значит дефолтный (правило 7). */
  mode: string | null | undefined;
}

/** Кому из выделения реально слать приказ о смене режима (правила 5–7). */
export function fireModeTargets(
  fleets: readonly FireModeFleet[],
  me: string,
  next: string,
): string[] {
  return fleets
    .filter((f) => f.owner === me && f.artillery && (f.mode ?? DEFAULT_FIRE_MODE) !== next)
    .map((f) => f.id);
}
