// Геометрия «хвоста» маркера флота — пипсы трюма и счётчик «×N» за кормой.
//
// Вынесена из main.ts ради теста на живой дефект: у СТОЯЩЕГО у мира флота поза
// радиальная (нос от центра планеты), и локальный +y хвоста смотрел ВНУТРЬ орбиты.
// Пока кольцо было широким (44px), хвост помещался между кораблём и диском планеты;
// после ужатия кольца (−30%, а на дальнем зуме ещё ×0.5 = 15.5px) ряды пипсов легли
// прямо на спрайт планеты — «текстурки заполненности трюма съезжают» (плейтест).
// Лечение — не двигать константы, а развернуть хвост НАРУЖУ для стоящей позы: тогда
// он не касается диска ни при каком радиусе кольца. В полёте поза тангенциальная и
// хвост, как прежде, тянется назад по курсу — там разворота нет.
//
// РАСКЛАДКА РЯДОВ ПИПСОВ (REFM-116) — здесь же: шапка этого файла заявила пипсы своей
// темой с самого начала, а владел он только базисом. Сама раскладка стояла в кадровом
// цикле — три выражения и тернарник, из которых не читалось, ЧТО решается.
//
// 1. **Два ряда делятся по ФОРМЕ, а не по источнику.** Ромбы — эскадрильи в трюме,
//    квадраты — десант. Смешай их в один ряд, и «сколько чего» перестанет читаться с
//    одного взгляда: форма здесь и есть подпись.
// 2. **Грузящаяся единица встаёт в ряд СВОЕЙ формы,** а не отдельным рядом «в пути».
//    Место в трюме она занимает уже сейчас, и переезд пипса по окончании погрузки
//    читался бы как «груз прыгнул».
// 3. **Ряд ограничен восемью, остаток уходит в «+N».** Длинный хвост перекрыл бы
//    соседние флоты; но и врать нельзя, поэтому непоместившееся названо числом.
// 4. **Ряд центрирован по хвосту, и «+N» входит в ширину.** Забудь про него — и хвост
//    с остатком поедет вбок относительно маркера.
// 5. **Второй ряд опускается под первый, только если первый НЕПУСТ.** Иначе квадраты
//    висели бы с отступом от эмблемы, как будто ряд ромбов пропал, а не отсутствует.
// 6. **Счётчик «×N» опускается только когда рядов ДВА.** Он стоит под хвостом, и
//    единственный ряд оставил бы под собой пустую полосу.
// 7. **Доля погрузки ЗАЖАТА в [0, 1].** Часы матча идут своим ходом: без зажима
//    недостроенный пипс успел бы вырасти за свой размер, а перемотка назад дала бы
//    отрицательный радиус — и `arc`/`fillRect` рисовали бы мусор.

/** Угол базиса хвоста: локальный +y уходит за корму (в полёте) или наружу от планеты
 *  (стоящий флот в радиальной позе — см. шапку файла). */
export function tailTheta(ang: number, staticDock: boolean): number {
  return ang + Math.PI / 2 + (staticDock ? Math.PI : 0);
}

/** Точка ячейки хвоста: локальные (lx, ly) в повёрнутом базисе от якоря маркера. */
export function tailAt(
  ax: number,
  ay: number,
  th: number,
  lx: number,
  ly: number,
): { x: number; y: number } {
  return {
    x: ax + lx * Math.cos(th) - ly * Math.sin(th),
    y: ay + lx * Math.sin(th) + ly * Math.cos(th),
  };
}

/** Шаг ячейки хвоста в px — им же меряются отступы рядов (правила 5–6). */
export const CARGO_CELL = 8;
/** Сколько пипсов влезает в один ряд; остальное — «+N» (правило 3). */
export const CARGO_ROW_MAX = 8;
/** Ширина, которую занимает хвостовое «+N» (правило 4). */
const OVER_W = 12;

/** Один пипс груза: чем он нарисуется и, если грузится, чем именно. */
export interface CargoPip<L> {
  kind: 'wing' | 'troop' | 'load';
  load?: L;
}

/** Два ряда пипсов: ромбы и квадраты. */
export interface CargoRows<L> {
  diamonds: CargoPip<L>[];
  squares: CargoPip<L>[];
}

/**
 * Разложить груз по рядам ФОРМЫ (правила 1–2). `isWing` отвечает, эскадрилья ли
 * грузящаяся единица — предикат приходит снаружи, чтобы модуль не знал игровых данных.
 */
export function cargoRows<L extends { unit: string }>(
  wingPips: number,
  troops: number,
  loads: readonly L[],
  isWing: (unit: string) => boolean,
): CargoRows<L> {
  const diamonds: CargoPip<L>[] = [];
  const squares: CargoPip<L>[] = [];
  for (let i = 0; i < wingPips; i++) diamonds.push({ kind: 'wing' });
  for (let i = 0; i < troops; i++) squares.push({ kind: 'troop' });
  for (const load of loads) (isWing(load.unit) ? diamonds : squares).push({ kind: 'load', load });
  return { diamonds, squares };
}

/** Раскладка одного ряда: сколько рисуем, сколько в «+N» и где центр первой ячейки. */
export interface CargoRowLayout {
  shown: number;
  over: number;
  /** Локальный x центра первой ячейки (правило 4). */
  firstX: number;
}

/** Уместить ряд в хвост: обрезать по пределу и отцентровать (правила 3–4). */
export function cargoRowLayout(count: number): CargoRowLayout {
  const shown = Math.min(count, CARGO_ROW_MAX);
  const over = count - shown;
  const width = shown * CARGO_CELL + (over > 0 ? OVER_W : 0);
  return { shown, over, firstX: -width / 2 + CARGO_CELL / 2 };
}

/** Локальный y ряда квадратов: под ромбами, если те есть (правило 5). */
export function squareRowY(baseY: number, diamonds: number): number {
  return diamonds ? baseY + CARGO_CELL : baseY;
}

/** Локальный y счётчика «×N»: ниже на ячейку, только когда рядов ДВА (правило 6). */
export function tallyY(baseY: number, diamonds: number, squares: number): number {
  return diamonds && squares ? baseY + CARGO_CELL : baseY;
}

/** Доля погрузки, зажатая в [0, 1] (правило 7). */
export function loadFill(now: number, startAt: number, doneAt: number): number {
  return Math.min(1, Math.max(0, (now - startAt) / (doneAt - startAt)));
}
