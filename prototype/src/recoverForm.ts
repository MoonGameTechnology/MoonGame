/**
 * Просьба выслать ссылку для сброса пароля (REFM-161).
 *
 * Шестнадцатый срез сетевой секции. Сам сброс живёт в `passwordReset.ts` (REFM-19), а
 * ПРОСЬБА о нём — три решения внутри `submitRecover`: что делать с пустым полем, что
 * ответить игроку и что перенести с предыдущего экрана. Главное из них выглядит как
 * недоделка — ответ сервера не разбирается ВООБЩЕ, — и без записанной причины его
 * рано или поздно «починят».
 *
 * 1. **Ответ игроку ОДИН И ТОТ ЖЕ, что бы ни случилось.** Это зеркало анти-перечисления
 *    на сервере (`authApi.ts`): разный текст для «адрес найден» и «адрес не найден»
 *    превратил бы форму восстановления в проверку, есть ли у человека здесь учётка —
 *    кто угодно смог бы перебором выяснить, кто из его знакомых тут играет. Поэтому и
 *    сбой сети глотается: «сервер недоступен» появлялось бы только на ОДНОЙ из веток и
 *    тем самым отличало бы их. Цена известна и принята: игрок без связи услышит «письмо
 *    отправлено» и будет ждать письма, которого никто не посылал.
 * 2. **Пустое поле — не запрос, а подсказка ПОЛЮ.** Отправлять пустоту бессмысленно, а по
 *    правилу 1 сервер ответил бы тем же «письмо отправлено»: человек ушёл бы ждать письмо,
 *    которое некуда слать. Пустота — единственный случай, когда форма отвечает иначе, и
 *    она видна клиенту без сервера, так что ничего не выдаёт.
 * 3. **Адрес переносится с экрана регистрации.** Игрок вводил его строкой выше; заставлять
 *    печатать второй раз ровно в тот момент, когда он не помнит пароль, — лишний повод
 *    бросить. Переносится очищенным от пробелов: скопированный из письма адрес часто
 *    приезжает с хвостом.
 */

/** Чем кончился запрос к `/auth/recover` — с точки зрения КЛИЕНТА (правило 1). */
export type RecoverOutcome =
  /** Сервер ответил (любым кодом). */
  | 'answered'
  /** До сервера не дошли. */
  | 'unreachable';

/** Что делать с тем, что игрок набрал. */
export type RecoverStep =
  /** Поле пустое: просим заполнить и никуда не ходим (правило 2). */
  | { kind: 'need-mail'; key: 'auth.need-mail' }
  /** Отправляем просьбу с очищенным адресом. */
  | { kind: 'send'; email: string };

/** Единственный ответ игроку — он не зависит ни от чего (правило 1). */
export const RECOVER_SAID = 'auth.recover.sent';

/** Идти ли на сервер и с каким адресом (правило 2). */
export function recoverStep(typed: string): RecoverStep {
  const email = typed.trim();
  return email ? { kind: 'send', email } : { kind: 'need-mail', key: 'auth.need-mail' };
}

/** Что показать после попытки. Исход НЕ влияет на ответ — в этом и есть правило 1. */
export function recoverAnswer(_outcome: RecoverOutcome): typeof RECOVER_SAID {
  return RECOVER_SAID;
}

/** Адрес, подставляемый в форму восстановления с экрана регистрации (правило 3). */
export function carryEmail(fromRegister: string): string {
  return fromRegister.trim();
}
