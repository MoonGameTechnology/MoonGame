/**
 * RESIL-1 · «Выстрелил и забыл» с НАЗВАННЫМ исходом — браузерная половина.
 *
 * Серверный близнец — `packages/server/src/detach.ts`, и цена у них РАЗНАЯ. На сервере
 * необработанное отклонение убивает процесс, а с ним все матчи разом; в браузере вкладка
 * переживёт его молча. Отсюда и соблазн ничего не делать — но тихо проглоченный сбой
 * стоит своего: не сохранилось, не отправилось, не открылось, и ни строчки нигде. Разбор
 * такой жалобы («нажал — ничего») начинается с пустой консоли и упирается в неё же.
 *
 * Поэтому исход называется здесь, одной строкой с тем же префиксом `[detached]`, что и на
 * сервере: в консоли вкладки её видно так же, как в `moongame logs`.
 *
 * **Что показывается ИГРОКУ: ничего нового — и это решение, а не недоделка.** Отказ,
 * который игрока касается, ему уже показан там, где он понятен: серверный код отказа
 * выводит `host.note('✖ ' + errText(code))` в самом запросе (`corpScreen.ts`'s `corpFetch`
 * и его родня). Сюда доходит ДРУГОЕ — отклонение, которого не ждали: баг, а не игровое
 * условие. Назвать его игроку нечем, кроме «что-то пошло не так», а такая строка не
 * говорит ни ему, ни разбору ничего — зато занимает место настоящего сообщения.
 *
 * `what` обязателен по той же причине, что и на сервере: голый стек не отвечает на
 * вопрос «ЧТО именно не доехало».
 */
export function detach(what: string, work: Promise<unknown>): void {
  work.catch((err: unknown) => {
    console.error(`[detached] ${what}:`, err);
  });
}
