/**
 * Что стройка сообщает игроку (REFM-175).
 *
 * ПУСКАТЬ ли событие в ленту решает фог-гейт `recapGate.ts` (RECAP-FOG): своё игрок узнаёт
 * всегда, чужое — только на опознанном узле, и соло обязано повторять тот же фильтр, что
 * сервер применяет в сети. Здесь следующий шаг, до сих пор стоявший в кадре: что именно
 * говорит каждое из трёх событий стройки и что за собой тянет.
 *
 * 1. **Три события — три текста, и «улучшено» называет УРОВЕНЬ.** «Улучшено» без уровня
 *    неотличимо от «построено»: игрок качает здание много раз, и строка обязана говорить,
 *    докуда он дошёл.
 * 2. **Якорь на мир несёт только РАЗРУШЕНИЕ.** Взрыв — происшествие, к которому игрок
 *    захочет прыгнуть камерой; своя достроенная шахта — ожидаемое событие, прыгать
 *    незачем, а лишний якорь превращает всю ленту в кнопки.
 * 3. **Неизвестное сборке здание всё равно называется — своим идентификатором.** Данные
 *    могут разъехаться с клиентом; молча выкинуть строку значит скрыть от игрока, что на
 *    его мире что-то произошло. Пусть кодом, но в ленте.
 * 4. **Готовая крепость ставит зенитки.** Единственный побочный эффект в группе, и он
 *    привязан к КОНКРЕТНОМУ зданию, а не к факту стройки: остальные постройки ничего не
 *    включают, и заводить им общий крючок «после стройки» значило бы приглашать туда
 *    случайную логику.
 */

/** Событие стройки, о котором рассказывают игроку. */
export type BuildLogKind = 'constructed' | 'upgraded' | 'destroyed';

/** Что сказать про событие и что оно тянет за собой. */
export interface BuildLogLine {
  /** Ключ строки ленты. */
  key: 'log.build.done' | 'log.build.upgraded' | 'log.build.destroyed';
  /** Нужна ли подстановка уровня (правило 1). */
  needsLevel: boolean;
  /** Прыгает ли лента камерой на этот мир (правило 2). */
  anchored: boolean;
}

/** Что стройка сообщает игроку (правила 1, 2).
 *
 *  ORB-3: правила 4 («готовый звёздный форт ставит миру зенитки») больше нет —
 *  орбитальное ПКО самостоятельная постройка, и получить её иначе, чем построив,
 *  нельзя. Вместе с правилом ушёл и аргумент `building`: строке ленты вид здания
 *  больше ни на что не влияет. */
export function buildLogLine(kind: BuildLogKind): BuildLogLine {
  if (kind === 'upgraded') {
    return { key: 'log.build.upgraded', needsLevel: true, anchored: false };
  }
  if (kind === 'destroyed') {
    return { key: 'log.build.destroyed', needsLevel: false, anchored: true };
  }
  return { key: 'log.build.done', needsLevel: false, anchored: false };
}
