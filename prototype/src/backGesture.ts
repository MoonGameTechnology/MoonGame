// REFM-198: что ОЗНАЧАЕТ нажатие «Назад».
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Лестницу «какой слой закрыть первым» уже держит `backLayers.ts`.
// Но у Back есть второй, независимый вопрос: а что делать, когда закрывать НЕЧЕГО, — и вот
// он до сих пор жил россыпью в трёх местах main.ts (обработчик `popstate`, кадровый цикл,
// шеврон ‹) с разными формулировками одного и того же условия. Ошибается такой разброд
// ТИХО и дорого: неверный вердикт либо выгружает страницу вместе с живым матчем (игрок
// теряет сессию одним случайным нажатием), либо, наоборот, не делает НИЧЕГО — ровно баг
// BF-31, когда вторую ступень истории оставляли «системе», а её в обычной вкладке нет.
// Ни то, ни другое не падает и не логируется: снаружи это просто «Back сломался».
//
// ПРАВИЛА И ПРИЧИНЫ:
//
// 1. Есть что закрыть — закрываем, и на этом всё. Пока на экране лежит хоть один слой,
//    Back обязан разбирать стопку, а не выходить: игрок нажимает «назад» на ВИДИМОЕ окно,
//    и выход из матча вместо закрытия окна выглядел бы потерей данных на ровном месте.
//
// 2. Закрыли слой — сентинел ставится заново, если под ним ЕЩЁ есть слои ИЛИ идёт матч.
//    Сентинел это одна ступень истории; она тратится на каждое нажатие, и без нового
//    `pushState` следующий Back уйдёт мимо нас — в выгрузку страницы.
//
// 3. Матч идёт, закрывать нечего — первое нажатие только ПРЕДУПРЕЖДАЕТ. Аппаратный Back
//    на телефоне жмут вслепую и случайно; одно такое нажатие не должно стоить матча.
//
// 4. Второе нажатие в пределах окна выходит по-настоящему. Окно короткое (2.5 с) именно
//    потому, что подтверждение должно быть ОСОЗНАННЫМ: через минуту игрок уже не помнит
//    подсказку, и «второе» нажатие для него снова первое — поэтому по истечении окна
//    счёт начинается заново, с новой подсказки.
//
// 5. Матча нет (хаб, экран входа) — предупреждаем, но сентинел НЕ ставим: здесь следующий
//    Back и должен закрыть приложение. Ставить ступень значило бы запереть игрока внутри
//    вкладки, из которой он честно попросился выйти.
//
// 6. Кадровый цикл — это страховочная сетка, а не рабочий путь: он взводит сентинел, если
//    тот почему-то не взведён, но НЕ вмешивается в окно подсказки — там ступень уже
//    поставил обработчик `popstate`, и вторая ступень съела бы настоящее второе нажатие,
//    превратив выход в бесконечную подсказку.
//
// 7. Escape при наборе текста игнорируется. В поле ввода Escape — это «снять фокус /
//    отменить набор» самого браузера; перехватив его, мы бы закрыли окно ПОД полем, а
//    игрок увидел бы, что чат сожрал его реплику вместе с окном.
//
// 8. Шеврон ‹ никогда не показывает подсказку: видимая кнопка обязана срабатывать с
//    одного нажатия. Подсказка существует только потому, что аппаратный Back невидим и
//    жмётся случайно; на кнопке, в которую целятся пальцем, «нажмите ещё раз» читается
//    как поломка.

/** Вердикт аппаратного (или браузерного) Back. */
export type BackAction =
  /** Верхний слой закрыт — больше ничего не происходит. */
  | 'closed'
  /** Матч идёт, подтверждение получено — выходим в хаб. */
  | 'exit'
  /** Матч идёт, это первое нажатие — предупреждаем и ждём второго. */
  | 'hint'
  /** Матча нет — предупреждаем; следующее нажатие закроет приложение. */
  | 'leave';

/** Вердикт видимой кнопки ‹ — тех же состояний, но без ступени подтверждения. */
export type ChevronAction = 'closed' | 'exit' | 'system-back';

/** Окно двойного нажатия. `performance.now()` здесь уместен: это UI прототипа, а не ядро. */
export const BACK_EXIT_WINDOW_MS = 2500;

/** Ещё длится ли окно подтверждения после подсказки (правило 4). */
export function exitWindowOpen(now: number, hintAt: number): boolean {
  return now - hintAt <= BACK_EXIT_WINDOW_MS;
}

/**
 * Что делает нажатие Back. `closed` — уже полученный ответ лестницы (`backLayers.ts`):
 * закрытие слоя это побочный эффект, и решать по нему можно только ПОСЛЕ него.
 */
export function backAction(
  closed: boolean,
  inMatch: boolean,
  now: number,
  hintAt: number,
): BackAction {
  if (closed) return 'closed'; // правило 1
  if (!inMatch) return 'leave'; // правило 5
  return exitWindowOpen(now, hintAt) ? 'exit' : 'hint'; // правила 3–4
}

/** Ставить ли сентинел заново после закрытия слоя (правило 2). */
export function rearmAfterClose(moreLayers: boolean, inMatch: boolean): boolean {
  return moreLayers || inMatch;
}

/** Взводит ли сентинел подсказка «нажмите ещё раз» (правило 4: второму нажатию нужна своя ступень). */
export function rearmAfterHint(action: BackAction): boolean {
  return action === 'hint';
}

/** Страховочная сетка кадрового цикла (правило 6). */
export function selfHealArm(
  armed: boolean,
  layersOpen: boolean,
  inMatch: boolean,
  now: number,
  hintAt: number,
): boolean {
  if (armed) return false;
  return layersOpen || (inMatch && !exitWindowOpen(now, hintAt));
}

/** Набирает ли игрок текст прямо сейчас (правило 7). */
export function typingTarget(tagName: string | undefined, contentEditable: boolean): boolean {
  return contentEditable || tagName === 'INPUT' || tagName === 'TEXTAREA';
}

/** Спрашивать ли лестницу по нажатию клавиши (правило 7). */
export function escapeConsultsLadder(key: string, typing: boolean): boolean {
  return (key === 'Escape' || key === 'Esc') && !typing;
}

/** Что делает шеврон ‹ (правило 8). */
export function chevronAction(closed: boolean, inMatch: boolean): ChevronAction {
  if (closed) return 'closed';
  return inMatch ? 'exit' : 'system-back';
}
