/**
 * ONB-5: когда брифовать вернувшегося игрока и что показывать (REFM-74).
 *
 * Мир идёт, пока игрока нет: фоновая вкладка догоняет время при возврате, а на сервере
 * матч живёт круглосуточно. Дайджест «пока тебя не было» — ответ на это, но он же
 * легко превращается в назойливое окно, поэтому политика показа здесь важнее вёрстки.
 *
 * 1. **Уход засекается только В МАТЧЕ.** Свернуть вкладку в хабе — не отлучка из боя,
 *    и по возвращении брифовать нечего.
 * 2. **Короткий отскок брифинга не даёт.** Переключился на секунду и обратно — окно на
 *    полэкрана было бы наказанием за обычную работу с вкладками.
 * 3. **Точка отсчёта — ИГРОВОЕ время ухода**, а не реальное: пока игрока не было, мир
 *    мог прожить и час, и сутки, и сводка должна покрывать ровно этот отрезок.
 * 4. **Метка ухода одноразовая.** Не сняв её при возврате, второй возврат покажет тот
 *    же отрезок ещё раз.
 * 5. **Пустой дайджест не показывается** — брифинг ни о чём хуже, чем его отсутствие.
 * 6. **Сначала «внимание», потом остальное:** война, захват, потеря идут выше рутины,
 *    иначе важное утонет в списке.
 */

/** Короче этого отлучка не считается отлучкой. */
export const QUICK_GLANCE_MS = 15_000;

/** Засекать ли уход при скрытии вкладки (правило 1). */
export function marksAway(hidden: boolean, inMatch: boolean): boolean {
  return hidden && inMatch;
}

/** Состояние на момент возвращения. */
export interface ReturnState {
  /** Игровое время в момент ухода; `null` — ухода не засекали. */
  awayFromGameTime: number | null;
  /** Идёт ли матч сейчас. */
  inMatch: boolean;
  /** Реальное время ухода и возвращения. */
  awayAtRealMs: number;
  nowRealMs: number;
}

/**
 * С какого ИГРОВОГО момента брифовать вернувшегося — или `null`, если брифинг не нужен
 * (правила 1–3). Метку ухода вызывающий снимает в любом случае (правило 4).
 */
export function briefSince(st: ReturnState): number | null {
  if (st.awayFromGameTime === null || !st.inMatch) return null;
  if (st.nowRealMs - st.awayAtRealMs < QUICK_GLANCE_MS) return null;
  return st.awayFromGameTime;
}

/** Показывать ли собранный дайджест (правило 5). */
export function worthShowing(count: number): boolean {
  return count > 0;
}

/** Разбор списка на «внимание» и «остальное» с сохранением порядка (правило 6). */
export function splitByAttention<I extends { high: boolean }>(
  items: readonly I[],
): { hi: I[]; lo: I[] } {
  return { hi: items.filter((i) => i.high), lo: items.filter((i) => !i.high) };
}
