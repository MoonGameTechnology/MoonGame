/**
 * Зеркало опыта командующего: серверный итог против местного (REFM-53).
 *
 * Опыт копится за законченные матчи и живёт в двух местах сразу: на сервере — как
 * долговременный итог, общий для всех устройств, и локально — как то, что это
 * устройство уже успело начислить. Сводить их надо осторожно.
 *
 * 1. **Опыт ТОЛЬКО РАСТЁТ — берётся максимум, а не серверное число.** Сервер
 *    авторитетен по своей природе, но между «матч закончился» и «сервер зачёл награду»
 *    есть окно: устройство уже показало игроку новый уровень. Взять серверное число
 *    буквально значит отобрать уровень на глазах — и вернуть его через минуту. Оба
 *    сходятся сами, как только зачисление доедет.
 * 2. **Чужая форма тела не затирает местное.** `xp` обязан быть КОНЕЧНЫМ числом:
 *    строка, `null`, `NaN` и бесконечность — это «ответ непонятен», а не «опыта ноль».
 * 3. **Перерисовка только при изменении.** Панель хаба перерисовывается на каждом
 *    заходе, и без этого признака открытая вкладка дёргалась бы впустую.
 */

/** Итог сведения: сколько опыта теперь и надо ли перерисовывать панель. */
export interface XpSync {
  xp: number;
  changed: boolean;
}

/** Достать опыт из ответа сервера. `null` — ответ непонятен (правило 2). */
export function parseCommanderXp(body: unknown): number | null {
  const xp = (body as { xp?: unknown } | null)?.xp;
  return typeof xp === 'number' && Number.isFinite(xp) ? xp : null;
}

/**
 * Свести местный опыт с ответом сервера. Непонятный ответ оставляет всё как есть,
 * понятный — поднимает до максимума, но никогда не опускает (правило 1).
 */
export function syncCommanderXp(local: number, body: unknown): XpSync {
  const server = parseCommanderXp(body);
  if (server === null) return { xp: local, changed: false };
  const xp = Math.max(local, server);
  return { xp, changed: xp !== local };
}
