/**
 * Как клиент узнаёт, чем на этом сервере является позывной (REFM-154).
 *
 * Тринадцатый срез сетевой секции. Один и тот же клиент играет и на сервере с
 * аккаунтами (позывной — это ЛОГИН, его закрывает пароль), и на сервере без них
 * (позывной — просто имя). Что именно из этого — клиент спрашивает у `/auth/status`, и
 * весь разбор ответа стоял внутри `probeAuthMode`: `try`, короткое замыкание по `res.ok`,
 * приведение тела и `catch`, — четыре решения в одном выражении, причём каждое из них
 * когда-то было настоящей поломкой.
 *
 * 1. **Ответ «не 2xx» — это не ошибка, а ответ «аккаунтов тут нет».** Игру часто
 *    открывают с обычной раздачи файлов, где `/auth/status` отдаёт 404-страницу. Считать
 *    такой ответ бедой значит ругаться на самом обычном пути входа.
 * 2. **Тело разбираем ТОЛЬКО у ответа 2xx.** Голый `res.json()` на HTML-теле 404 бросал
 *    `SyntaxError` в консоль — ровно там, где ничего не сломано, и настоящие ошибки в
 *    этом шуме терялись.
 * 3. **Не дошли до сервера — это ОТДЕЛЬНЫЙ ответ «не знаю», а не «аккаунтов нет».**
 *    Для карточки входа разницы нет (поле пароля не раскрываем в обоих случаях), а вот
 *    для ДОПУСКА она решающая. Пока эти два случая были одним значением, оно попадало в
 *    `joinLanding` как «сервер без аккаунтов, пускать сразу» — и посторонний, открывший
 *    ссылку на партию, уезжал на карту вместо экрана входа: проба до сервера не дошла, а
 *    её молчание прочли как разрешение. Значение, спроектированное падать ОТКРЫТЫМ ради
 *    косметики, оказалось входом решения о доступе. Теперь оно этого не может: «не знаю»
 *    называется своим именем, а кто как его трактует — решает вызывающий.
 *    Режим аккаунтов по-прежнему включает ровно одно: честное «да» от живого сервера.
 * 4. **На приветственной карточке форму раскрывают только НОВИЧКУ.** Запомненный
 *    позывной значит, что карточку вообще пропустили, — раскрывать на ней логин и пароль
 *    незачем: их никто не увидит, а `suggestCallsign()` затёр бы уже введённое имя.
 */
import { httpBase } from './matchQuery';

/** Чем на этом сервере является позывной. */
export type IdentityMode =
  /** Позывной — логин, его закрывает пароль (SES-2.5). */
  | 'accounts'
  /** Позывной — просто имя, пароля нет (прежнее рукопожатие). */
  | 'nicks'
  /** Спросить не удалось — сервер не ответил или ответ не разобрался (правило 3).
   *  НЕ синоним `'nicks'`: там сервер сказал «аккаунтов нет», здесь он не сказал
   *  ничего. Решения о ДОПУСКЕ обязаны считать это закрытой дверью. */
  | 'unknown';

/** Ответ сервера в том виде, в каком его отдаёт `fetch` (правила 1–2). */
export interface ProbeResponse {
  ok: boolean;
  json: () => Promise<unknown>;
}

/** Адрес пробы — тот же сервер, что и сокет (`matchQuery.ts`, правило 2). */
export function authStatusUrl(wsBase: string): string {
  return `${httpBase(wsBase)}/auth/status`;
}

/**
 * Что означает проба `/auth/status` (правила 1–3). Запрос делает вызывающий: сюда
 * приходит функция, чтобы её сбой (связи нет) и сбой разбора тела попадали в тот же
 * разбор, а не расползались по двум `catch` в разных местах.
 */
export async function identityMode(probe: () => Promise<ProbeResponse>): Promise<IdentityMode> {
  try {
    const res = await probe();
    if (!res.ok) return 'nicks'; // правило 1: 404 — это ответ, а не беда
    const body = (await res.json()) as { enabled?: unknown }; // правило 2: только у 2xx
    return body.enabled === true ? 'accounts' : 'nicks';
  } catch {
    return 'unknown'; // правило 3: не дошли или тело не разобралось — мы НЕ ЗНАЕМ
  }
}

/** Раскрывать ли логин с паролем прямо на приветственной карточке (правило 4). */
export function revealSignup(mode: IdentityMode, rememberedNick: string): boolean {
  return mode === 'accounts' && rememberedNick.trim() === '';
}
