import type { GameState, PlanetId, PlayerId } from './gameState';

/**
 * Чей это мир В ГЛАЗАХ игрока — тот владелец, которого он видит на своей карте.
 *
 * Правила, у которых исход зависит от владельца мира (право прохода), не должны
 * отвечать по НАСТОЯЩЕМУ владельцу там, где игрок его не видит: иначе отказ становится
 * разведкой. «Нет права прохода» в ответ на приказ в неразведанную провинцию говорит
 * игроку, что там чужая территория, а окно войны в соло ещё и называет хозяина.
 *
 * Ответ:
 *  · свой мир — свой (свои границы игрок знает всегда);
 *  · мир из памяти тумана (`state.fog`, её пишет модуль видимости и обновляет на каждом
 *    шаге часов, так что опознанный СЕЙЧАС мир там свежий) — владелец из снимка;
 *  · мир, которого игрок не видел, — `null`: для него это ничья земля;
 *  · памяти нет вовсе (`state.fog` отсутствует) — настоящий владелец. Так деградирует
 *    хост без модуля видимости (тумана нет, всё видно), и так же читается проекция
 *    сетевого клиента: `visibleState` срезает `fog`, а владельцев неопознанных миров
 *    уже подменил памятью или `null` — то есть в ней настоящий владелец и есть видимый.
 */
export function knownOwner(state: GameState, viewerId: PlayerId, planetId: PlanetId): PlayerId | null {
  const planet = state.planets[planetId];
  if (!planet) return null;
  if (planet.owner === viewerId) return viewerId;
  if (state.fog === undefined) return planet.owner;
  const snap = state.fog[viewerId]?.[planetId];
  return snap ? snap.owner : null;
}
