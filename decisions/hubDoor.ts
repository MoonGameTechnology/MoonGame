/**
 * Главная дверь хаба (UIX-10.1): одна крупная кнопка над списком режимов.
 *
 * Хаб открывают ради одного из двух дел — вернуться в начатую партию или, новичку, пройти
 * обучение. Раньше главной кнопкой стояло «ИГРАТЬ СЕЙЧАС» (сетевой обозреватель), под ней
 * в одинаковом сером виде «Продолжить одиночную партию», «Одиночная игра», «Sector Zero» и
 * «Полигон», а предложение обучения ждало ниже, карточкой между ними и «Моими партиями».
 *
 * 1. **Есть одиночное сохранение — дверь «Продолжить»**, с картой и днём партии, даже у
 *    новичка: начатое важнее урока, а обучение остаётся в «Ещё → Обучение».
 * 2. **Сохранение не читается — та же дверь, но закрытая.** Причину пишет строка под ней.
 *    Спрятать дверь значило бы молча потерять партию: сохранение не удаляется, и игрок
 *    должен видеть, что оно есть.
 * 3. **Сохранения нет, обучение не пройдено и не пропущено — «Начать обучение».**
 * 4. **Иначе двери нет.** Список режимов и есть выбор; кнопка, повторяющая «Одиночную
 *    игру» строкой ниже, была бы шумом.
 */

/** Одиночное сохранение, как его прочитал клиент. */
export type SoloSaveSlot =
  /** Слот пуст. */
  | 'empty'
  /** Хранилище недоступно или сохранение не разбирается этой версией. */
  | 'unreadable'
  /** Читаемая партия: её карта и время мира. */
  | { mapId: string; time: number };

export type HubDoor =
  | { kind: 'continue'; mapId: string; time: number }
  | { kind: 'broken' }
  | { kind: 'tutorial' }
  | { kind: 'none' };

/** Какая дверь стоит над режимами (правила 1–4). `newcomer` — обучение не пройдено и не
 *  пропущено (`welcomeMode` прототипа). */
export function hubDoor(save: SoloSaveSlot, newcomer: boolean): HubDoor {
  if (typeof save === 'object') return { kind: 'continue', mapId: save.mapId, time: save.time };
  if (save === 'unreadable') return { kind: 'broken' };
  return newcomer ? { kind: 'tutorial' } : { kind: 'none' };
}
