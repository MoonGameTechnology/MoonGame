/**
 * Два тира зенитного огня: чем ближняя зенитка отличается от орбитального залпа (REFM-112).
 *
 * Планета отстреливается от чужих эскадр дважды по-разному: раз в час уходит тяжёлый
 * ОРБИТАЛЬНЫЙ залп, а каждые 15 минут работает БЛИЖНЯЯ зенитка. На карте это два разных
 * события, и игрок обязан различать их не читая журнал. Отличия стояли семью тернарниками
 * `shot.close ? … : …`, разбросанными по одному кадру рисования, — и из них не читалось,
 * что это ОДНА таблица: поправишь цвет, забудешь про сияние, и тиры сольются.
 *
 * Жизнь и затухание сюда не копируются: ими заведует `flashFx.ts` (REFM-70), и до этого
 * выноса в кадре лежала их третья копия (`age > 700`, `1 - age / 700`) — ровно та
 * ошибка, от которой предостерегает шапка `fogView.ts`.
 *
 * 1. **Тир решает ВЕСЬ вид разом** — цвет трассы, её яркость и толщину, рисунок штриха,
 *    силу сияния, цвет вспышки и её размер. Одно решение, одна запись.
 * 2. **Ближний огонь ТИШЕ орбитального по всем осям сразу:** бледнее, тоньше, мельче,
 *    холоднее. Он и случается вчетверо чаще — сравняй их, и частая мелочь утопит редкое
 *    тяжёлое событие в шуме.
 * 3. **Вспышка попадания РАСТЁТ от стартового радиуса** — попадание читается как
 *    расширяющийся хлопок, а не как точка, которая просто гаснет.
 * 4. **Трасса ПОЛЗЁТ вверх** (штрих сдвигается со временем): неподвижный пунктир читался
 *    бы как статичная линия связи, а не как очередь, уходящая от поверхности.
 */

/** Тир зенитного огня. */
export type FlakTier = 'orbital' | 'close';

/** Как выглядит этот тир (правила 1–2). */
export interface FlakLook {
  /** Цвет трассы и её сияния. */
  color: string;
  /** Непрозрачность трассы до затухания. */
  alpha: number;
  /** Толщина трассы. */
  width: number;
  /** Рисунок штриха. */
  dash: readonly [number, number];
  /** Сила сияния до поправки на графические настройки. */
  blur: number;
  /** Цвет вспышки попадания. */
  burstColor: string;
  /** Стартовый радиус вспышки. */
  burstFrom: number;
  /** На сколько вспышка вырастает за свою жизнь (правило 3). */
  burstGrow: number;
}

/** Жизнь трассы в миллисекундах — одна на оба тира. */
export const FLAK_LIFE_MS = 700;
/** Делитель хода штриха: чем меньше, тем быстрее ползёт трасса (правило 4). */
const DASH_SPEED = 12;

const LOOKS: Record<FlakTier, FlakLook> = {
  // Часовой залп с орбиты: тяжёлое оранжевое копьё — редкое и заметное.
  orbital: {
    color: '#ff8a3d',
    alpha: 0.7,
    width: 1.1,
    dash: [3, 5],
    blur: 8,
    burstColor: '#ffd29b',
    burstFrom: 2,
    burstGrow: 5,
  },
  // Ближняя зенитка каждые 15 минут: тоньше, бледнее, холоднее и с меньшим хлопком.
  close: {
    color: '#9adfe8',
    alpha: 0.55,
    width: 0.8,
    dash: [2, 4],
    blur: 5,
    burstColor: '#d9f4f7',
    burstFrom: 1.5,
    burstGrow: 3,
  },
};

/** Тир по признаку «это ближняя зенитка». */
export function flakTier(close: boolean): FlakTier {
  return close ? 'close' : 'orbital';
}

/** Весь вид тира одной записью (правило 1). */
export function flakLook(tier: FlakTier): FlakLook {
  return LOOKS[tier];
}

/** Радиус вспышки попадания в этом возрасте трассы (правило 3). */
export function flakBurstRadius(look: FlakLook, progress: number): number {
  return look.burstFrom + progress * look.burstGrow;
}

/** Сдвиг штриха: трасса ползёт от поверхности вверх (правило 4). */
export function flakDashOffset(ageMs: number): number {
  return -ageMs / DASH_SPEED;
}
