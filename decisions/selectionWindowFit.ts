/**
 * Ширина окна выбора на ПК — по содержимому (UIX-14.2).
 *
 * Окно сведений на ПК горизонтальное: сведения текут колонками газетой, чтобы низ не уходил
 * под прокрутку (решение владельца 2026-09-26). Ширина у окна была одна — 1040 px, — и
 * карточка из трёх строк и шести кнопок растягивалась на весь экран, а три колонки из четырёх
 * стояли пустыми. Заказ владельца 2026-10-16 по окну эскадры в воздухе: «окно растянуто, хотя
 * контента там для этого нет. Нужно, чтоб размер окна зависел от заполнения». Окно мира
 * сжимается по числу блоков вкладки с 2026-09-29 (UIX-14.1); здесь — все остальные карточки:
 * эскадра в воздухе, чужой флот, группа флотов, мина, ракета, развилка дорог.
 *
 * 1. **Окно — наименьшее, в котором видно всё.** Ширина растёт колонкой газеты только тогда,
 *    когда содержимое не влезло в прежнюю ступень.
 * 2. **Колонку добавляет только высота.** Колонка нужна, когда сведения не влезли в окно по
 *    высоте, — так горизонтальное окно и осталось окном без прокрутки.
 * 3. **Ступени — колонки по ~230 px.** Одна, две, три и четыре колонки — те же 440, 560, 810 и
 *    1040 px, что у окна мира (`holographic.css`). Рядом с колонкой приказов (320 px) места на
 *    две: 760 и прежние 1040 px.
 * 4. **Не влезло и в последнюю ступень — последняя ступень.** Окно не шире, чем было до правки.
 * 5. **Своя раскладка — своя ширина.** Окно флота консолью (макет владельца 2026-09-27),
 *    раскрытые подробности и окно мира со вкладками или без разведки меряют себя сами;
 *    окно одних приказов узкое и без газеты.
 */

/** Раскладка окна, которой ширина подбирается по содержимому. */
export type FitLayout =
  /** Одни сведения: колонки газеты на всю ширину окна. */
  | 'info'
  /** Приказы столбцом слева, сведения газетой справа. */
  | 'orders';

/** Сколько колонок газеты может занять раскладка (правило 3). */
export const FIT_MAX_COLUMNS: Readonly<Record<FitLayout, number>> = { info: 4, orders: 2 };

/** Что видно в окне выбора прямо сейчас. */
export interface SelectionWindowShape {
  /** В окне сведения о выбранном. */
  info: boolean;
  /** В окне ряд приказов. */
  commands: boolean;
  /** Окно флота консолью. */
  fleetConsole: boolean;
  /** Раскрыта секция подробностей. */
  details: boolean;
  /** Окно мира со вкладками или без разведки. */
  world: boolean;
}

/** Подбирать ли окну ширину по содержимому и в какой раскладке; `null` — у окна своя (правило 5). */
export function fitLayout(shape: SelectionWindowShape): FitLayout | null {
  if (!shape.info || shape.fleetConsole || shape.details || shape.world) return null;
  return shape.commands ? 'orders' : 'info';
}

/**
 * Сколько колонок газеты нужно окну (правила 1, 2 и 4). `hidesContent(n)` — прячет ли окно
 * в `n` колонок часть содержимого: его ставят на ступень и меряют.
 */
export function fitColumns(layout: FitLayout, hidesContent: (columns: number) => boolean): number {
  const most = FIT_MAX_COLUMNS[layout];
  for (let columns = 1; columns < most; columns++) if (!hidesContent(columns)) return columns;
  return most;
}
