/**
 * Какие флоты попадают под тап по карте и в каком порядке (REFM-164).
 *
 * Кто ЗАБИРАЕТ тап, решает `tapPriority.ts` (REFM-64), а что делать с перебором стопки —
 * `tapCycle.ts` (REFM-65). Между ними оставался сбор самих претендентов: три звена
 * (видимость, радиус, порядок) стояли одной цепочкой `filter().map().filter().sort()`
 * прямо в `selectAt`, и ни одно из них не объясняло себя.
 *
 * 1. **Под тап попадают свои и ВИДИМЫЕ чужие.** Чужой флот выделяется для ОСМОТРА —
 *    панель покажет состав без кнопок приказов. Но только опознанный или пойманный
 *    радаром: выделить флот, которого игрок не видит, значит выдать разведданные, которых
 *    у него нет, — туман войны обходится одним тапом по пустому месту.
 * 2. **Флот без рисуемой позиции — не претендент.** Точки нет (флот нечем показать на
 *    карте) — значит, тапнуть по нему игрок не мог: засчитать такое попадание значит
 *    выделить невидимое, причём тем вернее, чем ближе тап к центру экрана.
 * 3. **Радиус — это «в пределах», а не «ближе всех».** Объект за радиусом не претендент
 *    вовсе, и радиус у пальца шире, чем у курсора (правило 44 пикселей): иначе на телефоне
 *    попасть в флот можно было бы только чудом.
 * 4. **Ближайший первым.** Порядок нужен обеим веткам: мобильной (ей нужен только первый)
 *    и перебору на ПК (ему нужны все по очереди). Без сортировки «ближайший» зависел бы от
 *    порядка обхода объекта флотов — то есть от того, в каком порядке их создали, а не от
 *    того, куда игрок целился.
 */

/** Флот глазами тапа: свой ли, видно ли его и где он нарисован. */
export interface FleetAt {
  id: string;
  /** Свой флот — видимость не спрашивают (правило 1). */
  mine: boolean;
  /** Чужой опознан или пойман радаром (`fogView.ts`). */
  visible: boolean;
  /** Точка на экране; `null` — рисовать негде (правило 2). */
  anchor: { x: number; y: number } | null;
}

/** Претенденты под тапом, ближайший первым (правила 1–4). */
export function fleetsUnderTap(
  fleets: Iterable<FleetAt>,
  x: number,
  y: number,
  radius: number,
): string[] {
  const hits: Array<{ id: string; d: number }> = [];
  for (const f of fleets) {
    if (!f.mine && !f.visible) continue; // правило 1
    if (!f.anchor) continue; // правило 2
    const d = Math.hypot(x - f.anchor.x, y - f.anchor.y);
    if (d < radius) hits.push({ id: f.id, d }); // правило 3
  }
  hits.sort((a, b) => a.d - b.d); // правило 4
  return hits.map((h) => h.id);
}
