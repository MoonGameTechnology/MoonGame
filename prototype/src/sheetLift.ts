/**
 * Подъём камеры из-под нижнего листа на телефоне (REFM-83).
 *
 * На телефоне панель выезжает снизу и закрывает примерно половину экрана. Открылась она
 * ПРО выбранный объект — и обидно, если именно его и накрыла. Поэтому в момент открытия
 * камера подтягивает объект в видимую верхнюю половину.
 *
 * 1. **Двигаем только в МОМЕНТ открытия** (закрыт → открыт). `renderPanel` гоняется
 *    каждый кадр, и без этого условия камера ползла бы всё время, пока лист открыт.
 * 2. **Только на телефоне.** На ПК панель стоит сбоку и карту не закрывает — там подъём
 *    был бы рывком без причины.
 * 3. **Двигаем, только если объект НИЖЕ порога.** Над порогом он и так виден, а лишний
 *    скачок камеры сбивает игрока с того места, куда он только что смотрел.
 * 4. **Поднимаем до `SHEET_TARGET`** — в верхнюю половину, а не впритык к порогу: иначе
 *    объект встанет ровно на кромку листа.
 * 5. **Порог и цель — доли высоты экрана, а не пиксели.** Лист меряется в `vh`, и на
 *    длинном экране пиксельный порог сработал бы не там.
 */

/** Ниже этой доли высоты объект прячется под листом. */
export const SHEET_HIDDEN = 0.42;

/** Куда поднимаем: доля высоты от верха экрана. */
export const SHEET_TARGET = 0.3;

/** Открылся ли лист прямо сейчас — и надо ли вообще двигать камеру (правила 1–2). */
export function opensNow(open: boolean, was: boolean, mobile: boolean): boolean {
  return open && !was && mobile;
}

/** На сколько поднять камеру; 0 — двигать не нужно (правила 3–5). */
export function liftBy(anchorY: number | null, vh: number): number {
  if (anchorY === null || anchorY <= vh * SHEET_HIDDEN) return 0;
  return anchorY - vh * SHEET_TARGET;
}
