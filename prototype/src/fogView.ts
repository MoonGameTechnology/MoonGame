/**
 * Что игрок видит про узел карты под туманом (REFM-62).
 *
 * Туман прячет чужие миры, но не саму карту: сетка путей должна оставаться целой, иначе
 * игрок не поймёт, куда вообще можно лететь. Отсюда четыре разных вида одного узла.
 *
 * 1. **Пустой узел — НЕ секрет.** У него нет ни владельца, ни гарнизона, ни построек:
 *    прятать нечего. Спрятать его значило бы оставить дыру в сетке путей — карта
 *    соврала бы о собственной топологии, а не о чужих силах.
 * 2. **Неопознанный мир показывается ПАМЯТЬЮ, а не правдой.** Последнее, что игрок
 *    видел своими глазами, — честная информация; нынешнее состояние — нет. Подставь
 *    сюда текущее, и туман перестанет что-либо скрывать.
 * 3. **Никогда не виденный мир — это «?», а не пустое место.** Игрок должен знать, что
 *    система там ЕСТЬ: скрыт её состав, а не её существование.
 * 4. **Свой мир виден в деталях без опознания.** Опознание — про чужое; требовать его
 *    для собственного тыла значит ослепить игрока на своей же территории.
 *
 * Правило 4 живёт ОДНОЙ функцией специально: оно нужно и панели, и отрисовке радиусов,
 * и когда условие было выписано дважды, второе место про него забыли — тап по
 * неисследованной системе рисовал её радарные окружности с подписями, выдавая и
 * владельца, и наличие радара, и его радиус, пока панель честно писала «нет телеметрии».
 */

/** Каким показывать узел. */
export type NodeView =
  | 'void' // пустой узел — чистая геометрия, всегда виден (правило 1)
  | 'full' // опознан — полная картинка
  | 'remembered' // не опознан, но виден в памяти — последнее известное (правило 2)
  | 'unexplored'; // никогда не видели — «?» (правило 3)

/** Что известно про узел на момент отрисовки. */
export interface NodeSight {
  /** Тип сектора; `'empty'` — путевая точка. */
  sector: string;
  /** Опознан ли узел прямо сейчас (или туман выключен). */
  identified: boolean;
  /** Есть ли о нём запись в памяти разведки. */
  remembered: boolean;
}

/** Решить, каким видом рисовать узел. */
export function nodeView(sight: NodeSight): NodeView {
  if (sight.sector === 'empty') return 'void'; // правило 1
  if (sight.identified) return 'full';
  return sight.remembered ? 'remembered' : 'unexplored'; // правила 2–3
}

/**
 * Видно ли мир В ДЕТАЛЯХ: опознан ИЛИ свой (правило 4). Одно место на весь клиент —
 * им пользуются и панель, и отрисовка радарных радиусов.
 */
export function seesDetails(sight: { identified: boolean; mine: boolean }): boolean {
  return sight.identified || sight.mine;
}
