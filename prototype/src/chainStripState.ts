/**
 * Что показывает полоска режима «Приказ» и какие её кнопки живы (REFM-79).
 *
 * Полоска — единственный орган управления режимом: пока она врёт, игрок жмёт кнопки,
 * которые ничего не сделают, или не видит той единственной, что ему нужна.
 *
 * 1. **Самогашение: режим не висит над пустотой.** Флоты гибнут и меняют владельца прямо
 *    во время планирования; чужие и погибшие выпадают из режима, а если не осталось ни
 *    одного — режим закрывается сам.
 * 2. **«Отменить» живёт по ЖЕСТАМ, а не по шагам.** Наращивание часов повторными тапами
 *    складывается в один жест из нескольких шагов, и снимать его надо целиком.
 * 3. **«Домой» доступна, только если план ещё влезает по шагам И у финиша есть свой
 *    мир.** Иначе кнопка обещает шаг, которого не будет.
 * 4. **Пустой черновик при живом плане — это «Очистить», а не «Отправить».** Другого
 *    способа снять уже отправленный приказ у игрока нет.
 * 5. **Отправлять можно либо непустой черновик, либо пустой поверх живого плана** (тот
 *    же случай стирания); пустое поверх пустого — кнопка ни о чём.
 * 6. **Предупреждение о перезаписи — когда у выбранных флотов РАЗНЫЕ планы.** Один
 *    приказ затрёт несколько разных, и сказать об этом надо ДО отправки.
 */

/** Флоты, остающиеся в режиме: живые и всё ещё свои (правило 1). */
export function stayingFleets(
  ids: readonly string[],
  ownerOf: (id: string) => string | null | undefined,
  me: string,
): string[] {
  return ids.filter((id) => ownerOf(id) === me);
}

/** Вход для состояния полоски. */
export interface StripInput {
  /** Шаги черновика. */
  steps: number;
  /** Границы жестов черновика. */
  gestures: number;
  /** Потолок шагов из ядра. */
  cap: number;
  /** Живые планы выбранных флотов, сериализованные для сравнения. */
  plans: readonly string[];
  /** Есть ли у финиша черновика свой мир, куда вести «Домой». */
  hasHome: boolean;
}

/** Что полоска показывает и что на ней нажимается. */
export interface StripState {
  canUndo: boolean;
  canHome: boolean;
  clearMode: boolean;
  canSend: boolean;
  overwrite: boolean;
}

/** Есть ли у кого-то из выбранных живой план. */
export function anyLivePlan(plans: readonly string[]): boolean {
  return plans.some((p) => p !== '[]');
}

/** Разные ли планы у выбранных флотов — значит отправка их перезапишет (правило 6). */
export function plansDiffer(plans: readonly string[]): boolean {
  return plans.some((p) => p !== plans[0]);
}

/** Состояние полоски целиком (правила 2–6). */
export function stripState(input: StripInput): StripState {
  const live = anyLivePlan(input.plans);
  return {
    canUndo: input.gestures > 0,
    canHome: input.steps < input.cap && input.hasHome,
    clearMode: input.steps === 0 && live,
    canSend: input.steps > 0 || live,
    overwrite: plansDiffer(input.plans),
  };
}
