/**
 * ИМЯ ПРОВИНЦИИ для игрока (PVR-6.19, просьба владельца 2026-09-25: «нормальные имена
 * провинциям»).
 *
 * На картах глав Sector Zero игрок видел идентификаторы узлов: подпись на карте и строки
 * журнала — `home_a`, `spore_cloud`, `pirate_den`, а заголовок карточки — хэш-имя
 * (`HELIOS-3`, `prototype/src/planetName.ts`). У одного мира было два имени, и ни одно не
 * было именем.
 *
 * 1. **Имя — текст для игрока, поэтому живёт в `/localization`, а не в карте.** Ключ
 *    ВЫВОДИТСЯ из id карты и узла: `province.<карта>.<узел>`, подчёркивания узла — в
 *    дефисы (`home_a` → `province.pve-1.home-a`). Карта (`data/maps`), данные и манифест
 *    не меняются: имя — подпись клиента, а не правило мира.
 * 2. **Ключ — по КАРТЕ, а не по одному узлу.** Одни и те же id узлов (`drift`, `veil`,
 *    `home_a`) стоят на разных картах, и у каждой карты свои имена.
 * 3. **Нет имени — `null`, и запасной текст выбирает ВЫЗЫВАЮЩИЙ.** У песочницы имён нет
 *    (сетка `C2R1`, сотня узлов на frontier), и там у каждого места своя привычка:
 *    карточка мира показывает хэш-имя, подпись и журнал — координату. Решение не
 *    выбирает за них и не выдаёт ключ вместо имени.
 *
 * Полноту имён карт глав держит тест рядом: каждый узел `pve-*` назван на обоих языках,
 * и пропущенное имя не доедет до игрока сырым id. Импорт — из `core`, а не `runtime`:
 * клиент грузит одну локаль (LOC-6), как в `refusalText.ts`.
 */
import { hasKey, t } from '../localization/core';

/** Ключ имени узла `nodeId` на карте `mapId` (правила 1–2). */
export function provinceKey(mapId: string, nodeId: string): string {
  return `province.${mapId}.${nodeId.replace(/_/g, '-')}`;
}

/** Имя провинции на языке игрока; `null` — у карты имён нет (правило 3). */
export function provinceName(mapId: string | undefined, nodeId: string): string | null {
  if (mapId === undefined) return null;
  const key = provinceKey(mapId, nodeId);
  return hasKey(key) ? t(key) : null;
}
