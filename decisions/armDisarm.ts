/**
 * Что гаснет, когда игрок жмёт СОСЕДНЮЮ команду ряда (REFM-195), и что гасит всё
 * остальное: Back, смена матча, пустое выделение, ✕ окна выбора, отмена мобильного
 * приказа, спрятанный ряд (REFM-207). Какие из этих поводов забывают и сам выбор —
 * правило 16 (REFM-208).
 *
 * У командного ряда семь взводимых состояний: прицелы (слияние, обстрел, штурм), три
 * поповера-меню (огонь, каст, десант) и набор группы. Преамбула обработчика гасила их
 * восемью рукописными `if`'ами вида «команда не моя ⇒ гасну», у каждого свой список
 * исключений. Ошибается это ТИХО и двумя разными способами, оба уже случались бы сами
 * собой при добавлении новой кнопки:
 *
 *  · забыли внести подкоманду в список СВОЕГО состояния — и меню закрывается под пальцем
 *    от собственной же кнопки («+1» десанта гасил бы ⇅-меню);
 *  · забыли внести НОВОЕ состояние в преамбулу — и взведённый прицел переживает чужой
 *    приказ, а следующий тап по карте срабатывает не тем, чего игрок ждал.
 *
 * Правила ниже — таблица вместо россыпи, каждое с причиной.
 *
 * 1. **Состояние держится только СВОИМИ командами.** Взведённый прицел — это обещание
 *    «следующий тап значит вот это»; чужой приказ обещание отменяет, иначе игрок целится
 *    одним, а попадает другим.
 * 2. **Список своих команд включает подкоманды меню.** Поповер живёт, пока игрок работает
 *    ВНУТРИ него: `fmset` для огня, `castdo` для каста, `tstep`/`tmax`/`tok` для десанта.
 *    Без них меню закрывалось бы от нажатия на собственную кнопку.
 * 3. **У набора группы своими считаются `pick` и `more`.** Настоящий приказ выводит из
 *    набора (группа уже выделена и приказ примет), а ☰ и сам переключатель ⊕ — нет:
 *    они часть той же сессии выбора.
 * 4. **Кнопка без команды гасит ВСЁ.** `dataset.cmd` может быть пустым; трактовать это как
 *    «команда неизвестна, значит своя» значило бы оставить взведённым то, что игрок уже
 *    ничем не подтвердит.
 * 5. **Прицелы, у которых нет своей кнопки в ряду, гаснут от ЛЮБОЙ его кнопки.** Их
 *    подтверждает тап по карте (герой, высадка, удар крыла, отход, приказ союзнику) или по
 *    карточке базы (слияние звеньев), поэтому «своей» команды в ряду у них нет вовсе.
 * 6. **`chainMode` в таблицу НЕ входит — и это решение, а не пропуск.** В режиме цепочки
 *    полоска ЗАМЕНЯЕТ ряд: других команд там физически нет, а выход только своими кнопками
 *    (`chexit`/`chsend`), Back и Escape.
 * 7. **«Курс» гасят команды, которые взводят другое намерение или открывают поповер
 *    ряда.** Прямой приказ (стоп, форс-марш, авто-штурм) и ☰ его не трогают: включить
 *    форс-марш и потом ткнуть в точку — обычный порядок. Порог отхода (`qretr`) — такой же
 *    поповер, как деление, десант и каст, и гасит «Курс» наравне с ними.
 *
 * Остальные поводы (REFM-207). Раньше каждый был своим рукописным списком, и двух
 * одинаковых среди одиннадцати не было: смена матча в соло гасила одно, в сети другое, а
 * прицелы героя, удара и союзника не гасили ни она, ни Back.
 *
 * 8. **Смена матча гасит ВСЁ.** Прицел или меню старого матча указывают на флоты, героев
 *    и базы, которых в новом нет; соло и сеть идут одной строкой.
 * 9. **Back снимает любой прицел, но не поповер — у поповеров своя ступень выше.** Прицел
 *    героя, удара, союзника и слияния звеньев переживал Back, и следующий тап по карте
 *    срабатывал. На ПК «Атака» и набор группы уходили мимо ступени прицела: Escape снимал
 *    выделение целиком, а не прицел, как у «Курса».
 * 10. **Пустое выделение гасит всё, что держится за выделение, и только это.** Прицелы
 *     ряда, набор группы, меню ряда, окно деления, слияние звеньев (его подтверждают в
 *     панели, которая закрылась). Прицелы из окон — отход (окно боя), каст и высадка (окно
 *     героя), удар (карточка базы), приказ союзнику (его окно) — взводятся без выделения и
 *     им не отменяются. На ПК набор группы раньше переживал снятие выделения и держал
 *     пустое окно «0 флотов» (плейтест 2026-09-26).
 * 11. **✕ окна выбора — это пустое выделение и ☰.** Крестик закрывает окно целиком.
 * 12. **Отмена мобильного приказа гасит то, что ждёт подтверждения в его полоске:**
 *     «Курс», штурм, атаку, слияние и набор группы.
 * 13. **Спрятанный ряд гасит то, что живёт В РЯДУ:** его прицелы и меню. Окно деления
 *     живёт своим правилом (`splitDialog.ts`), а прицелы из окон ряда не требуют.
 * 14. **☰ на телефоне — поповер, на ПК — вид ряда.** Телефон сворачивает его пустым
 *     выделением, Back и выбором приказа; на ПК он остаётся, как его оставил игрок.
 * 15. **Взведённый прицел гасит остальные прицелы.** Два прицела сразу — это тап, который
 *     сработает не тем: владельца тапа выберет приоритет, а игрок целился последним.
 *     Поповер при этом не гаснет: меню — не намерение для карты.
 * 16. **Выбор забывают три повода: смена матча, пустое выделение и ✕ окна выбора**
 *     (REFM-208). Выбор — это выделенные флоты или мир, осмотр чужого флота, цель
 *     мобильного приказа на подтверждении и список «флот или мир». Флоты старого матча в
 *     новом не существуют, а id стартовых флотов (`p2-1`) повторяются: осмотр чужого флота
 *     переживал смену матча в соло и показывал флот нового матча с тем же id. Пустое
 *     выделение и ✕ и есть забытый выбор. Back, отмена мобильного приказа и спрятанный ряд
 *     выбор держат: снимается прицел, а выделение остаётся (правило 9).
 */

/** Взводимое состояние командного ряда, которое гаснет от чужой команды. */
export type ArmedState = 'merge' | 'cast' | 'troops' | 'assault' | 'engage' | 'retreat' | 'pick';

/**
 * Команды, при которых состояние ОСТАЁТСЯ взведённым. Правила 2–3: сюда входят и
 * подкоманды поповера, и то, что не считается «настоящим приказом».
 */
export const KEEPS_ARMED: Record<ArmedState, readonly string[]> = {
  merge: ['merge'],
  cast: ['cast', 'castdo'],
  troops: ['troops', 'tstep', 'tmax', 'tok'],
  assault: ['attack'],
  // ATK-1: «Атака» держится только своей кнопкой — как и остальные прицелы.
  engage: ['engage'],
  // Окошко порога авто-отхода держит только своя кнопка: выбор ступени (`retrset`) — это
  // уже приказ, и окошко после него закрывается.
  retreat: ['qretr'],
  pick: ['pick', 'more'],
};

/**
 * Прицелы, которые гасит ЛЮБАЯ кнопка ряда (правило 5). Список называет то, у чего своих
 * команд в ряду нет вовсе, и объясняет, почему их нет в таблице.
 */
export const ALWAYS_DISARMED = [
  'heroAim',
  'heroSpawnAim',
  'strikeAim',
  'retreatAim',
  'allyAim',
  'squadMerge',
] as const;

/** Правила 1, 2 и 4: остаётся ли состояние взведённым при этой команде. */
export function keepsArmed(state: ArmedState, cmd: string | undefined): boolean {
  return cmd !== undefined && KEEPS_ARMED[state].includes(cmd);
}

/** Читается на месте вызова лучше отрицания: гасит ли эта команда состояние. */
export function disarms(state: ArmedState, cmd: string | undefined): boolean {
  return !keepsArmed(state, cmd);
}

/** Всё, что взводится или открывается поверх ряда и карты. Имя — переменная владельца. */
export type Flag =
  | 'aiming'
  | 'assaultAim'
  | 'engageAim'
  | 'merging'
  | 'pickMode'
  | 'retreatAim'
  | 'heroAim'
  | 'heroSpawnAim'
  | 'strikeAim'
  | 'allyAim'
  | 'squadMerge'
  | 'cmdMore'
  | 'castMenu'
  | 'retreatMenu'
  | 'troopsPlan'
  | 'splitState';

/** Прицелы: следующий тап (по карте, у слияния звеньев — по карточке) значит вот это. */
export const AIMS: readonly Flag[] = [
  'aiming',
  'assaultAim',
  'engageAim',
  'merging',
  'pickMode',
  'retreatAim',
  'heroAim',
  'heroSpawnAim',
  'strikeAim',
  'allyAim',
  'squadMerge',
];

/** Поповеры и окно ряда: не намерение для карты, а открытое меню. */
export const POPOVERS: readonly Flag[] = [
  'cmdMore',
  'castMenu',
  'retreatMenu',
  'troopsPlan',
  'splitState',
];

/** Всё вместе: смена матча гасит именно это (правило 8). */
export const FLAGS: readonly Flag[] = [...AIMS, ...POPOVERS];

/**
 * Повод погасить. Кнопка ряда — отдельно (`commandDisarms`): там решает сама команда. У
 * окна деления своя ступень Back, и гасит она его одно — это не список, а один флаг.
 */
export type Reason =
  'match' | 'back-aim' | 'back-popover' | 'deselect' | 'dismiss' | 'mobile-cancel' | 'bar-hidden';

/** Прицелы и меню, живущие в ряду (правила 10 и 13). */
const ROW_AIMS: readonly Flag[] = ['aiming', 'assaultAim', 'engageAim', 'merging'];
const ROW_MENUS: readonly Flag[] = ['castMenu', 'retreatMenu', 'troopsPlan'];
const DESELECT: readonly Flag[] = [
  ...ROW_AIMS,
  'pickMode',
  ...ROW_MENUS,
  'splitState',
  'squadMerge',
];

/** Что гасит каждый повод на обеих платформах. */
export const DISARMED_BY: Record<Reason, readonly Flag[]> = {
  match: FLAGS, // правило 8
  'back-aim': AIMS, // правило 9
  'back-popover': ROW_MENUS, // правило 9: ступень поповеров выше ступени прицела
  deselect: DESELECT, // правило 10
  dismiss: [...DESELECT, 'cmdMore'], // правило 11
  'mobile-cancel': [...ROW_AIMS, 'pickMode'], // правило 12
  'bar-hidden': [...ROW_AIMS, ...ROW_MENUS], // правило 13
};

/** Что телефон гасит сверх этого: ☰ там поповер (правило 14). */
export const PHONE_ALSO: Partial<Record<Reason, readonly Flag[]>> = {
  deselect: ['cmdMore'],
  'back-popover': ['cmdMore'],
};

/** Правила 8–14: что гасит повод на этой платформе. */
export function disarmedBy(reason: Reason, phone: boolean): Flag[] {
  const extra = phone ? (PHONE_ALSO[reason] ?? []) : [];
  return [...new Set([...DISARMED_BY[reason], ...extra])];
}

/** Правило 16: поводы, которые забывают и сам выбор. */
export const FORGETS_SELECTION: readonly Reason[] = ['match', 'deselect', 'dismiss'];

export function forgetsSelection(reason: Reason): boolean {
  return FORGETS_SELECTION.includes(reason);
}

/** Правило 15: что гаснет, когда взводится `flag`. Поповер не гасит ничего. */
export function armDisarms(flag: Flag): Flag[] {
  return AIMS.includes(flag) ? AIMS.filter((other) => other !== flag) : [];
}

/** Состояние ряда из таблицы REFM-195 — под именем своей переменной. */
const ROW_FLAG: Record<ArmedState, Flag> = {
  merge: 'merging',
  cast: 'castMenu',
  troops: 'troopsPlan',
  assault: 'assaultAim',
  engage: 'engageAim',
  retreat: 'retreatMenu',
  pick: 'pickMode',
};

/** Правило 7: команды, после которых «Курс» больше не взведён. Сама `move` его переключает. */
export const DROPS_MOVE: readonly string[] = [
  'engage',
  'attack',
  'merge',
  'pick',
  'target',
  'split',
  'troops',
  'cast',
  'qretr',
];

/** Правило 14: выбор приказа на телефоне сворачивает ☰, откуда его выбрали. */
export const PHONE_FOLDS_MORE: readonly string[] = [
  'move',
  'engage',
  'merge',
  'attack',
  'pick',
  'target',
];

/** Правила 1–7 и 14: что гасит кнопка ряда `cmd` до того, как исполнится сама. */
export function commandDisarms(cmd: string | undefined, phone: boolean): Flag[] {
  const out: Flag[] = [];
  for (const state of Object.keys(KEEPS_ARMED) as ArmedState[])
    if (disarms(state, cmd)) out.push(ROW_FLAG[state]);
  out.push(...ALWAYS_DISARMED);
  if (cmd !== undefined && DROPS_MOVE.includes(cmd)) out.push('aiming');
  if (phone && cmd !== undefined && PHONE_FOLDS_MORE.includes(cmd)) out.push('cmdMore');
  return out;
}
