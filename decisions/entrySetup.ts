/**
 * Что предлагает экран входа в сетевой матч и когда можно входить (ENTRY-2).
 *
 * Соло-экран «Настройка схватки» даёт игроку три решения: совет учёных, стартовую точку
 * на карте и дом карточкой. Сетевой вход давал ОДНО — список домов, где кресло
 * подставлялось само («первое свободное», `seatPicker.ts`, правило 2). Стартовую точку
 * выбрать было нельзя вовсе, и оттого казалось, что дом к ней привязан.
 *
 * Здесь — половина решения, общая для обоих клиентов: что показать и когда пускать.
 * Разметку и рисование карты держит хозяин экрана.
 *
 * 1. **Порядок миров стабилен — он приходит от сервера.** Список обновляется, пока
 *    игрок выбирает; пересортировка (по имени, по дому, по обходу ключей) перетасовала
 *    бы миры под курсором, и человек потерял бы тот, который присматривал.
 * 2. **Занятый мир остаётся В СПИСКЕ и не выбирается.** Убирать его нельзя: карта — это
 *    расклад матча, и дырка на месте соперника читается как «там пусто», хотя там сидит
 *    живой игрок. Показать и запретить честнее, чем спрятать.
 * 3. **Дом больше не зависит от места (BF-30).** «Дом полон» перестало существовать:
 *    дом и стартовая точка уходят на сервер отдельными полями, поэтому пока в матче есть
 *    хоть один свободный мир, доступен ЛЮБОЙ дом этого матча. Считать свободные кресла
 *    на дом — модель ДО расцепления, и она запрещала бы законный выбор.
 * 4. **Кнопка входа заперта, пока не выбран свободный мир.** Пустой выбор отправил бы
 *    игрока на сервер без места, и тот посадил бы «куда-нибудь» — выбор превратился бы в
 *    пожелание (тот же довод, что у `seatJoin.ts`, правило 1). Дом при этом
 *    НЕобязателен: не выбрал — играешь домом, который приписан твоему месту в раскладе.
 * 5. **Если твой мир заняли, пока ты думал, — выбор сбрасывается, а не переезжает.**
 *    Подставить соседний значит отправить человека играть не туда, куда он смотрел.
 *    И это состояние отличимо от «ничего не выбирал»: экрану есть что сказать, а молча
 *    погасшая кнопка выглядит поломкой.
 */

/** Место матча в том виде, в каком его отдаёт сервер (`GET /matches/:id/seats`). */
export interface MatchSeat {
  playerId: string;
  faction: string;
  /** Родной мир места; `null` — сервер его не знает. */
  start: string | null;
  taken: boolean;
}

/** Стартовый мир на выбор. */
export interface StartWorld {
  /** Кресло, которое достанется вместе с миром — оно и уедет в `?slot=`. */
  slot: string;
  /** Мир на карте; `null` — рисовать нечего, но место всё равно занимаемо. */
  planetId: string | null;
  /** Дом, приписанный месту в раскладе. Подсказка, а не обязанность (правило 3). */
  faction: string;
  /** Занято живым игроком — не выбирается (правило 2). */
  taken: boolean;
}

/** Что экран предлагает игроку. */
export interface EntryOffer {
  /** Миры в порядке сервера (правило 1). */
  worlds: StartWorld[];
  /** Дома ЭТОГО матча, по первому появлению — из них и рисуются карточки (правило 3). */
  houses: string[];
  /** Сколько миров ещё свободно. Ноль — входить некуда. */
  free: number;
}

/** Разложить места сервера в предложение экрана (правила 1–3). */
export function entryOffer(seats: readonly MatchSeat[]): EntryOffer {
  const worlds: StartWorld[] = seats.map((s) => ({
    slot: s.playerId,
    planetId: s.start,
    faction: s.faction,
    taken: s.taken,
  }));
  const houses: string[] = [];
  for (const s of seats) if (!houses.includes(s.faction)) houses.push(s.faction);
  return { worlds, houses, free: worlds.filter((w) => !w.taken).length };
}

/** Можно ли уже входить: выбран мир, и он всё ещё свободен (правило 4). */
export function startEnabled(slot: string | null, worlds: readonly StartWorld[]): boolean {
  if (slot === null) return false;
  const world = worlds.find((w) => w.slot === slot);
  return world !== undefined && !world.taken;
}

/** Что стало с выбором после обновления списка (правило 5). */
export type SelectionFate =
  /** Мир на месте и свободен — выбор держим. */
  | { kind: 'kept'; slot: string }
  /** Мир заняли или он исчез из расклада — выбор сброшен, игроку надо сказать. */
  | { kind: 'lost' }
  /** Игрок ещё ничего не выбирал — сообщать не о чем. */
  | { kind: 'none' };

/** Пережил ли выбор обновление списка (правило 5). */
export function reconcileSelection(
  slot: string | null,
  worlds: readonly StartWorld[],
): SelectionFate {
  if (slot === null) return { kind: 'none' };
  const world = worlds.find((w) => w.slot === slot);
  if (world === undefined || world.taken) return { kind: 'lost' };
  return { kind: 'kept', slot };
}
