/**
 * Что выбирает ПРОСТОЙ тап по карте — и что выбирает ПОВТОРНЫЙ тап туда же (REFM-65).
 *
 * Под одной точкой лежит, как правило, не один объект: свои флоты стоят на орбите
 * своего же мира, стопкой друг на друге. Кто из них достаётся игроку — правило игры,
 * а не «что первым попалось в цикле».
 *
 * 1. **Мир идёт ПОСЛЕ флотов, но идёт.** Флот, припаркованный на своём мире, раньше
 *    навсегда закрывал этот мир от тапа. Мир — последний кандидат, а не выброшенный.
 * 2. **Повторный тап в ту же точку берёт СЛЕДУЮЩЕГО.** Так стопка разбирается тапами
 *    на месте, без зума и без «попади мимо».
 * 3. **Тап по новому месту начинается с верхнего.** Если текущий выбор не из этой
 *    стопки, перебор стартует с нуля — иначе новый тап отдавал бы случайный номер.
 * 4. **Один кандидат — он и остаётся.** Перебор по кругу из одного не должен ничего
 *    «сбрасывать»: тап по своему единственному флоту не снимает его выделение.
 * 5. **Пусто — значит снять выделение.** Тап по пустому космосу это осознанное «ничего».
 *
 * На телефоне перебора НЕТ (правило заморожено): палец толще, стопка разбирается
 * зумом, и цикл там воровал бы выбор у игрока. Тап отдаёт ближайший СВОЙ флот, иначе
 * мир, иначе ничего — `touchPick`.
 */

/** Что оказалось выбрано под тапом. */
export interface TapPick {
  kind: 'fleet' | 'planet';
  id: string;
}

/** Одинаковый ли это выбор (сравнение по значению — `TapPick` пересоздаётся). */
export function samePick(a: TapPick | null, b: TapPick | null): boolean {
  if (!a || !b) return a === b;
  return a.kind === b.kind && a.id === b.id;
}

/**
 * Кандидаты под тапом, сверху вниз: свои флоты (ближайший первым — порядок задаёт
 * вызывающий) и мир под ними (правило 1).
 */
export function tapCandidates(fleetIds: readonly string[], worldId: string | null): TapPick[] {
  const cands: TapPick[] = fleetIds.map((id) => ({ kind: 'fleet', id }));
  if (worldId) cands.push({ kind: 'planet', id: worldId });
  return cands;
}

/**
 * Следующий кандидат: от текущего выбора на шаг вперёд по кругу (правило 2), а если
 * текущего в стопке нет — с верхнего (правило 3). Пустая стопка → `null` (правило 5).
 */
export function nextPick(cands: readonly TapPick[], current: TapPick | null): TapPick | null {
  if (cands.length === 0) return null;
  const at = cands.findIndex((c) => samePick(c, current));
  return cands[(at + 1) % cands.length] ?? null;
}

/** Тап пальцем: ближайший свой флот, иначе мир, иначе ничего. Перебора нет. */
export function touchPick(fleetId: string | null, worldId: string | null): TapPick | null {
  if (fleetId) return { kind: 'fleet', id: fleetId };
  if (worldId) return { kind: 'planet', id: worldId };
  return null;
}
