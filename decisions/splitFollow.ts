/**
 * Выделение после «Разделить» (замечание владельца 2026-09-29: «после разделения флота
 * должен выделяться отделённый флот»). Игрок только что собрал в окне новую часть — ей он
 * и собирается отдать следующий приказ, а на исходном флоте выделение оставляло его
 * искать отделённый значок на карте.
 *
 * Id новой части клиент заранее не знает: его выдаёт ядро (`fleet:<игрок>:<время>:<seq>`)
 * и сообщает событием `fleet.split { from, to, owner }`. В соло событие приходит сразу из
 * редьюсера, в сети — со снимком сервера, поэтому клиент запоминает, ЧЕЙ раскол ждёт, а
 * решение принимается по событию. Чужой раскол и раскол другого флота (бот, второй
 * приказ) выделение не трогают.
 */
export interface SplitEvent {
  readonly from?: unknown;
  readonly to?: unknown;
  readonly owner?: unknown;
}

/** Какой флот выделить по событию раскола, или `null` — не трогать выделение. */
export function splitSelectTarget(
  awaitingFrom: string | null,
  ev: SplitEvent,
  me: string,
): string | null {
  if (awaitingFrom === null || ev.owner !== me || ev.from !== awaitingFrom) return null;
  return typeof ev.to === 'string' ? ev.to : null;
}
