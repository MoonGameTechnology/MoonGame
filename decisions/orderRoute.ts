/**
 * Куда уходит приказ игрока: на сервер, в локальный редьюсер или в отказ (REFM-147).
 *
 * Шестой срез сетевой секции. Предыдущие разбирали ВХОДЯЩЕЕ — чей сокет (`socketFate.ts`),
 * что значит первый снимок (`netWelcome.ts`), что делает каждый (`snapshotIngest.ts`),
 * как живёт цикл переподключения (`reconnectCycle.ts`). Здесь — ИСХОДЯЩЕЕ: три ветки
 * `playerOrder()`, стоявшие одна за другой вперемешку с побочными действиями.
 *
 * 1. **В сети клиент шлёт НАМЕРЕНИЕ и не трогает локальный редьюсер.** Решает сервер
 *    (server-authority). Примени клиент приказ у себя — тот выглядел бы принятым ровно до
 *    следующего снимка, который его сотрёт: игрок увидел бы необъяснимый откат своего же
 *    действия и перестал бы верить экрану.
 * 2. **Связь оборвана, но клиент жив — приказ В ОЧЕРЕДЬ (NETA2-5).** Локальное применение
 *    здесь — та же ложь, что в правиле 1, только злее: приказ исчезнет на первом же
 *    `welcome`, потому что сервер о нём не узнал. Но и отказывать не за что: у транспорта
 *    есть очередь (`connectionLost()` → outbox → флаш на реконнектном `welcome` под свежей
 *    сессией), и приказ уходит, как только провод оживает. Игроку про это говорят — «уйдёт
 *    после переподключения», — иначе он не поймёт, почему исполнения ещё нет.
 *    **Клиента нет — вот тогда отказ:** очередить некуда, приказ не уйдёт никогда, и молча
 *    проглотить его нельзя — игрок будет ждать исполнения, которого не будет.
 * 3. **Возврат значит «приказ не ОТВЕРГНУТ сейчас», а не «приказ исполнен».** В соло это
 *    честный исход редьюсера, в сети и при обрыве — всегда «не отвергнут», потому что
 *    исход асинхронный. Разница видна покадровым циклам (`resolvePendingMerges`): по
 *    отказу они выбрасывают приказ, иначе пережимали бы его каждый кадр — бесконечная
 *    очередь тостов отказа (ловилось на живом плейтесте).
 * 4. **Обучение учится в сети на НАМЕРЕНИИ, а в соло на ПРИНЯТОМ приказе.** Ответа сервера
 *    в момент отправки ещё нет, и ждать его — значит подвесить шаг тура на сетевую задержку;
 *    в соло ждать нечего, поэтому шаг двигает только принятый приказ. Отказ не учит ничему.
 */

/** Куда уходит приказ. */
export type OrderRoute =
  /** Сеть жива: намерение уходит серверу, локальное состояние не трогаем (правило 1). */
  | 'send'
  /** Связь оборвана, клиент жив: приказ в очередь транспорта (правило 2). */
  | 'queue'
  /** Связь оборвана и очередить некуда: отказ с сообщением игроку (правило 2). */
  | 'refuse'
  /** Соло: локальный редьюсер и есть истина (правило 3). */
  | 'local';

/** Когда шаг обучения узнаёт о приказе (правило 4). */
export type TourLearns = 'now' | 'on-accept' | 'never';

export interface OrderPlan {
  route: OrderRoute;
  tour: TourLearns;
}

/** Что известно к моменту приказа. */
export interface OrderContext {
  /** Идёт сетевой матч. */
  net: boolean;
  /** Есть живой клиент транспорта, которым можно отправить. */
  hasClient: boolean;
  /** Жив цикл переподключения (связь оборвана, место ещё не занято). */
  reconnecting: boolean;
}

/** Куда уходит этот приказ и что из этого узнаёт обучение (правила 1–4). */
export function orderPlan(ctx: OrderContext): OrderPlan {
  if (ctx.net && ctx.hasClient) return { route: 'send', tour: 'now' };
  // Очередь — это отложенная отправка, поэтому обучение считает её отправкой (правило 4):
  // намерение выражено, а ждать доставки значит вешать шаг тура на длину обрыва.
  if (ctx.reconnecting) return ctx.hasClient
    ? { route: 'queue', tour: 'now' }
    : { route: 'refuse', tour: 'never' };
  return { route: 'local', tour: 'on-accept' };
}
